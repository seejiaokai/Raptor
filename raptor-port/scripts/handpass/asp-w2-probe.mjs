// asp-w2 probe: learn the world before the scenarios (desktop only). Reads only.
import * as L from './asp-w2-lib.mjs'
const { sleep, J } = L
console.log('asp-w2-probe v1')
const W = L.mk('probe', L.SIZES.d)
const { b, p } = await L.world(L.SIZES.d, W)
await L.signIn(p, 'ad', 'a')
console.log('today', await L.today(p), 'week', await L.weekOf(p))
console.log('Hex', J(await p.evaluate(id => { const q = window.PEOPLE[id]; return { cs: q.cs, seat: q.seat, san: !!q.san } }, L.HEX)))
console.log('nick', J(await p.evaluate(() => { const q = window.PEOPLE.nick; return q ? { cs: q.cs, seat: q.seat, san: !!q.san } : null })))
console.log('sat', J(await p.evaluate(() => { const d = window.DAYS[5]; return { dutywaves: (d.dutywaves || []).map(w => (w.rows || []).map(r => r.role)), sims: Object.keys(d.sims || d.sim || {}), keys: Object.keys(d) } })))
console.log('tue', J(await p.evaluate(() => { const d = window.DAYS[1]; return { dutywaves: (d.dutywaves || []).map(w => (w.rows || []).map(r => r.role)), ground: (d.ground || []).length, ah: (d.allhands || []).length } })))
const f = await L.mainFixture(p, W, 5)
console.log('fixture', J(f))
console.log('chips', J(await p.evaluate(() => [...document.querySelectorAll('#schedBoard [data-oilsent], #schedBoard .oilcount')].filter(e => e.getBoundingClientRect().width > 0).map(e => e.outerHTML.slice(0, 160)))))
const r = await L.readCount(p, W, f.a.row.rid)
console.log('count', J(r))
await W.pic(p, 'win')
await L.closeWin(p, W)
await L.closeBoard(p, W)
await L.go(p, 'leavewar'); await sleep(800)
const c = (await L.lwCell(p, W, L.HEX, '2026-07-16')).cell
await W.press(p, c, 'cell')
await W.press(p, '[data-testid="bid-more"]:visible', 'more')
await W.press(p, '[data-testid="bid-postout"]:visible', 'postout')
console.log('po sheet', J(await p.evaluate(() => [...document.querySelectorAll('[data-testid^="po-"]')].filter(e => e.getBoundingClientRect().width > 0).map(e => e.dataset.testid + ' cls=' + e.className + ' ap=' + e.getAttribute('aria-pressed') + ' "' + e.innerText.replace(/\s+/g, ' ').slice(0, 80) + '"'))))
await W.pic(p, 'posheet')
console.log('errors', J(W.errs))
await b.close()
