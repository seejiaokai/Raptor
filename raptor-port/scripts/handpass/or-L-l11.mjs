import { open, fileInput, toWeek, shot, saveRes, errs, browser, toast, inputsOf, become, bellRead, csId, weekRows } from './or-L-lib.mjs'
const R = {}
const { ctx, page } = await open('ad', 'a')   // clock fixed at 22 Jun 2026 09:00 = "today" for this walk
R.filed = await fileInput(page, { type: 'Training', people: ['Ranger', 'Hex', 'Hunter'], from: '2026-07-15', to: '2026-07-15', timed: ['10:00', '11:00'], title: 'L11 training' })
R.todayInBrowser = await page.evaluate(() => new Date().toISOString())
const hunter = await csId(page, 'Hunter')
await page.evaluate(() => window.go('leavewar')); await page.waitForTimeout(1500)
await page.locator('[data-testid="month-JUN"]').click(); await page.waitForTimeout(900)
const cell = page.locator(`[data-testid="cell-${hunter}-2026-06-22"]`).first()
await cell.scrollIntoViewIfNeeded(); await cell.click(); await page.waitForTimeout(600)
await shot(page, 'l11-1-cell-sheet')
R.sheetTestids = await page.evaluate(() => [...document.querySelectorAll('[data-testid]')].filter(e => e.offsetParent && /bid|post|sheet/.test(e.dataset.testid)).map(e => e.dataset.testid))
await page.locator('[data-testid="bid-postout"]').click(); await page.waitForTimeout(700)
await shot(page, 'l11-2-after-PO')
R.afterPO = await page.evaluate(() => [...document.querySelectorAll('[data-testid]')].filter(e => e.offsetParent && /bid|post|sheet|po-/.test(e.dataset.testid)).map(e => e.dataset.testid))
R.deleteChip = await page.locator('[data-testid="po-delete"]').count()
await page.locator('[data-testid="po-delete"]').click(); await page.waitForTimeout(400)
R.poLine = await page.locator('[data-testid="po-line"]').innerText().catch(() => null)
await shot(page, 'l11-3-delete-chosen')
await page.locator('[data-testid="po-confirm"]').click(); await page.waitForTimeout(700)
R.afterConfirm = await page.evaluate(() => [...document.querySelectorAll('button, [data-testid]')].filter(e => e.offsetParent && /tap again|really|delete|confirm/i.test(e.textContent + (e.dataset.testid || ''))).map(e => (e.dataset.testid || '') + ':' + e.textContent.trim().slice(0, 50)))
const again = page.locator('button', { hasText: /tap again|delete hunter/i }).first()
if (await again.count()) { await shot(page, 'l11-3b-armed'); await again.click(); await page.waitForTimeout(1000) }
R.toast = await toast(page)
await shot(page, 'l11-4-after-delete')
R.inputs = (await inputsOf(page, 'L11 training')).map(r => ({ people: r.people, by: r.by }))
R.hunterStillOnRoster = await page.evaluate(h => !!window.PEOPLE[h], hunter)
await toWeek(page)
R.weekRow = await weekRows(page, 2, 'L11 training')
for (const cs of ['Ranger', 'Hex']) { await become(page, cs, 'member'); R['bell_' + cs] = await bellRead(page, `l11-bell-${cs}`) }
saveRes('L11', R)
console.log(JSON.stringify(R, null, 1))
console.log('ERRS', errs.join('\n'))
await browser.close()
