import * as L from './cal-F-lib2.mjs'
const b = await L.launch()
const ctx = await L.newCtx(b)
const p = await L.newPage(ctx)
await L.signIn(p, 'ad')
await L.go(p, 'inputs')
await L.toastSpy(p)
const [ace, anvil, basher, saber, ranger] = await L.ids(p, ['Ace', 'Anvil', 'Basher', 'Saber', 'Ranger'])
await L.openNew(p, '2026-07-18')
await p.selectOption('#inpEditType', 'Duty')
await L.pickSeveral(p, [ace, anvil, basher])
await L.setWhen(p, { allday: true, remarks: 'oil group' })
await p.locator('#inpEditSave').click()
await L.answerOil(p, 'yes')
await L.sleep(500)
// admin opens the entry: look at the editor
await p.locator('[data-testid="idy-list"] [data-testid="idy-people"]').first().click().catch(async () => { await p.locator('#inpCal .ib-bar').filter({ hasText: '+2' }).first().click() })
await L.sleep(500)
console.log('ADMIN editor testids', await p.evaluate(() => [...document.querySelectorAll('#inpEditPop [data-testid]')].map(e => e.dataset.testid).join(' ')))
console.log('ADMIN editor text', await p.evaluate(() => document.getElementById('inpEditPop').innerText.replace(/\s+/g, ' ').slice(-700)))
await L.pic(p, 'r6-admin-editor')
await p.locator('#inpEditCancel').click(); await L.sleep(300)
for (const [nm, id] of [['Ace', ace], ['Basher', basher]]) {
  await p.evaluate(i => { window.raptorMe(i); window.raptorRole('member') }, id); await L.sleep(500)
  await p.locator('#inpCal .ib-bar').filter({ hasText: '+2' }).first().click(); await L.sleep(600)
  console.log(nm, 'editor testids', await p.evaluate(() => [...document.querySelectorAll('#inpEditPop [data-testid]')].map(e => e.dataset.testid).join(' ')))
  console.log(nm, 'editor text', await p.evaluate(() => document.getElementById('inpEditPop').innerText.replace(/\s+/g, ' ').slice(-600)))
  await L.pic(p, 'r6-editor-' + nm)
  await p.locator('#inpEditCancel').click().catch(() => {}); await L.sleep(300)
}
console.log(JSON.stringify(L.errors))
await b.close()
