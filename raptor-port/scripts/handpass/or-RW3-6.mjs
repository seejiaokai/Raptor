import { open, fileInput, toWeek, toBoard, closeBoardMode, shot, saveRes, errs, browser, toast, inputsOf, become, bellRead, deleteUser, weekRows, boardRows, calRead, listText, sleep } from './or-RW3-lib.mjs'
const R = {}
const { ctx, page } = await open('ad', 'a')
await become(page, 'Ranger', 'member')
R.filed = await fileInput(page, { type: 'Training', people: ['Hex', 'Hunter'], from: '2026-07-15', to: '2026-07-15', timed: ['10:00', '11:00'], title: 'RW3 training' })
R.filedBy = R.filed[0]?.by
await become(page, 'Saber', 'admin')
R.weekBefore = await weekRows(page, 2, 'RW3 training')
R.del = await deleteUser(page, 'Hunter')
await shot(page, 'rw3-6-1-after-delete')
R.inputs = (await inputsOf(page, 'RW3 training')).map(r => ({ people: r.people, by: r.by }))
await toWeek(page)
R.weekRow = await weekRows(page, 2, 'RW3 training')
await page.locator('#eWeek .day:not(.peek)').nth(2).locator('.sec-grnd .pl-row', { hasText: 'RW3 training' }).first().screenshot({ path: 'docs/img/handpass/2026-10-12-one-rule/RW3/rw3-6-2-week-row.png' })
R.personalLine = await page.evaluate(() => [...document.querySelectorAll('#eWeek .day:not(.peek)')][2]?.innerText.split('\n').filter(l => /RW3 training/i.test(l)).slice(0, 6))
await toBoard(page, 2)
R.boardRow = await boardRows(page, 'RW3 training')
await shot(page, 'rw3-6-3-board')
await closeBoardMode(page)
R.cal = await calRead(page, '2026-07-15', 'rw3-6-4-cal')
R.list = (await listText(page)).filter(t => /RW3 training/i.test(t))
await shot(page, 'rw3-6-5-list')
for (const cs of ['Ranger', 'Hex']) { await become(page, cs, 'member'); R['bell_' + cs] = await bellRead(page, `rw3-6-bell-${cs}`) }
await become(page, 'Saber', 'admin')
R.bell_Saber = await bellRead(page, 'rw3-6-bell-Saber')
saveRes('RW3-6', R)
console.log(JSON.stringify({ ...R, cal: { cards: R.cal.cards } }, null, 1))
console.log('ERRS', errs.join('\n'))
await browser.close()
