/* S9 — Export, change, Import, reload (D admin).  node scripts/handpass/trk1105-walk-s9.mjs */
import { open, back, keys, diffKeys, classify, ocuAny, grade, mark, click, shot, exportFile, importFile, answerDialogs, dragBall, ballPos, revealBall, words, mk, sleep, SCRATCH } from './trk1105-walk-lib.mjs'
import { readFileSync, writeFileSync } from 'node:fs'
console.log('trk1105-walk-s9 v1')
const L = mk('S9')
const { browser, page, errors } = await open({})
const f1 = await exportFile(page, 'S9-1-before.json')
const j1 = JSON.parse(readFileSync(f1, 'utf8'))
const nCharts = j1.charts ? Object.keys(j1.charts.syllabi || j1.charts.byId || j1.charts).length : 0
L.ok('Export file parses and names charts and students', 'D', 'admin', !!j1.charts && !!j1.students, `top ${Object.keys(j1).join(',')}; contains ${JSON.stringify(j1.contains)}; students courses ${JSON.stringify((j1.students?.courses||[]).map(c => c.name))}; alert "${(exportFile.lastAlert||'').slice(0,90).replace(/\n/g,' ')}"`)
await mark(page, 'ST-02', 'dco', false); await mark(page, 'ST-01', 'dco', false)
// change a ball's typed detail, move a ball, in Edit chart layout, then ✓ Done → Save
await click(page, '#sylMenuBtn'); await click(page, '#arrangeBtn'); await sleep(700)
const c1 = await revealBall(page, 'ST-01')
await page.mouse.dblclick(c1.x, c1.y); await page.waitForSelector('#edCrew', { state: 'visible' })
await page.fill('#edCrew', 'WALKCREW1105'); await click(page, '#edSave'); await sleep(600)
const p0 = await ballPos(page, 'ACG-03')
await dragBall(page, 'ACG-03', 70, 0)
const p1 = await ballPos(page, 'ACG-03')
L.note('ACG-03 position before / after the drag', JSON.stringify({ p0, p1 }))
await shot(page, 'S9-1-arranged')
await click(page, '#sylMenuBtn'); await click(page, '#arrangeBtn'); await sleep(500)
const sc = page.locator('#page-tracker button:visible:has-text("Save changes")').first()
L.note('Save changes button present', String(await sc.count()))
await sc.click()
const dl1 = await answerDialogs(page, /^Save/i, 4000)
L.note('Done-editing dialog', JSON.stringify(dl1))
await sleep(1200)
await shot(page, 'S9-2-after-save-changes')
const f2 = await exportFile(page, 'S9-2-changed.json')
const j2 = JSON.parse(readFileSync(f2, 'utf8'))
const s1 = JSON.stringify(j1.charts), s2 = JSON.stringify(j2.charts)
L.ok('the changes reached the export (charts differ from the first file)', 'D', 'admin', s1 !== s2 && s2.includes('WALKCREW1105'), `chart json ${s1.length}→${s2.length}; has WALKCREW1105 ${s2.includes('WALKCREW1105')}`)
const k0 = await keys(page)
await importFile(page, f1)
const dl2 = await answerDialogs(page, [/^Replace/i, /^Yes/i, /^Import/i, /^OK/i], 9000)
L.note('Import dialogs', JSON.stringify(dl2))
await sleep(1800)
const pic = await shot(page, 'S9-3-after-import')
const k1 = await keys(page), cl = classify(diffKeys(k0, k1))
L.ok('Import: every changed key is under raptor:tracker/; none under ocu:', 'D', 'admin', cl.ocu.length === 0 && ocuAny(k1).length === 0 && cl.other.length === 0 && cl.tracker.length > 0, `tracker ${cl.tracker.length} ocuLocal ${cl.ocuLocal.length} appOwn ${cl.appOwn.length} other ${cl.other.length}`, pic)
const p2 = await ballPos(page, 'ACG-03').catch(() => null)
const f3 = await exportFile(page, 'S9-3-afterimport.json')
const j3 = JSON.parse(readFileSync(f3, 'utf8'))
const s3 = JSON.stringify(j3.charts)
const J = x => JSON.stringify(x), c1o = JSON.parse(s1), c3o = JSON.parse(s3), c2o = JSON.parse(s2)
L.ok('after Import the ball is back where the FILE had it (layout equals the first file, not the changed one)', 'D', 'admin', J(c3o.layouts) === J(c1o.layouts) && J(c3o.layouts) !== J(c2o.layouts), 'layouts equal file ' + (J(c3o.layouts) === J(c1o.layouts)) + '; ACG-03 x file/changed/after = ' + [c1o.layouts?.sb2026?.['ACG-03']?.x, c2o.layouts?.sb2026?.['ACG-03']?.x, c3o.layouts?.sb2026?.['ACG-03']?.x])
const detail = s3.includes('WALKCREW1105')
L.ok('a detail typed after the file was made is NOT wiped by Import (D122); every other chart part equals the file', 'D', 'admin', detail && J({ ...c3o, eventInfoBySyl: c1o.eventInfoBySyl }) === J(c1o) || J(c3o) === J(c1o), 'WALKCREW kept: ' + detail)
const g = [await grade(page, 'ST-02'), await grade(page, 'ST-01')]
L.note('student marks after import (file had none; the import rule: marks follow the file)', JSON.stringify(g))
await page.reload(); await back(page, 'a', false)
const f4 = await exportFile(page, 'S9-4-afterreload.json')
const s4 = JSON.stringify(JSON.parse(readFileSync(f4, 'utf8')).charts)
const g4 = [await grade(page, 'ST-02'), await grade(page, 'ST-01')]
L.ok('reload: the imported state stands (same as straight after Import)', 'D', 'admin', s4 === s3 && JSON.stringify(g4) === JSON.stringify(g), `charts equal to post-import ${s4 === s3}; grades ${g4}`, await shot(page, 'S9-4-reloaded'))
L.note('errors', errors.join(' | ').slice(0, 500) || 'none')
await browser.close()
L.save('S9')
