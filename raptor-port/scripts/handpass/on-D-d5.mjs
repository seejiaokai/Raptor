import { launch, world, bye, rec, FRI, THU } from './on-D-lib.mjs'
const browser = await launch()
const w = await world(browser, { tag: 'D5' }); const { page, tid } = w
await w.giveWarden()
const t1 = await w.fileIt(THU, { type: 'Training', people: ['bane'], from: '09:00', to: '12:00', title: 'Two day course', toDay: FRI })
const m1 = await w.fileIt(FRI, { type: 'Meeting', people: ['mamba'], from: '14:00', to: '15:00', title: 'Safety board' })
w.say('filed', await page.evaluate(([a, b]) => [a, b].map(i => JSON.stringify(window.INPUTS.find(r => r.iid === i))), [t1, m1]))
await w.makeHoliday('Founders Days', [THU, FRI])
const win = tid('win-oilday')
w.say('lists open', await win.count())
w.say('title', (await win.locator('.win-ttl').innerText().catch(() => '')).replace(/\s+/g, ' '))
w.say('lead', await tid('odl-lead').innerText().catch(() => 'none')); w.say('count', await tid('odl-count').innerText().catch(() => ''))
w.say('cards', await win.locator('.icard').evaluateAll(es => es.map(e => e.innerText.replace(/\s+/g, ' ').trim())))
w.say('measure', await w.measure('[data-testid="win-oilday"]'))
await w.hush(); await w.shot('D5-list')
await w.press(tid(`odl-yes-${t1}`))
await w.press(tid('odl-save')); await page.waitForTimeout(700)
w.say('after save', await page.evaluate(([a, b]) => [a, b].map(i => { const r = window.INPUTS.find(x => x.iid === i); return `${r.title}:${JSON.stringify(r.oil || null)}` }), [t1, m1]))
await w.closeCal()
w.say('Saber lines', await w.bellLines()); w.say('Saber lit', await w.bellLit())
await w.hush(); await w.shot('D5-saber-bell', { x: 700, y: 0, width: 740, height: 300 }); await w.closeBell()
await w.me('nact')
w.say('Warden lit', await w.bellLit()); w.say('Warden lines', await w.bellLines())
await w.hush(); await w.shot('D5-warden-bell', { x: 700, y: 0, width: 740, height: 300 })
await w.press(page.locator('[data-testid="bell-list"] .bl-line').first()); await page.waitForTimeout(500)
w.say('Warden list title', (await win.locator('.win-ttl').innerText().catch(() => '')).replace(/\s+/g, ' ')); w.say('count', await tid('odl-count').innerText().catch(() => ''))
w.say('cards', await win.locator('.icard').evaluateAll(es => es.map(e => e.innerText.replace(/\s+/g, ' ').trim())))
await w.shot('D5-warden-list')
w.say('errors', await bye(w))
await browser.close()
