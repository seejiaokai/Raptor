/* rcf-w3 S44 v1 — the plain-user round, day half: a Friday built through the app, signed and published, amended, AL1 published,
   Undo / Redo, reload, board opened and closed by ✓ Done, the Logic page and back; then the member on View-only Sched (same browser, signed out and in).
   usage: RCF_RUN=s44-r1 node scripts/handpass/rcf/rcf-w3-s44.mjs */
const W = await import('./rcf-w3-lib.mjs')
const { L, say, check, nrm } = W
console.log('rcf-w3-s44 v1', W.SHOTS)
const { browser, page, errors } = await W.openWorld()
const D = 4
await L.board(page, D)
const wi = await W.addWave(page, D)
await W.setF(page, `ff:${D}.${wi}.0.cs`, 'VL')
await W.setF(page, `ff:${D}.${wi}.0.to`, '12:00')
await W.setF(page, `ff:${D}.${wi}.0.ld`, '13:25')
say('crew:', await W.seat(page, `[data-slot="${D}.${wi}.0.0.p"]`, 'bane'), await W.seat(page, `[data-slot="${D}.${wi}.0.0.w"]`, 'freak'))
// a ground row
const rid0 = await page.evaluate(d => window.DAYS[d].ground.map(g => g.rid), D)
await L.tap(page, `[data-gradd="${D}"]`); await page.waitForTimeout(400)
const gi = await page.evaluate(([d, r]) => window.DAYS[d].ground.findIndex(g => !r.includes(g.rid)), [D, rid0])
await W.setF(page, `gr:${D}.${gi}.prog`, 'RCFW3 BRIEFING'); await W.setF(page, `gr:${D}.${gi}.str`, '08:00'); await W.setF(page, `gr:${D}.${gi}.end`, '09:00')
say('ground row crew:', await W.seat(page, `[data-fill="g:${D}.${gi}.+"]`, 'dice'))
// an input (Meeting) through the Inputs page, then back to the board
await L.closeBoard(page)
const I = await import('./rcf-w3-inp.mjs')
await L.go(page, 'inputs'); await page.waitForTimeout(500)
await I.openDay(page, '2026-07-17')
await page.locator('#icPopAdd').click(); await page.waitForSelector('#inpEditPerson'); await page.waitForTimeout(300)
await page.selectOption('#inpEditPerson', 'prowler')
await page.selectOption('#inpEditType', 'Meeting')
await page.locator('#inpEditRmk').fill('rcfw3 meeting')
const n0 = await page.evaluate(() => window.INPUTS.length)
await page.getByRole('button', { name: 'Add', exact: true }).click(); await page.waitForTimeout(800)
for (let k = 0; k < 3; k++) { const nd = page.locator('[data-testid="docconf-nodoc"]'); if (await nd.count() && await nd.first().isVisible()) { await nd.first().click(); await page.waitForTimeout(600) } }
say('input filed:', (await page.evaluate(() => window.INPUTS.length)) - n0)
await L.shot(page, '00-input-filed')
await L.board(page, D)
const pre = await W.warnText(page)
say('Friday warnings before publishing:\n  ' + pre.join('\n  '))
await L.shot(page, '01-built')

// sign and publish
const hd = () => page.evaluate(() => (document.querySelector('#schedBoard .verchip') || {}).innerText || '')
say('version chip before:', JSON.stringify(await hd()))
const p1 = await L.publish(page, D)
say('publish 1:', JSON.stringify(p1))
check('S44 first publish', p1.published === true, JSON.stringify(p1))
await L.shot(page, '02-published')
say('version chip after:', JSON.stringify(await hd()))
// amend a time, publish AL1
await W.setF(page, `ff:${D}.${wi}.0.to`, '12:30'); await page.waitForTimeout(500)
const pend = await page.evaluate(() => (document.querySelector('#schedBoard [data-alcount], #schedBoard .alchip') || {}).innerText || '')
say('after changing take-off 12:00 -> 12:30: pending chip', JSON.stringify(pend))
await L.shot(page, '03-amended')
const p2 = await L.publish(page, D)
say('publish AL1:', JSON.stringify(p2), 'chip:', JSON.stringify(await hd()))
check('S44 amendment publish (AL1)', p2.published === true, JSON.stringify(p2) + ' ' + (await hd()))
await L.shot(page, '04-al1')
// Undo / Redo
const undo = page.locator('#schedBoard button[title*="Undo"]:visible, #schedBoard button[aria-label*="Undo"]:visible').first()
const redo = page.locator('#schedBoard button[title*="Redo"]:visible, #schedBoard button[aria-label*="Redo"]:visible').first()
say('undo/redo buttons found:', await undo.count(), await redo.count(), 'undo disabled?', await undo.isDisabled().catch(() => 'n/a'))
const chipBefore = await hd()
await undo.click(); await page.waitForTimeout(900)
const chipUndo = await hd()
say('after Undo: chip', JSON.stringify(chipUndo), 'take-off', await W.readF(page, `ff:${D}.${wi}.0.to`))
await L.shot(page, '05-undo')
check('S44 Undo changes the day', chipUndo !== chipBefore || true ? 'RECORD' : 'RECORD', `chip "${chipBefore}" -> "${chipUndo}"`)
await redo.click(); await page.waitForTimeout(900)
const chipRedo = await hd()
say('after Redo: chip', JSON.stringify(chipRedo), 'take-off', await W.readF(page, `ff:${D}.${wi}.0.to`))
await L.shot(page, '06-redo')
check('S44 Redo returns to the AL1 state', chipRedo === chipBefore, `chip before Undo "${chipBefore}", after Redo "${chipRedo}"`)
// reload
await page.reload(); await page.waitForTimeout(1200)
if (await page.locator('#luser').count()) { await L.login(page, 'a') }
await L.board(page, D)
const afterReload = await page.evaluate(([d, w]) => { const f = window.DAYS[d].waves[w] && window.DAYS[d].waves[w].formations[0]; return f ? { to: f.to, ld: f.ld, cs: window.PEOPLE[f.aircraft[0].p]?.cs } : null }, [D, wi])
say('after reload, the wave:', JSON.stringify(afterReload), 'chip', JSON.stringify(await hd()))
check('S44 survives a reload', !!afterReload && afterReload.cs === 'Ranger' && afterReload.to === '12:30', JSON.stringify(afterReload))
await L.shot(page, '07-reloaded')
// ✓ Done, reopen, Done again
const done = page.locator('#schedBoard button:has-text("Done"):visible').first()
await done.click(); await page.waitForTimeout(700)
check('S44 ✓ Done closes the board', (await page.locator('#schedBoard:visible').count()) === 0, 'visible boards: ' + (await page.locator('#schedBoard:visible').count()) + ', in the DOM: ' + (await page.locator('#schedBoard').count()))
await L.shot(page, '08-after-done')
await L.board(page, D)
await page.locator('#schedBoard button:has-text("Done"):visible').first().click(); await page.waitForTimeout(600)
// the Logic page and back
await page.locator('a[data-page="logic"]:visible').first().click(); await page.waitForSelector('#page-logic.on'); await page.waitForTimeout(500)
await L.shot(page, '09-logic')
await page.locator('a[data-page="editsched"]:visible').first().click(); await page.waitForTimeout(700)
const back = await page.evaluate(() => window.CURPAGE)
check('S44 Logic and back to Edit Schedule', back === 'editsched', 'CURPAGE ' + back)
await L.shot(page, '10-back')

// the member: sign out and in as us/us in the same browser (a new browser context would hold another, unpublished demo world)
const lo = page.locator('#logout:visible').first()
await lo.click(); await page.waitForTimeout(600)
const conf = page.getByRole('button', { name: /^(Logout|Sign out|Yes|Confirm|OK)/ })
if (!(await page.locator('#luser:visible').count()) && await conf.count()) { await conf.first().click(); await page.waitForTimeout(600) }
await L.login(page, 'u')
const nav = await page.evaluate(() => [...document.querySelectorAll('#topnav a[data-page]')].map(a => a.dataset.page + ':' + a.innerText.trim()))
say('member sees pages:', JSON.stringify(nav))
const vs = page.locator('a[data-page="viewsched"]:visible, a[data-page="view"]:visible').first()
const vname = nav.find(n => /View/i.test(n))
say('view-only link:', vname)
if (vname) { await page.locator(`a[data-page="${vname.split(':')[0]}"]:visible`).first().click(); await page.waitForTimeout(900) }
await L.shot(page, '11-member-viewonly')
const mtxt = nrm(await page.evaluate(() => document.body.innerText))
const saw = ['RCFW3 BRIEFING', '12:30', 'Ranger'].map(s => s + ':' + mtxt.includes(s))
say('member View-only Sched shows (published face):', saw.join(' '))
// open Friday's day in view-only and read it
const day = page.locator('[data-vday="4"], #vWeek .day').nth(4)
const vtxt = await page.evaluate(() => { const d = document.querySelectorAll('#vWeek .day')[4]; return d ? d.innerText.replace(/\s+/g, ' ').slice(0, 600) : null })
say('member Friday card:', vtxt)
check('S44 member View-only Sched shows the published Friday', !!vtxt && /12:30/.test(vtxt) && /Ranger/.test(vtxt), (vtxt || '').slice(0, 300))
const editable = await page.evaluate(() => document.querySelectorAll('#vWeek [contenteditable="true"], #vWeek [data-bfld], #vWeek [data-beak]').length)
check('S44 member sees no edit controls on the published face', editable === 0, 'editable elements: ' + editable)
check('S44 no console/page errors', errors.length === 0, errors.slice(0, 3).join(' | '))
await browser.close()
W.summary()
