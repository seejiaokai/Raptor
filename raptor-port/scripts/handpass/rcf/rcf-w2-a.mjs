import { fileURLToPath } from 'node:url'
import { dirname, resolve } from 'node:path'
import { writeFileSync } from 'node:fs'
const HERE = dirname(fileURLToPath(import.meta.url))
const RUN = process.env.RUN || 'a1'
process.env.HP_URL ||= 'http://localhost:4291'
process.env.HP_SHOTS ||= resolve(HERE, '../../../docs/img/handpass/2026-11-12-rules-check-fixes/w2/' + RUN)
const W = await import('./rcf-w2-lib.mjs')
const F = await import('./rcf-w2-fx.mjs')
const { L, sleep, check, PASSIF, shot } = W
const { DI, sortie, ground, readAll, swapIn, toastText } = F
const browser = await W.launch()
const warnCrop = (page, name) => page.locator('#schedBoard .sb-warn').first().screenshot({ path: process.env.HP_SHOTS + '/' + name + '.png' }).then(() => name + '.png')

/* ===== S20 + S21 ===== */
{
  const { page } = await W.world(browser)
  const bane = await W.pid(page, 'Ranger'), stiff = await W.pid(page, 'Saber')
  await W.openBoard(page, DI)
  const s = await sortie(page, { who: bane })
  const g = await ground(page, { who: bane })
  await W.openWarnFold(page)
  let o = await readAll(page, bane, 'built')
  const c0 = F.clashLine(o)
  PASSIF('S20.0 fixture: Ranger clash between VL BFM sortie and BRIEFING shows red', c0 && /clash/.test(c0) && o.boardRings.some(x => /RED/.test(x)), JSON.stringify(c0) + ' | ' + o.head + ' | board ' + o.boardRings + ' | week ' + o.weekRings + ' | wk ' + o.weekCount, await warnCrop(page, 's20-0-built'))
  const ix = Number(c0.split(':')[0])
  await W.hideIx(page, DI, ix)
  o = await readAll(page, bane, 'hidden')
  const c1 = F.clashLine(o)
  PASSIF('S20.1 hide with ✕: struck line kept, no ring on board or week, count drops', c1 && /HID\+struck:reset/.test(c1) && !o.boardRings.some(x => /RED/.test(x)) && !o.weekRings.some(x => /RED/.test(x)), JSON.stringify(c1) + ' | ' + o.head + ' | board ' + o.boardRings + ' | week ' + o.weekRings + ' | wk ' + o.weekCount, await warnCrop(page, 's20-1-hidden'))
  await shot(page, 's20-1-hidden-board')
  /* retime both, keeping the overlap; rename the ground row */
  await W.setF(page, `ff:${DI}.${s.gi}.0.to`, '1215'); await W.setF(page, `ff:${DI}.${s.gi}.0.ld`, '1315')
  await W.setF(page, `gr:${DI}.${g.ri}.str`, '1215'); await W.setF(page, `gr:${DI}.${g.ri}.end`, '1245')
  o = await readAll(page, bane, 'retimed')
  let c = F.clashLine(o)
  PASSIF('S20.2 both items retimed (overlap kept): clash still hidden', c && /HID\+struck/.test(c) && !o.boardRings.some(x => /RED/.test(x)), JSON.stringify(c) + ' | board ' + o.boardRings + ' | wk ' + o.weekCount, await warnCrop(page, 's20-2-retimed'))
  await W.setF(page, `gr:${DI}.${g.ri}.prog`, 'DEBRIEF')
  o = await readAll(page, bane, 'renamed')
  c = F.clashLine(o)
  PASSIF('S20.3 ground row renamed DEBRIEF: still hidden', c && /HID\+struck/.test(c) && /DEBRIEF/.test(c) && !o.boardRings.some(x => /RED/.test(x)), JSON.stringify(c) + ' | board ' + o.boardRings + ' | week ' + o.weekRings + ' | wk ' + o.weekCount, await warnCrop(page, 's20-3-renamed'))
  /* close the board once and picture the week */
  await W.closeBoard(page); await sleep(400)
  await page.evaluate(d => document.querySelector(`#eWeek .day[data-day="${d}"]`).scrollIntoView({ block: 'center', inline: 'center' }), DI)
  await shot(page, 's20-3-week-hidden')
  await page.locator(`#eWeek .day[data-day="${DI}"]`).first().screenshot({ path: process.env.HP_SHOTS + '/s20-3-week-day.png' })
  await W.openBoard(page, DI); await W.openWarnFold(page)
  /* S21: delete the ground row and re-make it with the same words */
  await L.tap(page, `[data-grdel="${DI}.${g.ri}"]`); await sleep(500)
  const askDel = await page.locator('.confirm:visible, .modal:visible, [role=dialog]:visible').count()
  if (askDel) { console.log('NOTE a confirm appeared on ground delete'); await page.getByRole('button', { name: /^(Delete|Remove|Yes|OK)/ }).first().click().catch(() => {}); await sleep(400) }
  const nG = await page.evaluate(d => window.DAYS[d].ground.length, DI)
  console.log('ground rows after delete', nG)
  o = await readAll(page, bane, 'ground row deleted')
  const g2 = await ground(page, { prog: 'DEBRIEF', str: '1215', end: '1245', who: bane })
  await W.openWarnFold(page)
  o = await readAll(page, bane, 'ground row re-made, same words')
  c = F.clashLine(o)
  PASSIF('S21.1 ground row deleted and re-made with the same words: the new clash SHOWS red', c && /live/.test(c) && o.boardRings.some(x => /RED/.test(x)), JSON.stringify(c) + ' | ' + o.head + ' | board ' + o.boardRings + ' | week ' + o.weekRings + ' | wk ' + o.weekCount, await warnCrop(page, 's21-1-remade'))
  await shot(page, 's21-1-remade-board')
  /* hide the new one then replace the man on both items */
  await W.hideIx(page, DI, Number(c.split(':')[0]))
  o = await readAll(page, bane, 'new clash hidden again')
  PASSIF('S21.2 the re-made clash can be hidden too', /HID/.test(F.clashLine(o) || ''), JSON.stringify(F.clashLine(o)))
  const u1 = await F.unseat2(page, `[data-slot="${DI}.${s.gi}.0.0.p"]`)
  const u2 = await F.unseat2(page, `[data-slot="g:${DI}.${g2.ri}"]`)
  const r1 = await F.seatIn(page, `[data-slot="${DI}.${s.gi}.0.0.p"]`, stiff)
  const r2 = await F.seatIn(page, `[data-fill="g:${DI}.${g2.ri}.+"]`, stiff)
  console.log('unseat/seat toasts', JSON.stringify([u1, u2, r1, r2]))
  const who = await page.evaluate(([d, gi, ri]) => [window.DAYS[d].waves[gi].formations[0].aircraft[0].p, window.DAYS[d].ground[ri].who], [DI, s.gi, g2.ri])
  console.log('who now', who, 'saber is', stiff)
  o = await readAll(page, stiff, 'man replaced by Saber on both')
  c = F.clashLine(o)
  PASSIF('S21.3 a different man on the same two items: the new clash SHOWS red with a ring', who[0] === stiff && who[1] === stiff && c && /live/.test(c) && o.boardRings.some(x => /RED/.test(x)), 'seats=' + who + ' | ' + JSON.stringify(c) + ' | Saber board ' + o.boardRings + ' | week ' + o.weekRings + ' | ' + o.head, await warnCrop(page, 's21-3-man-replaced'))
  await shot(page, 's21-3-replaced-board')
  await page.close()
}

