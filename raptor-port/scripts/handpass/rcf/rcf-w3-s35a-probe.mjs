/* rcf-w3 s35a probe v1 — the Inputs page's add window */
const W = await import('./rcf-w3-lib.mjs')
const { L, say } = W
console.log('rcf-w3-s35a v1')
const { browser, page } = await W.openWorld()
await L.go(page, 'inputs')
await page.waitForTimeout(800)
await L.shot(page, '0-inputs')
const ids = async () => (await page.evaluate(() => [...document.querySelectorAll('[id], [data-testid]')].filter(e => e.offsetWidth > 0).map(e => (e.id ? '#' + e.id : '') + (e.dataset.testid ? '[' + e.dataset.testid + ']' : '')).filter(Boolean))).join(' ')
say('visible ids:', await ids())
const I = await import('./rcf-w3-inp.mjs'); await I.openDay(page, '2026-07-17')
await page.waitForTimeout(500)
say('after day click:', await ids())
await L.shot(page, '1-day')
await page.locator('#icPopAdd').click(); await page.waitForTimeout(600)
say('after + add:', await ids())
await L.shot(page, '2-add-window')
const sel = await page.evaluate(() => [...document.querySelectorAll('select')].filter(e => e.offsetWidth > 0).map(e => (e.id || e.name || '') + ': ' + [...e.options].map(o => o.value + '=' + o.text).join('|').slice(0, 300)))
say('selects:', JSON.stringify(sel))
await browser.close()
