/* rcf-w3 s31a probe v1 — an In-time line and the R box on Friday: what the screen says */
const W = await import('./rcf-w3-lib.mjs')
const { L, say, nrm } = W
console.log('rcf-w3-s31a v1', W.SHOTS)
const { browser, page, errors } = await W.openWorld()
await L.board(page, 4)
const wi = await W.addWave(page, 4)
await W.setF(page, `ff:4.${wi}.0.cs`, 'VL')
await W.setF(page, `ff:4.${wi}.0.to`, '12:00')
await W.setF(page, `ff:4.${wi}.0.rl`, '10:00')
await W.seat(page, `[data-slot="4.${wi}.0.0.p"]`, 'bane')
await L.tap(page, 'button:has-text("+ In-time")'); await page.waitForTimeout(500)
const els = await page.evaluate(() => [...document.querySelectorAll('#schedBoard *')].filter(e => e.offsetWidth > 0 && /IN TIME/.test(e.value || e.textContent || '') && e.children.length === 0).map(e => e.tagName + ' ' + e.getAttributeNames().map(a => a + '=' + e.getAttribute(a)).join(' ').slice(0, 160)))
say('in-time boxes:', JSON.stringify(els), JSON.stringify(await page.evaluate(() => window.DAYS[4].waves.map(w => w.intimes))))
await L.shot(page, 'intime-added')
const key = (els[0] && (els[0].match(/data-bfld=([^ ]+)/) || [])[1]) || (els[0] && (els[0].match(/data-txt=([^ ]+)/) || [])[1])
say('key', key)
if (key) { await W.setF(page, key, '09:00 RALLY'); await page.waitForTimeout(500) }
say('intimes:', JSON.stringify(await page.evaluate(() => window.DAYS[4].waves.map(w => w.intimes))))
await L.shot(page, 'intime-typed')
say('warnings:\n ' + (await W.warnText(page)).join('\n '))
const pk = await page.evaluate(() => [...document.querySelectorAll('#schedBoard [data-person="bane"]')].filter(e => e.offsetWidth > 0 && !e.closest('#sbRoster')).map(e => e.className + ' | title=' + e.title))
say('Ranger puck:', JSON.stringify(pk))
// week header
await L.closeBoard(page); await L.go(page, 'editsched')
const head = await page.evaluate(() => { const d = document.querySelector('#eWeek .day[data-day="4"]'); return d ? d.innerText.replace(/\s+/g, ' ').slice(0, 700) : null })
say('week Friday text:', head)
await L.shot(page, 'week')
await browser.close()
