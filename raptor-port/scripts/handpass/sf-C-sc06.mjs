const { p } = await ctxOpen(b, {})
await go(p, 'editsched')
await p.evaluate(() => window.addWave(4, 'sc')); await sleep(500)
await openBoard(p, 4)
// SC AM: MAIN Saber; SPARE rows: Torch (ignite, row 2) and Nomad (razer, row 3). Torch stands in for "Viper".
const st = []
st.push(await bPut(p, 4, 0, 0, 0, 'p', ['vinci']))
