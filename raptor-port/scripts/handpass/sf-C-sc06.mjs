// palette barred: arm an empty sim seat inside Torch's hours and look at the roster
await p.locator('#schedBoard [data-sradd="4.oft"]:visible').first().click(); await sleep(500)
const sim2 = await p.evaluate(() => window.DAYS[4].sims.oft.length - 1)
await bType(p, `#schedBoard [data-bfld="sr:4.oft.${sim2}.label"]`, 'EP-6'); await bType(p, `#schedBoard [data-bfld="sr:4.oft.${sim2}.str"]`, '09:00'); await bType(p, `#schedBoard [data-bfld="sr:4.oft.${sim2}.end"]`, '10:30')
await p.locator(`#schedBoard [data-slot="s:4.oft.${sim2}.p"]:visible`).first().click(); await sleep(500)
const pal = await p.evaluate(() => { const e = document.querySelector('#sbRoster .rpuck[data-person="ignite"]'); const r = document.querySelector('#sbRoster .rpuck[data-person="razer"]'); return { torch: e ? { cls: e.className, title: e.title } : null, ridge: r ? { cls: r.className, title: r.title } : null } })
await shot(p, '6-03-palette')
rec(S, 'palette with an empty 09:00-10:30 sim seat armed (SC AM flying)', 'Torch barred with the reason; Nomad (standing by with R typed too, same shift) also barred — he flies', pal, /bar|dis|busy|clash/i.test(JSON.stringify(pal.torch)) ? 'PASS' : 'RECORD', 'C-6-03-palette.png')
await p.keyboard.press('Escape'); await sleep(300)
