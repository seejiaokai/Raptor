rec(S, 'Torch on SC AM SPARE (R 06:30) and SC PM MAIN (R 13:00)', 'no overlap clash at 13:00; long-day note 06:30 -> 19:00', { tmp, w5 }, !w5.some(x => /Torch/.test(x) && /SC PM/.test(x)) && w5.some(x => /Torch/.test(x) && /long work day/.test(x) && /06:30/.test(x) && /19:00/.test(x)) ? 'PASS' : 'FAIL', 'C-6-06-am-pm-abut.png')
rec(S, 'browser error list', 'empty', errors, errors.length ? 'FAIL' : 'PASS')
