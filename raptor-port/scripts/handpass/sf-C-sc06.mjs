await bType(p, bf(4, 0, 0, 'rl'), '')
const w2 = await warnLines(p)
rec(S, 'R cleared', 'back to quiet for Torch', w2.filter(x => /Torch/.test(x)), !w2.some(x => /Torch/.test(x) && /clash/.test(x)) ? 'PASS' : 'FAIL')
await p.locator('#schedBoard [data-safly="4.0.0.2"]:visible').first().click(); await sleep(600)
const w3 = await warnLines(p), c3 = await chipLine(p)
await shot(p, '6-04-hand-tick')
rec(S, "tick Torch's SPARE chip by hand instead of R", 'hard clashes for Torch only; Nomad (not ticked) keeps his standing-by wording (OD but standing), not the flying one (OD but tasked)', { w3, c3 }, w3.filter(x => /Torch/.test(x)).length >= 2 && !w3.some(x => /Nomad/.test(x) && /tasked/.test(x)) ? 'PASS' : 'FAIL', 'C-6-04-hand-tick.png')
// SC duty desk
await p.locator('#schedBoard [data-dwadd="4"]:visible').first().click(); await sleep(500)
const dwBtns = await p.evaluate(() => [...document.querySelectorAll('button')].filter(e => e.offsetParent && /SC|AVALON|BB|Standard|Duty/i.test(e.innerText)).map(e => e.innerText.trim().slice(0, 30)).slice(0, 12))
console.log('after + Block buttons:', dwBtns)
await shot(p, '6-05-add-block-menu')
rec(S, '+ Block menu on the Duties section', 'RECORD what the menu offers', dwBtns, 'RECORD', 'C-6-05-add-block-menu.png')
await p.locator('button').filter({ hasText: /^SC Shift/ }).first().click(); await sleep(700)
const dwi = await p.evaluate(() => window.DAYS[4].dutywaves.length - 1)
const scd = await L.bPutFill(p, `d:4.${dwi}.0.+`, ['ignite'])
const wD = await warnLines(p)
const deskRow = await p.evaluate(i => { const r = window.DAYS[4].dutywaves[i].rows[0]; return r ? r.role + ' ' + r.str + '-' + r.end : null }, dwi)
await shot(p, '6-05b-sc-desk')
rec(S, 'Torch also on an SC duty desk (SC Shift block) while SC AM SPARE is ticked', 'RECORD: the desk clashes with the flying SPARE', { scd, deskRow, w: wD.filter(x => /Torch/.test(x)) }, 'RECORD', 'C-6-05b-sc-desk.png')
// SC AM spare (ticked) and SC PM main abutting at 13:00, R on both
await bType(p, bf(4, 0, 1, 'rl'), '13:00')
await bType(p, bf(4, 0, 0, 'rl'), '06:30')
