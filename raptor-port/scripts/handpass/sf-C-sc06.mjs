st.push(await bPut(p, 4, 0, 0, 3, 'p', ['pike']))
// a 10:00 sim and an 11:00-12:00 ground item, Torch on both
await p.locator('#schedBoard [data-sradd="4.oft"]:visible').first().click(); await sleep(500)
const simIdx = await p.evaluate(() => window.DAYS[4].sims.oft.length - 1)
await bType(p, `#schedBoard [data-bfld="sr:4.oft.${simIdx}.label"]`, 'EP-5'); await bType(p, `#schedBoard [data-bfld="sr:4.oft.${simIdx}.str"]`, '10:00'); await bType(p, `#schedBoard [data-bfld="sr:4.oft.${simIdx}.end"]`, '10:45')
st.push(await bPutKey(p, `s:4.oft.${simIdx}.p`, ['ignite']))
const grIdx = 1
await bType(p, `#schedBoard [data-bfld="gr:4.${grIdx}.prog"]`, 'AIRCREW ADMIN')
st.push(await bPutFill(p, `g:4.${grIdx}.+`, ['ignite']))
rec(S, 'set-up: SC AM SPARE Torch (+Nomad), Torch on OFT 10:00-11:30 and a ground item 11:00-12:00', 'seated', st, st.every(x => x !== 'FAILED') ? 'PASS' : 'NOT WALKED')
const w0 = await warnLines(p), c0 = await chipLine(p)
const pk0 = await puckAt(p, '4.0.0.2.p')
await shot(p, '6-01-standing-by')
rec(S, 'SC AM standing by (no R, no tick)', 'nothing warns for Torch (a spare is free)', { w0, c0, pk0 }, !w0.some(x => /Torch|Wildcard/.test(x) && /clash|rest|double/i.test(x)) ? 'PASS' : 'FAIL', 'C-6-01-standing-by.png')
// type R
await bType(p, bf(4, 0, 0, 'rl'), '06:30')
const w1 = await warnLines(p), c1 = await chipLine(p)
const pkSp = await puckAt(p, '4.0.0.2.p'), pkSim = await puckAt(p, `s:4.oft.${simIdx}.p`), pkGr = await puckAt(p, `g:4.${grIdx}`), pkNomad = await puckAt(p, '4.0.0.3.p')
await shot(p, '6-02-R-typed')
const torchClash = w1.filter(x => /Torch/.test(x))
rec(S, 'type SC AM R 06:30', 'hard clashes for Torch against the sim and the ground item; whole shift now flies (D1044), so the shift-mate Nomad is checked too', { w1, c1, pkSp: pkSp && pkSp.cls, pkSim: pkSim && pkSim.cls, pkGr: pkGr && pkGr.cls, pkNomad: pkNomad && pkNomad.cls }, torchClash.length >= 2 && !w1.some(x => /Nomad/.test(x) && /clash/.test(x)) ? 'PASS' : 'FAIL', 'C-6-02-R-typed.png')
rec(S, 'Torch puck on the SPARE row, the sim and the ground item', 'red ring on each', { sp: pkSp && pkSp.title, sim: pkSim && pkSim.title, gr: pkGr && pkGr.title, ridge: pkNomad && pkNomad.title }, ringed(pkSp) && ringed(pkSim) && ringed(pkGr) && true ? 'PASS' : 'FAIL')
