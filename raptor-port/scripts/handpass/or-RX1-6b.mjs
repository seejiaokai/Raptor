// RX1-6b — compare a Personal Saturday row with a Training Saturday row in OIL Earn (puck look, titles)
import { launch, openWorld, fileX, shotX, rowIdx, inputOf, errs, openBoard, centre, boardRowEl, log, drag2, rosterPuckOf, waitQuiet, oilOn } from './or-RX1-lib.mjs'
const browser = await launch()
const { page: p } = await openWorld(browser, { fresh: false })
const DI = 5
const a = await fileX(p, { type: 'Personal', person: 'Ranger', from: '2026-07-18', to: '2026-07-18', timed: ['09:00', '12:00'], title: 'Own thing' })
const b = await fileX(p, { type: 'Training', person: 'Tally', from: '2026-07-18', to: '2026-07-18', timed: ['13:00', '15:00'], title: 'Drill', oil: 'yes' })
log('filed', a.made[0].iid, b.made[0].iid, 'oilq', a.oilSeen, b.oilSeen)
