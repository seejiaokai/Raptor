const rows = await p.evaluate(() => [...document.querySelectorAll('#schedBoard .sb-arow')].filter(e => e.offsetParent).map(r => ({ cls: String(r.className), text: r.innerText.replace(/\s+/g, ' ').trim().slice(0, 80), pucks: [...r.querySelectorAll('.puck')].map(e => ({ cls: String(e.className), title: e.getAttribute('title'), parent: String(e.parentElement.className), parentTitle: e.parentElement.getAttribute('title'), opacity: getComputedStyle(e).opacity, filter: getComputedStyle(e).filter, aria: e.getAttribute('aria-label'), out: e.outerHTML.slice(0, 220) })) })))
log('rows', rows)
const gp = p.locator('#schedBoard .sb-panel.grnd, #schedBoard .sb-panel').filter({ hasText: /Own thing|PERSONAL|Drill/i }).first()
await p.locator('#schedBoard .sb-arow:visible').filter({ hasText: /Drill/i }).first().evaluate(e => e.scrollIntoView({ block: 'center' }))
await p.waitForTimeout(300)
await shotX(p, 'rx1-6b-1-personal-vs-training-oilearn')
const pr = p.locator('#schedBoard .sb-arow:visible .puck', { hasText: 'Ranger' }).first()
await pr.hover(); await p.waitForTimeout(1200)
await shotX(p, 'rx1-6b-2-hover-ranger')
log('tooltip-ish nodes visible', await p.evaluate(() => [...document.querySelectorAll('body *')].filter(e => e.offsetParent && /earns no OIL|no OIL/i.test(e.textContent) && e.children.length === 0).map(e => e.tagName + '.' + e.className + ':' + e.textContent.slice(0, 100))))
log('errs', errs)
