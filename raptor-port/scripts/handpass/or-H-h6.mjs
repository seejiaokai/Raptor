import { launch, open, fileInput, openFromList, describeWin, shot, WIN, toastMark, toastsSince, save, errs, as, badgeText, bellRead } from './or-H-lib.mjs'
const out = {}
const log = (k, v) => { out[k] = v; console.log('## ' + k + ' ' + JSON.stringify(v)) }
const browser = await launch()
const { ctx, page } = await open(browser)
const who = iid => page.evaluate(i => { const r = window.INPUTS.find(x => x.iid === i); return r ? { people: r.people.map(e => (window.PEOPLE[e.p]?.cs || e.p) + '(by ' + (window.PEOPLE[e.by]?.cs || e.by) + ')'), by: window.PEOPLE[r.by]?.cs, modBy: window.PEOPLE[r.modBy]?.cs, type: r.type, date: r.date } : null }, iid)
const listRow = iid => page.evaluate(i => { const e = document.querySelector(`[data-popiid="${i}"]`); return e ? e.innerText.replace(/\s+/g, ' ') : null }, iid)
await as(page, 'Saber')
const r = await fileInput(page, { type: 'Training', person: 'Ranger', from: '2026-07-15', to: '2026-07-15', timed: ['10:00', '11:00'] })
const iid = r[0].iid
log('filed', await who(iid))
await as(page, 'Ranger')
await openFromList(page, iid)
await page.locator(`${WIN} [data-testid="pp-several"]`).click(); await page.waitForTimeout(300)
await page.locator(`${WIN} [data-pp="nick"]`).click(); await page.waitForTimeout(250)
log('picker-before-save', (await describeWin(page)).picker)
await shot(page, 'H6-1-tally-picked')
let m = await toastMark(page)
await page.locator('#inpEditSave').click(); await page.waitForTimeout(700)
log('after-add-tally', { toast: await toastsSince(page, m), inputs: await who(iid), win: await page.locator(WIN).count(), list: await listRow(iid) })
await shot(page, 'H6-2-after-add')
/* he may go on changing: reopen, change the time */
await openFromList(page, iid)
const d = await describeWin(page)
log('reopened', { fields: d.fields.map(f => f.id + '=' + f.value), buttons: d.buttons.map(b => b.id + ':' + b.text).filter(t => t.length > 4), picker: d.picker, tail: d.text.slice(-200) })
await shot(page, 'H6-3-reopened')
await page.fill('#inpEditEnd', '11:30')
m = await toastMark(page)
await page.locator('#inpEditSave').click(); await page.waitForTimeout(700)
log('retimed', { toast: await toastsSince(page, m), inputs: await page.evaluate(i => window.INPUTS.find(x => x.iid === i).e, iid) })
/* hand over: himself out, Hex in, one save */
await openFromList(page, iid)
await page.locator(`${WIN} [data-pp="bane"]`).click(); await page.waitForTimeout(200)
await page.locator(`${WIN} [data-pp="rocky"]`).click(); await page.waitForTimeout(200)
log('picker-handover', (await describeWin(page)).picker)
m = await toastMark(page)
await page.locator('#inpEditSave').click(); await page.waitForTimeout(700)
log('after-handover', { toast: await toastsSince(page, m), inputs: await who(iid), win: await page.locator(WIN).count(), winTail: await page.locator(WIN).evaluate(w => w.innerText.replace(/\s+/g, ' ').slice(-300)).catch(() => null) })
await shot(page, 'H6-4-handover-refused')
/* second case: the input is Ranger ALONE (filed by Saber); he swaps himself for Hex in one save */
await as(page, 'Saber')
const r2 = await fileInput(page, { type: 'Training', person: 'Ranger', from: '2026-07-16', to: '2026-07-16', timed: ['10:00', '11:00'] })
const iid2 = r2[0].iid
log('b-filed', await who(iid2))
await as(page, 'Ranger')
await openFromList(page, iid2)
await page.locator(`${WIN} [data-testid="pp-several"]`).click(); await page.waitForTimeout(300)
await page.locator(`${WIN} [data-pp="rocky"]`).click(); await page.waitForTimeout(200)
await page.locator(`${WIN} [data-pp="bane"]`).click(); await page.waitForTimeout(200)
log('b-picker', (await describeWin(page)).picker)
await shot(page, 'H6-5-alone-handover-set')
m = await toastMark(page)
await page.locator('#inpEditSave').click(); await page.waitForTimeout(700)
log('b-after-handover', { toast: await toastsSince(page, m), inputs: await who(iid2), win: await page.locator(WIN).count(), winTail: await page.locator(WIN).evaluate(w => w.innerText.replace(/\s+/g, ' ').slice(-300)).catch(() => null) })
await shot(page, 'H6-6-alone-handover-result')
log('errors', errs)
save('H6', out)
await browser.close()
