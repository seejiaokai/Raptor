// RX4-2: the delete's route. Ranger files an OD for Ranger, Hex, Hunter; Saber publishes Wed; Admin -> Users -> Ranger -> Delete; then Hex's 10:00.
import * as L from './or-RX4-lib.mjs'
const { j } = L
const out = {}
const { ctx, page: p } = await L.open('us', 'us')
out.filed = await L.fileInput(p, { type: 'OD', people: ['Ranger', 'Hex', 'Hunter'], from: L.ISO, to: L.ISO })
console.log('filed', j(out.filed))
const iid = out.filed[0].iid
await L.signOut(p); await L.signIn(p, 'ad', 'a')
out.pub = await L.signAndPublish(p, L.DI); console.log('PUBLISH', j(out.pub))
out.c0 = await L.counts(p, { noBoard: true }); console.log('COUNTS 0', L.fmt(out.c0))
await L.toMonth(p, L.ISO); await L.openDay(p, L.ISO)
out.card0 = (await L.dayCardText(p)).filter(t => /OD|Hex/.test(t)); console.log('card0', j(out.card0))
await L.shot(p, 'rx4-2-1-card-before'); await L.closeDay(p)
out.del = await L.deleteUser(p, 'Ranger'); console.log('delete:', j(out.del))
await L.shot(p, 'rx4-2-2-after-delete')
const idOd = () => p.evaluate(() => window.INPUTS.filter(r => r.type === 'OD' && /Jul 15/.test(r.date)).map(r => ({ iid: r.iid.slice(-5), people: (r.people || []).map(e => window.PEOPLE[e.p]?.cs || ('gone:' + e.p)), by: window.PEOPLE[r.by]?.cs || ('gone:' + r.by) })))
out.inputsAfterDelete = await idOd(); console.log('OD inputs after delete', j(out.inputsAfterDelete))
await L.toMonth(p, L.ISO); await L.openDay(p, L.ISO)
out.cardAfterDelete = (await L.dayCardText(p)).filter(t => /OD|Hex/.test(t)); console.log('cardAfterDelete', j(out.cardAfterDelete))
await L.shot(p, 'rx4-2-3-card-after-delete'); await L.closeDay(p)
out.c1 = await L.counts(p, { keepWin: true, noBoard: false }); console.log('COUNTS after delete', L.fmt(out.c1))
await L.shot(p, 'rx4-2-4-togoout-after-delete')
out.win1 = await L.winRead(p)
await p.locator('.chgwin .win-x').first().click().catch(() => {}); await p.waitForTimeout(300)
// Hex's typed 10:00
await L.toWeek(p)
const row = L.day(p).locator('.sec-unav .pl-row').filter({ has: p.locator('.puck', { hasText: 'Hex' }) }).first()
await row.scrollIntoViewIfNeeded(); await p.waitForTimeout(300)
out.rowBefore = (await row.innerText()).replace(/\s+/g, ' '); console.log('Hex row before:', out.rowBefore)
await L.shot(p, 'rx4-2-5-hex-row-before')
const box = row.locator('.t-s').first()
await box.click(); await p.keyboard.press('Control+A'); await p.keyboard.type('10:00'); await box.evaluate(x => x.blur()); await p.waitForTimeout(900)
out.toastType = await L.toast(p); console.log('toast:', out.toastType)
out.inputsAfterType = await idOd(); console.log('OD inputs after typing', j(out.inputsAfterType))
out.c2 = await L.counts(p, { keepWin: true, noBoard: false }); console.log('COUNTS after Hex typed', L.fmt(out.c2))
await L.shot(p, 'rx4-2-6-togoout-hex-own')
out.winAll = await L.winRead(p)
await p.locator('.chgwin .win-x').first().click().catch(() => {}); await p.waitForTimeout(300)
await L.toMonth(p, L.ISO); await L.openDay(p, L.ISO)
out.cardFinal = (await L.dayCardText(p)).filter(t => /OD|Hex/.test(t)); console.log('cardFinal', j(out.cardFinal))
await L.shot(p, 'rx4-2-7-card-final'); await L.closeDay(p)
console.log('ERRORS', L.errs.join(' | ') || 'none')
out.errs = L.errs.slice()
L.saveRes('2', out)
await ctx.close(); await L.browser.close()
