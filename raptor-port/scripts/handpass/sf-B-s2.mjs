import { launch, proveBundle, phone, addWaveAndSeat, openBoard, shot, zoom, wait, tapEl, typeBox, scrollTo, publishDay, chips, openWarn, pending, puckInfo, weekTo, weekPage } from './sf-B-lib.mjs'
console.log('sf-B-s2 v2')
await proveBundle()
const browser = await launch()
const rec = (id, ok, note) => console.log(ok === true ? 'PASS' : ok === false ? 'FAIL' : 'RECORD', id, '::', note)
const badge = (p, di) => p.evaluate(di => (document.querySelectorAll('#eWeek .day')[di].querySelector('.badge') || {}).innerText || 'none', di)
try {
  const { ctx, page: p, errors } = await phone(browser, 'a')
  const DI = 5, SEL = '#schedBoard'
  await addWaveAndSeat(p, DI, 'avalon', [[0, 0], [0, 1], [0, 2], [0, 3]])
  await p.evaluate(() => { window.addWave(6, ''); const g = window.DAYS[6].waves.length - 1; window.fillSlot(`6.${g}.0.0.p`, 'dj') })
  await openBoard(p, 6)
  await typeBox(p, p.locator(`${SEL} [data-bfld="ff:6.0.0.to"]`), '0900')
  await p.evaluate(() => window.closeScheduler && window.closeScheduler()); await wait(p, 600)
  await openBoard(p, DI)
  console.log('publish Sat', JSON.stringify(await publishDay(p, DI)))
  await scrollTo(p, p.locator(`${SEL} [data-sarole="5.0.0.0"]`).last(), 250)
  let c = await chips(p, SEL)
  rec('2-1', c.length === 4 && c.every(x => x.tag === 'BUTTON' && x.txt === 'FLIES'), `Pub Sat, AVALON standing by, before R: ${c.length} chips ${c.map(x => x.txt + '/' + x.tag).join(',')}; chip size ${c[0].w}x${c[0].h} css px; pending "${await pending(p)}"`)
  await shot(p, 'B-2-1-board-dashed')
  const z = await typeBox(p, p.locator(`${SEL} [data-bfld="ff:5.0.0.rl"]`), '1830')
  c = await chips(p, SEL)
  const lit = c.filter(x => /✓ FLIES/.test(x.txt) && x.tag === 'SPAN')
  rec('2-2', lit.length === 4 && c.length === 4 && z.scale === 1, `R 18:30 typed by finger tap + keyboard; page zoom scale ${z.scale} (not zoomed); ${lit.length} lit non-button chips of ${c.length}; title "${lit[0]?.title}"; pending "${await pending(p)}"`)
  await scrollTo(p, p.locator(`${SEL} [data-bfld="ff:5.0.0.rl"]`).first(), 250)
  await shot(p, 'B-2-2-board-lit')
  await p.evaluate(() => window.scrollTo(0, 0)); await wait(p, 200)
  const wl = await openWarn(p)
  rec('2-3', null, `Saturday warning list: ${wl}`)
  await shot(p, 'B-2-3-board-sat-warnings')
  await tapEl(p, p.locator(`${SEL} .wh[data-sbwtog]`), { label: 'close warn' })
  // Sunday through the board's next-day button
  await p.evaluate(() => window.scrollTo(0, 0))
  await tapEl(p, p.locator('#sbNextDay:visible'), { label: 'next day' }); await wait(p, 900)
  const wl2 = await openWarn(p)
  const pk = await puckInfo(p, SEL, 'dj')
  rec('2-4', /crew rest/i.test(wl2) && pk.some(x => /hard/.test(x.cls)), `Sunday board (SBDAY ${await p.evaluate(() => window.SBDAY)}): Ace puck classes ${JSON.stringify(pk.map(x => x.cls))}; warnings: ${wl2}`)
  await shot(p, 'B-2-4-board-sun-warnings')
  await tapEl(p, p.locator(`${SEL} .wh[data-sbwtog]`), { label: 'close warn' })
  await scrollTo(p, p.locator(`${SEL} [data-bfld="ff:6.0.0.to"]`), 250)
  await shot(p, 'B-2-5-board-sun-ace')
  // the week
  await p.evaluate(() => document.querySelector('#sbDone').click()); await wait(p, 800)
  await p.evaluate(() => window.go('editsched')); await wait(p, 700)
  let pg = await weekTo(p, ctx, 5)
  console.log('week page', pg, 'Sat badge', await badge(p, 5))
  const wk = await chips(p, '#eWeek .day:nth-child(6)')
  rec('2-5', wk.length === 4 && wk.every(x => x.tag === 'SPAN' && /✓ FLIES/.test(x.txt)), `Edit Schedule week (phone) Saturday: ${wk.length} chips, all lit non-buttons: ${wk.every(x => x.tag === 'SPAN')}; chip size ${wk[0]?.w}x${wk[0]?.h}; day badge "${await badge(p, 5)}"`)
  await scrollTo(p, p.locator('#eWeek .day:nth-child(6) .saflies').first(), 220)
  await shot(p, 'B-2-6-week-sat-lit')
  pg = await weekTo(p, ctx, 6)
  const aw = await puckInfo(p, '#eWeek .day:nth-child(7)', 'dj')
  rec('2-6', aw.some(x => /hard/.test(x.cls)), `Edit Schedule week Sunday (page ${pg}): Ace puck classes ${JSON.stringify(aw.map(x => x.cls + ' | ' + x.title))}`)
  await scrollTo(p, p.locator('#eWeek .day:nth-child(7) [data-person="dj"].puck').first(), 220)
  await shot(p, 'B-2-7-week-sun-ace')
  // clear R by finger on Saturday's board
  await p.evaluate(() => window.openScheduler(5)); await p.waitForSelector(SEL); await wait(p, 800)
  await scrollTo(p, p.locator(`${SEL} [data-bfld="ff:5.0.0.rl"]`).first(), 250)
  await typeBox(p, p.locator(`${SEL} [data-bfld="ff:5.0.0.rl"]`), '')
  c = await chips(p, SEL)
  rec('2-7', c.length === 4 && c.every(x => x.tag === 'BUTTON'), `R cleared: rl="${await p.evaluate(() => window.DAYS[5].waves[0].formations[0].rl)}" ${c.length} chips ${c.map(x => x.txt + '/' + x.tag).join(',')}; pending "${await pending(p)}"`)
  await shot(p, 'B-2-8-board-cleared')
  await tapEl(p, p.locator('#sbNextDay:visible'), { label: 'next day' }); await wait(p, 900)
  const pk2 = await puckInfo(p, SEL, 'dj')
  rec('2-8', pk2.every(x => !/hard/.test(x.cls)), `Sunday after R cleared: Ace classes ${JSON.stringify(pk2.map(x => x.cls))}`)
  await shot(p, 'B-2-9-board-sun-clean')
  console.log('errors', JSON.stringify(errors))
} finally { await browser.close() }
