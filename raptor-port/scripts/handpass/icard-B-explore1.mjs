import * as L from './icard-B-lib.mjs'
const browser = await L.launch()
const { ctx, page: p } = await L.open(browser, { width: 1440, height: 900 })
await L.openDay(p, '2026-07-20', false)
await L.press(false, p.locator('#icPopAdd')); await p.locator(L.WIN).waitFor()
await L.shot(p, 'x1-new')
const dump = async (label) => {
  const t = await p.locator(L.WIN).evaluate(w => w.innerText)
  const ids = await p.locator(L.WIN).evaluate(w => [...w.querySelectorAll('[id],[data-testid]')].map(e => (e.id ? '#' + e.id : '') + (e.getAttribute('data-testid') ? '[tid=' + e.getAttribute('data-testid') + ']' : '') + ':' + e.tagName).join(' | '))
  console.log('-----', label, '\n', t.replace(/\n+/g, ' / ').slice(0, 1500), '\n', ids.slice(0, 2500))
}
await dump('new default')
const opts = await p.locator('#inpEditType option').evaluateAll(os => os.map(o => o.value + '=' + o.textContent))
console.log('TYPES', opts.join(' ; '))
await p.selectOption('#inpEditType', 'ATT C')
await dump('ATT C')
await L.shot(p, 'x1-attc')
await p.selectOption('#inpEditType', 'LL')
await dump('LL')
await L.shot(p, 'x1-ll')
const people = await p.locator('#inpEditPerson option').evaluateAll(os => os.map(o => o.value + '=' + o.textContent))
console.log('PEOPLE', people.join(' ; '))
console.log(L.errs)
await browser.close()
