// walker C, scenario 11 — bidding that ended by its date (desktop)
const CL = await import('./lw-m4-walk-c-lib.mjs')
const L = await CL.setup('c', 's11')
const H = CL.mk(L)
const { T, rec, shot, press, vis, txt } = L
console.log('[lw-m4-walk-c6 v3]')
L.clearOut()
const size = 'desk'
const w = await L.newCtx(size)
const P = w.page
const say = (...a) => console.log(...a)
const wait = ms => P.waitForTimeout(ms)
async function openDates() { await press(w, T('open-chip')); await P.waitForSelector(T('open-dates'), { state: 'visible' }); await wait(500) }
async function closeDates() { await press(w, T('open-dates-close')); await wait(400) }
try {
  await L.signIn(w, 'member')
  await L.openCell(w, 'bane', '2026-01-13'); await L.placeLeave(w, 'LL')
  await L.switchTo(w, 'admin')
  await openDates()
  /* the seed's Jan-Mar stretch closed first, so the only stretch is the one the walk opens */
  for (const k of ['2026-01', '2026-02', '2026-03']) { await press(w, T(`od-month-${k}`)); await wait(500) }
  say('   lines after closing Jan-Mar:', await txt(P, T('od-lines')))
  await press(w, T('od-more')); await wait(500)
  await press(w, T('od-new-day-2026-01-06')); await wait(300)
  await press(w, T('od-new-day-2026-01-09')); await wait(400)
  await shot(w, '11a-picked-range')
  say('   apply button:', await txt(P, T('od-apply')))
  await press(w, T('od-apply')); await wait(600)
  say('   lines:', await txt(P, T('od-lines')))
  await shot(w, '11b-opendates-after')
  await closeDates()
  /* the admin's bell now (before the dates end) */
  const adminBell0 = await H.bell(w); await shot(w, '11c-admin-bell-before'); await L.closeBell(w)
  say('   admin bell before the dates end:', adminBell0.map(l => l.text + ' [' + l.unread + ']').join(' | '))
  await L.switchTo(w, 'member')
  const b0 = await H.bell(w)
  await shot(w, '11d-ranger-bell-before')
  say('   ranger bell before the dates end:', b0.map(l => (l.unread ? '*' : '') + l.text).join(' | '))
  await L.closeBell(w)
  /* pin the war's today past the stretch (member's session; no switchTo afterwards: it would re-pin 5 Jan) */
  await P.evaluate(t => window.lwSetMemberToday(t), '2026-01-12')
  await wait(800)
  const todayRing = await P.evaluate(() => document.querySelector('[data-testid="head-2026-01-12"]')?.className || '')
  say('   head of 12 Jan class:', todayRing)
  const b1 = await H.bell(w)
  await shot(w, '11e-ranger-bell-after-pin')
  say('   ranger bell after pin:', b1.map(l => (l.unread ? '*' : '') + l.text).join(' | '))
  const fresh = H.bellDiff(b0, b1)
  const ended = b1.filter(l => /bidding closed/.test(l.text) && /dates ended/.test(l.text))
  rec('11 bell follows the pinned today -> "... bidding closed · its dates ended", no name', size,
    ended.length >= 1 && ended.every(l => !/Saber/.test(l.text)) ? 'PASS' : (b1.length === b0.length ? 'NOT WALKED' : 'FAIL'),
    `before ${b0.length} lines, after ${b1.length}; ended lines: ${ended.map(l => l.text).join(' | ')}; new: ${fresh.map(l => l.text).join(' | ')}`, ['11e-ranger-bell-after-pin'])
  await L.closeBell(w)
  /* (b) leave the Leave War and come back, today still pinned at 12 Jan */
  await P.evaluate(() => window.go('inputs')); await wait(600)
  await P.evaluate(() => window.go('leavewar')); await wait(900)
  const b2 = await H.bell(w); await shot(w, '11f-bell-after-return')
  say('   (b) after leaving and returning:', b2.map(l => (l.unread ? '*' : '') + l.text).join(' | '))
  await L.closeBell(w)
  /* (c) sign out, pin 12 Jan on the sign-in page, sign in as Ranger again, read his bell */
  await P.evaluate(() => { const b = document.querySelector('#logout'); if (b) b.click() })
  await P.waitForSelector('#luser', { timeout: 15000 })
  await P.evaluate(t => window.lwSetMemberToday && window.lwSetMemberToday(t), '2026-01-12')
  await P.fill('#luser', 'us'); await P.fill('#lpass', 'us')
  await P.click('#loginForm button[type=submit]')
  await P.waitForSelector('#vWeek .day', { state: 'attached' })
  await P.evaluate(t => window.lwSetMemberToday && window.lwSetMemberToday(t), '2026-01-12')
  await L.openWar(w, 'member')
  const b3 = await H.bell(w); await shot(w, '11g-bell-after-signin-at-12jan')
  say('   (c) signed in again with today pinned 12 Jan:', b3.map(l => (l.unread ? '*' : '') + l.text).join(' | '))
  const ended3 = b3.filter(l => /bidding closed/.test(l.text) && /dates ended/.test(l.text))
  rec('11c bell after signing in again with today at 12 Jan', size, ended3.length >= 1 && ended3.every(l => !/Saber/.test(l.text)) ? 'PASS' : 'FAIL', `ended lines: ${ended3.map(l => l.text).join(' | ')}; all: ${b3.map(l => l.text).join(' | ')}`, ['11g-bell-after-signin-at-12jan'])
  await L.closeBell(w)
  /* (d) no pin at all: a fresh page load, signed in as Ranger on the real clock (27 Oct 26, long after 9 Jan) */
  await P.evaluate(() => { const b = document.querySelector('#logout'); if (b) b.click() })
  await P.waitForSelector('#luser', { timeout: 15000 })
  await P.goto(L.PLAIN); await P.waitForSelector('#luser')
  await P.fill('#luser', 'us'); await P.fill('#lpass', 'us')
  await P.click('#loginForm button[type=submit]')
  await P.waitForSelector('#vWeek .day', { state: 'attached' })
  await L.openWar(w, 'member')
  const b4 = await H.bell(w); await shot(w, '11h-bell-no-pin')
  say('   (d) no pin, real clock:', b4.map(l => (l.unread ? '*' : '') + l.text).join(' | '))
  const chip = await txt(P, T('open-chip'))
  const ended4 = b4.filter(l => /bidding closed/.test(l.text) && /dates ended/.test(l.text))
  rec('11d bell on the real clock (no pin)', size, ended4.length >= 1 && ended4.every(l => !/Saber/.test(l.text)) ? 'PASS' : 'FAIL', `chip "${chip}"; ended lines: ${ended4.map(l => l.text).join(' | ')}; all: ${b4.map(l => l.text).join(' | ')}`, ['11h-bell-no-pin'])
  say('   the "6 Jan - 9 Jan open" line still there?', b1.some(l => /6 Jan.*9 Jan.*bidding open/.test(l.text)))
} catch (e) {
  rec('ERROR', size, 'FAIL', String(e).slice(0, 400))
  await shot(w, 'error').catch(() => {})
}
if (w.errs.length) rec('console', size, 'FAIL', w.errs.join(' || ').slice(0, 800))
L.writeResults('s11')
await w.ctx.close()
await L.closeBrowser()
console.log('DONE')
