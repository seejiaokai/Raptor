import { open, fileInput, toWeek, shot, saveRes, errs, browser, csId, toast, unavailRows, lwStagePublished, lwCells, calRead, leaveInputs, sleep } from './or-RW3-lib.mjs'
const R = {}
const { ctx, page } = await open('ad', 'a')
R.filed = await fileInput(page, { type: 'LL', people: ['Drifter', 'Hex', 'Hunter'], from: '2026-07-13', to: '2026-07-17' })
R.stage = await lwStagePublished(page)
const names = ['Drifter', 'Hex', 'Hunter']
const hex = await csId(page, 'Hex')
await page.evaluate(h => { window.raptorMe(h); window.raptorRole('member') }, hex); await sleep(700)
R.badge = await page.evaluate(() => (document.querySelector('header, .topbar')?.innerText || '').replace(/\s+/g, ' ').slice(0, 200))
await page.locator('[data-testid="month-JUL"]').click().catch(() => {}); await sleep(900)
const cell = page.locator(`[data-testid="cell-${hex}-2026-07-15"]`).first()
await cell.scrollIntoViewIfNeeded(); await cell.click(); await sleep(600)
R.sheetOpen = await page.locator('[data-testid="remarks-field"]').count()
R.fieldWas = await page.locator('[data-testid="remarks-field"]').inputValue()
R.fieldDisabled = await page.locator('[data-testid="remarks-field"]').isDisabled()
R.sheetText = await page.evaluate(() => (document.querySelector('[data-testid="remarks-field"]')?.closest('[data-testid]')?.parentElement?.innerText || '').replace(/\s+/g, ' ').slice(0, 300))
await shot(page, 'rw3-2-1-sheet-as-hex')
await page.locator('[data-testid="remarks-field"]').fill('Dental')
await shot(page, 'rw3-2-2-typed')
await page.locator('[data-testid="remarks-save"]').click(); await sleep(800)
R.toast = await toast(page)
R.sheetTextAfter = await page.evaluate(() => (document.querySelector('[data-testid="remarks-field"]')?.closest('[data-testid]')?.parentElement?.innerText || 'NO SHEET').replace(/\s+/g, ' ').slice(0, 300))
await shot(page, 'rw3-2-3-after-save')
R.inputs = await leaveInputs(page)
R.cells = await lwCells(page, names, 'rw3-2-4-war')
await page.evaluate(() => window.raptorRole('admin')); await sleep(300)
await toWeek(page)
R.unavailWed = await unavailRows(page, '#eWeek', 2)
await page.locator('#eWeek .day:not(.peek)').nth(2).locator('.sec-unav').scrollIntoViewIfNeeded()
await page.locator('#eWeek .day:not(.peek)').nth(2).locator('.sec-unav').screenshot({ path: 'docs/img/handpass/2026-10-12-one-rule/RW3/rw3-2-5-unav.png' })
R.calWed = await calRead(page, '2026-07-15', 'rw3-2-6-cal')
saveRes('RW3-2', R)
console.log(JSON.stringify({ ...R, calWed: R.calWed.cards, inputs: R.inputs.filter(r => /Hex|Drifter|Hunter/.test(r.people.join())) }, null, 1))
console.log('ERRS', errs.join('\n'))
await browser.close()
