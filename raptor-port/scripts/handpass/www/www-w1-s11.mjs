/* www W1 scenario 11 — the Logic row "A flight". usage: [PHONE=1] node scripts/handpass/www/www-w1-s11.mjs */
const PHONE = process.env.PHONE === '1'
process.env.WWW_RUN ||= 's11-' + (PHONE ? 'p' : 'd')
const H = await import('./www-w1-lib.mjs')
const { X, say, sleep, L, nrm } = H
const size = PHONE ? '402' : '1536'
const P = PHONE ? 'p' : 'd'
const w = await X.open({ phone: PHONE })
const { page } = w
const R = (did, exp, saw, v, pic) => X.row('11 Logic A flight', size, did, exp, saw, v, pic)
await L.go(page, 'logic'); await sleep(600)
// 1. found by the page: the row's group and order
const order = await page.evaluate(() => {
  const sets = [...document.querySelectorAll('.lgset')].filter(e => e.getBoundingClientRect().width > 0)
  const names = sets.map(e => e.querySelector('.lgnm')?.innerText.trim())
  const grp = e => { let p = e.closest('[class*="lgcard"], .lgcard, section, .card'); const h = p && p.querySelector('h2,h3,.lgh,.lgcardh,.ttl'); return h ? h.innerText.trim() : '' }
  const i = names.indexOf('A flight'), j = names.indexOf('A sim')
  return { i, j, grpFlight: grp(sets[i]), grpSim: grp(sets[j]), near: names.slice(Math.max(0, i - 2), j + 2) }
})
await X.pic(w, `11-1-page-${P}`)
R('opened Logic; read the group and order of "A flight" and "A sim"', 'A flight in "Rows with no end time", before "A sim"', JSON.stringify(order), order.i >= 0 && order.j === order.i + 1 && /no end time/i.test(order.grpFlight) ? 'PASS' : 'FAIL', `11-1-page-${P}.png`)
// search
await page.locator('#lgSearch:visible').first().fill('A flight'); await sleep(500)
const vis = await page.evaluate(() => [...document.querySelectorAll('.lgset')].filter(e => e.getBoundingClientRect().width > 0).map(e => e.querySelector('.lgnm')?.innerText.trim()))
await X.pic(w, `11-2-search-${P}`)
R('typed "A flight" in the Logic search', 'the row "A flight" is found', JSON.stringify(vis), vis.includes('A flight') ? 'PASS' : 'FAIL', `11-2-search-${P}.png`)
await page.locator('#lgSearch:visible').first().fill('landing'); await sleep(500)
const vis2 = await page.evaluate(() => [...document.querySelectorAll('.lgset')].filter(e => e.getBoundingClientRect().width > 0).map(e => e.querySelector('.lgnm')?.innerText.trim()))
await X.pic(w, `11-2b-search2-${P}`)
R('typed "landing" in the Logic search', 'RECORD which rows', JSON.stringify(vis2), 'RECORDED', `11-2b-search2-${P}.png`)
await page.locator('#lgSearch:visible').first().fill(''); await sleep(400)
// 2. 90 and leave
await H.logicOpen(w, true)
await X.pic(w, `11-3-edit-${P}`)
let v = await H.setSetting(w, 'fltLen', '90')
const s1 = await H.strip(w)
await X.pic(w, `11-4-90-${P}`)
R('Edit; typed 90 in "A flight"; left the box', 'box reads 1h30; the strip appears', `box: ${v}; strip: ${JSON.stringify(s1)}`, v === '1h30' && s1.length ? 'PASS' : 'FAIL', `11-4-90-${P}.png`)
const sentence = 'Published days keep their old settings until published again.'
R('read the strip note', `the strip's note is one sentence "${sentence}"`, JSON.stringify(s1.map(s => s.text)), s1.some(s => s.text.includes(sentence) && !/Clash/i.test(s.text)) ? 'PASS' : 'FAIL', `11-4-90-${P}.png`)
// 3. another value then Reset at once (no blur between)
const inp = page.locator('[data-lgset="fltLen"]:visible').first()
await inp.evaluate(e => e.scrollIntoView({ block: 'center' }))
if (PHONE) await inp.tap(); else await inp.click()
await inp.fill('45')
const rs = page.locator('[data-lgreset="fltLen"]:visible').first()
await X.pic(w, `11-5-45typed-${P}`)
await X.press(w, '[data-lgreset="fltLen"]', { after: `11-5b-reset-after-tap-${P}` })
await sleep(900)
v = await H.readSetting(w, 'fltLen')
await X.pic(w, `11-6-reset-${P}`)
const s2 = await H.strip(w)
R('typed 45 and pressed the row Reset at once (no leaving the box)', 'box back to 1h; no later save overwrites it', `box: ${v}; strip: ${JSON.stringify(s2.map(s => s.text))}`, v === '1h' ? 'PASS' : 'FAIL', `11-6-reset-${P}.png`)
await sleep(1500)
v = await H.readSetting(w, 'fltLen')
R('waited 1.5s after Reset', 'still 1h', v, v === '1h' ? 'PASS' : 'FAIL', `11-6-reset-${P}.png`)
// 4. bounds
for (const bad of ['10', '500']) {
  v = await H.setSetting(w, 'fltLen', bad)
  const toast = await page.evaluate(() => (document.getElementById('toastEl')?.textContent || '').trim())
  const note = await page.evaluate(() => [...document.querySelectorAll('.lgset[data-lgkey="fltLen"] *')].filter(e => e.getBoundingClientRect().width > 0 && e.children.length === 0).map(e => e.innerText.trim()).filter(Boolean))
  await X.pic(w, `11-7-bound-${bad}-${P}`)
  R(`typed ${bad} (outside 15-480 min); left the box`, 'refused: the box does not keep it; the bounds are explained', `box: ${v}; toast: ${toast}; row text: ${JSON.stringify(note)}`, ['1h', '8h', '15 min'].includes(v) || (v !== bad && v !== (bad === '10' ? '10 min' : '8h20')) ? 'PASS' : 'FAIL', `11-7-bound-${bad}-${P}.png`)
  // lesson 16: tap away, tap box afresh, type what it shows
  await page.locator('#lgSearch:visible').first().click().catch(() => {}); await sleep(300)
  const shown = await H.readSetting(w, 'fltLen')
  v = await H.setSetting(w, 'fltLen', shown)
  await X.pic(w, `11-8-afresh-${bad}-${P}`)
  R(`after the refusal of ${bad}: tapped away, tapped the box afresh, typed the figure it showed (${shown})`, 'accepted, box reads the same as it showed', `box: ${v}`, nrm(v) === nrm(shown) ? 'PASS' : 'FAIL', `11-8-afresh-${bad}-${P}.png`)
}
// 5. reload with 90 set
v = await H.setSetting(w, 'fltLen', '90')
await H.logicDone(w)
await sleep(400)
await page.reload(); await page.waitForSelector('#luser, #vWeek .day', { state: 'attached', timeout: 15000 })
if (await page.locator('#luser:visible').count()) await L.login(page, 'a')
await L.go(page, 'logic'); await sleep(600)
v = await H.readSetting(w, 'fltLen')
const s3 = await H.strip(w)
await X.pic(w, `11-9-reload-${P}`)
R('set 90, Done, reloaded the page, opened Logic', 'A flight still 1h30; the strip shown', `box: ${v}; strip: ${JSON.stringify(s3.map(s => s.text))}`, v === '1h30' && s3.length ? 'PASS' : 'FAIL', `11-9-reload-${P}.png`)
// 6. the strip: Reset removes it, set again shows it again; measure the page after each (lesson 17)
const m = () => page.evaluate(() => ({ sw: document.documentElement.scrollWidth, cw: document.documentElement.clientWidth, sh: document.documentElement.scrollHeight }))
const m1 = await m()
await H.logicOpen(w, true)
await X.press(w, '#lgReset', { after: `11-10-resetall-after-tap-${P}` }); await sleep(600)
const q = page.getByRole('button', { name: /^(Reset|Yes|Confirm|OK)/ }).filter({ hasText: /Reset|Yes|Confirm|OK/ })
const s4 = await H.strip(w); const m2 = await m()
await X.pic(w, `11-10-resetall-${P}`)
R('pressed "Reset to standard"', 'strip gone, A flight back to 1h', `strip: ${JSON.stringify(s4.map(s => s.text))}; box: ${await H.readSetting(w, 'fltLen')}; page ${JSON.stringify(m1)} -> ${JSON.stringify(m2)}`, s4.length === 0 && (await H.readSetting(w, 'fltLen')) === '1h' ? 'PASS' : 'FAIL', `11-10-resetall-${P}.png`)
await H.setSetting(w, 'fltLen', '75')
const s5 = await H.strip(w); const m3 = await m()
await X.pic(w, `11-11-again-${P}`)
R('typed 75 after the Reset; strip shown again', 'strip back, page not wider than the screen', `strip: ${JSON.stringify(s5.map(s => s.text))}; page ${JSON.stringify(m3)}`, s5.length && m3.sw <= m3.cw ? 'PASS' : 'FAIL', `11-11-again-${P}.png`)
await H.setSetting(w, 'fltLen', '1h')
await H.logicDone(w)
// 7. one-row heights (lesson 23b): the Logic row's side-by-side boxes
const hts = await page.evaluate(() => [...document.querySelectorAll('.lgset[data-lgkey="fltLen"], .lgset[data-lgkey="simLen"]')].map(e => ({ k: e.dataset.lgkey, h: Math.round(e.getBoundingClientRect().height), vh: Math.round((e.querySelector('.lgv') || e).getBoundingClientRect().height) })))
R('measured the row boxes "A flight" and the next row', 'RECORD', JSON.stringify(hts), 'RECORDED', `11-11-again-${P}.png`)
// 8. as Ranger (member) read only — desktop and phone
await w.browser.close()
const w2 = await X.open({ phone: PHONE, who: 'u' })
await L.go(w2.page, 'logic').catch(e => say('go logic failed', e.message)); await sleep(700)
const hasEdit = await w2.page.locator('#lgEdit:visible').count()
const inputs = await w2.page.locator('[data-lgset]:visible').count()
const val = nrm(await w2.page.locator('[data-lgkey="fltLen"] .val').first().innerText().catch(() => 'NOT SHOWN'))
await w2.page.screenshot({ path: `${X.SHOTS}/11-12-member-${P}.png` })
X.row('11 Logic A flight', size, 'signed in as Ranger; opened Logic; looked for Edit and boxes; A flight row', 'readable, no Edit, no editable box', `Edit buttons: ${hasEdit}; boxes: ${inputs}; A flight reads: ${val}`, hasEdit === 0 && inputs === 0 && val ? 'PASS' : 'FAIL', `11-12-member-${P}.png`)
const strip2 = await H.strip(w2)
X.row('11 Logic A flight', size, 'Ranger: the strip', 'RECORD', JSON.stringify(strip2.map(s => s.text)), 'RECORDED', `11-12-member-${P}.png`)
await X.fin(w2)
