/* www W2 extras: (a) AVALON START 20:00 no END + next-day item, (c) SC wave line made to fly with no END, (d) Sunday "Breaks Monday" trace, (b) day details from a 👁.
   usage (from raptor-port/): [PHONE=1] node scripts/handpass/www/www-w2-s13.mjs */
const PHONE = process.env.PHONE === '1'
process.env.WWW_RUN ||= 's13-' + (PHONE ? 'p' : 'd')
const H = await import('./www-w2-lib2.mjs')
const { X, say, sleep, L } = H
const P = PHONE ? 'p' : 'd', size = PHONE ? '402' : '1536'
const R = (did, exp, saw, v, pic) => X.row('extras a-d', size, did, exp, saw, v, pic)
say('www-w2-s13 v1', size)
const w = await X.open({ phone: PHONE })
const { page } = w
const FRI = X.FRI, SAT = X.SAT, SUN = X.SUN, MON = X.MON
const key = cs => page.evaluate(c => Object.keys(window.PEOPLE).find(k => window.PEOPLE[k].cs === c), cs)
const torch = await key('Torch'), comet = await key('Comet'), havoc = await key('Havoc'), diesel = await key('Diesel')
// (a) AVALON line, START 20:00 END blank, Torch; Saturday ground item 06:00
await X.board(w, FRI)
const aw = await X.addWave(w, FRI, 'avalon')
const al = await page.evaluate(([i, g]) => window.DAYS[i].waves[g].formations.map((f, k) => ({ k, cs: f.cs, shift: f.shift })), [FRI, aw])
say('AVALON lines', JSON.stringify(al))
await H.setF(w, `ff:${FRI}.${aw}.0.to`, '20:00')
say('seat', await X.seat(w, `[data-slot="${FRI}.${aw}.0.0.p"]`, torch))
const fa = await H.bwf(w, /Torch/)
await X.pic(w, `13-a1-avalon-fri-${P}`)
R('(a) AVALON line START 20:00, END blank, Torch: Friday warnings', 'its own missing-END warning (RECORD)', JSON.stringify(fa), 'RECORDED', `13-a1-avalon-fri-${P}.png`)
await X.closeBoard(w)
await X.board(w, SAT)
await H.gRow(w, SAT, 'EARLY GROUND', '06:00', '07:00', torch)
const sa = await H.bwf(w, /Torch/)
await X.pic(w, `13-a2-avalon-sat-${P}`)
R('(a) Saturday ground item 06:00 for Torch', 'no crew-rest line from the END-less AVALON; RECORD', JSON.stringify(sa), 'RECORDED', `13-a2-avalon-sat-${P}.png`)
await X.closeBoard(w)
// (c) SC line made to fly (B typed), no END, Comet; START 20:00
await X.board(w, FRI)
const sw = await X.addWave(w, FRI, 'sc')
await H.setF(w, `ff:${FRI}.${sw}.0.to`, '20:00')
await H.setF(w, `ff:${FRI}.${sw}.0.br`, '19:00')
say('seat', await X.seat(w, `[data-slot="${FRI}.${sw}.0.0.p"]`, comet))
const fc = await H.bwf(w, /Comet/)
await X.pic(w, `13-c-sc-flying-${P}`)
R('(c) Friday SC line START 20:00 with B 19:00 typed (made to fly), END blank, Comet', 'its own warning that the END is missing (RECORD)', JSON.stringify(fc), 'RECORDED', `13-c-sc-flying-${P}.png`)
await X.closeBoard(w)
await X.board(w, SAT)
await H.frFlight(w, SAT, '04:00', '', comet, 'COMET SAT')
const sc2 = await H.bwf(w, /Comet/)
await X.pic(w, `13-c2-sc-sat-${P}`)
R('(c) Saturday flight 04:00 for Comet after the END-less flying SC line', 'no crew-rest line caused by the SC line (RECORD)', JSON.stringify(sc2), 'RECORDED', `13-c2-sc-sat-${P}.png`)
await X.closeBoard(w)
// (d) Sunday 23:30 flight Havoc, landing blank; Monday flight T/O 16:00
await X.board(w, SUN)
await H.frFlight(w, SUN, '23:30', '', havoc, 'HAV SUN')
await X.closeBoard(w)
await X.board(w, MON)
await H.frFlight(w, MON, '16:00', '', havoc, 'HAV MON')
const md = await H.bwf(w, /Havoc/)
await X.pic(w, `13-d1-monday-${P}`)
R('(d) Monday flight T/O 16:00 for Havoc after a Sunday 23:30 flight, landing blank', 'a crew-rest line saying "landing assumed 00:30 (T/O + 1h)"', JSON.stringify(md), md.some(l => /assumed/.test(l)) ? 'PASS' : 'RECORDED', `13-d1-monday-${P}.png`)
await X.closeBoard(w)
const tr = await X.trace(w, '#eWeek', SUN, havoc)
await X.pic(w, `13-d2-sunday-trace-${P}`)
R('(d) Sunday: tapped Havoc\'s puck', 'the forward "Breaks Monday" trace row (RECORD whole)', JSON.stringify(tr), tr.items.some(l => /Breaks Monday|Crew rest/.test(l)) ? 'PASS' : 'RECORDED', `13-d2-sunday-trace-${P}.png`)
const sw2 = await X.weekWarn(w, '#eWeek', SUN)
R('(d) Sunday week strip', 'RECORD the "Breaks Monday" row', JSON.stringify(sw2.items.filter(l => /Havoc/.test(l))) + ' head ' + sw2.head, sw2.items.some(l => /Breaks Monday/.test(l)) ? 'PASS' : 'RECORDED', '')
// (b) publish Friday, then find the 👁 controls and open day details
await X.board(w, FRI)
const pub = await H.signAndPublish(w, FRI)
say('PUBLISH', JSON.stringify(pub))
await X.closeBoard(w)
const eyes = await page.evaluate(() => [...document.querySelectorAll('#eWeek [class*=eye], #eWeek [data-vwver], #eWeek [data-eye], #eWeek [title*="ook" i]')].filter(e => e.getBoundingClientRect().width).map(e => e.tagName + '|' + String(e.className).slice(0, 30) + '|' + Object.keys(e.dataset).join(',') + '|' + (e.title || '').slice(0, 50)).slice(0, 10))
say('EYES', JSON.stringify(eyes))
await X.pic(w, `13-b1-after-publish-${P}`)
R('(b) published Friday: the 👁 controls on the week', 'RECORD the controls found', JSON.stringify(pub) + ' | ' + JSON.stringify(eyes), eyes.length ? 'RECORDED' : 'NOT WALKED', `13-b1-after-publish-${P}.png`)
await X.fin(w)
