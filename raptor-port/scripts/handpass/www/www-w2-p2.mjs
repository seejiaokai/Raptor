/* www w2 probe 2: Friday flight 12:00, a 13:10-13:20 ground item; roster with/without seat armed; ALL AVAIL placeholder seated. */
const PHONE = process.env.PHONE === '1'
process.env.WWW_WHO = 'w2'
process.env.WWW_RUN ||= 'p2-' + (PHONE ? 'p' : 'd')
const X = await import('./www-lib.mjs')
const { say, sleep, FRI } = X
say('www-w2-p2 v1')
const w = await X.open({ phone: PHONE })
const { page, P } = w
await X.board(w, FRI)
const wi = await X.addWave(w, FRI, '')
await X.typeIn(w, `[data-bfld="ff:${FRI}.${wi}.0.to"]`, '12:00')
await X.typeIn(w, `[data-bfld="ff:${FRI}.${wi}.0.msn"]`, 'VL BFM')
const g0 = await page.evaluate(d => window.DAYS[d].ground.length, FRI)
await X.press(w, `[data-gradd="${FRI}"]`, { scope: 'board' }); await sleep(400)
await X.typeIn(w, `[data-bfld="gr:${FRI}.${g0}.prog"]`, 'BRIEFING')
await X.typeIn(w, `[data-bfld="gr:${FRI}.${g0}.str"]`, '13:10')
await X.typeIn(w, `[data-bfld="gr:${FRI}.${g0}.end"]`, '13:20')
await X.ensureRoster(w)
const rosterHead = () => page.evaluate(() => [...document.querySelectorAll('#sbRoster .ap-grp, #sbRoster [class*=grp]')].map(e => e.innerText.replace(/\s+/g, ' ').slice(0, 60)).slice(0, 12))
say('ROSTER-HEADS no seat', JSON.stringify(await rosterHead()))
const rangerRow = () => page.evaluate(() => { const e = document.querySelector('#sbRoster .rpuck[data-person="bane"]'); return e ? e.outerHTML.slice(0, 400) : 'none' })
say('RANGER no seat', await rangerRow())
// arm the ground seat
await X.press(w, `[data-fill="g:${FRI}.${g0}.+"]`, { scope: 'board' }); await sleep(400)
say('ARMED', await page.evaluate(() => window.ARM && window.ARM.key))
say('ROSTER-HEADS seat armed', JSON.stringify(await rosterHead()))
say('RANGER armed', await rangerRow())
await X.pic(w, `p2-armed-${P}`)
await page.keyboard.press('Escape'); await page.evaluate(() => document.querySelector('#schedBoard [data-disarm]')?.click())
// seat ALL AVAIL on the flight p seat
say('seat ALL AVAIL', await X.seat(w, `[data-fill="g:${FRI}.${g0}.+"]`, 'allavail'))
await X.pic(w, `p2-seated-${P}`)
const pk = page.locator('#schedBoard .gr-people .puck.allavail:visible, #schedBoard [data-slot^="g:"] .puck.allavail:visible, #schedBoard tr .puck.allavail:visible').first()
await pk.evaluate(e => e.scrollIntoView({ block: 'center' })); await sleep(200)
if (PHONE) await pk.tap(); else await pk.click()
await sleep(800)
await X.pic(w, `p2-tapped-${P}`)
const win = await page.evaluate(() => [...document.querySelectorAll('[class*=avail], [id*=vail], [role=dialog]')].filter(e => e.getBoundingClientRect().width > 100).map(e => e.tagName + '#' + e.id + '.' + String(e.className).slice(0, 40) + ' :: ' + e.innerText.replace(/\s+/g, ' ').slice(0, 300)).slice(0, 8))
say('WIN', JSON.stringify(win))
say('PUCKHTML', await page.evaluate(() => { const e = document.querySelector('#schedBoard [data-fill^="g:4."] .puck.allavail, #schedBoard .puck.allavail:not(.sm)'); return e ? e.parentElement.outerHTML.slice(0, 900) : 'none' }))
const btns = await page.evaluate(() => [...document.querySelectorAll('#schedBoard .puck')].filter(e => e.getBoundingClientRect().width).map(e => e.innerText.replace(/\s+/g, ' ') + '|' + e.closest('[data-slot]')?.dataset.slot).slice(0, 10))
say('BOARD PUCKS', JSON.stringify(btns))
await X.fin(w)
