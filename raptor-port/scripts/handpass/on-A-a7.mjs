import { world, fileIt, openWeekDay, drag, rosterPuck, frameGrnd, rowFill, rowPeople, toast, toastsAll, undoState, oilOf, SAT, SAT_DI } from './on-A-lib.mjs'
const W = await world({ tag: 'A7' })
const { page, tid, press, shot, errors } = W
const iid = await fileIt(W, SAT, { type: 'Training', people: ['bane'], from: '09:00', to: '12:00', title: 'Range brief', oil: 'no' })
console.log('filed', iid, 'asked', W.lastAsked, 'oil', await oilOf(page, iid))
await openWeekDay(W, SAT_DI)
const fill = await rowFill(page, SAT_DI, 'Range brief')
console.log('fill', fill, 'row', await rowPeople(page, SAT_DI, fill))
const tally = await rosterPuck(page, 'nick')
await frameGrnd(page, SAT_DI); await page.waitForTimeout(300)
const tb = await tally.boundingBox(); console.log('tally box', JSON.stringify(tb))
const undo0 = await undoState(page)
await drag(page, tally, page.locator('#eWeek .day:not(.peek)').nth(SAT_DI).locator(`[data-fill="${fill}"] .addz`))
console.log('question', await tid('oilconf').count(), 'bar', await tid('oilbar').count())
console.log('toast', await toast(page), '| toasts', JSON.stringify((await toastsAll(page)).slice(-3)))
console.log('row after', await rowPeople(page, SAT_DI, fill), 'oil', await oilOf(page, iid), 'undo changed', (await undoState(page)) !== undo0)
await shot('A7-1-added-after-no')
console.log('errors', JSON.stringify(errors))
await W.ctx.close(); process.exit(0)
