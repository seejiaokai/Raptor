// Walker C, C2 - the crowd's switches end with the puck (desktop 1440x900).
import * as L from './or-C-lib.mjs'
const { browser, page: p, errs } = await L.openWorld()
const DI = 5, ISO = '2026-07-18'
const j = o => JSON.stringify(o)
const duty = (await L.fileInput(p, { type: 'Duty', person: 'Ranger', from: ISO, to: ISO, timed: ['09:00', '12:00'], oil: 'yes' }))[0]
console.log('filed', j(duty))
const day = () => p.locator('#eWeek .day:not(.peek)').nth(DI)
async function view() { await L.goEdit(p); await day().locator('.sec-grnd').first().scrollIntoViewIfNeeded(); await p.evaluate(() => window.scrollBy(0, 150)); await p.waitForTimeout(300) }
const addz = () => day().locator(`[data-fill="g:${DI}.0.+"] .addz`).first()
const aaPuck = () => day().locator(`[data-fill="g:${DI}.0.+"] [data-person="allavail"]`).first()
const roster = id => p.locator(`#eRoster .rpuck[data-person="${id}"]:visible`).first()
const rowNow = async () => j(await L.rowData(p, DI, duty.iid))
const inputNow = async () => j((await L.rec(p, duty.iid)).people)
async function empty() { const h = await day().getByText('GROUND PROGRAMME').first().boundingBox(); return { x: h.x + h.width + 120, y: h.y + 4 } }

await view()
let m = await L.toastMark(p)
await L.drag(p, roster('allavail'), addz())
console.log('fixture:', await L.toastsSince(p, m), await inputNow())

// the crowd, in OIL Earn on Saturday
await L.oilOn(p, DI, true)
const key = `i:${duty.iid}`
const chipNow = () => p.evaluate(k => { const c = document.querySelector(`#schedBoard [data-oilsent="${k}"]`); return c ? c.textContent.trim() + ' | ' + (c.getAttribute('title') || '') : null }, key)
console.log('chip at start:', await chipNow())
await L.openCrowd(p, key)
const c0 = await L.crowd(p)
console.log('crowd tabs', j(c0.tabs), 'foot', c0.foot, 'rows', c0.rows.length)
const hasRanger = c0.rows.some(r => r.cs === 'Ranger'), hasTally = c0.rows.some(r => r.cs === 'Tally')
console.log('Ranger in crowd?', hasRanger, 'Tally in crowd?', hasTally)
await L.crowdTab(p, /earns OIL/i)
const c1 = await L.crowd(p)
const pick = c1.rows.filter(r => r.cs !== 'Ranger').slice(0, 3)
console.log('first crowd rows', j(pick))
const off = [pick[0], pick[1]]
for (const o of off) { await L.crowdToggle(p, o.id); console.log('switched off', o.cs, '| foot:', (await L.crowd(p)).foot, '| toast:', await L.toastNow(p)) }
const c2 = await L.crowd(p)
console.log('tabs after', j(c2.tabs)); console.log('HTML off:', await p.evaluate(id => document.querySelector('.availwin [data-awp="' + id + '"]').outerHTML.slice(0, 400), off[0].id), ' HTML on:', await p.evaluate(id => document.querySelector('.availwin [data-awp="' + id + '"]').outerHTML.slice(0, 400), pick[2].id))
console.log('row states after', j(c2.rows.filter(r => off.some(o => o.id === r.id)).map(r => ({ cs: r.cs, cls: r.cls }))), 'a control row', j(c2.rows.find(r => r.id === pick[2].id)))
await L.shot(p, 'c2-1-two-off')
await L.crowdClose(p)
console.log('chip after two off:', await chipNow())
await L.oilOn(p, DI, false)

// drag ALL AVAIL off to empty space (on the week), then drop it back
await view()
m = await L.toastMark(p)
await L.drag(p, aaPuck(), await empty())
console.log('ALL AVAIL dragged off:', await L.toastsSince(p, m), '| input:', await inputNow())
await L.shot(p, 'c2-2-off-row')
m = await L.toastMark(p)
await L.drag(p, roster('allavail'), addz())
console.log('ALL AVAIL dropped back:', await L.toastsSince(p, m), '| input:', await inputNow(), '| row:', await rowNow())
await L.oilOn(p, DI, true)
console.log('chip after drop back:', await chipNow())
await L.openCrowd(p, key)
await L.crowdTab(p, /earns OIL/i)
const c3 = await L.crowd(p)
console.log('tabs', j(c3.tabs), 'the two men now:', j(c3.rows.filter(r => off.some(o => o.id === r.id)).map(r => ({ cs: r.cs, cls: r.cls }))))
await L.shot(p, 'c2-3-dropped-back')
await L.crowdClose(p)
await L.oilOn(p, DI, false)

// Tally in, one man off, Ranger dragged off
await view()
m = await L.toastMark(p)
await L.drag(p, roster(await L.csId(p, 'Tally')), addz())
console.log('Tally added:', await L.toastsSince(p, m), '| input:', await inputNow())
await L.oilOn(p, DI, true)
await L.openCrowd(p, key); await L.crowdTab(p, /earns OIL/i)
const c4a = await L.crowd(p)
const one = c4a.rows.find(r => r.id === off[0].id)
await L.crowdToggle(p, one.id)
const c4 = await L.crowd(p)
console.log('switched off one:', one.cs, '| row now', j(c4.rows.find(r => r.id === one.id)), '| tabs', j(c4.tabs), '| Ranger/Tally in crowd:', c4.rows.some(r => r.cs === 'Ranger'), c4.rows.some(r => r.cs === 'Tally'))
await L.shot(p, 'c2-4-one-off-tally-in')
await L.crowdClose(p)
await L.oilOn(p, DI, false)
await view()
const rangerPuck = day().locator(`[data-fill="g:${DI}.0.+"] [data-person="bane"]`).first()
m = await L.toastMark(p)
await L.drag(p, rangerPuck, await empty())
console.log('Ranger dragged off:', await L.toastsSince(p, m), '| input:', await inputNow())
await L.oilOn(p, DI, true)
await L.openCrowd(p, key); await L.crowdTab(p, /earns OIL/i)
const c5 = await L.crowd(p)
console.log('after Ranger left: man', one.cs, 'row', j(c5.rows.find(r => r.id === one.id)), '| tabs', j(c5.tabs), '| Ranger now in crowd:', c5.rows.some(r => r.cs === 'Ranger'), '| the other man', j(c5.rows.find(r => r.id === off[1].id)))
await L.shot(p, 'c2-5-after-ranger-off')
console.log('ERRORS', errs.join(' | ') || 'none')
await browser.close()
