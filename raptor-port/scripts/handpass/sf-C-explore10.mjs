import { launch, ctxOpen, openBoard, closeBoard, bPut, bType, bf, bPublish, sleep, shot, warns, errors, go } from './sf-C-lib.mjs'
const b = await launch()
const { p } = await ctxOpen(b, {})
await go(p, 'editsched')
await p.evaluate(() => { window.addWave(5, 'avalon') }); await sleep(500)
await openBoard(p, 5)
for (const [gi, li, ai, pid] of [[0,0,0,'stiff'],[0,0,1,'bane'],[0,0,2,'slipway'],[0,0,3,'dj']]) await bPut(p, 5, gi, li, ai, 'p', [pid])
await bPublish(p, 5)
await bType(p, bf(5, 0, 0, 'rl'), '18:30')
const bt = await p.evaluate(() => [...document.querySelectorAll('#schedBoard button, #schedBoard [data-chgday], #schedBoard [data-histbtn]')].filter(e => e.offsetParent && /pend|change|AL1|history/i.test(e.innerText + ' ' + e.title + ' ' + Object.keys(e.dataset))).map(e => e.tagName + '|' + e.className + '|' + JSON.stringify(e.dataset) + '|' + e.innerText.trim().slice(0, 30) + '|' + e.title.slice(0, 60)))
console.log(bt.join('\n'))
await shot(p, 'explore10')
console.log(errors)
await b.close()
