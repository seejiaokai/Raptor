// RX1-4 — a drop that REPLACES (crew list onto Ranger's puck) and one that SWAPS (a man from a flying seat)
import { launch, openWorld, fileX, shotX, rowIdx, inputOf, errs, toWeek, openBoard, centre, weekRowEl, weekRowNames, boardRowEl, boardRowNames, weekLines, boardLines, inputsSurf, closeDayWin, listRow, log, drag2, drag3, rosterPuckOf, toastMark, toastsSince, toastNow, waitQuiet, undoTitle, undoRedo } from './or-RX1-lib.mjs'
const browser = await launch()
const { page: p } = await openWorld(browser, { fresh: false })
const DI = 2
const f = await fileX(p, { type: 'Personal', person: 'Ranger', from: '2026-07-15', to: '2026-07-15', timed: ['17:00', '18:00'] })
const iid = f.made[0].iid
log('filed', f.made, 'oil', f.oilSeen)
const ri = await rowIdx(p, DI, iid)
const inp = async () => { const r = await inputOf(p, iid); return { people: r.people, by: r.raw } }
const seat = () => p.evaluate(() => { const a = window.DAYS[2].waves[0].formations[1].aircraft[0]; const c = id => (window.PEOPLE[id] || {}).cs || id || null; return { p: c(a.p), w: c(a.w) } })
/* (a) Tally from the crew list onto Ranger's puck (board) */
await openBoard(p, DI)
let row = boardRowEl(p, DI, ri); await centre(row); await p.waitForTimeout(300); await waitQuiet(p)
await shotX(p, 'rx1-4-1-board-before')
let m = await toastMark(p)
await drag2(p, await rosterPuckOf(p, '#sbRoster', 'Tally'), row.locator('.puck').first())
log('a toasts', await toastsSince(p, m), '| now', await toastNow(p), '| oilq', await p.locator('[data-testid="oilconf"]').count())
log('a people', (await inputOf(p, iid)).people, 'board row', (await boardRowNames(p, DI, ri)).names, 'lines', await boardLines(p, DI))
await shotX(p, 'rx1-4-2-board-tally-instead')
const sf = await inputsSurf(p, iid, '2026-07-15'); log('a card', sf); await shotX(p, 'rx1-4-3-card-tally')
await closeDayWin(p)
log('a list', await listRow(p, iid))
await openBoard(p, DI)
log('undo title', await undoTitle(p))
const u1 = await undoRedo(p, 'undo'); log('a undo', u1, 'toast', await toastNow(p), '| people', (await inputOf(p, iid)).people, 'board row', (await boardRowNames(p, DI, ri)).names)
row = boardRowEl(p, DI, ri); await centre(row); await p.waitForTimeout(200)
await shotX(p, 'rx1-4-4-board-after-undo')
/* (b) a man from a flying seat onto Ranger's puck (week) */
await waitQuiet(p)
await toWeek(p)
const seatEl = p.locator('#eWeek .day:not(.peek) [data-slot="2.0.1.0.p"]').first()
const seatBefore = await seat(); log('b seat before', seatBefore)
const wrow = weekRowEl(p, DI, ri); await centre(wrow); await p.waitForTimeout(300)
await shotX(p, 'rx1-4-5-week-before-swap')
m = await toastMark(p)
await drag3(p, seatEl.locator('.puck').first(), weekRowEl(p, DI, ri).locator('.puck').first())
log('b toasts', await toastsSince(p, m), '| now', await toastNow(p), '| oilq', await p.locator('[data-testid="oilconf"]').count())
log('b people', (await inputOf(p, iid)).people, 'seat after', await seat(), 'week row', (await weekRowNames(p, DI, ri)).names, 'lines', await weekLines(p, DI))
await centre(weekRowEl(p, DI, ri)); await p.waitForTimeout(200); await shotX(p, 'rx1-4-6-week-row-after-swap')
await seatEl.evaluate(e => e.scrollIntoView({ block: 'center' })); await p.waitForTimeout(200); await shotX(p, 'rx1-4-7-seat-after-swap')
const sf2 = await inputsSurf(p, iid, '2026-07-15'); log('b card', sf2); await shotX(p, 'rx1-4-8-card-after-swap')
await closeDayWin(p)
await toWeek(p)
const u2 = await undoRedo(p, 'undo'); log('b undo', u2, 'toast', await toastNow(p), '| people', (await inputOf(p, iid)).people, 'seat', await seat(), 'week row', (await weekRowNames(p, DI, ri)).names)
await centre(weekRowEl(p, DI, ri)); await p.waitForTimeout(200); await shotX(p, 'rx1-4-9-after-undo')
/* any "one person's own" anywhere on the page text? */
log('page has "one person" phrase', await p.evaluate(() => /one person.s own/i.test(document.body.innerText)))
log('errs', errs)
await browser.close()
