// walker C, scenarios 6, 7, 8 — never twice (the Inputs page remark), Approvals is no Undo step, Redo on Approvals (desktop)
const CL = await import('./lw-m4-walk-c-lib.mjs')
const L = await CL.setup('c', 's678')
const H = CL.mk(L)
const { T, rec, shot, press, vis, txt } = L
console.log('[lw-m4-walk-c4 v3]')
L.clearOut()
const size = 'desk'
const w = await L.newCtx(size)
const P = w.page
let before = []
const say = (...a) => console.log(...a)
const wait = ms => P.waitForTimeout(ms)
async function memberBell(id, label) {
  await L.switchTo(w, 'member')
  const after = await H.bell(w)
  const fresh = H.bellDiff(before, after)
  await shot(w, `${id}-bell`)
  say(`   bell after ${label}: all=${after.length} new=${fresh.length}`, fresh.map(l => `${l.unread ? '*' : ''}${l.text}`).join(' | '))
  before = after
  return { fresh, after }
}
const state = async who => (await L.apprLines(P)).filter(l => l.who === 'bane').map(l => `${l.text.match(/(Mon|Tue|Wed|Thu|Fri) \d+ \w+/)?.[0]}:${l.lit || (/Already approved/.test(l.text) ? 'approved-elsewhere(' + (l.text.match(/Already approved by \w+/)?.[0]) + ')' : 'pending')}`).join(' ; ')
const disabled = id => P.locator(id).first().evaluate(e => e.disabled || e.getAttribute('aria-disabled') === 'true')
try {
  await L.signIn(w, 'member')
  await H.bid(w, '2026-01-07')
  await H.bid(w, '2026-01-09')
  await H.bid(w, '2026-01-13')
  before = await H.bell(w); await L.closeBell(w)

  /* ---- 6: never twice ---- */
  await L.switchTo(w, 'admin')
  await L.openApprovals(w)
  await H.pressLoc(w, H.lineBtn(w, '7 Jan', 'appr-approve')); await wait(500)
  let r = await memberBell('6a', 'approval of 7 Jan')
  rec('6a an approval tells once: exactly one line, no "You were added" Inputs line beside it', size, r.fresh.length === 1 && /Your leave.*7 Jan.*LL approved.*Saber/.test(r.fresh[0].text) && !r.after.some(l => /added/i.test(l.text) && !/added and approved/.test(l.text)) ? 'PASS' : 'FAIL', `${r.fresh.length} new: ` + r.fresh.map(l => l.text).join(' | ') + ` ;; all: ` + r.after.map(l => l.text).join(' | '), ['6a-bell'])
  await L.closeBell(w)
  /* the remark changed on the Inputs page by Saber */
  await L.switchTo(w, 'admin')
  await P.evaluate(() => window.go('inputs')); await wait(900)
  await P.getByRole('button', { name: 'List' }).first().click(); await wait(600)
  await P.click('#inRangeBtn'); await wait(400)
  await P.getByText('All dates', { exact: true }).first().click(); await wait(700)
  await P.selectOption('#inFPerson', { label: 'Ranger' }); await wait(600)
  await shot(w, '6b-inputs-list')
  const row = P.locator('#intbl tr').filter({ hasText: '7 Jan' }).first()
  say('   Inputs row for 7 Jan found:', await row.count())
  await row.click(); await wait(700)
  await shot(w, '6b-input-window')
  await P.locator('#inpEditRmk').click(); await P.keyboard.type('bring the form'); await wait(300)
  await P.locator('#inpEditSave').click(); await wait(800)
  await shot(w, '6b-after-save')
  r = await memberBell('6b', 'remark changed on the Inputs page')
  rec('6b Saber changes the remark on the Inputs page -> Ranger told once, "Remark changed"', size, r.fresh.length === 1 && /Remark changed/.test(r.fresh[0].text) ? 'PASS' : 'FAIL', `${r.fresh.length} new: ` + r.fresh.map(l => l.text).join(' | '), ['6b-input-window', '6b-after-save', '6b-bell'])
  await L.closeBell(w)

  /* ---- 7 and 8: Approvals is no Undo step; Redo on Approvals ---- */
  await L.switchTo(w, 'admin')
  await L.openApprovals(w)
  say('   lines at start:', await state(w))
  const count0 = await L.tabCount(P)
  await H.pressLoc(w, H.lineBtn(w, '9 Jan', 'appr-approve')); await wait(500)
  say('   after Approve 9 Jan:', await state(w), '| count', await L.tabCount(P))
  await shot(w, '7a-approved')
  const undoTitle = await P.locator('#undoBtn').getAttribute('title')
  await L.undo(w)
  say('   after Undo:', await state(w), '| count', await L.tabCount(P), '| undo title', undoTitle, '| redo disabled', await disabled('#redoBtn'))
  await shot(w, '7b-after-undo')
  const afterUndo = await state(w)
  /* 8: Redo straight away */
  await L.redo(w)
  const afterRedo = await state(w)
  say('   after Redo:', afterRedo, '| count', await L.tabCount(P))
  await shot(w, '8a-after-redo')
  const redoLit = /9 Jan:approved/.test(afterRedo)
  /* a second tap on the lit Approve sends it back */
  await H.pressLoc(w, H.lineBtn(w, '9 Jan', 'appr-approve')); await wait(500)
  const afterSecond = await state(w)
  say('   after the second tap:', afterSecond)
  await shot(w, '8b-second-tap')
  rec('8 Approve, Undo, Redo -> lit "Approved" again; a second tap sends it back', size, /9 Jan:pending/.test(afterUndo) && redoLit && /9 Jan:pending/.test(afterSecond) ? 'PASS' : 'FAIL', `after Undo "${afterUndo}"; after Redo "${afterRedo}"; after second tap "${afterSecond}"`, ['7b-after-undo', '8a-after-redo', '8b-second-tap'])
  /* 7: Approve, Undo, leave Approvals, open it again, Redo */
  await H.pressLoc(w, H.lineBtn(w, '13 Jan', 'appr-approve')); await wait(500)
  const s1 = await state(w)
  await L.undo(w)
  const s2 = await state(w)
  await L.openGrid(w); await wait(600)
  await shot(w, '7c-grid-after-undo')
  await L.openApprovals(w); await wait(500)
  const s3 = await state(w)
  const redoDisabled = await disabled('#redoBtn')
  await shot(w, '7d-approvals-reopened')
  await L.redo(w)
  const s4 = await state(w)
  await shot(w, '7e-after-redo')
  say('   7: approve', s1, '| undo', s2, '| reopened', s3, '| redo disabled', redoDisabled, '| redo', s4)
  rec('7 Approve, Undo, leave Approvals, reopen, Redo -> Redo still works', size, /13 Jan:approved/.test(s1) && /13 Jan:pending/.test(s2) && !redoDisabled && /13 Jan:approved/.test(s4) ? 'PASS' : 'FAIL', `approve "${s1}"; undo "${s2}"; reopened "${s3}"; redo button disabled ${redoDisabled}; after redo "${s4}"`, ['7c-grid-after-undo', '7d-approvals-reopened', '7e-after-redo'])
  /* the changes window shows nothing for "Approvals opened" or "taken back" */
  await P.evaluate(() => window.go('editsched')); await wait(1200)
  await press(w, '#histBtn'); await wait(900)
  await shot(w, '7f-changes-window')
  const hist = (await P.evaluate(() => document.body.innerText)).replace(/\s+/g, ' ')
  const hasOpened = /Approvals opened|opened Approvals|Approvals/i.test(hist.split('Changes')[1] || hist)
  const hasTaken = /taken back/i.test(hist)
  say('   changes window mentions Approvals:', hasOpened, '| "taken back":', hasTaken)
  say('   changes window text (head):', hist.slice(0, 600))
  rec('7f the changes window shows nothing for "Approvals opened" or "taken back"', size, !hasOpened && !hasTaken ? 'PASS' : 'FAIL', `mentions Approvals ${hasOpened}; "taken back" ${hasTaken}`, ['7f-changes-window'])
} catch (e) {
  rec('ERROR', size, 'FAIL', String(e).slice(0, 400))
  await shot(w, 'error').catch(() => {})
}
if (w.errs.length) rec('console', size, 'FAIL', w.errs.join(' || ').slice(0, 800))
L.writeResults('s678')
await w.ctx.close()
await L.closeBrowser()
console.log('DONE')
