// W2 scenario 11 — Medical, the Upchit date. VERSION 1
// usage: node s11.mjs desktop|phone
import { openWorld, tools } from './lib.mjs'
const WHICH = process.argv[2] || 'desktop'
console.log(`s11 VERSION 1 — ${WHICH}`)
const w = await openWorld(WHICH)
const { page, TOUCH } = w
const t = tools(w, `${WHICH}-s11`)
const toast = () => page.evaluate(() => [...document.querySelectorAll('body *')].filter(e => { const cs = getComputedStyle(e); if (cs.position !== 'fixed') return false; const r = e.getBoundingClientRect(); return r.width > 0 && r.top > innerHeight * 0.6 && (e.innerText || '').trim() && e.children.length < 4 }).map(e => e.innerText.trim().replace(/\s+/g, ' ')).join(' | '))
const dialogs = () => page.evaluate(() => [...document.querySelectorAll('[role=dialog], .win, .confirm, .modal, .sheet')].filter(e => e.getBoundingClientRect().width > 0).map(e => (e.getAttribute('data-testid') || e.className) + ' :: ' + e.innerText.replace(/\s+/g, ' ').slice(0, 400)))

await page.evaluate(() => window.go('inputs')); await page.waitForTimeout(500)
await t.press('#inMedBtn')
const pend = page.locator('.medsec.med-pend .medcard')
const nPend = await pend.count()
const cardText = (await pend.first().innerText()).replace(/\s+/g, ' ')
console.log(`S11 pending cards ${nPend}: "${cardText}"`)
const dnBefore = (await page.locator('.medsec.med-down').innerText()).replace(/\s+/g, ' ')
const doneBefore = (await page.locator('.medsec.med-done').innerText()).replace(/\s+/g, ' ')
await pend.first().scrollIntoViewIfNeeded(); await t.press('.medsec.med-pend .medcard')
await page.waitForSelector('#docViewPop:not([hidden])')
await t.press('#docViewUpchit'); await page.waitForSelector('#inpEditUpDate')
await page.waitForTimeout(300)
const fit = await t.boxFits('#inpEditUpDate', '[data-testid="win-inputedit"] .win-body', 'Upchit date')
const read0 = await t.text('#inpEditUpDate'), v0 = await t.val('#inpEditUpDate')
console.log(`S11 box reads "${read0.replace(/\s+/g, ' ')}" (${v0})`)
await t.shot('s11-form')
await t.press('#inpEditUpDate')
const c = await t.cardOnTop('Upchit date')
await t.shot('s11-calendar-open')
const dayBefore = await page.evaluate(v => { const d = new Date(v + 'T00:00:00Z'); d.setUTCDate(d.getUTCDate() - 1); return d.toISOString().slice(0, 10) }, v0)
if (c.month !== dayBefore.slice(0, 7)) { await t.press(+dayBefore.slice(5, 7) < +c.month.slice(5, 7) ? '[data-testid="dcal-prev"]' : '[data-testid="dcal-next"]') }
await t.pick(dayBefore)
const formUp = await t.vis('[data-testid="win-inputedit"]'), calGone = !(await t.vis('[data-testid="dcal-card"]'))
const read1 = await t.text('#inpEditUpDate'), v1 = await t.val('#inpEditUpDate')
console.log(`S11 after picking ${dayBefore}: form still up=${formUp}, calendar gone=${calGone}; box reads "${read1.replace(/\s+/g, ' ')}" (${v1})`)
await t.shot('s11-picked')
await t.press('#inpEditSave'); await page.waitForTimeout(600)
const dl = await dialogs()
console.log('S11 after Save: toast', JSON.stringify(await toast()), '| dialogs:', JSON.stringify(dl).slice(0, 900))
console.log('S11 buttons visible now:', JSON.stringify(await page.$$eval('button', es => es.filter(e => e.getBoundingClientRect().width > 0 && e.closest('[data-testid^="win-"], [role=dialog], .win, .confirm, .modal') ).map(e => (e.id || '') + '[' + e.innerText.trim().replace(/\s+/g, ' ').slice(0, 30) + ']').slice(0, 15))))
await t.shot('s11-after-save')
const asks = []
const dlgText = () => page.evaluate(() => { const ds = [...document.querySelectorAll('div')].filter(e => { const r = e.getBoundingClientRect(); return r.width > 200 && /No medical document|Upchit summary|summary|Confirm|Are you sure/i.test((e.querySelector('h1,h2,h3,[class*=title]') || {}).innerText || '') }); return ds.slice(-1).map(e => e.innerText.replace(/\s+/g, ' ').slice(0, 500)).join('') })
asks.push(await page.evaluate(() => { const b = [...document.querySelectorAll('button')].filter(e => e.getBoundingClientRect().width > 0 && /^(No document|Upload)$/.test(e.innerText.trim())); const d = b[0] && b[0].closest('div[class]'); return (d && d.parentElement ? d.parentElement.innerText : '').replace(/\s+/g, ' ').slice(0, 400) }))
await page.locator('button', { hasText: /^No document$/ }).first().evaluate(e => e.click()); await page.waitForTimeout(600)
await t.shot('s11-after-no-document')
const vis2 = await page.$$eval('button', es => es.filter(e => e.getBoundingClientRect().width > 0).map(e => (e.id || '') + '[' + e.innerText.trim().replace(/\s+/g, ' ').slice(0, 30) + ']'))
console.log('S11 after "No document": visible buttons', JSON.stringify(vis2.slice(-14)))
console.log('S11 page text around (dialogs)', JSON.stringify(await page.evaluate(() => { const ds = [...document.querySelectorAll('[class*=modal], [class*=confirm], [class*=sheet], [role=dialog], [class*=dlg], [class*=pop]')].filter(e => e.getBoundingClientRect().width > 100); return ds.map(e => e.className + ' :: ' + e.innerText.replace(/\s+/g, ' ').slice(0, 500)) })))
console.log('S11 toast', JSON.stringify(await toast()))
console.log('S11 first-ask text:', asks[0])
await w.page.screenshot({ path: 'docs/img/handpass/2026-10-13-one-date-calendar/w2/' + WHICH + '-s11-summary.png' })
const sumText = await page.locator('.upconf-pop').innerText().then(x => x.replace(/\s+/g, ' ')).catch(() => '')
console.log('S11 summary asks:', sumText)
await page.locator('button', { hasText: /^Save upchit$/ }).first().evaluate(e => e.click()); await page.waitForTimeout(700)
const tt = await toast()
const sec = async cls => (await page.locator(cls).innerText().catch(() => '(none)')).replace(/\s+/g, ' ')
const after = { down: await sec('.medsec.med-down'), pend: await sec('.medsec.med-pend'), done: await sec('.medsec.med-done') }
console.log('S11 after Save upchit: toast', JSON.stringify(tt), '| form still up:', await t.vis('[data-testid="win-inputedit"]'))
console.log('S11 sections after:', JSON.stringify(after))
console.log('S11 sections before:', JSON.stringify({ down: dnBefore, done: doneBefore }))
await t.shot('s11-after-saved')
const ok = fit.ok && c.wholly && c.onTop && formUp && calGone && v1 === dayBefore
t.rec('11', WHICH, ok ? 'PASS' : 'CHECK', `box reads "${read0.replace(/\s+/g, ' ')}" before; card wholly=${c.wholly} onTop=${c.onTop}; picked ${dayBefore}: form still up=${formUp}, calendar gone=${calGone}, box reads "${read1.replace(/\s+/g, ' ')}"; Save asked: no certificate attached (No document / Upload), then a summary "${sumText}"; after Save upchit: toast "${tt}"; Medical afterwards: pending "${after.pend}" | complete "${after.done}"`, `${WHICH}-s11-form.png / s11-calendar-open.png / s11-picked.png / s11-summary.png / s11-after-saved.png`)
console.log('RESULTS', JSON.stringify(t.results, null, 1))
console.log('errors', JSON.stringify(w.errors))
await w.browser.close()
