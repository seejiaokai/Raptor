import { openWorld, tools, adminCategory } from './lib.mjs'
console.log('probe4 VERSION 1')
const w = await openWorld(process.argv[2] || 'phone')
const t = tools(w, 'probe4')
const { page } = w
await adminCategory(page, '^Users')
await page.locator('#accAddPostIn').scrollIntoViewIfNeeded()
await page.fill('#accAddCs', 'Probey'); await page.fill('#accAddIni', 'PB')
await page.selectOption('#accAddSeat', 'FCP'); await page.selectOption('#accAddCat', 'C')
await t.press('#accAddPostIn'); await t.pick(t.addDays(10))
await t.press('#accAdd'); await page.waitForTimeout(500)
const look = async () => {
  await page.evaluate(() => window.go('leavewar')); await page.waitForTimeout(900)
  await page.evaluate(() => window.lwSetRole('admin')); await page.waitForTimeout(300)
  await t.press('[data-testid="month-OCT"]'); await page.waitForTimeout(900)
  console.log(JSON.stringify(await page.evaluate(() => ({ all: [...document.querySelectorAll('span.cs')].filter(x => /prob/i.test(x.textContent)).map(x => x.textContent + '|' + (x.closest('tr') || {}).getAttribute?.('data-testid')), rows: document.querySelectorAll('tr[data-testid^="row-"]').length, groups: [...document.querySelectorAll('tr')].filter(r => /· ?\d+$/.test((r.innerText||'').trim()) && (r.innerText||'').length < 30).map(r => r.innerText.trim().replace(/\s+/g,' ')), cat: [...document.querySelectorAll('tr')].filter(r => /CAT [A-D]/.test(r.innerText||'') && (r.innerText||'').length < 12).length, anyText: /Probey/.test(document.body.innerText) }))))
}
await look()
// archive and restore with later date
await adminCategory(page, '^Users')
await page.fill('#accFind', 'Probey'); await page.waitForTimeout(300)
await t.press('#accList .acc-main:has-text("Probey")'); await t.press('#accEdArchive'); await page.waitForTimeout(500)
await page.fill('#accFind', '')
if ((await page.locator('#accArchToggle').getAttribute('aria-expanded')) !== 'true') await t.press('#accArchToggle')
await t.press('#accArchList .acc-main:has-text("Probey")')
await t.press('#accArPostIn'); await t.press('[data-testid="dcal-next"]'); await t.pick(t.addDays(21))
await t.press('#accArRestore'); await page.waitForTimeout(600)
await look()
await page.waitForTimeout(2500)
console.log('later', JSON.stringify(await page.evaluate(() => [...document.querySelectorAll('span.cs')].filter(x => /prob/i.test(x.textContent)).map(x => x.textContent))))
await t.press('[data-testid="month-NOV"]'); await page.waitForTimeout(1500)
console.log('nov', JSON.stringify(await page.evaluate(() => [...document.querySelectorAll('span.cs')].filter(x => /prob/i.test(x.textContent)).map(x => x.textContent))))
await page.screenshot({ path: 'docs/img/handpass/2026-10-13-one-date-calendar/w2/probe4.png' })
await w.browser.close()
