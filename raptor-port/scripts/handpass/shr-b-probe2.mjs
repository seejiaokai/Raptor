// Walker b — probe 2: what the LL label on the week opens (reads only; nothing pressed inside it)
console.log('shr-b-probe2 v1')
const B = await (await import('./shr-b-lib.mjs')).setup('probe2')
const { start, fileInput, go, sleep, log, J, showDay } = B
const w = await start('desk')
await fileInput(w, 'P', B.WED, { type: 'LL', people: [B.RANGER, B.HEX], from: '08:00', to: '10:00' })
await go(w.page, 'editsched'); await sleep(600); await showDay(w.page, 2)
const lbl = w.page.locator('#eWeek .day[data-day="2"] .sec-unav [data-inpedit][data-iuw="bane"]').first()
await lbl.click(); await sleep(1200)
const wins = await w.page.evaluate(() => [...document.querySelectorAll('[data-testid]')].filter(e => e.getBoundingClientRect().width > 50 && /win|sheet|pop/i.test(e.getAttribute('data-testid'))).map(e => e.getAttribute('data-testid') + ' ' + e.className + ' :: ' + (e.textContent || '').replace(/\s+/g, ' ').slice(0, 300)))
log('P', 'windows ' + J(wins))
const ids = await w.page.evaluate(() => [...document.querySelectorAll('[id^="inpEdit"]')].filter(e => e.getBoundingClientRect().width > 1).map(e => e.id + '=' + (e.value ?? '') + ' ' + e.tagName))
log('P', 'inpEdit ids ' + J(ids))
const pp = await w.page.evaluate(() => [...document.querySelectorAll('[data-pp]')].filter(e => e.getBoundingClientRect().width > 1).map(e => e.getAttribute('data-pp') + ':' + e.getAttribute('aria-pressed')))
log('P', 'pp ' + J(pp))
await w.page.screenshot({ path: process.env.WR4_OUT + '/probe2-full.png' })
await B.done()
