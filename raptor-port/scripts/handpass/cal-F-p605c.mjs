const foot = await p.evaluate(() => {
  const w = document.querySelector('[data-testid="win-inputedit"]')
  const sc = [...w.querySelectorAll('*')].find(e => e.scrollHeight > e.clientHeight + 4 && getComputedStyle(e).overflowY !== 'visible')
  if (sc) sc.scrollTop = sc.scrollHeight
  const ro = w.querySelector('[data-testid="inped-ro"]')
  return { scroller: sc ? (sc.className || sc.tagName) : null, ro: ro ? ro.innerText : null, buttons: [...w.querySelectorAll('button')].filter(x => x.offsetParent !== null).map(x => x.innerText.trim()).filter(Boolean).slice(-6) }
})
await L.sleep(300)
await p.locator('[data-testid="win-inputedit"]').screenshot({ path: L.SHOTS + '/zz-p605c-foot.png' })
console.log(JSON.stringify(foot))
await L.pic(p, 'p605c-foot-of-window')
