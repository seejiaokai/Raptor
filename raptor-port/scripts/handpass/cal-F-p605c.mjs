await L.go(p, 'inputs')
await L.toastSpy(p)
const [ranger, echo, saber] = await L.ids(p, ['Ranger', 'Echo', 'Saber'])
await L.be(p, ranger, 'member')
await L.openNew(p, '2026-07-31')
await p.selectOption('#inpEditType', 'Meeting')
await L.pickSeveral(p, [ranger, echo])
await L.setWhen(p, { allday: true, remarks: 'p605c one' })
await p.locator('#inpEditSave').click(); await L.sleep(700)
