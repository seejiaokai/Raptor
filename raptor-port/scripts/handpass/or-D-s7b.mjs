// D7 (part 2) — the schedule's window at 844x390 (the Meeting is filed first on the phone's upright size, in the same world)
import { open, fileInput, shot, sleep, log, errs, browser, goWeek, unfoldWeek, popInfo, swipeIn, settleScroll } from './or-D-lib.mjs'
const { ctx, page } = await open({ viewport: { width: 390, height: 844 } })
await fileInput(page, { type: 'Meeting', people: ['Drifter', 'Hunter', 'Blade'], from: '2026-07-15', to: '2026-07-15', timed: ['14:00', '15:00'], title: 'Range brief' })
await page.setViewportSize({ width: 844, height: 390 }); await sleep(1500)
await goWeek(page); await sleep(800)
log('D7b layout:', JSON.stringify(await page.evaluate(() => ({ iw: window.innerWidth, ih: window.innerHeight, sw: document.documentElement.scrollWidth }))))
await shot(page, 'D7-844x390-09-week')
// open from the Personal Inputs line: which control is there at this width?
const lines = await page.evaluate(() => [...document.querySelectorAll('#page-editsched .day:not(.peek) .sec-inp .pl-row .inpedit, #page-editsched .day:not(.peek) [data-pitog]')].map(e => e.tagName + '|' + e.className + '|' + (e.innerText || '').slice(0, 30)))
log('D7b controls:', JSON.stringify(lines))
await page.evaluate(() => { const t = document.querySelector('#page-editsched .day:not(.peek) [data-pitog="2"]'); if (t && /show/.test(t.innerText)) t.click() }); await sleep(500)
const il = page.locator('#page-editsched .day:not(.peek) .sec-inp .pl-row', { hasText: 'Range brief' }).first()
await il.evaluate(e => e.scrollIntoView({ block: 'center', inline: 'center' })); await sleep(600)
await il.locator('.inpedit').tap({ timeout: 8000 }).catch(e => log('D7b could not tap the line:', String(e).slice(0, 200)))
await sleep(900)
const pi = await popInfo(page)
log('D7b window from the schedule at 844x390:', JSON.stringify(pi && { box: pi.box, gapTop: pi.gapTop, gapBottom: pi.gapBottom, vw: pi.vw, vh: pi.vh, content: pi.content, shown: pi.shown, save: pi.save, del: pi.del }))
await shot(page, 'D7-844x390-10-sched-window')
if (pi) {
  const before = await page.evaluate(() => JSON.stringify({ y: Math.round(window.scrollY), x: Math.round(window.scrollX) }))
  for (const dy of [-250, -250, -250, 250, 250, 250]) await swipeIn(page, 422, 200, dy)
  const after = await page.evaluate(() => JSON.stringify({ y: Math.round(window.scrollY), x: Math.round(window.scrollX) }))
  const p2 = await popInfo(page)
  log('D7b page behind before / after six swipes inside the window:', before, after, '| window scrollTop', p2 && p2.scrollTop, '| save/del', JSON.stringify(p2 && { save: p2.save, del: p2.del }))
  await shot(page, 'D7-844x390-11-sched-after-swipes')
}
log(errs)
await ctx.close(); await browser.close()
