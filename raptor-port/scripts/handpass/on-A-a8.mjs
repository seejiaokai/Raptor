import { world, fileIt, makeHoliday, openWeekDay, drag, rosterPuck, frameGrnd, rowFill, rowPeople, toast, toastsAll, undoState, oilOf, flashing, FRI, FRI_DI } from './on-A-lib.mjs'
const W = await world({ tag: 'A8' })
const { page, tid, press, shot, errors } = W
const id1 = await fileIt(W, FRI, { type: 'Training', people: ['bane', 'mamba'], from: '09:00', to: '12:00', title: 'Range brief' })
const id2 = await fileIt(W, FRI, { type: 'Meeting', people: ['nick', 'harpoon'], from: '14:00', to: '15:00', title: 'Safety board' })
console.log('filed', id1, id2, 'asked', W.lastAsked)
console.log('holiday', JSON.stringify(await makeHoliday(W, FRI, 'National Day', { later: true })))
const oils = async () => (await oilOf(page, id1)) + ' || ' + (await oilOf(page, id2))
console.log('oils after Later', await oils())
await openWeekDay(W, FRI_DI)
const f1 = await rowFill(page, FRI_DI, 'Range brief'), f2 = await rowFill(page, FRI_DI, 'Safety board')
console.log('fills', f1, f2)
const people = async () => (await rowPeople(page, FRI_DI, f1)) + ' || ' + (await rowPeople(page, FRI_DI, f2))
console.log('rows', await people())
await frameGrnd(page, FRI_DI); await page.waitForTimeout(300)
const slotOf = (f, name) => page.evaluate(([di, f, name]) => { const day = [...document.querySelectorAll('#eWeek .day')].filter(d => !d.classList.contains('peek'))[di]; const p = day.querySelector(`[data-fill="${f}"]`); const el = [...p.querySelectorAll('.puck')].find(x => x.textContent.trim().startsWith(name)); return el ? el.parentElement.getAttribute('data-slot') : null }, [FRI_DI, f, name])
const rangerSlot = await slotOf(f1, 'Ranger')
console.log('Ranger slot', rangerSlot)
const rangerPuck = page.locator('#eWeek .day:not(.peek)').nth(FRI_DI).locator(`[data-slot="${rangerSlot}"] .puck`)
const target = page.locator('#eWeek .day:not(.peek)').nth(FRI_DI).locator(`[data-fill="${f2}"] .addz`)
const before = await people(), oil0 = await oils(), undo0 = await undoState(page)
await drag(page, rangerPuck, target)
console.log('Q', await tid('oilconf').count(), await tid('oilconf-lead').innerText().catch(() => 'NO'), '|', await tid('oilconf-cancel').innerText().catch(() => ''), '|', await tid('oilconf-save').innerText().catch(() => ''), 'saveDisabled', await tid('oilconf-save').isDisabled().catch(() => null), 'heading', await page.locator('[data-testid="oilconf"] .airpop-head b').innerText().catch(() => ''))
console.log('rows during question unchanged', (await people()) === before)
await shot('A8-1-question-move')
await press(tid('oilconf-cancel')); await page.waitForTimeout(150)
await shot('A8-2-flash')
await page.waitForTimeout(500)
console.log('bar', await tid('oilbar-text').innerText().catch(() => 'NO'), '|', await tid('oilbar-answer').innerText().catch(() => ''), '|', await tid('oilbar-ok').innerText().catch(() => ''))
console.log('after cancel rows', await people(), 'unchanged', (await people()) === before, 'oils unchanged', (await oils()) === oil0)
await press(tid('oilbar-answer')); await page.waitForTimeout(300)
console.log('question again', await tid('oilconf-lead').innerText().catch(() => 'NO'))
await press(tid('oil-yes')); await press(tid('oilconf-save')); await page.waitForTimeout(600)
console.log('toast', await toast(page))
console.log('after answer rows', await people(), 'oils', await oils())
await shot('A8-3-moved')
await page.locator('#undoBtn').click(); await page.waitForTimeout(600)
console.log('after ONE undo rows', await people(), 'same as before', (await people()) === before, 'oils back', (await oils()) === oil0)
console.log('errors', JSON.stringify(errors))
await W.ctx.close(); process.exit(0)
