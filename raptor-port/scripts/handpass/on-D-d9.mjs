import { launch, world, bye, rec, FRI } from './on-D-lib.mjs'
const browser = await launch()
const w = await world(browser, { tag: 'D9' }); const { page, tid } = w
await w.giveWarden()
const ids = await w.fileFriday(); await w.makeHoliday('National Day', [FRI])
await w.press(tid(`odl-yes-${ids[2]}`)); w.say('count with pick', await tid('odl-count').innerText())
const card = tid('win-oilday').locator('.icard').filter({ hasText: 'Safety board' }).first()
await w.press(card.locator('b').first()); await page.waitForTimeout(500)
w.say('input window open', await page.locator('#inpEditPop:visible').count()); w.say('pop title', await page.locator('#inpEditPop #inpEditOwnTitle').first().inputValue())
await w.press(page.locator('#inpEditDel')); await page.waitForTimeout(500)
w.say('toast', await w.toast())
await page.waitForTimeout(400)
w.say('pop closed', await page.locator('#inpEditPop:visible').count() === 0)
w.say('list still up', await tid('win-oilday').count())
w.say('count', await tid('odl-count').innerText()); w.say('cards', await tid('win-oilday').locator('.icard').evaluateAll(es => es.map(e => e.innerText.replace(/\s+/g, ' ').slice(0, 40))))
w.say('Safety board still in INPUTS', await page.evaluate(i => !!window.INPUTS.find(r => r.iid === i), ids[2]))
const sd = await tid('odl-save').isDisabled(); w.say('Save disabled', sd)
w.say('undo', await w.undoInfo())
await w.hush(); await w.shot('D9-list-after-delete', { x: 960, y: 80, width: 480, height: 480 }); await w.unhush()
if (!sd) { await w.press(tid('odl-save')); await page.waitForTimeout(600); w.say('pressed Save; toast', await w.toast()); w.say('list', await tid('win-oilday').count()); w.say('undo after', await w.undoInfo()) }
await w.press(tid(`odl-yes-${ids[1]}`)); w.say('count after pick on Gate duty', await tid('odl-count').innerText()); await w.press(tid('odl-save')); await page.waitForTimeout(600)
w.say('toast after Save', await w.toast()); w.say('list', await tid('win-oilday').count())
w.say('state', await w.state(ids)); w.say('INPUTS count with Safety board title', await page.evaluate(() => window.INPUTS.filter(r => r.title === 'Safety board').length)); w.say('error list', w.errors)
await w.shot('D9-after-save')
await bye(w); await browser.close()
