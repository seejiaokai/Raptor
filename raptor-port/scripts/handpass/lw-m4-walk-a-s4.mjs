// Walker A, route 2: scenarios 4 and 5 (Approve all, the month chip, Pick dates, New). Desktop, admin.
process.env.LW_OUT ||= '../../docs/img/handpass/2026-10-27-lw-m4/a/s4'
const A = await import('./lw-m4-walk-a-lib.mjs')
const { L, bidBatch, pressLoc, lineLoc, lineInfo, topbarUndo, topbarRedo } = A
const { T, rec, shot, txt } = L
console.log('[lw-m4-walk-a-s4 v1]')
L.clearOut()
const w = await L.newCtx('desk')
const P = w.page
const size = 'desk'
const allBtn = P.locator(T('appr-approve-all'))
const allState = async () => ({ text: (await allBtn.innerText()).trim(), armed: ((await allBtn.getAttribute('class')) || '').includes('armed') })
const litCount = () => P.evaluate(() => [...document.querySelectorAll('.appr-line')].filter(e => /lit-approved/.test(e.className)).length)
const pendCount = () => P.evaluate(() => [...document.querySelectorAll('.appr-line')].filter(e => !/lit-/.test(e.className) && !e.classList.contains('stale')).length)
const lineCount = () => P.evaluate(() => document.querySelectorAll('.appr-line').length)
const toastText = () => P.evaluate(() => { const t = [...document.querySelectorAll('[class*="toast"], [role="status"]')].map(e => e.innerText.trim()).filter(Boolean); return t.join(' | ') })
try {
  await L.signIn(w, 'member')
  await bidBatch(w, 'bane', [{ iso: '2026-01-12' }, { iso: '2026-01-14' }, { iso: '2026-01-19', portion: 'am' }, { iso: '2026-01-26' }, { iso: '2026-01-27' }, { iso: '2026-02-09', type: 'OIL' }, { iso: '2026-02-16' }])
  await L.switchTo(w, 'admin')
  await L.openApprovals(w)
  const n0 = await lineCount(), tab0 = await L.tabCount(P)
  console.log('lines', n0, 'tab', tab0, 'approve all', JSON.stringify(await allState()))
  await shot(w, 'a-s4-0-start')
  /* ---- 4a: two separate taps ~1 s apart ---- */
  await pressLoc(w, allBtn); await P.waitForTimeout(400)
  const armed = await allState()
  await shot(w, 'a-s4-4a-armed')
  await P.waitForTimeout(700)
  await pressLoc(w, allBtn); await P.waitForTimeout(700)
  const lit = await litCount(), tabAfter = await L.tabCount(P), allAfter = await allState()
  await shot(w, 'a-s4-4a-all-approved')
  rec('4a Approve all: first tap arms, second approves every shown line', size, armed.armed && /tap again/.test(armed.text) && lit === n0 ? 'PASS' : 'FAIL', `armed: ${JSON.stringify(armed)}; after second tap ${lit} of ${n0} lines lit approved; tab count ${tab0} -> ${tabAfter}; button now ${JSON.stringify(allAfter)}`, ['a-s4-4a-armed', 'a-s4-4a-all-approved'])
  await topbarUndo(w)
  const lit1 = await litCount(), pend1 = await pendCount(), tab1 = await L.tabCount(P)
  await shot(w, 'a-s4-4a-after-one-undo')
  rec('4b ONE Undo brings every line back', size, lit1 === 0 && pend1 === n0 ? 'PASS' : 'FAIL', `after one Undo: ${lit1} lit, ${pend1} pending of ${n0}; tab ${tab1}; toast "${await toastText()}"`, ['a-s4-4a-after-one-undo'])
  /* (4c, the fast taps, is its own run: lw-m4-walk-a-s4b.mjs) */
  /* ---- 4d: armed, then change the month filter -> disarmed ---- */
  await pressLoc(w, P.locator(T('appr-all'))); await P.waitForTimeout(300)
  await pressLoc(w, allBtn); await P.waitForTimeout(300)
  const a1 = await allState()
  await pressLoc(w, P.locator(T('appr-m-2026-01'))); await P.waitForTimeout(400)
  const a2 = await allState()
  await shot(w, 'a-s4-4d-after-month-chip')
  rec('4d armed, then the month filter changes -> disarmed', size, a1.armed && !a2.armed && /^Approve all \d+$/.test(a2.text) ? 'PASS' : 'FAIL', `before: ${JSON.stringify(a1)}; after Jan chip: ${JSON.stringify(a2)}`, ['a-s4-4d-after-month-chip'])
  /* ---- 5a: a month chip: Approve all approves exactly what shows ---- */
  const janLines = await lineCount()
  await pressLoc(w, allBtn); await P.waitForTimeout(400)
  const s5 = await allState()
  await P.waitForTimeout(600)
  await pressLoc(w, allBtn); await P.waitForTimeout(600)
  const janLit = await litCount()
  await shot(w, 'a-s4-5a-jan-approved')
  await pressLoc(w, P.locator(T('appr-all'))); await P.waitForTimeout(500)
  const febState = await P.evaluate(() => [...document.querySelectorAll('.appr-line')].map(e => ({ d: e.querySelector('.appr-dlink').innerText, lit: (e.className.match(/lit-(\w+)/) || [])[1] || 'pending' })))
  await shot(w, 'a-s4-5a-all-after-jan')
  const outside = febState.filter(l => /Feb/.test(l.d)), inside = febState.filter(l => /Jan/.test(l.d))
  rec('5a month chip: Approve all approves exactly what shows', size, janLit === janLines && inside.every(l => l.lit === 'approved') && outside.length > 0 && outside.every(l => l.lit === 'pending') ? 'PASS' : 'FAIL', `Jan chip showed ${janLines} lines, armed "${s5.text}", ${janLit} lit; with All: Jan lines ${inside.map(l => l.lit).join('/')}, Feb lines ${outside.map(l => l.d + ':' + l.lit).join(', ')}`, ['a-s4-5a-jan-approved', 'a-s4-5a-all-after-jan'])
  /* a Feb request on the grid is still waiting (dashed), a Jan one approved (solid) */
  await L.openGrid(w)
  await L.reachCell(w, 'bane', '2026-02-16')
  const cellFeb = await P.evaluate(() => { const c = document.querySelector('[data-testid="cell-bane-2026-02-16"]'); return c ? c.innerHTML.replace(/\s+/g, ' ').slice(0, 300) : null })
  await P.locator(T('cell-bane-2026-02-16')).scrollIntoViewIfNeeded()
  const cb = await P.locator(T('cell-bane-2026-02-16')).boundingBox()
  await shot(w, 'a-s4-5a-grid-feb-cell', { clip: { x: Math.max(0, cb.x - 120), y: Math.max(0, cb.y - 60), width: 300, height: 120 } })
  console.log('feb cell html', cellFeb)
  await L.openApprovals(w)
  /* ---- 5b: Pick dates range ---- */
  await pressLoc(w, P.locator(T('appr-pick'))); await P.waitForTimeout(400)
  /* the picker opens on January; the Feb days are on the next month */
  await pressLoc(w, P.locator(T('appr-range-next'))); await P.waitForTimeout(300)
  await pressLoc(w, P.locator(T('appr-range-day-2026-02-02'))); await P.waitForTimeout(250)
  await pressLoc(w, P.locator(T('appr-range-day-2026-02-10'))); await P.waitForTimeout(500)
  const selTxt = await txt(P, T('appr-range-foot'))
  await shot(w, 'a-s4-5b-range-picked')
  const rangeLines = await P.evaluate(() => [...document.querySelectorAll('.appr-line')].map(e => ({ d: e.querySelector('.appr-dlink').innerText, lit: (e.className.match(/lit-(\w+)/) || [])[1] || 'pending' })))
  console.log('selection', selTxt, 'lines in range', JSON.stringify(rangeLines))
  const stR0 = await allState()
  await pressLoc(w, allBtn); await P.waitForTimeout(400)
  const stR1 = await allState()
  await P.waitForTimeout(600)
  await pressLoc(w, allBtn); await P.waitForTimeout(600)
  const litInRange = await litCount()
  await shot(w, 'a-s4-5b-range-approved')
  await pressLoc(w, P.locator(T('appr-all'))); await P.waitForTimeout(500)
  const afterRange = await P.evaluate(() => [...document.querySelectorAll('.appr-line')].map(e => ({ d: e.querySelector('.appr-dlink').innerText, lit: (e.className.match(/lit-(\w+)/) || [])[1] || 'pending' })))
  await shot(w, 'a-s4-5b-all-after-range')
  const inR = afterRange.filter(l => /(2|3|9|10) Feb/.test(l.d)), outR = afterRange.filter(l => /(16|24) Feb/.test(l.d))
  rec('5b Pick dates (a range): Approve all approves exactly the range', size, litInRange === rangeLines.length && rangeLines.length > 0 && outR.length > 0 && outR.every(l => l.lit === 'pending') ? 'PASS' : 'FAIL', `selection "${selTxt}"; range showed ${rangeLines.length} lines, ${litInRange} lit after the second tap; button ${stR0.text} -> ${stR1.text}; inside: ${inR.map(l => l.d + ':' + l.lit).join(', ')}; outside: ${outR.map(l => l.d + ':' + l.lit).join(', ')}`, ['a-s4-5b-range-picked', 'a-s4-5b-range-approved', 'a-s4-5b-all-after-range'])
  /* ---- 5c: New ---- */
  await pressLoc(w, P.locator(T('appr-new'))); await P.waitForTimeout(500)
  const newLines = await P.evaluate(() => [...document.querySelectorAll('.appr-line')].map(e => ({ d: e.querySelector('.appr-dlink').innerText, who: e.dataset.testid, lit: (e.className.match(/lit-(\w+)/) || [])[1] || 'pending' })))
  const stN0 = await allState()
  await shot(w, 'a-s4-5c-new')
  console.log('New shows', JSON.stringify(newLines), JSON.stringify(stN0))
  const pendBefore = await P.evaluate(() => 0)
  await pressLoc(w, allBtn); await P.waitForTimeout(400)
  await P.waitForTimeout(600)
  await pressLoc(w, allBtn); await P.waitForTimeout(600)
  await shot(w, 'a-s4-5c-new-approved')
  await pressLoc(w, P.locator(T('appr-all'))); await P.waitForTimeout(500)
  const afterNew = await P.evaluate(() => [...document.querySelectorAll('.appr-line')].map(e => ({ d: e.querySelector('.appr-dlink').innerText, lit: (e.className.match(/lit-(\w+)/) || [])[1] || 'pending' })))
  await shot(w, 'a-s4-5c-all-after-new')
  const notNew = afterNew.filter(l => /(24 Feb)/.test(l.d))
  rec('5c New: Approve all approves exactly the New lines', size, newLines.length > 0 && notNew.every(l => l.lit === 'pending') ? 'PASS' : 'FAIL', `New showed ${newLines.length} lines (${newLines.map(l => l.d).join(', ')}); a demo request not new (24 Feb) is ${notNew.map(l => l.lit).join(',')}; all lines now: ${afterNew.map(l => l.d + ':' + l.lit).join(', ')}`, ['a-s4-5c-new', 'a-s4-5c-new-approved', 'a-s4-5c-all-after-new'])
  /* ---- 5d: Pick dates closes on a press outside it and on Escape ---- */
  await pressLoc(w, P.locator(T('appr-pick'))); await P.waitForTimeout(400)
  const open1 = (await P.locator(T('appr-range')).count()) > 0
  await shot(w, 'a-s4-5d-open')
  await P.mouse.click(1400, 700); await P.waitForTimeout(400)
  const closed1 = (await P.locator(T('appr-range')).count()) === 0
  await shot(w, 'a-s4-5d-after-outside-press')
  await pressLoc(w, P.locator(T('appr-pick'))); await P.waitForTimeout(400)
  const open2 = (await P.locator(T('appr-range')).count()) > 0
  await P.keyboard.press('Escape'); await P.waitForTimeout(400)
  const closed2 = (await P.locator(T('appr-range')).count()) === 0
  const focusAfter = await P.evaluate(() => document.activeElement && (document.activeElement.dataset.testid || document.activeElement.tagName))
  await shot(w, 'a-s4-5d-after-escape')
  rec('5d Pick dates closes on a press outside and on Escape', size, open1 && closed1 && open2 && closed2 ? 'PASS' : 'FAIL', `opened ${open1}, closed by an outside press ${closed1}; opened ${open2}, closed by Escape ${closed2}; focus after Escape: ${focusAfter}`, ['a-s4-5d-open', 'a-s4-5d-after-outside-press', 'a-s4-5d-after-escape'])
} catch (e) {
  rec('ERROR', size, 'FAIL', String(e).slice(0, 500))
  await shot(w, 'a-s4-error').catch(() => {})
}
console.log('errs', JSON.stringify(w.errs))
L.writeResults('s4')
await w.ctx.close(); await L.closeBrowser()
console.log('DONE')
