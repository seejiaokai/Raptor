// RX1-7 — a MEMBER's face: Ranger files a Personal input for Hex and Hunter; Hex reads and takes himself out; Ranger adds Drifter
import { launch, openWorld, fileX, shotX, inputOf, errs, log, as, bellRead, describeWin, openFromList, WIN, csId, inputsSurf, closeDayWin, closeWindow } from './or-RX1-lib.mjs'
const browser = await launch()
const { page: p } = await openWorld(browser, { who: 'us', pass: 'us', fresh: false })
const badge = () => p.evaluate(() => document.getElementById('roleBadge').textContent)
log('signed in as', await badge())
/* the switch: what is it now? (read through the gear only if there is one) */
log('gear present for a member', await p.locator('#inGear').count())
await p.evaluate(() => window.go('inputs')); await p.waitForTimeout(300)
if (await p.locator('#inListBtn[aria-pressed="false"]').count()) await p.locator('#inListBtn').click()
await p.waitForTimeout(300)
await p.locator('#inNew').click(); await p.locator(WIN).waitFor()
await p.selectOption('#inpEditType', 'Personal')
log('Several people switch present for a member', await p.locator(`${WIN} [data-testid="pp-several"]`).count())
await p.locator('#inpEditCancel').click(); await p.waitForTimeout(200)
const had = await p.evaluate(() => window.INPUTS.map(r => r.iid))
const f = await fileX(p, { type: 'Personal', people: ['Hex', 'Hunter'], from: '2026-07-15', to: '2026-07-15', timed: ['12:00', '13:00'] })
log('filed', f.made, 'oil', f.oilSeen, 'toasts', f.toasts, 'stillOpen', f.stillOpen, f.winText)
if (!f.made || !f.made.length) { await shotX(p, 'rx1-7-0-not-saved'); log('errs', errs); await browser.close(); process.exit(0) }
const iid = f.made[0].iid
const who = async () => { const r = await p.evaluate(i => { const x = window.INPUTS.find(r => r.iid === i); return x ? { people: x.people.map(e => (window.PEOPLE[e.p] || {}).cs || e.p), by: (window.PEOPLE[x.by] || {}).cs, modBy: (window.PEOPLE[x.modBy] || {}).cs } : null }, iid); return r }
log('INPUTS', await who())
const sf = await inputsSurf(p, iid, '2026-07-15'); log('card as Ranger', sf); await shotX(p, 'rx1-7-1-ranger-card')
await closeDayWin(p)
/* Hex */
await as(p, 'Hex'); log('now', await badge())
log('Hex bell', await bellRead(p, { close: false })); await shotX(p, 'rx1-7-2-hex-bell')
await p.locator('#notifyBell').click().catch(() => {}); await p.waitForTimeout(250)
await openFromList(p, iid)
const d = await describeWin(p)
log('Hex window', { fields: d.fields.map(f => f.id + '=' + f.value + (f.disabled ? '(ro)' : '')), buttons: d.buttons.map(b => b.id + ':' + b.text).filter(t => t.length > 3), picker: d.picker, tail: d.text.slice(-420) })
await shotX(p, 'rx1-7-3-hex-window')
const pressedNow = () => p.locator(WIN).evaluate(w => [...w.querySelectorAll('[data-pp][aria-pressed="true"]')].map(b => b.getAttribute('data-pp')).join(','))
const pb = await pressedNow()
await p.locator(`${WIN} [data-pp]`, { hasText: 'Ace' }).first().click({ force: true }).catch(() => {}); await p.waitForTimeout(250)
log('Hex tries to pick Ace: pressed before/after', pb, await pressedNow(), 'INPUTS', await who())
log('Hex: Save present', await p.locator('#inpEditSave').count(), '| takeout present', await p.locator('[data-testid="inped-takeout"]').count())
await p.locator(`${WIN} [data-testid="inped-takeout"]`).scrollIntoViewIfNeeded()
await p.locator(`${WIN} [data-testid="inped-takeout"]`).click(); await p.waitForTimeout(500)
log('after first press', await p.locator(WIN).evaluate(w => w.innerText.replace(/\s+/g, ' ').slice(-300)))
await shotX(p, 'rx1-7-4-hex-confirm')
const tm = await p.evaluate(() => (window.__toasts || []).length)
await p.locator(`${WIN} button:visible`, { hasText: 'Take me out' }).last().click(); await p.waitForTimeout(700)
log('after Take me out: toasts', await p.evaluate(m => (window.__toasts || []).slice(m).map(t => t.text), tm), 'INPUTS', await who(), 'window open', await p.locator(WIN).count())
await shotX(p, 'rx1-7-5-hex-after-out')
/* Ranger again */
await as(p, 'Ranger'); log('now', await badge())
log('Ranger bell', await bellRead(p, { close: false })); await shotX(p, 'rx1-7-6-ranger-bell')
await p.locator('#notifyBell').click().catch(() => {}); await p.waitForTimeout(250)
await openFromList(p, iid)
const d2 = await describeWin(p)
log('Ranger window', { buttons: d2.buttons.map(b => b.id + ':' + b.text).filter(t => t.length > 3), picker: d2.picker, tail: d2.text.slice(-300) })
await shotX(p, 'rx1-7-7-ranger-window')
const drifter = await csId(p, 'Drifter')
await p.locator(WIN + ' [data-testid="pp-several"]').click(); await p.waitForTimeout(250)
log('Ranger switched Several people on: pressed', await p.locator(WIN).evaluate(w => [...w.querySelectorAll('[data-pp][aria-pressed="true"]')].map(b => (window.PEOPLE[b.getAttribute('data-pp')] || {}).cs).join(',')))
await p.locator(`${WIN} [data-pp="${drifter}"]`).click(); await p.waitForTimeout(250)
const tm2 = await p.evaluate(() => (window.__toasts || []).length)
await p.locator('#inpEditSave').click(); await p.waitForTimeout(700)
log('Ranger adds Drifter: oil q', await p.locator('[data-testid="oilconf"]').count(), 'toasts', await p.evaluate(m => (window.__toasts || []).slice(m).map(t => t.text), tm2), 'window open', await p.locator(WIN).count(), 'INPUTS', await who())
await shotX(p, 'rx1-7-8-ranger-after-add')
const sf2 = await inputsSurf(p, iid, '2026-07-15'); log('card after', sf2); await shotX(p, 'rx1-7-9-card-after')
log('errs', errs)
await browser.close()
