const say = (k, v) => console.log(k, '::', typeof v === 'string' ? v : JSON.stringify(v))
const ranger = await pidOf(page, 'Ranger')
const rows = async () => await page.evaluate(() => [...document.querySelectorAll('#eWeek .day[data-day="5"] .pl-row, #eWeek .day[data-day="5"] .puck.allavail')].map(e => e.innerText.replace(/\s+/g, ' ').trim()).slice(0, 4))
