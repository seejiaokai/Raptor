// S5 - alternate plans keep their own placeholder rows and overrides (desktop, admin)
const C = await import('./aa-C-lib.mjs')
const { world, fileInput, shot, board, sleep, go, pubSat, closeBoard, editWeek, face, fs, cr, crS, undoRedo, reload, altPlan, switchTo, planMenuItems, pidOf, earnRead, pend, viewDay, pvBar, pvTap } = C
