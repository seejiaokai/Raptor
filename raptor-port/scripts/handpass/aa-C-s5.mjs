await go(page, 'editsched'); await sleep(300)
say('1 + Alt Plan', await altPlan(page, 5)); await sleep(400)
say('2 deny Ranger in Plan B (live)', await earnRead(page, [ranger], { tap: ranger }))
await closeBoard(page)
say('2 week rows (Plan B)', await rows())
// the view-only drafts picker (day not issued yet): look at Plan A
await go(page, 'viewsched'); await sleep(500)
const opts = await page.evaluate(() => [...document.querySelectorAll('#vWeek .day[data-day="5"] select')].map(s => ({ cls: s.className, opts: [...s.options].map(o => (o.selected ? '*' : '') + o.text + '=' + o.value) })))
say('3 view-only pickers', opts)
const dver = page.locator('#vWeek .day[data-day="5"] select[data-dver]').first()
if (await dver.count()) {
  const val = await dver.evaluate(s => [...s.options].find(o => o.value.startsWith('d:'))?.value)
  await dver.selectOption(val); await sleep(700)
  await shot(page, 'S5-01-viewonly-planA-preview')
  say('3 view-only bar', await page.evaluate(() => document.querySelector('#vWeek .day[data-day="5"] .dprev-bar')?.innerText))
}
await go(page, 'editsched'); await sleep(500)
say('3 edit bar', await pvBar(page, 5))
await shot(page, 'S5-02-edit-preview')
say('3 press Switch to this plan', await pvTap(page, 5, 'data-draftgo'))
await sleep(500)
say('3 after switch', fs(await face(page)))
say('3 plan menu', await planMenuItems(page, 5)); await page.keyboard.press('Escape')
say('3 Plan A earn state', await earnRead(page, [ranger])); await closeBoard(page)
// selector: to B and back to A
say('4 selector -> Plan B', await switchTo(page, 5, /Plan B/)); await sleep(400)
say('4 B earn', await earnRead(page, [ranger])); await closeBoard(page)
say('4 selector -> Plan A', await switchTo(page, 5, /Plan A/)); await sleep(400)
say('4 A earn', await earnRead(page, [ranger])); await closeBoard(page)
await go(page, 'editsched')
say('5 issue plan A', await pubSat(page, 5)); await closeBoard(page)
say('5 face', fs(await face(page)))
say('5 credits (Plan A issued)', crS(await cr(page)))
await go(page, 'editsched')
say('6 selector -> Plan B on a published day', await switchTo(page, 5, /Plan B/)); await sleep(500)
say('6 face', fs(await face(page)))
say('6 credits after switch (issued unchanged)', crS(await cr(page)))
await go(page, 'editsched')
say('6 B earn', await earnRead(page, [ranger])); await closeBoard(page)
await shot(page, 'S5-03-planB-published-day')
// replay check
say('7 undo', await undoRedo(page, 'undo'))
say('7 after undo', fs(await face(page))); say('7 earn', await earnRead(page, [ranger])); await closeBoard(page)
say('7 credits after undo', crS(await cr(page)))
await go(page, 'editsched')
