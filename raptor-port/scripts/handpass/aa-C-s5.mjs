// issue the selected plan (B, Ranger denied)
say('8 issue Plan B as AL1', await pubSat(page, 5)); await closeBoard(page)
say('8 face', fs(await face(page)))
say('8 credits after AL1 (Ranger 0, others HO expected)', crS(await cr(page)))
await shot(page, 'S5-04-final-credits')
say('errors', w.errors)
await w.browser.close()
