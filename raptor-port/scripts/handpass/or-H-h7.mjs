import { launch, open, fileInput, openFromList, describeWin, shot, WIN, toastMark, toastsSince, save, errs, as, badgeText, bellRead } from './or-H-lib.mjs'
const out = {}
const log = (k, v) => { out[k] = v; console.log('## ' + k + ' ' + JSON.stringify(v)) }
const browser = await launch()
const { ctx, page } = await open(browser)
const who = iid => page.evaluate(i => { const r = window.INPUTS.find(x => x.iid === i); return r ? { people: r.people.map(e => (window.PEOPLE[e.p]?.cs || e.p)), by: window.PEOPLE[r.by]?.cs, type: r.type, date: r.date } : null }, iid)
await as(page, 'Ranger')
const r = await fileInput(page, { type: 'Meeting', people: ['Tally', 'Hex'], from: '2026-07-15', to: '2026-07-15', timed: ['13:00', '14:00'], title: 'Gear check' })
const iid = r[0].iid
log('filed', await who(iid))
await as(page, 'Saber')
await page.evaluate(() => window.go('inputs')); await page.waitForTimeout(300)
await page.locator('#inGear').click(); await page.waitForTimeout(300)
log('switch-before', await page.locator('[data-testid="iset-memberfile"]').isChecked())
await page.locator('[data-testid="iset-memberfile"]').uncheck(); await page.waitForTimeout(200)
await shot(page, 'H7-1-switch-off')
const m = await toastMark(page)
await page.locator('[data-testid="win-inputsset"] button', { hasText: /^Save$/ }).click(); await page.waitForTimeout(500)
log('switch-saved', { toast: await toastsSince(page, m), win: await page.locator('[data-testid="win-inputsset"]').count() })
await as(page, 'Ranger')
await openFromList(page, iid)
const d = await describeWin(page)
log('ranger-window', { fields: d.fields.map(f => f.id + '=' + f.value), buttons: d.buttons.map(b => b.id + ':' + b.text).filter(t => t.length > 4), picker: d.picker, tail: d.text.slice(-300) })
await shot(page, 'H7-2-ranger-window')
await page.locator(`${WIN} .win-body, ${WIN}`).first().evaluate(w => { const b = w.querySelector('[class*=body]') || w; b.scrollTop = b.scrollHeight })
await shot(page, 'H7-3-ranger-window-bottom')
const tl = page.locator('#inpEditOwnTitle'); const tv = await tl.inputValue().catch(() => null)
await tl.click({ force: true }).catch(() => {}); await page.keyboard.type('ZZ')
log('typed', { before: tv, after: await tl.inputValue().catch(() => null) })
log('save-button', await page.locator('#inpEditSave').count())
log('takeout-button', await page.locator('[data-testid="inped-takeout"]').count())
await page.locator('#inpEditCancel').click().catch(() => {})
/* can Ranger still file for others? */
await page.evaluate(() => window.go('inputs')); await page.waitForTimeout(300)
await page.locator('#inNew').click(); await page.locator(WIN).waitFor()
const nd = await describeWin(page)
log('new-window-as-ranger', { several: nd.buttons.filter(b => b.id === 'pp-several').length, text: nd.text.slice(0, 260) })
await shot(page, 'H7-4-new-window')
log('errors', errs)
save('H7', out)
await browser.close()
