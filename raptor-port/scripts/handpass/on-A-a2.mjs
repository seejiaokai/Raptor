import { world, usualSat, groundNow, oilOf, drag, puckSel, rowSel, frameBoard, flashing, toast, toastsAll, undoState, undoPress, measure, bellLit, bellText, liveBell, toMonth, openDay, closeDay, SAT_DI, SAT, URL } from './on-A-lib.mjs'
const W = await world({ tag: 'A2', fresh: false })
const { page, tid, press, shot, errors } = W
const readCards = async () => {
  await toMonth(W); await openDay(W, SAT)
  const c = await page.evaluate(() => [...document.querySelectorAll('[data-testid="win-inputsday"] .icard')].map(e => e.innerText.replace(/\s+/g, ' ').trim()))
  const cell = await page.evaluate(iso => (document.querySelector(`[data-icday="${iso}"]`) || {}).innerText, '2026-07-18')
  return { cards: c, cell: (cell || '').replace(/\s+/g, ' ') }
}
const iid = await usualSat(W)
const before = await groundNow(page)
const oil0 = await oilOf(page, iid)
await frameBoard(page)
const undo0 = await undoState(page)
await drag(page, page.locator(puckSel(1)), page.locator(puckSel(0)))
console.log('Q1', await tid('oilconf-lead').innerText().catch(() => 'NO'))
await press(tid('oilconf-cancel')); await page.waitForTimeout(300)
console.log('bar', await tid('oilbar-text').innerText().catch(() => 'NO'))
await press(tid('oilbar-answer')); await page.waitForTimeout(300)
console.log('bar gone, question back', await tid('oilbar').count(), await tid('oilconf').count(), await tid('oilconf-lead').innerText().catch(() => 'NO'), 'swapDisabled', await tid('oilconf-save').isDisabled())
await shot('A2-1-question-again')
await press(tid('oil-yes'))
console.log('yes text', await tid('oil-yes').innerText(), 'swap enabled', !(await tid('oilconf-save').isDisabled()))
await press(tid('oilconf-save')); await page.waitForTimeout(150)
console.log('flash after swap', JSON.stringify(await flashing(page, [puckSel(0), puckSel(1)])))
await shot('A2-2-after-swap-flash')
await page.waitForTimeout(500)
console.log('toast', await toast(page), '| all toasts', JSON.stringify(await toastsAll(page)))
console.log('ground', JSON.stringify(await groundNow(page)), 'oil', await oilOf(page, iid), 'bar/question', await tid('oilbar').count(), await tid('oilconf').count(), 'undo changed', (await undoState(page)) !== undo0)
await frameBoard(page)
await shot('A2-3-swapped')
// Earn mode
await page.locator('#sbOil').click(); await page.waitForTimeout(800)
const oilp = await page.evaluate(() => [...document.querySelectorAll('#schedBoard [data-oilp]')].filter(e => e.offsetParent !== null).map(e => ({ who: window.PEOPLE[e.dataset.oilp]?.cs, item: e.dataset.oilitem, txt: e.innerText.replace(/\s+/g, ' '), on: e.classList.contains('on') })))
console.log('OIL EARN', JSON.stringify(oilp))
await shot('A2-4-oilearn')
await page.locator('#sbOil').click(); await page.waitForTimeout(500)
// card
console.log('CARDS after swap', JSON.stringify(await readCards()))
await shot('A2-5-card-after-swap')
await closeDay(W)
// back to board for Undo
await page.evaluate(() => window.go('editsched')); await page.waitForTimeout(500)
await page.locator(`#eWeek [data-sbday="${SAT_DI}"]`).first().evaluate(e => { e.scrollIntoView({ block: 'center', inline: 'center' }); e.click() }); await page.waitForSelector('#sbBoard .sb-sec', { state: 'attached' }); await page.waitForTimeout(500)
console.log('UNDO', await undoPress(W, 'undo'))
console.log('after undo ground', JSON.stringify(await groundNow(page)), 'oil', await oilOf(page, iid), 'matches before', JSON.stringify(await groundNow(page)) === JSON.stringify(before), (await oilOf(page, iid)) === oil0)
console.log('toast', await toast(page))
await frameBoard(page); await shot('A2-6-undone')
