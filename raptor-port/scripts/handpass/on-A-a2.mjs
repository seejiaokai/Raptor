await page.reload(); await page.waitForSelector('#vWeek .day, #loginForm', { state: 'attached' }); await page.waitForTimeout(500)
if (await page.locator('#loginForm').isVisible().catch(() => false)) { await page.fill('#luser', 'ad'); await page.fill('#lpass', 'a'); await page.click('#loginForm button[type=submit]'); await page.waitForSelector('#vWeek .day', { state: 'attached' }); await page.waitForTimeout(500) }
console.log('after reload ground', JSON.stringify(await groundNow(page)), 'oil', await oilOf(page, iid))
await page.addStyleTag({ content: '*{scroll-behavior:auto !important}' })
console.log('CARDS after reload', JSON.stringify(await readCards()))
await shot('A2-8-reload-card')
console.log('errors', JSON.stringify(errors))
await W.ctx.close(); process.exit(0)
