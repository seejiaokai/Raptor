import { open, go, version, tapBox, bringLow } from './kbs-A-lib.mjs'
version('a12c-2')
const { browser, page } = await open()
await go(page, 'quals')
await tapBox(page, page.locator('#qEdit')); await page.waitForTimeout(800)
const cell = page.locator('#page-quals input.qinit:not(.qflt)').nth(20)
await bringLow(cell, 800)
await tapBox(page, cell); await page.waitForTimeout(500)
await page.evaluate(() => { window.__box = document.activeElement })
await page.evaluate(() => window.scrollBy(0, 40)); await page.waitForTimeout(500)
console.log('focused, scrollBy 40: connected?', await page.evaluate(() => window.__box.isConnected), 'active', await page.evaluate(() => document.activeElement.tagName))
await page.evaluate(() => { window.__box.focus(); })
console.log('refocus ok', await page.evaluate(() => document.activeElement === window.__box))
await page.evaluate(() => { const v = window.__vv; v.height = innerHeight - 336; v.dispatchEvent(new Event('resize')) })
await page.waitForTimeout(600)
console.log('keys up with focus: connected?', await page.evaluate(() => window.__box.isConnected))
await browser.close()
