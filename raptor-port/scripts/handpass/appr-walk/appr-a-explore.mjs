import * as C from './appr-a-common.mjs'
console.log('[appr-a-explore v1]')
C.initLog('appr-a-explore-log.txt')
const { browser, page } = await C.launchReal125({ w: 1550, h: 917 })
const errs = []; C.watchErrors(page, errs)
const n = await C.stageWorld(page)
C.note('lines ' + n)
C.note(JSON.stringify(await C.geo(page)))
C.note(JSON.stringify(await C.counts(page)))
const ids = await C.lineIds(page)
C.note(ids.join(','))
const html = await page.evaluate(sel => {
  const l = document.querySelector(`${sel} [data-testid^="appr-line-"]`)
  return l.outerHTML.slice(0, 3000)
}, C.PAGE)
C.note(html)
const head = await page.evaluate(sel => document.querySelector(`${sel} .appr-head`)?.outerHTML.slice(0, 2500), C.PAGE)
C.note(head)
for (const id of ids.slice(0, 19)) C.note(JSON.stringify(await C.lineInfo(page, id)) + ' ' + await page.evaluate(([s, id]) => document.querySelector(`${s} [data-testid="${id}"]`).innerText.replace(/\s+/g, ' ').slice(0, 140), [C.PAGE, id]))
await C.shot(page, 'explore-top')
C.note('errors ' + JSON.stringify(errs))
await Promise.race([browser.close(), C.sleep(8000)])
process.exit(0)
