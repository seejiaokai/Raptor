/* wwf w1 scenario 1 — cold Monday across the week boundary. usage (from raptor-port/): [RUN=x] node scripts/handpass/wwf/wwf-w1-s01.mjs */
import * as H from './wwf-w1-lib.mjs'
const X = await H.init(process.env.RUN || 's01', process.env.PHONE === '1')
const { say, sleep, row, pic } = X
const w = await X.open({ phone: process.env.PHONE === '1' })
const { page } = w
const SZ = process.env.PHONE === '1' ? 'phone' : 'desktop'
const crewOf = ls => ls.filter(l => H.crew(l))
const S = 'S1'
await H.gotoWeek(X, w, H.SUNDAY_WK, 'editsched')
const d = await H.makeDesk(X, w, 6, { tpl: 'sc', str: '20:00', end: '', people: ['bane', 'freak'] })
say('desk made', JSON.stringify(d.r))
await X.closeBoard(w)
await pic(w, '01-sunday-week-desk')
await H.gotoWeek(X, w, H.MONDAY_WK, 'editsched')
await X.board(w, 0)
const wi = await H.flight2(X, w, 0, { to: '10:20', ld: '11:20', br: '08:00', front: 'bane', rear: 'freak' })
const wi2 = await H.flight2(X, w, 0, { to: '06:00', ld: '07:00', br: '06:00', front: null, rear: null })
await X.closeBoard(w)
await pic(w, '02-monday-built')
// ---- COLD: reload, open Monday directly
await H.reload(X, w)
say('after reload week', await page.evaluate(() => document.querySelector('.wk.on')?.dataset.wk))
await H.gotoWeek(X, w, H.MONDAY_WK, 'editsched')
const asrt = await page.evaluate(() => { const f = window.DAYS[0].waves[0].formations[0]; return window.PEOPLE[f.aircraft[0].p]?.cs + '/' + window.PEOPLE[f.aircraft[0].w]?.cs + ' br=' + f.br + ' to=' + f.to })
say('Monday after reload', asrt)
let ww = await X.weekWarn(w, '#eWeek', 0)
say('COLD Monday strip', ww.head, JSON.stringify(ww.items))
await pic(w, '03-cold-monday-strip')
let dd = await X.dayDetails(w, '#eWeek', 0)
say('COLD Monday day details', JSON.stringify(dd))
await pic(w, '04-cold-monday-daydetails')
await X.closeDayPop(w, 'done')
row(S, SZ, 'Sunday desk START 20:00, END blank, Ranger + Echo; Monday flight B 08:00 TO 10:20; reload; open Monday cold', 'no crew-rest line for Ranger or Echo (blank END contributes no ending)', 'strip: ' + ww.head + ' | crew lines: ' + JSON.stringify(crewOf(ww.items)) + ' | details crew lines: ' + JSON.stringify(crewOf(dd.items)) + ' | fixture ' + asrt, crewOf(ww.items).length === 0 && crewOf(dd.items || []).length === 0 ? 'PASS' : 'FAIL', 'w1/s01/03-cold-monday-strip.png')
// picker cold
let pk = await H.pickerRead(X, w, 0, `[data-slot="0.${wi2}.0.0.p"]`, ['bane', 'rocky'], 'cold-p-')
const pkw = await H.pickerRead(X, w, 0, `[data-slot="0.${wi2}.0.0.w"]`, ['freak', 'rocky'], 'cold-w-')
say('COLD picker rear', JSON.stringify(pkw))
say('COLD picker', JSON.stringify(pk))
// ---- warm: visit Sunday week, read Sunday trace, back to Monday
await H.gotoWeek(X, w, H.SUNDAY_WK, 'editsched')
let tr = await X.trace(w, '#eWeek', 6, 'bane')
say('Sunday forward trace blank END', JSON.stringify(tr))
await pic(w, '05-sunday-trace-blank')
const peek = await page.evaluate(() => { const e = document.querySelector('#eWeek [class*=peek]'); return e ? { cls: e.className, text: e.innerText.replace(/\s+/g, ' ').slice(0, 300), witems: e.querySelectorAll('.witem,.wtr,.warn').length } : null })
say('peek', JSON.stringify(peek))
await H.gotoWeek(X, w, H.MONDAY_WK, 'editsched')
ww = await X.weekWarn(w, '#eWeek', 0)
say('WARM Monday strip', ww.head, JSON.stringify(ww.items))
row(S, SZ, 'visit Sunday week, return to Monday (warm)', 'same as cold: no crew-rest line', 'crew lines: ' + JSON.stringify(crewOf(ww.items)), crewOf(ww.items).length === 0 ? 'PASS' : 'FAIL', 'w1/s01/05-sunday-trace-blank.png')
// ---- type END 23:00
await H.gotoWeek(X, w, H.SUNDAY_WK, 'editsched')
await H.setEnd(X, w, 6, d.wi, 0, '23:00')
await X.closeBoard(w)
tr = await X.trace(w, '#eWeek', 6, 'bane')
say('Sunday forward trace END 23:00 (Ranger)', JSON.stringify(tr))
await pic(w, '06-sunday-trace-2300')
const tr2 = await X.trace(w, '#eWeek', 6, 'freak')
say('Sunday forward trace END 23:00 (Echo)', JSON.stringify(tr2))
row(S, SZ, 'type Sunday END 23:00; tap Ranger puck on Sunday', 'forward mark: Breaks Monday (clear 11:00)', 'Ranger trace ' + JSON.stringify(tr.items) + ' | Echo trace ' + JSON.stringify(tr2.items), tr.items.length ? 'PASS' : 'FAIL', 'w1/s01/06-sunday-trace-2300.png')
await H.gotoWeek(X, w, H.MONDAY_WK, 'editsched')
ww = await X.weekWarn(w, '#eWeek', 0)
say('END2300 Monday strip', ww.head, JSON.stringify(ww.items))
await pic(w, '07-monday-strip-2300')
dd = await X.dayDetails(w, '#eWeek', 0)
say('END2300 Monday details', JSON.stringify(dd))
await pic(w, '08-monday-details-2300')
await X.closeDayPop(w, 'done')
const rb = crewOf(ww.items).filter(l => /Ranger/.test(l)), eb = crewOf(ww.items).filter(l => /Echo/.test(l))
row(S, SZ, 'load Monday after typing END 23:00', 'crew-rest breach for Ranger and Echo: clear 11:00, report 08:00', 'Ranger ' + JSON.stringify(rb) + ' Echo ' + JSON.stringify(eb) + ' details ' + JSON.stringify(crewOf(dd.items || [])), rb.length && eb.length ? 'PASS' : 'FAIL', 'w1/s01/07-monday-strip-2300.png')
pk = await H.pickerRead(X, w, 0, `[data-slot="0.${wi2}.0.0.p"]`, ['bane', 'rocky'], 'e2300-p-')
const pkw2 = await H.pickerRead(X, w, 0, `[data-slot="0.${wi2}.0.0.w"]`, ['freak', 'rocky'], 'e2300-w-')
say('END2300 picker rear', JSON.stringify(pkw2))
say('END2300 picker', JSON.stringify(pk))
// ---- clear END again
await H.gotoWeek(X, w, H.SUNDAY_WK, 'editsched')
await H.setEnd(X, w, 6, d.wi, 0, '')
await X.closeBoard(w)
tr = await X.trace(w, '#eWeek', 6, 'bane')
say('Sunday trace after clearing', JSON.stringify(tr))
await pic(w, '09-sunday-trace-cleared')
await H.gotoWeek(X, w, H.MONDAY_WK, 'editsched')
ww = await X.weekWarn(w, '#eWeek', 0)
say('CLEARED Monday strip', ww.head, JSON.stringify(ww.items))
await pic(w, '10-monday-strip-cleared')
row(S, SZ, 'clear Sunday END again; load Monday', 'crew-rest line gone; Sunday trace gone', 'Monday crew lines ' + JSON.stringify(crewOf(ww.items)) + ' trace ' + JSON.stringify(tr.items), crewOf(ww.items).length === 0 && tr.items.length === 0 ? 'PASS' : 'FAIL', 'w1/s01/10-monday-strip-cleared.png')
await X.fin(w)
