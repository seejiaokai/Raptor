/* wwf w1 scenario 5, second half — plan-switch Undo, day template save/apply, paste a time. */
export async function run({ X, H, w, page, D, N, S, SZ, crewOf, step, blocks, sw, planMenuDump }) {
  const { say, sleep, row, pic } = X
  // ---- plan switch Undo / Redo
  await step('plan switch undo', async () => {
    const before = await page.evaluate(() => document.querySelector('#eWeek [data-planmenu="1"]')?.innerText.replace(/\s+/g, ' '))
    await sw(/Plan A/i, 'undoA')
    const sel1 = await page.evaluate(() => document.querySelector('#eWeek [data-planmenu="1"]')?.innerText.replace(/\s+/g, ' '))
    say('plan switch: before', before, 'after switching to A', sel1, await blocks(D))
    await X.press(w, '#undoBtn'); await sleep(800)
    const sel2 = await page.evaluate(() => document.querySelector('#eWeek [data-planmenu="1"]')?.innerText.replace(/\s+/g, ' '))
    say('after Undo of plan switch', sel2, await blocks(D)); await pic(w, '07b-undo-plan-switch')
    const ww = await X.weekWarn(w, '#eWeek', N); say('Wed strip after plan-switch Undo', ww.head, JSON.stringify(ww.items))
    await X.press(w, '#redoBtn'); await sleep(800)
    const sel3 = await page.evaluate(() => document.querySelector('#eWeek [data-planmenu="1"]')?.innerText.replace(/\s+/g, ' '))
    say('after Redo of plan switch', sel3, await blocks(D)); await pic(w, '07c-redo-plan-switch')
    const ww2 = await X.weekWarn(w, '#eWeek', N); say('Wed strip after plan-switch Redo', ww2.head, JSON.stringify(ww2.items))
    row(S, SZ, 'switch to Plan A, then Undo, then Redo', 'restored behaviour matches the restored END (Undo -> B 22:00 line; Redo -> A no line)', `selector: ${before} -> ${sel1} -> Undo ${sel2} -> Redo ${sel3}; Wed after Undo ${JSON.stringify(crewOf(ww.items))} after Redo ${JSON.stringify(crewOf(ww2.items))}`, 'SEE-LOG', 'w1/s05/07b-undo-plan-switch.png')
  })
  // ---- day template save / apply
  await H.gotoWeek(X, w, H.MONDAY_WK, 'editsched')
  await step('day template', async () => {
    await X.press(w, `#eWeek [data-daytplopen="${D}"]`); await sleep(500)
    await X.press(w, '[data-daytplsave]'); await sleep(700)
    const nm = page.locator('.modal input:visible').first()
    if (await nm.count()) { await nm.fill('SC desk day'); await nm.blur() }
    await pic(w, '12-day-tpl-saved')
    await X.press(w, '.modal-foot .primary'); await sleep(500)
  })
  const TD = 3, TN = 4
  await step('apply template', async () => {
    await X.press(w, `#eWeek [data-daytplopen="${TD}"]`); await sleep(600)
    say('apply menu', await page.evaluate(() => [...document.querySelectorAll('.wm')].filter(e => e.offsetWidth).map(e => [...e.attributes].filter(a => /^data-/.test(a.name)).map(a => a.name + '=' + a.value).join(' ') + '|' + e.innerText.replace(/\s+/g, ' ')).join(' ;; ')))
    await pic(w, '13-apply-menu')
    await page.locator('.wm:visible', { hasText: /SC desk day/i }).first().click(); await sleep(900)
    await pic(w, '14-applied')
    say('Thu after apply', await blocks(TD))
    await X.board(w, TD)
    await pic(w, '15-thu-board-after-apply')
    say('Thu seats', await page.evaluate(() => [...document.querySelectorAll('#schedBoard [data-fill^="d:3."] .puck')].map(e => e.dataset.person).join(',') || 'nobody'))
    const end0 = await page.evaluate(() => window.DAYS[3].dutywaves.map(b => (b.sa || '-') + ':' + b.rows[0].str + '-' + b.rows[0].end).join(' | '))
    say('Thu desk times', end0)
    say('seat Ranger', await X.seat(w, '[data-fill="d:3.0.0.+"]', 'bane'))
    await X.closeBoard(w)
    await X.board(w, TN)
    await H.flight2(X, w, TN, { to: '09:00', ld: '10:00', br: '08:00', front: 'bane', rear: null })
    await X.closeBoard(w)
    let ww = await X.weekWarn(w, '#eWeek', TN); say('Fri strip after template + seated (END as copied)', ww.head, JSON.stringify(ww.items)); await pic(w, '16-fri-strip-copied')
    const copied = crewOf(ww.items)
    // clear END on Thu by typing, then paste valid text, then clear
    await X.board(w, TD)
    await X.typeIn(w, '[data-bfld="dr:3.0.0.end"]', '')
    await X.closeBoard(w)
    ww = await X.weekWarn(w, '#eWeek', TN); say('Fri strip END cleared', ww.head, JSON.stringify(ww.items)); await pic(w, '17-fri-strip-cleared')
    const cleared = crewOf(ww.items)
    await X.board(w, TD)
    const box = page.locator('#schedBoard [data-bfld="dr:3.0.0.end"]:visible').first()
    await box.click(); await page.keyboard.insertText('23:00'); await page.keyboard.press('Enter'); await box.blur(); await sleep(500)
    say('after paste', await page.evaluate(() => window.DAYS[3].dutywaves[0].rows[0].end))
    await X.closeBoard(w)
    ww = await X.weekWarn(w, '#eWeek', TN); say('Fri strip after pasting 23:00', ww.head, JSON.stringify(ww.items)); await pic(w, '18-fri-strip-pasted')
    const pasted = crewOf(ww.items)
    await X.board(w, TD)
    await X.typeIn(w, '[data-bfld="dr:3.0.0.end"]', '')
    await X.closeBoard(w)
    ww = await X.weekWarn(w, '#eWeek', TN); const cl2 = crewOf(ww.items)
    row(S, SZ, 'day saved as a template then applied to Thu; re-seat Ranger; Fri flight B 08:00; END as copied / cleared / pasted 23:00 / cleared', 'identity kept: cleared -> none; pasted 23:00 -> a line; cleared again -> none', `copied(END as saved): ${JSON.stringify(copied)} | cleared: ${JSON.stringify(cleared)} | pasted: ${JSON.stringify(pasted)} | cleared again: ${JSON.stringify(cl2)}`, !cleared.length && pasted.length && !cl2.length ? 'PASS' : 'FAIL', 'w1/s05/18-fri-strip-pasted.png')
  })
  // ---- View-only Sched's saved-plan selector (never-published day): RECORD day details
  await step('view-only plan preview', async () => {
    await H.gotoWeek(X, w, H.MONDAY_WK, 'viewsched')
    await page.evaluate(d => document.querySelector(`#vWeek .day[data-day="${d}"]`)?.scrollIntoView({ inline: 'center' }), D); await sleep(400)
    const sel = page.locator(`#vWeek select[data-dver="${D}"]`).first()
    say('view-only plan select', await sel.count(), await sel.evaluate(e => [...e.options].map(o => o.value + ':' + o.text + (o.selected ? '*' : '')).join(' | ')).catch(() => 'none'))
    await pic(w, '19-viewonly-week')
    const opts = await sel.evaluate(e => [...e.options].filter(o => !o.selected).map(o => o.value))
    say('inactive option', JSON.stringify(opts))
    await sel.selectOption(opts[0]); await sleep(900)
    await pic(w, '21-viewonly-plan-preview')
    const dd = await X.dayDetails(w, '#vWeek', D); say('view-only inactive-plan day details', JSON.stringify(dd)); await pic(w, '22-viewonly-plan-details'); await X.closeDayPop(w, 'done')
    const txt = await page.evaluate(d => document.querySelector(`#vWeek .day[data-day="${d}"]`)?.innerText.replace(/\s+/g, ' ').slice(0, 600), D); say('view-only plan preview text', txt)
    const ww = await X.weekWarn(w, '#vWeek', D); say('view-only preview strip', ww.head, JSON.stringify(ww.items))
    row(S, SZ, 'View-only Sched: preview an inactive saved plan of Tue 28 Jul (never published)', 'RECORD (flag-free preview; day details text recorded)', `strip: ${ww.head} items ${JSON.stringify(ww.items)} | details ${JSON.stringify(dd.items)}`, 'RECORDED', 'w1/s05/21-viewonly-plan-preview.png')
  })
}
