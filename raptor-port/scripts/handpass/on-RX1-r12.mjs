import * as L from './on-RX1-lib.mjs'
const W = await L.world({ tag: 'R12' })
const { page, tid, shot, press } = W
const J = o => JSON.stringify(o)
const saber = await L.idOf(page, 'Saber')
const ids = []
ids.push(await L.fileIt(W, L.FRI, { type: 'Training', people: ['bane', 'nick'], from: '09:00', to: '12:00', title: 'Range brief' }))
ids.push(await L.fileIt(W, L.FRI, { type: 'Duty', people: [saber], title: 'Gate duty' }))
ids.push(await L.fileIt(W, L.FRI, { type: 'Meeting', people: ['mamba'], from: '14:00', to: '15:00', title: 'Safety board' }))
console.log('filed', J(ids), 'Saber id', saber, J(await Promise.all(ids.map(i => L.recOf(page, i)))))
console.log('holiday', J(await L.makeHoliday(W, L.FRI, 'National Day', { later: true })))
await page.evaluate(() => window.go('inputs')); await page.waitForTimeout(500)
console.log('bell, admin view', J(await L.liveBell(page)), J(await L.bellLines(W, false)))
await W.hush(); await shot('RX1-12-1-admin-bell'); await W.unhush()
await L.clickBell(W)  // close it
const chip = () => page.locator('button, a, span, div').filter({ hasText: /^SABER\s*·\s*(ADMIN|MEMBER)$/i }).locator('visible=true').last()
console.log('chip text', await chip().innerText().catch(() => 'NOT FOUND'))
await chip().click(); await page.waitForTimeout(800)
console.log('chip text after press', await chip().innerText().catch(() => 'NOT FOUND'), 'role', await page.evaluate(() => (window.ROLE || window.role || '')))
console.log('bell, member view', J(await L.liveBell(page)))
await W.hush(); await shot('RX1-12-2-member-view'); await W.unhush()
await L.clickBell(W)
await page.waitForTimeout(600)
const lines = await page.evaluate(() => { const l = document.querySelector('[data-testid="bell-list"]'); return l ? [...l.querySelectorAll('.bl-line')].map(x => x.innerText.replace(/s+/g, ' ').trim()) : null })
console.log('member view: after ONE tap on the bell: bell list', J(lines), 'question', await tid('oilconf').count(), 'lead', await tid('oilconf-lead').innerText().catch(() => ''), 'head', await page.locator('[data-testid="oilconf"] .airpop-head b').innerText().catch(() => ''), 'one-list window', await tid('win-oilday').count(), 'input window', await page.locator('#inpEditPop:not([hidden])').count())
await W.hush(); await shot('RX1-12-3-member-tap-bell'); await W.unhush()
if (await tid('oilconf').count()) { await press(tid('oilconf-cancel')); await page.waitForTimeout(500) }
if (await tid('bell-list').count()) await L.clickBell(W)
await page.keyboard.press('Escape'); await page.waitForTimeout(300)
console.log('after closing: question', await tid('oilconf').count(), 'bell list', await tid('bell-list').count(), 'bell', J(await L.liveBell(page)), 'chip', await chip().innerText().catch(() => 'NOT FOUND'))
await chip().click(); await page.waitForTimeout(800)
console.log('chip text after second press', await chip().innerText().catch(() => 'NOT FOUND'))
console.log('bell, back to admin', J(await L.liveBell(page)))
const adminLines = await L.bellLines(W, false)
console.log('admin again bell lines', J(adminLines))
await W.hush(); await shot('RX1-12-4-admin-again'); await W.unhush()
console.log('errors', J(W.errors))
await W.ctx.close(); process.exit(0)
