import { open, go, version, shot, tapBox, bringLow, scenario, keysUp, keysDown, state, record } from './kbs-A-lib.mjs'
version('a10')
const { browser, page, errors } = await open()
await go(page, 'admin')
await page.evaluate(() => document.getElementById('admWaveTpl').click()); await page.waitForTimeout(900)
await tapBox(page, page.getByRole('button', { name: '+ New wave template' })); await page.waitForTimeout(700)
const addLine = page.getByRole('button', { name: /\+ Add line/i })
console.log('add line buttons', await addLine.count())
for (let i = 0; i < 3; i++) { const b = addLine.first(); await bringLow(b, 500).catch(() => {}); await tapBox(page, b); await page.waitForTimeout(400) }
await shot(page, 'A10-lines')
const geo = () => page.evaluate(() => { const box = document.querySelector('#waveTplModal').firstElementChild; const r = box.getBoundingClientRect(); const t = [...box.querySelectorAll('*')].find(x => x.children.length === 0 && /Wave templates/i.test(x.textContent)); const tr = t && t.getBoundingClientRect(); return { box: [Math.round(r.top), Math.round(r.bottom)], tr: box.style.translate, st: box.scrollTop, max: box.scrollHeight - box.clientHeight, title: tr && [Math.round(tr.top), Math.round(tr.bottom)] } })
const last = page.locator('#waveTplModal input.tm[placeholder=LD]').last()
console.log('geo start', JSON.stringify(await geo()))
const o = await scenario(page, 'A10', last, { what: 'Wave templates: last line LD box', inWindow: true, keepUp: true })
const gUp = await geo(); console.log('geo up', JSON.stringify(gUp))
await keysDown(page)
const gDn = await geo(); const sDn = await state(page, await last.elementHandle())
await shot(page, 'A10-3-down')
record({ id: 'A10-down', what: 'A10 keys down', geoUp: gUp, geoDown: gDn, endRect: sDn.rect, summary: 'A10 keys down: geo ' + JSON.stringify(gDn) + ' LD rect ' + JSON.stringify(sDn.rect) + ' (while up: ' + JSON.stringify(gUp) + ')' })
console.log('errors', errors)
await browser.close()
