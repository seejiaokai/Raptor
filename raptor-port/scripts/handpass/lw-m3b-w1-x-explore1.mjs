// exploration only (no verdicts): how the bid window reads, which testids exist, where the fixture lands
const M = await import('./lw-m3b-w1-lib.mjs')
const { L, T } = M
const w = await M.start('phone')
const P = w.page
console.log('bundle:', await M.scriptCheck(w))
const ids = await M.ids(P)
console.log('ids', JSON.stringify(ids).slice(0, 400))
const iso = '2026-11-10'
await L.reachCell(w, 'bane', iso)
await L.openCellR(w, 'bane', iso)
await P.waitForSelector(T('bid-picker'), { timeout: 5000 })
console.log('window:', await L.txt(P, T('bid-picker')))
console.log('tids:', JSON.stringify(await P.evaluate(() => [...document.querySelector('[data-testid="bid-picker"]').querySelectorAll('[data-testid]')].map(e => e.dataset.testid))))
console.log('tick:', await P.locator(T('bid-approve-tick')).getAttribute('aria-checked'))
await M.setSwitch(w, false)
console.log('tick after:', await P.locator(T('bid-approve-tick')).getAttribute('aria-checked'))
await M.settled(w, 'x-explore-bidwin')
const ok = await L.placeLeave(w, 'LL')
console.log('placed', ok)
console.log('cell', JSON.stringify(await M.cellWords(P, 'bane', iso)))
await L.openCellR(w, 'bane', iso)
await P.waitForTimeout(500)
console.log('window2:', await L.txt(P, '[role=dialog], .bidsheet') )
console.log('dump:', JSON.stringify(await L.sheetDump(P)).slice(0, 1500))
console.log('decide:', JSON.stringify(await M.btnState(P, ['decide-approve', 'decide-refuse', 'bid-LL', 'bid-OL', 'bid-clear'])))
await M.settled(w, 'x-explore-bidwin2')
console.log('errs', w.errs)
await w.ctx.close(); await M.closeBrowser()
