// E1a — Event row, "PH" preset, "This day", Fri 17 Jul; three inputs on Fri 17; Warden second admin
import { launch, session, lw, ON_FRI, FRI, addRow } from './on-E-lib.mjs'
const browser = await launch()
await session(browser, 'E1a', async s => {
  const { page, press, say, shot, tid, measure, bell, openBell, closeBell, inputsOf } = s
  say('Warden has an admin sign-in', await s.giveWarden())
  const ids = []
  for (const spec of ON_FRI) ids.push(await s.fileIt(FRI, spec))
  say('filed', ids)
  const war = lw(page)
  await war.go('JUL')
  await war.openEventSheet(0, FRI)
  say('sheet open', await tid('event-sheet').count())
  await shot('1-sheet')
  const chips = await page.evaluate(() => [...document.querySelectorAll('[data-testid^="event-quick-"]')].map(b => [b.dataset.testid, b.textContent]))
  say('presets', chips)
  const ph = chips.find(c => c[1] === 'PH')
  await press(page.locator(`[data-testid="${ph[0]}"]`))
  say('readout', await tid('event-readout').innerText())
  say('scope', await page.evaluate(() => [...document.querySelectorAll('[data-testid^="event-scope-"]')].map(b => b.dataset.testid + ':' + b.className)))
  await press(tid('event-scope-day'))
  await shot('2-ph-picked')
  say('before save: list up?', await tid('win-oilday').count())
  await press(tid('event-apply'))
  await page.waitForTimeout(900)
  say('list up on the Leave War page?', await tid('win-oilday').count())
  say('current page', await page.evaluate(() => window.CURPAGE))
  const win = tid('win-oilday')
  if (await win.count()) {
    say('title', (await win.locator('.win-ttl').innerText()).replace(/\s+/g, ' '))
    say('lead', await tid('odl-lead').innerText().catch(() => ''))
    say('count', await tid('odl-count').innerText())
    say('cards', await win.locator('.icard').count())
    say('left', await tid('odl-left').innerText())
    say('save disabled', await tid('odl-save').isDisabled())
    say('measure list', await measure('[data-testid="win-oilday"]'))
    await shot('3-list-over-leavewar')
    await press(tid('odl-later')); await page.waitForTimeout(400)
    say('list gone after Later', await tid('win-oilday').count() === 0)
  }
  say('oil after Later', await inputsOf(ids))
  await shot('4-after-later')
  say('Saber bell (Leave War page)', await bell())
  await openBell()
  say('Saber bell list', await bell())
  await shot('5-saber-bell')
  await closeBell()
  await page.evaluate(() => window.raptorMe('nact')); await page.waitForTimeout(500)
  say('Warden bell lit', await bell())
  await openBell()
  say('Warden bell list', await bell())
  await shot('6-warden-bell')
  addRow({ id: 'E1a-data', ids })
})
await browser.close()
