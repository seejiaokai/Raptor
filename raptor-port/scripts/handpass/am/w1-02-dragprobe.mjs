/* w1 — diagnose a wave drag on the phone board (a driver check, not a scenario): does the press lift the
   wave (.rowdrag), does the pointer over the target light it (.rowdrop), what is under the pointer. */
process.env.HP_SHOTS = 'C:/Users/User/projects/Raptor/raptor-port/docs/img/handpass/2026-09-24-amendment/w1'
const L = await import('./w1-lib.mjs')
const { open, editWeek, board, STATE, WIDTHS, shot } = L
const w = process.argv[2] || 'phone'
const { browser, page, errors } = await open({ ...WIDTHS[w], state: STATE })
await editWeek(page)
await board(page, 3)
const grip = page.locator('#schedBoard .sb-go[data-move="mv:w.3.0"] .wvgrip:visible').first()
const tgt = page.locator('#schedBoard .sb-go[data-move="mv:w.3.1"] .sb-go-h:visible').first()
console.log('grip count', await grip.count(), 'target count', await tgt.count())
await grip.evaluate(e => e.scrollIntoView({ block: 'start' }))
await page.waitForTimeout(300)
const g = await grip.boundingBox(), t = await tgt.boundingBox()
console.log('grip box', g, 'target box', t, 'viewport', page.viewportSize())
const under = (x, y) => page.evaluate(([x, y]) => { const e = document.elementFromPoint(x, y); return e ? `${e.tagName}.${e.className}`.slice(0, 80) + ' in ' + (e.closest('[data-move]') || {}).dataset?.move : 'nothing' }, [x, y])
console.log('under grip', await under(g.x + g.width / 2, g.y + g.height / 2))
await page.mouse.move(g.x + g.width / 2, g.y + g.height / 2)
await page.mouse.down()
await page.waitForTimeout(200)
console.log('lifted?', await page.evaluate(() => [...document.querySelectorAll('.rowdrag')].map(e => e.dataset.move)))
const t2 = await tgt.boundingBox()
console.log('target box after press', t2)
const tx = t2.x + 30, ty = Math.min(t2.y + t2.height / 2, page.viewportSize().height - 60)
console.log('under target point', await under(tx, ty))
await page.mouse.move(tx, ty, { steps: 14 })
await page.waitForTimeout(200)
console.log('drop lit?', await page.evaluate(() => [...document.querySelectorAll('.rowdrop')].map(e => e.dataset.move)))
await shot(page, `dragprobe-${w}`)
await page.mouse.up()
await page.waitForTimeout(600)
console.log('order', await page.evaluate(() => window.DAYS[3].waves.map(x => x.label)))
console.log('errors', errors)
await browser.close()
