// Re-walk A1 — visits (the save-on-open fix, D1430). Run from raptor-port/.
process.env.LW_OUT ||= '../../docs/img/handpass/2026-10-27-lw-m4/rewalk/a'
const { L, placeBid, headerText } = await import('./lw-m4-walk-a-lib.mjs')
const { T, rec, shot, press, vis, txt } = L
console.log('[lw-m4-rw-a1 v1]')
const w = await L.newCtx('desk')
const P = w.page
const newInfo = () => P.evaluate(() => {
  const n = document.querySelector('[data-testid="appr-new"]')
  return n ? { text: n.innerText.replace(/\s+/g, ' ').trim(), html: n.outerHTML.slice(0, 400), dot: !!n.querySelector('.appr-dot:not(.none)') } : null
})
const sub = () => txt(P, T('appr-sub'))
try {
  await L.signIn(w, 'admin')
  await L.openApprovals(w)
  const s0 = await sub(); const n0 = await newInfo()
  console.log('first open sub:', s0, '| new:', JSON.stringify(n0))
  await shot(w, 'a1-1-first-open')
  rec('A1.1 fresh world, first open: no "since" words', 'desk', s0 && !/since/i.test(s0) ? 'PASS' : 'FAIL', `sub="${s0}" new=${JSON.stringify(n0 && n0.text)}`, ['a1-1-first-open'])
  await L.openGrid(w)
  await L.switchTo(w, 'member')
  const ok = await placeBid(w, 'bane', '2026-01-13')
  rec('A1.2a member placed Jan 13', 'desk', ok ? 'PASS' : 'NOT WALKED', 'bid window closed after LL')
  await L.switchTo(w, 'admin')
  await L.openApprovals(w)
  const s1 = await sub(); const n1 = await newInfo()
  console.log('after bid sub:', s1, '| new:', JSON.stringify(n1))
  await shot(w, 'a1-2-after-bid')
  rec('A1.2 after member bid: "1 new since you last looked, <when>", New 1 with dot', 'desk', s1 && /1 new since you last looked/i.test(s1) && n1 && /New\s*1/.test(n1.text) && n1.dot ? 'PASS' : 'FAIL', `sub="${s1}" new=${JSON.stringify(n1 && n1.text)} dot=${n1 && n1.dot}`, ['a1-2-after-bid'])
  await P.reload(); await P.waitForSelector('#luser')
  await L.signIn(w, 'admin')
  if (!(await vis(P, T('approvals-page')))) await L.openApprovals(w)
  const s2 = await sub(); const n2 = await newInfo()
  console.log('after reload sub:', s2, '| new:', JSON.stringify(n2))
  await shot(w, 'a1-3-after-reload')
  rec('A1.3 reload: same words and time', 'desk', s2 === s1 && n2 && n2.text === (n1 && n1.text) ? 'PASS' : 'FAIL', `before="${s1}" after="${s2}" new=${JSON.stringify(n2 && n2.text)}`, ['a1-3-after-reload'])
  await L.openGrid(w)
  await L.openApprovals(w)
  const s3 = await sub(); const n3 = await newInfo()
  console.log('reopen sub:', s3, '| new:', JSON.stringify(n3))
  await shot(w, 'a1-4-reopen')
  rec('A1.4 leave and reopen: New 0, no dot, no "since"', 'desk', s3 && !/since/i.test(s3) && n3 && /New\s*0/.test(n3.text) && !n3.dot ? 'PASS' : 'FAIL', `sub="${s3}" new=${JSON.stringify(n3 && n3.text)} dot=${n3 && n3.dot}`, ['a1-4-reopen'])
  await L.switchTo(w, 'admin')
  await L.openApprovals(w)
  const s4 = await sub(); const n4 = await newInfo()
  console.log('after sign out/in sub:', s4, '| new:', JSON.stringify(n4))
  await shot(w, 'a1-5-signout-in')
  rec('A1.5 sign out and in: still New 0', 'desk', s4 && !/since/i.test(s4) && n4 && /New\s*0/.test(n4.text) && !n4.dot ? 'PASS' : 'FAIL', `sub="${s4}" new=${JSON.stringify(n4 && n4.text)}`, ['a1-5-signout-in'])
} catch (e) {
  rec('ERROR', 'desk', 'FAIL', String(e).slice(0, 300)); await shot(w, 'a1-error').catch(() => {})
}
if (w.errs.length) rec('console', 'desk', 'FAIL', w.errs.join(' || ').slice(0, 600))
await w.ctx.close()
L.writeResults('a1')
await L.closeBrowser()
console.log('DONE')
