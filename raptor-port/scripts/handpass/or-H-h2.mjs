import { launch, open, fileInput, openFromList, describeWin, shot, WIN, toastMark, toastsSince, inputOf, save, errs, as, badgeText, bellRead } from './or-H-lib.mjs'
const out = {}
const log = (k, v) => { out[k] = v; console.log('## ' + k + ' ' + JSON.stringify(v)) }
const browser = await launch()
const { ctx, page } = await open(browser)
const who = iid => page.evaluate(i => { const r = window.INPUTS.find(x => x.iid === i); return r ? { people: r.people.map(e => window.PEOPLE[e.p].cs), by: window.PEOPLE[r.by]?.cs, oil: r.oil, date: r.date } : null }, iid)
await as(page, 'Ranger'); log('badge', await badgeText(page))
const r = await fileInput(page, { type: 'Meeting', people: ['Tally', 'Hex'], from: '2026-07-18', to: '2026-07-18', timed: ['09:00', '10:00'], oil: 'yes' })
log('filed', r)
const iid = r[0].iid
log('inputs-after-file', await who(iid))
await as(page, 'Hex'); log('badge-hex', await badgeText(page))
await openFromList(page, iid)
log('window-hex', await describeWin(page))
await shot(page, 'H2-1-hex-window')
/* can Hex type, or press a puck? */
const dom = await page.evaluate(sel => ['inpEditType', 'inpEditOwnTitle', 'inpEditStart', 'inpEditEnd', 'inpEditRmk'].map(id => { const e = document.querySelector(sel + ' #' + id); if (!e) return id + ': none'; const cs = getComputedStyle(e); const r = e.getBoundingClientRect(); return id + ': tag=' + e.tagName + ' disabled=' + e.disabled + ' readOnly=' + e.readOnly + ' pe=' + cs.pointerEvents + ' box=' + Math.round(r.width) + 'x' + Math.round(r.height) + ' vis=' + cs.visibility + ' opacity=' + cs.opacity }), WIN)
log('hex-field-dom', dom)
const tl = page.locator('#inpEditOwnTitle'); const tv = await tl.inputValue()
await tl.click({ force: true }).catch(() => {}); await page.keyboard.type('ZZ'); 
log('hex-typed-in-title', { before: tv, after: await tl.inputValue() })
const pressedNow = () => page.locator(WIN).evaluate(w => [...w.querySelectorAll('[data-pp][aria-pressed="true"]')].map(b => b.getAttribute('data-pp')).join(','))
const pb = await pressedNow()
const ace = page.locator(`${WIN} [data-pp]`, { hasText: 'Ace' }).first(); log('ace-count', await ace.count())
await ace.click({ force: true }).catch(e => log('ace-click-err', String(e).slice(0, 100))); await page.waitForTimeout(300)
log('hex-pressed-ace', { pressedBefore: pb, pressedAfter: await pressedNow(), pickedText: await page.locator(WIN).evaluate(w => (w.innerText.match(/\d+ picked/) || [''])[0]), inputs: await who(iid) })
const sev = page.locator(`${WIN} [data-testid="pp-several"]`); await sev.click({ force: true }).catch(() => {}); await page.waitForTimeout(250)
log('hex-pressed-several-toggle', { pressedAfter: await pressedNow(), text: await page.locator(WIN).evaluate(w => (w.innerText.match(/[0-9]+ picked/) || [''])[0]) })
const allavail = page.locator(`${WIN} button`, { hasText: /^ALL AVAIL$/ }).first(); await allavail.click({ force: true }).catch(() => {}); await page.waitForTimeout(250)
log('hex-pressed-allavail', { pressedAfter: await pressedNow(), inputs: await who(iid) })
await shot(page, 'H2-1b-after-trying-pickers')
const m = await toastMark(page)
await page.locator(`${WIN} [data-testid="inped-takeout"]`).scrollIntoViewIfNeeded()
await page.locator(`${WIN} [data-testid="inped-takeout"]`).click(); await page.waitForTimeout(500)
log('after-first-press', { toast: await toastsSince(page, m), text: await page.locator(WIN).evaluate(w => w.innerText.replace(/\s+/g, ' ').slice(-400)), buttons: await page.locator(`${WIN} button:visible`).evaluateAll(bs => bs.map(b => (b.id || b.getAttribute('data-testid') || '') + '|' + b.innerText.trim()).filter(x => /take|stay|close/i.test(x))) })
await shot(page, 'H2-2a-confirm')
await page.locator(`${WIN} button:visible`, { hasText: 'Take me out' }).last().click(); await page.waitForTimeout(700)
log('after-take-out', { toast: await toastsSince(page, m), inputs: await who(iid), winOpen: await page.locator(WIN).count() })
await shot(page, 'H2-2-after-take-out')
await as(page, 'Ranger')
log('ranger-bell-after-hex-out', await bellRead(page, { close: false }))
await shot(page, 'H2-3-ranger-bell-open')
await page.locator('#notifyBell').click(); await page.waitForTimeout(250)
await as(page, 'Tally')
log('tally-bell-after-hex-out', await bellRead(page))
await as(page, 'Hex')
log('hex-bell', await bellRead(page))
const u = page.locator('#undoBtn'); log('undo-state', { vis: await u.isVisible(), disabled: await u.isDisabled() })
const m2 = await toastMark(page)
if (!(await u.isDisabled())) { await u.click(); await page.waitForTimeout(700) }
log('after-undo', { toast: await toastsSince(page, m2), inputs: await who(iid) })
await shot(page, 'H2-4-after-undo')
await as(page, 'Ranger')
log('ranger-bell-after-undo', await bellRead(page))
await as(page, 'Tally')
log('tally-bell-after-undo', await bellRead(page))
log('errors', errs)
save('H2', out)
await browser.close()
