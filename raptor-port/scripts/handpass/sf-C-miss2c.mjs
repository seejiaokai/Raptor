import * as L from './sf-C-lib.mjs'
const { launch, ctxOpen, openBoard, closeBoard, bPut, bType, bf, bPublish, sleep, shot, rec, go, errors, chipLine } = L
const S = 'A3'
const b = await launch()
const { p } = await ctxOpen(b, {})
await go(p, 'editsched'); await p.evaluate(() => window.addWave(5, 'sc')); await sleep(500)
await openBoard(p, 5)
await bPut(p, 5, 0, 0, 0, 'p', ['stiff']); await bPut(p, 5, 0, 0, 2, 'p', ['dice'])
await bPublish(p, 5)
await p.locator('#schedBoard [data-safly="5.0.0.2"]:visible').first().click(); await sleep(800)
const chipsOf = (scope) => p.evaluate(sc => { const d = [...document.querySelectorAll(sc + ' .day')][5]; return d ? [...d.querySelectorAll('.sabadges')].map(e => e.innerText.replace(/\s+/g, ' ').trim() + (e.querySelector('button.saflies') ? ' [BUTTON]' : '')) : null }, scope)
// board plans menu -> Original
await p.locator('#schedBoard [data-planmenu="5"]:visible').first().click(); await sleep(500)
await p.locator('.wavemenu [data-planpv]:visible').first().click(); await sleep(1000)
const bo = await p.evaluate(() => [...document.querySelectorAll('#schedBoard .sabadges')].filter(e => e.offsetParent).map(e => e.innerText.replace(/\s+/g, ' ').trim() + (e.querySelector('button.saflies') ? ' [BUTTON]' : '')))
await shot(p, 'A3-1-board-original')
rec(S, "the board looking at the Original (issued, before the tick)", 'chips drawn as issued: all dashed or none; nothing pressable', bo, bo.some(x => /BUTTON/.test(x)) ? 'FAIL' : (bo.some(x => /✓/.test(x)) ? 'FAIL' : 'RECORD'), 'C-A3-1-board-original.png')
await p.locator('#schedBoard [data-planmenu="5"]:visible').first().click(); await sleep(400)
await p.locator('.wavemenu [data-plangolive]:visible').first().click(); await sleep(800)
await closeBoard(p); await go(p, 'editsched')
await p.locator('#eWeek [data-planmenu="5"]:visible').first().click(); await sleep(500)
await p.locator('.wavemenu [data-planpv]:visible').first().click(); await sleep(1000)
const wo = await chipsOf('#eWeek')
await p.locator('#eWeek .day').nth(5).scrollIntoViewIfNeeded(); await sleep(300)
await shot(p, 'A3-2-week-original')
rec(S, 'the edit week looking at the Original', 'drawn as issued', wo, wo && wo.some(x => /BUTTON/.test(x)) ? 'FAIL' : 'RECORD', 'C-A3-2-week-original.png')
await p.locator('#eWeek [data-golive="5"]:visible').first().click().catch(() => {}); await sleep(600)
await go(p, 'viewsched'); await sleep(700)
const opts = await p.evaluate(() => { const s = document.querySelector('#vWeek select[data-dver="5"], #vWeek select[data-vwork="5"]'); return s ? [...s.options].map(o => o.value + '=' + o.text + (o.selected ? '*' : '')) : null })
const v1 = await chipsOf('#vWeek')
const sel = p.locator('#vWeek select[data-dver="5"], #vWeek select[data-vwork="5"]').first()
if (await sel.count()) await sel.selectOption('working').catch(() => {})
await sleep(900)
const v2 = await chipsOf('#vWeek')
await p.locator('#vWeek .day').nth(5).scrollIntoViewIfNeeded(); await sleep(300)
await shot(p, 'A3-3-viewonly-working')
rec(S, 'View-only Sched (admin): issued, then "Working draft"', 'issued: no tick; working draft: lit chip on the ticked row only, no button, no dashed chip', { opts, issued: v1, working: v2 }, (v2 || []).some(x => /BUTTON/.test(x)) ? 'FAIL' : ((v2 || []).some(x => /✓ FLIES/.test(x)) ? 'PASS' : 'RECORD'), 'C-A3-3-viewonly-working.png')
rec(S, 'browser error list', 'empty', errors, errors.length ? 'FAIL' : 'PASS')
await b.close()
