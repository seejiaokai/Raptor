import { launch, ctxOpen, sleep, go, shot, openBoard, addStandby, seat, bf, bType, errors, rec, chips, login, reload } from './sf-A-lib.mjs'
console.log('sf-A-s20c v1 (control: two tabs, two older kinds of edit)')
const b = await launch()
const DI = 5
const { ctx, p: A } = await ctxOpen(b, 's20cA')
const gi = await addStandby(A, DI, 'sc')
await seat(A, DI, gi, [[0, 0], [0, 1], [0, 2], [0, 3]])
await openBoard(A, DI); await sleep(1500)
const B = await ctx.newPage()
await B.goto('http://localhost:4322/'); await sleep(1500); await login(B)
await B.evaluate(() => window.go('editsched')); await sleep(600); await B.evaluate(d => window.openScheduler(d), DI); await B.waitForSelector('#schedBoard'); await sleep(1000)
await A.bringToFront()
const a = bType(A, `#schedBoard [data-bfld="fr:${DI}.${gi}.0.0"]`, 'AAA')
const bb = (async () => { const el = B.locator(bf(DI, gi, 0, 'rl') + ':visible').first(); await el.click(); await B.keyboard.type('0630'); await B.keyboard.press('Enter'); await B.mouse.click(250, 26); await sleep(500) })()
await Promise.all([a, bb]); await sleep(6000)
const read = p => p.evaluate(([d, g]) => { const f = window.DAYS[d].waves[g].formations[0]; return { rl: f.rl || '', rmk: f.aircraft[0].rmks || '' } }, [DI, gi])
console.log('A live', JSON.stringify(await read(A)), 'B live', JSON.stringify(await read(B)))
await reload(A)
console.log('A after reload', JSON.stringify(await read(A)))
console.log('errors', JSON.stringify(errors))
await ctx.close(); await b.close()
