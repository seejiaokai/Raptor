// D6 — OIL Earn by touch
import { open, fileInput, shot, sleep, log, goBoard, errs, browser, press, csId, toastBox, inputsOf, tapCdp, signAndPublish } from './or-D-lib.mjs'
const { ctx, page } = await open()
const f = await fileInput(page, { type: 'Training', people: ['Ranger', 'Tally'], ph: 'allavail', from: '2026-07-18', to: '2026-07-18', timed: ['09:00', '12:00'], title: 'Sat course', oil: 'yes' })
log('D6 filed', JSON.stringify(f))
const PUB = process.argv[2] === 'pub'
if (PUB) log('D6 sign + publish Sat:', JSON.stringify(await signAndPublish(page, 5)))
await goBoard(page, 5)
const b = page.locator('[data-oilmode]:visible').first()
await b.evaluate(e => e.scrollIntoView({ block: 'center' })); await sleep(300); await b.tap(); await sleep(900)
const norm = s => (s || '').replace(/\s+/g, ' ').trim()
const fig = () => page.evaluate(() => { const h = document.querySelector('#schedBoard .sb-ph'); return h ? h.innerText.replace(/\s+/g, ' ').trim() : null })
const boardText = () => page.evaluate(() => document.querySelector('#schedBoard').innerText.split('\n').map(x => x.trim()).filter(Boolean))
const rowSt = () => page.evaluate(() => { const r = [...document.querySelectorAll('#schedBoard .sb-panel.grnd .sb-arow')].find(x => x.offsetParent && /Ranger/.test(x.innerText)); if (!r) return null; return { seats: [...r.querySelectorAll('.seat.oilpk')].map(s => s.getAttribute('data-oilp') + ':' + (s.classList.contains('on') ? 'on' : 'off') + ':' + s.querySelector('.puck').className.replace(/puck |sm /g, '') + ':' + (s.querySelector('.oilamt') ? s.querySelector('.oilamt').innerText : 'no-amt')), count: (r.querySelector('.oilcount') || {}).innerText } })
const row = page.locator('#schedBoard .sb-panel.grnd .sb-arow:visible', { hasText: 'Ranger' }).first()
await row.evaluate(e => e.scrollIntoView({ block: 'center' })); await sleep(400)
const t0 = await boardText()
log('D6 OIL Earn on: day figure =', await fig(), '| row =', JSON.stringify(await rowSt()))
await shot(page, 'D6-01-oil-on')
const tally = row.locator('.seat.oilpk[data-oilp="nick"]')
await tally.tap(); await sleep(700)
const t1 = await boardText()
log('D6 tap on Tally (1): row =', JSON.stringify(await rowSt()), '| day figure =', await fig(), '| note =', (await toastBox(page)).text)
log('D6 board lines that changed with that tap:', JSON.stringify({ gone: t0.filter(x => !t1.includes(x)), came: t1.filter(x => !t0.includes(x)) }))
await shot(page, 'D6-02-tally-off')
await row.evaluate(e => e.scrollIntoView({ block: 'center' })); await sleep(300)
await tally.tap(); await sleep(700)
const t2 = await boardText()
log('D6 tap on Tally (2): row =', JSON.stringify(await rowSt()), '| day figure =', await fig(), '| note =', (await toastBox(page)).text, '| board back as at the start:', JSON.stringify(t2) === JSON.stringify(t0))
await shot(page, 'D6-03-tally-on')
// ALL AVAIL's counter
await row.evaluate(e => e.scrollIntoView({ block: 'center' })); await sleep(300)
await row.locator('.oilcount').tap(); await sleep(900)
await shot(page, 'D6-04-allavail-window')
const win = page.locator('.availwin')
log('D6 the window (by the counter):', JSON.stringify(await win.evaluate(e => { const r = e.getBoundingClientRect(); return { rect: [r.x, r.y, r.width, r.height].map(Math.round), text: e.innerText.replace(/\s+/g, ' ').slice(0, 300), tabs: [...e.querySelectorAll('.win-tab')].map(t => t.className + '|' + t.innerText.replace(/\s+/g, ' ')), pucks: [...e.querySelectorAll('[data-oilp],[data-person]')].length } })))
const tabs = win.locator('.win-tab')
await tabs.nth(0).tap(); await sleep(500)
log('D6 first tab tapped:', JSON.stringify(await tabs.evaluateAll(t => t.map(e => e.className + '|' + e.innerText.replace(/\s+/g, ' ')))))
await tabs.nth(1).tap(); await sleep(500)
log('D6 OIL tab tapped:', JSON.stringify(await tabs.evaluateAll(t => t.map(e => e.className + '|' + e.innerText.replace(/\s+/g, ' ')))))
await shot(page, 'D6-05-oil-tab')
const men = win.locator('.puck')
const nMen = await men.count()
log('D6 men in the OIL tab:', nMen)
const first = men.first()
const who = await first.evaluate(e => e.getAttribute('data-person') + '|' + e.className.toString() + '|' + e.innerText.replace(/\s+/g, ' '))
log('D6 first man:', who)
await first.tap(); await sleep(700)
log('D6 after tapping him: tabs', JSON.stringify(await tabs.evaluateAll(t => t.map(e => e.innerText.replace(/\s+/g, ' ')))), '| him:', await men.first().evaluate(e => e.className.toString() + '|' + e.innerText.replace(/\s+/g, ' ')), '| note =', (await toastBox(page)).text, '| counter on the row =', await page.evaluate(() => (document.querySelector('#schedBoard .oilcount') || {}).innerText), '| row =', JSON.stringify(await rowSt()))
await shot(page, 'D6-06-one-man-off')
await men.first().tap(); await sleep(600)
log('D6 tapped him again: tabs', JSON.stringify(await tabs.evaluateAll(t => t.map(e => e.innerText.replace(/\s+/g, ' ')))), '| him:', await men.first().evaluate(e => e.className.toString()))
log('D6 INPUTS', JSON.stringify(await inputsOf(page, 'Sat course')))
log(errs)
await ctx.close(); await browser.close()
