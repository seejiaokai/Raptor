// RX2-8 (two schedulers at once) — a new world, one page life (people changed in place)
import { launch, world, bye, FRI } from './on-RX2-lib.mjs'
const browser = await launch()
const w = await world(browser, { tag: 'R8' }); const { page, tid } = w
w.say('Warden admin', await w.giveWarden())
const ids = await w.fileFriday()
w.say('filed', ids)
await w.makeHoliday('National Day', FRI)
w.say('list after add', await w.listInfo())
await w.press(tid('odl-later')); await page.waitForTimeout(400)
await w.closeCal()
// as Saber: open the list from the bell, leave it open
await w.openBell()
await w.press(page.locator('[data-testid="bell-list"] .bl-line').first()); await page.waitForTimeout(500)
w.say('Saber list open from the bell', await w.listInfo())
await w.hush(); await w.shot('R8-1-saber-list-four')
// in place as Warden
await w.me('nact')
w.say('list still open after changing person', await w.listInfo())
await w.shot('R8-2-as-warden-list-up')
// open ONE of the inputs (Gate duty) in its own window by tapping the card name
const card = tid('win-oilday').locator('.icard').filter({ hasText: 'Gate duty' }).first()
await w.press(card.locator('b').first()); await page.waitForTimeout(600)
w.say('input window open', await page.locator('#inpEditPop:visible').count())
w.say('pop title', await page.locator('#inpEditPop #inpEditOwnTitle').first().inputValue().catch(() => '?'))
await w.shot('R8-3-warden-input-window')
await w.press(page.locator('#inpEditSave')); await page.waitForTimeout(600)
w.say('oilconf', await tid('oilconf').count())
w.say('oilconf text', (await tid('oilconf').innerText().catch(() => '')).replace(/\s+/g, ' ').slice(0, 200))
await w.shot('R8-4-warden-question')
await w.press(tid('oil-yes')); await w.press(tid('oilconf-save')); await page.waitForTimeout(700)
await page.locator('#inpEditPop').waitFor({ state: 'hidden', timeout: 4000 }).catch(() => w.say('pop still open', ''))
w.say('state after Warden answered', await w.state(ids))
w.say('list as Warden, now', await w.listInfo())
// back as Saber
await w.me('stiff')
w.say('list as Saber, now', await w.listInfo())
await w.hush(); await w.shot('R8-5-saber-list-three')
w.say('Saber bell line now (both bells peek)', await w.bothBells('R8-6-bells-before-save'))
// the list may have been closed by the bells reading; re-open it from Saber's bell if gone
if (!(await tid('win-oilday').count())) { await w.openBell(); const l = page.locator('[data-testid="bell-list"] .bl-line'); if (await l.count()) { await w.press(l.first()); await page.waitForTimeout(500) } w.say('re-opened list as Saber', await w.listInfo()) }
await w.press(tid('odl-yesall'))
w.say('after Yes to all', { count: (await tid('odl-count').innerText()).trim(), left: (await tid('odl-left').innerText()).trim(), saveDisabled: await tid('odl-save').isDisabled() })
await w.hush(); await w.shot('R8-7-yes-to-all')
await w.press(tid('odl-save')); await page.waitForTimeout(700)
w.say('after Save', await w.state(ids))
w.say('oil objects', await page.evaluate(ids => ids.map(i => JSON.stringify((window.INPUTS.find(r => r.iid === i) || {}).oil || null)), ids))
w.say('demo overseas duty oil', await page.evaluate(() => window.INPUTS.filter(r => r.type === 'OD' || /Overseas/i.test(JSON.stringify(r))).map(r => r.iid + ':' + JSON.stringify(r.oil || null))))
w.say('list closed', await tid('win-oilday').count() === 0)
w.say('bells after save', await w.bothBells('R8-8-bells-after'))
w.say('errors', await bye(w))
await browser.close()
