await shot(page, 'D4-08-after-delete')
log('D4 after Delete + confirm: window open', !!(await popInfo(page)), 'note', JSON.stringify(await toastBox(page)), '| inputs named Range brief:', (await inputsOf(page, 'Range brief')).length)
