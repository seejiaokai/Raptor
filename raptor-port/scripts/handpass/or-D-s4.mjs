await swipeIn(page, 200, 600, -450)
pi = await popInfo(page); log('D4 week window after the SECOND swipe', JSON.stringify({ scrollTop: pi.scrollTop, pageY: pi.pageY, save: pi.save, del: pi.del }))
await shot(page, 'D4-03-week-window-bottom')
// change for everyone: the start time
await page.fill('#inpEditStart', '14:30'); await sleep(300)
await press(page.locator('#inpEditSave')); await sleep(900)
log('D4 after ONE tap on Save: window open?', !!(await popInfo(page)), 'note', JSON.stringify(await toastBox(page)))
log('D4 INPUTS', JSON.stringify(await inputsOf(page, 'Range brief')))
