pi = await popInfo(page); log('D4 Delete / Save reachable at the end of the window?', JSON.stringify({ del: pi.del, save: pi.save }))
const question = () => page.evaluate(() => { const p = document.querySelector('#inpEditPop .airpop-box'); const t = p ? p.innerText : ''; const m = t.match(/Delete this input[^?]*\?/); return m ? m[0] : null })
