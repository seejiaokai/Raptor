await row.locator('.nm .ntx').first().tap(); await sleep(600)
log('D4 tap on the Ground row name -> window?', JSON.stringify(await popInfo(page)), '| focus:', await page.evaluate(() => document.activeElement && (document.activeElement.className + ' ' + (document.activeElement.getAttribute('data-txt') || ''))))
await shot(page, 'D4-01-row-name-tap')
await page.evaluate(() => document.activeElement && document.activeElement.blur && document.activeElement.blur())
