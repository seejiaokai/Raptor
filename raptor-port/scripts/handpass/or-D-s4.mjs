await shot(page, 'D4-05-board-line')
await brow.locator('.inpedit').tap(); await sleep(800)
pi = await popInfo(page); log('D4 board: tap on the Personal Inputs line -> window', JSON.stringify({ box: pi.box, pressed: pi.pressed, count: pi.count, start: pi.start, end: pi.end }))
await shot(page, 'D4-06-board-window')
await swipeIn(page, 200, 600, -450); await swipeIn(page, 200, 600, -450)
