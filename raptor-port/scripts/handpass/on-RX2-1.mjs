// RX2-1 (lengthened) and, in the same world, RX2-5 (renamed) — arg: "" for both
import { launch, world, bye, rec, FRI, THU, ON_FRI } from './on-RX2-lib.mjs'
const browser = await launch()
const w = await world(browser, { tag: 'R1' }); const { page, tid } = w
w.say('Warden admin', await w.giveWarden())
const ids = await w.fileFriday()
const thu = await w.fileIt(THU, { type: 'Training', people: ['hex'].filter(Boolean).length ? ['nick'] : ['nick'], from: '10:00', to: '11:00', title: 'Thu brief' })
w.say('filed', { ids, thu })
w.say('Fri/Thu inputs', await page.evaluate(() => window.INPUTS.filter(r => /2026-07-1[67]/.test(JSON.stringify(r))).map(r => `${r.iid}:${r.title || r.type}:${r.d || r.day || ''}:${JSON.stringify(r.oil || null)}`)))
const d0 = await w.makeHoliday('National Day', FRI)
w.say('form dates', d0)
w.say('list after add', await w.listInfo())
await w.hush(); await w.shot('R1-1-list-fri')
await w.press(tid('odl-later')); await page.waitForTimeout(400)
const b1 = await w.bothBells('R1-2-bells-before')
w.say('bells before', b1)
const undo0 = await w.undoInfo(); w.say('undo before', undo0)
// open the holiday on the list and change dates
await w.openHolidays()
await w.shot('R1-3-holidays-list')
w.say('hol lines', await page.locator('.hol-line').evaluateAll(es => es.map(e => e.dataset.from + '|' + (e.dataset.to || '') + '|' + e.innerText.replace(/\s+/g, ' '))))
await w.press(page.locator(`.hol-line[data-from="${FRI}"]`)); await page.waitForTimeout(500)
w.say('form buttons', await page.locator('[data-testid^="hol-"]').evaluateAll(es => es.map(e => e.dataset.testid)))
w.say('form dates at open', await page.evaluate(() => { const e = document.querySelector('[data-testid="hol-dates"]'); return e ? [e.dataset.from, e.dataset.to] : null }))
const d = await w.pickDates(THU, FRI)
w.say('form dates after picking', d)
await w.shot('R1-4-form')
await w.press(tid('hol-save')); await page.waitForTimeout(900)
w.say('hol err', await tid('hol-err').innerText().catch(() => '(none)'))
await w.closeSettings()
w.say('list after change', await w.listInfo())
w.say('measure list', await w.measureT('win-oilday'))
await w.hush(); await w.shot('R1-5-list-after')
const list = await w.listInfo()
if (list) { await w.press(tid('odl-later')); await page.waitForTimeout(400) }
await w.closeCal()
const b2 = await w.bothBells('R1-6-bells-after')
w.say('bells after', b2)
// open the list from a bell line (Warden) to see the title
await w.me('nact')
await w.openBell()
const ln = page.locator('[data-testid="bell-list"] .bl-line')
w.say('lines in Warden bell', await ln.count())
if (await ln.count()) { await w.press(ln.first()); await page.waitForTimeout(500); w.say('list from Warden bell', await w.listInfo()); await w.hush(); await w.shot('R1-7-list-from-bell'); await w.press(tid('odl-later')); await page.waitForTimeout(300) }
// ---- RX2-5: rename to "Founders Day", same dates
await w.me('stiff')
await w.hush()
const rn = await w.editHoliday(THU, { name: 'Founders Day' })
w.say('rename result', rn)
w.say('list after rename', await w.listInfo())
await w.hush(); await w.shot('R5-1-after-rename')
if (await tid('win-oilday').count()) { await w.press(tid('odl-later')); await page.waitForTimeout(400) }
await w.closeCal()
const b3 = await w.bothBells('R5-2-bells')
w.say('bells after rename', b3)
await w.me('nact'); await w.openBell()
{ const ln2 = page.locator('[data-testid="bell-list"] .bl-line'); w.say('lines', await ln2.count())
  if (await ln2.count()) { await w.press(ln2.first()); await page.waitForTimeout(500); w.say('list from bell after rename', await w.listInfo()); await w.hush(); await w.shot('R5-3-list-from-bell') } }
w.say('old name anywhere on screen (list/bell open)', await page.evaluate(() => document.body.innerText.includes('National Day')))
await w.openHolidays(); w.say('hol lines after rename', await page.locator('.hol-line').evaluateAll(es => es.map(e => e.innerText.replace(/\s+/g, ' '))))
w.say('old name on screen with holidays list open', await page.evaluate(() => document.body.innerText.includes('National Day')))
await w.shot('R5-4-holidays-list')
w.say('inputs state', await w.state([...ids, thu]))
w.say('errors', await bye(w))
await browser.close()
