import { open, fileInput, toWeek, shot, saveRes, errs, browser, csId, toast, unavailRows, lwStagePublished, lwCells, calRead, leaveInputs, sleep } from './or-RW3-lib.mjs'
const R = {}
const hexInputs = p => leaveInputs(p).then(a => a.filter(r => r.people.includes('Hex')))
/* ---- part a: a leave of one person, filed on the Inputs page ---- */
{
  const { ctx, page } = await open('ad', 'a')
  const hex = await csId(page, 'Hex')
  R.aFiled = await fileInput(page, { type: 'LL', person: 'Hex', from: '2026-07-13', to: '2026-07-17' })
  R.aStage = await lwStagePublished(page)
  R.aBefore = await hexInputs(page)
  await page.locator('[data-testid="month-JUL"]').click(); await sleep(900)
  const cell = page.locator(`[data-testid="cell-${hex}-2026-07-15"]`).first()
  await cell.scrollIntoViewIfNeeded(); await cell.click(); await sleep(600)
  R.aFieldWas = await page.locator('[data-testid="remarks-field"]').inputValue()
  await shot(page, 'rw3-3a-1-sheet')
  await page.locator('[data-testid="remarks-field"]').fill('Dental')
  await page.locator('[data-testid="remarks-save"]').click(); await sleep(800)
  await shot(page, 'rw3-3a-2-after-save')
  R.aAfter = await hexInputs(page)
  R.aCells = await lwCells(page, ['Hex'], 'rw3-3a-3-war')
  await toWeek(page)
  R.aUnavail = (await unavailRows(page, '#eWeek', 2)).filter(t => /Hex/.test(t))
  await page.locator('#eWeek .day:not(.peek)').nth(2).locator('.sec-unav').scrollIntoViewIfNeeded()
  await page.locator('#eWeek .day:not(.peek)').nth(2).locator('.sec-unav').screenshot({ path: 'docs/img/handpass/2026-10-12-one-rule/RW3/rw3-3a-4-unav.png' })
  R.aCal = await calRead(page, '2026-07-15', 'rw3-3a-5-cal')
  await ctx.close()
}
/* ---- part b: a leave the war itself approved ---- */
{
  const { ctx, page } = await open('ad', 'a')
  const hex = await csId(page, 'Hex')
  await page.evaluate(() => window.go('leavewar')); await sleep(1500)
  R.bStage0 = await page.locator('[data-testid="stage-now"]').innerText()
  await page.locator('[data-testid="month-JUL"]').click(); await sleep(900)
  const cell = () => page.locator(`[data-testid="cell-${hex}-2026-07-15"]`).first()
  await cell().scrollIntoViewIfNeeded(); await cell().click(); await sleep(600)
  await page.locator('[data-testid="bid-LL"]').click(); await sleep(700)
  R.bCellAfterBid = (await cell().innerText()) + ' | ' + (await cell().getAttribute('class'))
  await page.keyboard.press('Escape'); await sleep(400)
  await page.locator('[data-testid="stage-advance"]').click(); await sleep(600)
  R.bStage1 = await page.locator('[data-testid="stage-now"]').innerText()
  await cell().scrollIntoViewIfNeeded(); await cell().click(); await sleep(600)
  await page.locator('[data-testid="decide-approve"]').click(); await sleep(700)
  R.bCellAfterApprove = (await cell().innerText()) + ' | ' + (await cell().getAttribute('class'))
  await shot(page, 'rw3-3b-1-approved')
  await page.keyboard.press('Escape'); await sleep(400)
  R.bInputsAfterApprove = await hexInputs(page)
  await page.evaluate(() => window.go('leavewar')); await sleep(1300)
  await page.locator('[data-testid="stage-advance"]').click(); await sleep(700)
  R.bStage2 = await page.locator('[data-testid="stage-now"]').innerText()
  R.bInputsPublished = await hexInputs(page)
  const m = page.locator('[data-testid="month-JUL"]'); if (await m.count()) { await m.click(); await sleep(900) }
  await cell().scrollIntoViewIfNeeded(); await cell().click(); await sleep(600)
  R.bRemarkOpen = await page.locator('[data-testid="remarks-field"]').count()
  R.bFieldWas = R.bRemarkOpen ? await page.locator('[data-testid="remarks-field"]').inputValue() : null
  await shot(page, 'rw3-3b-2-sheet')
  if (R.bRemarkOpen) {
    await page.locator('[data-testid="remarks-field"]').fill('Dental')
    await page.locator('[data-testid="remarks-save"]').click(); await sleep(800)
  }
  await shot(page, 'rw3-3b-3-after-save')
  R.bAfter = await hexInputs(page)
  R.bCells = await lwCells(page, ['Hex'], 'rw3-3b-4-war')
  await toWeek(page)
  R.bUnavail = (await unavailRows(page, '#eWeek', 2)).filter(t => /Hex/.test(t))
  await page.locator('#eWeek .day:not(.peek)').nth(2).locator('.sec-unav').scrollIntoViewIfNeeded()
  await page.locator('#eWeek .day:not(.peek)').nth(2).locator('.sec-unav').screenshot({ path: 'docs/img/handpass/2026-10-12-one-rule/RW3/rw3-3b-5-unav.png' })
  R.bCal = await calRead(page, '2026-07-15', 'rw3-3b-6-cal')
  await ctx.close()
}
saveRes('RW3-3', R)
console.log(JSON.stringify(R, (k, v) => (k === 'bars' ? undefined : v), 1))
console.log('ERRS', errs.join('\n'))
await browser.close()
