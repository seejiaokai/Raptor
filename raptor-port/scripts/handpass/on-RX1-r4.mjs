import * as L from './on-RX1-lib.mjs'
const W = await L.world({ tag: 'R4' })
const { page, tid, shot, press } = W
const J = o => JSON.stringify(o)
const iid = await L.usualSat(W)
await L.frameBoard(page)
const b0 = { ground: await L.groundNow(page), oil: await L.oilOf(page, iid), undo: await L.undoState(page) }
await L.drag(page, page.locator(L.puckSel(1)), page.locator(L.puckSel(0)))
console.log('Q', await tid('oilconf').count(), await tid('oilconf-lead').innerText().catch(() => 'NO'))
await press(tid('oilconf-cancel')); await page.waitForTimeout(700)
console.log('bar up', await tid('oilbar').count(), await tid('oilbar-text').innerText().catch(() => 'NO'))
await shot('RX1-4-1-bar-up')
const oilBtn = page.locator('#sbOil')
console.log('OIL Earn button', await oilBtn.count(), await oilBtn.innerText().catch(() => ''), 'pressed?', await oilBtn.getAttribute('aria-pressed').catch(() => null), 'vis', await oilBtn.isVisible().catch(() => false))
await oilBtn.click(); await page.waitForTimeout(150)
console.log('150ms after OIL Earn on: bar', await tid('oilbar').count(), 'question', await tid('oilconf').count())
await page.waitForTimeout(700)
console.log('after OIL Earn on: bar', await tid('oilbar').count(), 'pressed', await oilBtn.getAttribute('aria-pressed').catch(() => null), 'ground', J(await L.groundNow(page)), 'oil', await L.oilOf(page, iid), 'undo same', (await L.undoState(page)) === b0.undo)
await shot('RX1-4-2-oil-earn-on')
await oilBtn.click(); await page.waitForTimeout(900)
console.log('after OIL Earn off: bar', await tid('oilbar').count(), 'pressed', await oilBtn.getAttribute('aria-pressed').catch(() => null), 'ground', J(await L.groundNow(page)), 'oil', await L.oilOf(page, iid), 'undo same', (await L.undoState(page)) === b0.undo, 'toasts', J((await L.toastsAll(page)).slice(-3)))
await L.frameBoard(page)
await shot('RX1-4-3-oil-earn-off')
console.log('errors', J(W.errors))
await W.ctx.close(); process.exit(0)
