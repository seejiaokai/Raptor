// RX1-2 — the picker for a Personal input: ALL AVAIL live on one day; greyed over two days
import { launch, openWorld, fileX, shotX, rowIdx, rowData, inputOf, errs, toWeek, openBoard, centre, weekRowEl, weekRowNames, boardRowEl, boardRowNames, weekLines, inputsSurf, closeDayWin, listRow, log, WIN, describeWin } from './or-RX1-lib.mjs'
const browser = await launch()
const { page: p } = await openWorld(browser, { fresh: false })
const DI = 3
const phState = () => p.evaluate(sel => [...document.querySelectorAll(`${sel} [data-ph]`)].map(b => ({ ph: b.getAttribute('data-ph'), pressed: b.getAttribute('aria-pressed'), disabled: b.disabled, ariaDisabled: b.getAttribute('aria-disabled'), cls: b.className, opacity: getComputedStyle(b).opacity })), WIN)
/* (a) one day, ALL AVAIL beside Ranger */
const stage = await fileX(p, { type: 'Personal', people: ['Ranger'], ph: 'allavail', from: '2026-07-16', to: '2026-07-16', timed: ['19:00', '20:00'], noSave: true })
log('a: pucks before save', await phState())
log('a: text', (await describeWin(p)).text.slice(0, 160))
await shotX(p, 'rx1-2-1-picker-one-day')
const toasts0 = await p.evaluate(() => (window.__toasts || []).length)
await p.locator('#inpEditSave').click(); await p.waitForTimeout(500)
log('a: oil question', await p.locator('[data-testid="oilconf"]').count(), 'win still open', await p.locator(WIN).count())
log('a: toasts', await p.evaluate(m => (window.__toasts || []).slice(m).map(t => t.text), toasts0))
await p.waitForTimeout(400)
const iid = await p.evaluate(had => window.INPUTS.filter(r => !had.includes(r.iid)).map(r => r.iid)[0], stage.had)
log('a: INPUTS', await p.evaluate(iid => { const r = window.INPUTS.find(x => x.iid === iid); return r ? { type: r.type, people: r.people.map(e => (window.PEOPLE[e.p] || {}).cs || e.p), date: r.date } : null }, iid))
const ri = await rowIdx(p, DI, iid)
log('a: ri', ri, await rowData(p, DI, iid))
await toWeek(p)
await centre(weekRowEl(p, DI, ri)); await p.waitForTimeout(300)
log('a: week row', await weekRowNames(p, DI, ri))
const aaTxt = await p.evaluate(([di, ri]) => { const t = document.querySelector(`#eWeek .day:not(.peek) [data-txt="gr:${di}.${ri}.prog"]`); const row = t.closest('.pl-row'); return [...row.querySelectorAll('.puck')].map(e => e.innerText.replace(/\s+/g, ' ').trim()) }, [DI, ri])
log('a: week row puck texts', aaTxt)
await shotX(p, 'rx1-2-2-week-row')
await openBoard(p, DI)
log('a: board row', await boardRowNames(p, DI, ri))
const boardTxt = await p.evaluate(([di, ri]) => { const t = [...document.querySelectorAll(`#schedBoard [data-bfld="gr:${di}.${ri}.prog"]`)].find(e => e.offsetParent); const row = t.closest('.sb-arow'); return [...row.querySelectorAll('.puck')].map(e => e.innerText.replace(/\s+/g, ' ').trim()) }, [DI, ri])
log('a: board row puck texts', boardTxt)
await centre(boardRowEl(p, DI, ri)); await shotX(p, 'rx1-2-3-board-row')
const sf = await inputsSurf(p, iid, '2026-07-16'); log('a: inputs surf', sf); await shotX(p, 'rx1-2-4-card')
await closeDayWin(p)
log('a: list', await listRow(p, iid))
/* (b) a new Personal over two days */
await p.evaluate(() => window.go('inputs'))
await p.waitForTimeout(300)
await fileX(p, { type: 'Personal', people: ['Ranger'], from: '2026-07-16', to: '2026-07-17', timed: ['19:00', '20:00'], noSave: true })
const b = await phState()
log('b: pucks two days', b)
const bt = (await describeWin(p)).text
log('b: text', bt.slice(0, 400))
await p.evaluate(sel => { const w = document.querySelector(sel); const b = w.querySelector('[data-ph]'); b && b.scrollIntoView({ block: 'center' }) }, WIN)
await p.waitForTimeout(200)
await shotX(p, 'rx1-2-5-picker-two-days')
// zoom on the pucks
const bb = await p.locator(`${WIN} [data-ph="allavail"]`).boundingBox()
await shotX(p, 'rx1-2-6-picker-two-days-zoom', { x: Math.max(0, bb.x - 20), y: Math.max(0, bb.y - 60), width: 460, height: 150 })
const reasons = await p.evaluate(sel => { const w = document.querySelector(sel); const t = [...w.querySelectorAll('*')].filter(e => e.children.length === 0 && /one day/i.test(e.textContent)).map(e => e.textContent.trim()); return t }, WIN)
log('b: reason text nodes', reasons)
// try pressing the greyed puck
await p.locator(`${WIN} [data-ph="allavail"]`).click({ force: true }).catch(() => {}); await p.waitForTimeout(250)
log('b: after pressing greyed ALL AVAIL', await phState(), (await describeWin(p)).text.slice(0, 120))
log('errs', errs)
await browser.close()
