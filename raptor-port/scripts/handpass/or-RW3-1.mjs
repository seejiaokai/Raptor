import { open, fileInput, toWeek, shot, saveRes, errs, browser, csId, toast, undoRedo, unavailRows, lwStagePublished, lwCells, calRead, leaveInputs, sleep, toMonth, barText } from './or-RW3-lib.mjs'
const R = {}
const { ctx, page } = await open('ad', 'a')
R.build = await page.evaluate(() => [...document.scripts].map(s => s.src).filter(Boolean))
R.filed = await fileInput(page, { type: 'LL', people: ['Drifter', 'Hex', 'Hunter'], from: '2026-07-13', to: '2026-07-17' })
R.stage = await lwStagePublished(page)
const names = ['Drifter', 'Hex', 'Hunter']
R.cellsBefore = await lwCells(page, names, 'rw3-1-1-war-before')
R.inputsBefore = await leaveInputs(page)
const hex = await csId(page, 'Hex')
await page.locator('[data-testid="month-JUL"]').click(); await sleep(900)
const cell = page.locator(`[data-testid="cell-${hex}-2026-07-15"]`).first()
await cell.scrollIntoViewIfNeeded(); await cell.click(); await sleep(600)
R.fieldWas = await page.locator('[data-testid="remarks-field"]').inputValue()
await shot(page, 'rw3-1-2-sheet')
await page.locator('[data-testid="remarks-field"]').fill('Dental')
await shot(page, 'rw3-1-3-typed')
await page.locator('[data-testid="remarks-save"]').click(); await sleep(800)
R.toast = await toast(page)
await shot(page, 'rw3-1-4-after-save')
R.inputsAfter = await leaveInputs(page)
R.cellsAfter = await lwCells(page, names, 'rw3-1-5-war-after')
await toWeek(page)
R.unavailWedAfter = await unavailRows(page, '#eWeek', 2)
R.unavailMonAfter = await unavailRows(page, '#eWeek', 0)
await page.locator('#eWeek .day:not(.peek)').nth(2).locator('.sec-unav').scrollIntoViewIfNeeded()
await page.locator('#eWeek .day:not(.peek)').nth(2).locator('.sec-unav').screenshot({ path: 'docs/img/handpass/2026-10-12-one-rule/RW3/rw3-1-6-unav-wed.png' })
R.calWed = await calRead(page, '2026-07-15', 'rw3-1-7-cal-wed')
R.calMon = await calRead(page, '2026-07-13', 'rw3-1-8-cal-mon')
await toWeek(page)
R.undo = await undoRedo(page, 'undo')
R.inputsUndo = await leaveInputs(page)
R.unavailWedUndo = await unavailRows(page, '#eWeek', 2)
R.cellsUndo = await lwCells(page, names, 'rw3-1-9-war-undo')
R.calWedUndo = await calRead(page, '2026-07-15', 'rw3-1-10-cal-undo')
await toWeek(page)
await page.locator('#eWeek .day:not(.peek)').nth(2).locator('.sec-unav').scrollIntoViewIfNeeded()
await page.locator('#eWeek .day:not(.peek)').nth(2).locator('.sec-unav').screenshot({ path: 'docs/img/handpass/2026-10-12-one-rule/RW3/rw3-1-11-unav-undo.png' })
saveRes('RW3-1', R)
console.log(JSON.stringify(R, null, 1))
console.log('ERRS', errs.join('\n'))
