import { launch, ctxOpen, SIZES, sleep, go, shot, buildSat, bPublish, bType, rlBox, rec, errors, openBoard, closeBoard, reload } from './lib.mjs'
console.log('sc12c v1')
const b = await launch()
const { ctx, p } = await ctxOpen(b, SIZES.desk, '12c')
await p.addInitScript(() => { const d = Object.getOwnPropertyDescriptor(HTMLIFrameElement.prototype, 'srcdoc'); if (d && d.set) Object.defineProperty(HTMLIFrameElement.prototype, 'srcdoc', { set(v) { window.__pdfHtml = String(v); return d.set.call(this, v) }, get() { return d.get.call(this) }, configurable: true }) })
await reload(p)
await buildSat(p)
await bType(p, rlBox(5, 0, 0), '08:30')
await bPublish(p, 5)
await closeBoard(p); await go(p, 'editsched')
await p.evaluate(() => { window.__pdfHtml = null })
await p.locator('#exportPdf').click(); await sleep(1200)
const h = await p.evaluate(() => window.__pdfHtml)
const rows = (h.match(/<tr[\s\S]*?<\/tr>/g) || []).map(r => r.replace(/<[^>]+>/g, '|').replace(/\|+/g, '|'))
const mine = rows.filter(r => /VL/.test(r) && /12:00/.test(r))
const heads = (h.match(/<th>[^<]*<\/th>/g) || []).slice(0, 10).join('')
rec('12', 'desk', 'a Saturday published with R 08:30; PDF', 'the Saturday VL row carries 08:30 under Rally, before the brief 09:40', { heads, vlRow: mine }, mine.some(r => /\|08:30\|09:40\|/.test(r)) ? 'PASS' : 'FAIL')
/* jump from a change line */
await openBoard(p, 5)
await bType(p, rlBox(5, 0, 0), '08:00')
await p.locator('#sbHist').click(); await sleep(700)
await p.locator('text=/To go out/').first().click(); await sleep(500)
await p.locator('text=/VL · rally/').first().click(); await sleep(900)
const act = await p.evaluate(() => ({ active: document.activeElement?.dataset?.bfld || document.activeElement?.tagName, flash: [...document.querySelectorAll('#schedBoard [class*=flash], #schedBoard [class*=jump], #schedBoard [class*=ring]')].map(e => (e.dataset.bfld || '') + '|' + e.className).slice(0, 5) }))
rec('12', 'desk', 'click the "VL · rally" line in the changes window', 'RECORD: the page goes to the R box', act, 'RECORD', await shot(p, 'A12-jump'))
console.log('errors', JSON.stringify(errors)); await b.close()
