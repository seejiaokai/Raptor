import { launch, ctxOpen, SIZES, sleep, go, shot, buildSat, bType, rlBox, rec, errors, hours, warns, addIt, itLines } from './lib.mjs'
console.log('sc10 v1')
const b = await launch()
const { ctx, p } = await ctxOpen(b, SIZES.desk, '10')
await buildSat(p, { to: '10:00', ld: '11:30' })
await bType(p, rlBox(5, 0, 0), '06:00')
const hR = await hours(p, ['Saber'])
const m1 = await p.evaluate(() => window.DAYS[5].waves[0].formations[0].rl)
await addIt(p, 5, 0)
const its = await itLines(p)
const w = await warns(p)
const hBoth = await hours(p, ['Saber'])
rec('10', 'desk', 'TO 10:00, R 06:00 typed, no lines; press "+ In-time"', '+ In-time fills 07:00 (TO less 3h) ignoring the box (RB6, D1031)', { rl: m1, lines: its }, /^07:00/.test(its[0] || '') ? 'PASS' : 'FAIL', await shot(p, 'A10-intime-fill'))
rec('10', 'desk', 'the start of the flyer after the in-time line is added', 'start stays 06:00 (box earlier than the in-time)', { hoursRonly: hR.Saber, hoursBoth: hBoth.Saber }, hR.Saber === hBoth.Saber ? 'PASS' : 'FAIL')
rec('10', 'desk', 'does "in-time 07:00 is later than rally 06:00" show', 'RECORD', { warnings: w.slice(0, 4) }, 'RECORD')
console.log('errors', JSON.stringify(errors)); await b.close()
