import { launch, ctxOpen, SIZES, sleep, go, shot, buildSat, bType, bf, rlBox, val, model, rec, errors, openBoard, hours, warns, closeBoard } from './lib.mjs'
console.log('sc17 v1')
const b = await launch()
const R = rlBox(5, 0, 0)
const { ctx, p } = await ctxOpen(b, SIZES.desk, '17')
await buildSat(p, { to: '12:00', ld: '17:00' })
const side = async () => (await warns(p)).filter(x => /long|day|hour|h\b/i.test(x) && !/OIL/.test(x))
const pk = () => p.evaluate(() => [...document.querySelectorAll('#schedBoard .puck[data-person="stiff"]')].filter(e => !e.closest('#sbRoster')).map(e => e.className + ' | ' + e.title))
const h0 = await hours(p, ['Saber'])
const s0 = await side()
rec('17', 'desk', 'TO 12:00 LD 17:00, R empty', 'no long-day note (nominal 09:00 to 19:00 = 10h); Insights from the nominal', { hours: h0, side: s0, puck: await pk() }, 'RECORD', await shot(p, 'A17-before'))
await bType(p, R, '05:00')
const h1 = await hours(p, ['Saber']); const s1 = await side(); const pu = await pk()
const longNote = (await warns(p)).concat(pu).some(x => /long/i.test(x))
rec('17', 'desk', 'type R 05:00', 'the grey long-day note appears (05:00 to 19:00 = 14h > 12h)', { side: s1, puck: pu, hoursNow: h1, deltaVsBase: h1.Saber - h0.Saber }, longNote ? 'PASS' : 'FAIL', await shot(p, 'A17-R0500'))
rec('17', 'desk', 'Insights hours with R 05:00', 'Insights counts from 05:00: nominal 09:00 start would add 240 min vs base only if base starts at 09:00', { h0, h1, delta: h1.Saber - h0.Saber, note: 'start of the base reading derived: 05:00 start minus delta' }, 'RECORD')
await bType(p, R, '')
const h2 = await hours(p, ['Saber']); const s2 = await side(); const pu2 = await pk()
rec('17', 'desk', 'clear R', 'long-day note goes; hours back to the base reading', { hoursNow: h2, base: h0, side: s2, puck: pu2 }, h2.Saber === h0.Saber && !(await warns(p)).concat(pu2).some(x => /long/i.test(x)) ? 'PASS' : 'FAIL', await shot(p, 'A17-cleared'))
console.log('errors', JSON.stringify(errors)); await b.close()
