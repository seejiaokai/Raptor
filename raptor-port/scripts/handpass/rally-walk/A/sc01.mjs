import { launch, ctxOpen, SIZES, sleep, go, shot, buildSat, model, bPublish, status, oilRead, rec, bType, rlBox, val, openBoard, errors } from './lib.mjs'
console.log('sc01 v1')
const b = await launch()
const sc = '01'
/* (a) before publishing */
{
  const { ctx, p } = await ctxOpen(b, SIZES.desk, 'sc01a')
  await buildSat(p)
  const r = rlBox(5, 0, 0)
  const v0 = await val(p, r)
  await p.locator(r + ':visible').first().click(); await sleep(250)
  const v1 = await val(p, r)
  const m1 = await model(p, 5, 0, 0)
  rec('1a', 'desk', 'click empty R (board)', 'suggestion 09:00 placed, highlighted', { before: v0, afterClick: v1, model: m1 }, (v1.v === '09:00' && v1.sel === '09:00') ? 'PASS' : 'FAIL')
  await p.keyboard.type('0830'); await sleep(100)
  await p.locator('#sbTitle, #schedBoard h1, body').first().click({ position: { x: 5, y: 5 } }).catch(() => {})
  await p.locator(rlBox(5, 0, 0)).first().blur().catch(() => {}); await sleep(300)
  const m2 = await model(p, 5, 0, 0)
  rec('1a', 'desk', 'type 0830, leave', 'R saved 08:30', m2, m2.rl === '08:30' ? 'PASS' : 'FAIL')
  const pubr = await bPublish(p, 5)
  const oil = await oilRead(p)
  await openBoard(p, 5)
  const pic = await shot(p, 'A01a-published-R0830', p.locator('#schedBoard .sb-go').first())
  rec('1a', 'desk', 'publish with R 08:30, OIL Earn mode read', 'full day (FO) for the crew', { pubr, oil }, oil.some(x => /FO/.test(x)) ? 'PASS' : 'FAIL', pic)
  await ctx.close()
}
/* (b) publish first, R empty; then type R */
{
  const { ctx, p } = await ctxOpen(b, SIZES.desk, 'sc01b')
  await buildSat(p)
  const pubr = await bPublish(p, 5)
  const oil0 = await oilRead(p)
  const st0 = await status(p)
  rec('1b', 'desk', 'publish with R empty', 'half day (HO)', { pubr, oil0, st0 }, oil0.some(x => /HO/.test(x)) ? 'PASS' : 'FAIL')
  const r = rlBox(5, 0, 0)
  await p.locator(r + ':visible').first().click(); await sleep(200)
  await p.keyboard.type('0830'); await p.locator(r).first().blur(); await sleep(500)
  const m = await model(p, 5, 0, 0)
  const st1 = await status(p)
  const dot = await p.evaluate(() => { const e = document.querySelector('#schedBoard [data-bfld="ff:5.0.0.rl"]'); const c = e.closest('.sb-line, .sb-row, tr, div'); return { cls: e.className, parentCls: e.parentElement?.className, parentHtml: e.parentElement?.outerHTML.slice(0, 400), pendingEls: [...document.querySelectorAll('#schedBoard .pend, #schedBoard [class*=pend], #schedBoard [class*=almark], #schedBoard [class*=goldd]')].length } })
  const pic1 = await shot(p, 'A01b-pending-R0830', p.locator('#schedBoard .sb-go').first())
  const topPic = await shot(p, 'A01b-pending-top')
  const oil1 = await oilRead(p)
  rec('1b', 'desk', 'type R 08:30 on the published day', 'pending mark, sign-offs wiped, gold dot on R, OIL still half', { model: m, st1, dot, oil1 }, (oil1.some(x => /HO/.test(x)) && st1.signs.every(v => !v || /^—/.test(v))) ? 'PASS' : 'RECORD', pic1)
  const pub2 = await bPublish(p, 5)
  const oil2 = await oilRead(p)
  const st2 = await status(p)
  rec('1b', 'desk', 'publish the amendment', 'full day (FO)', { pub2, st2, oil2 }, oil2.some(x => /FO/.test(x)) ? 'PASS' : 'FAIL')
  await ctx.close()
}
/* (c) as b but Undo before amending */
{
  const { ctx, p } = await ctxOpen(b, SIZES.desk, 'sc01c')
  await buildSat(p)
  await bPublish(p, 5)
  const r = rlBox(5, 0, 0)
  await p.locator(r + ':visible').first().click(); await sleep(200)
  await p.keyboard.type('0830'); await p.locator(r).first().blur(); await sleep(500)
  const stA = await status(p)
  await p.locator('#sbUndo').click(); await sleep(600)
  const m = await model(p, 5, 0, 0)
  const stB = await status(p)
  const oil = await oilRead(p)
  const pic = await shot(p, 'A01c-after-undo', p.locator('#schedBoard .sb-go').first())
  rec('1c', 'desk', 'type R 08:30 on published day, then Undo', 'R empty again, pending cleared, OIL half', { stA, stB, model: m, oil }, (m.rl === '' || m.rl == null) && oil.some(x => /HO/.test(x)) ? 'PASS' : 'FAIL', pic)
  await ctx.close()
}
