/* W2 probe (26 Sep 26) — READ-mostly survey of the ground before the walk: who is free, what the Inputs calendar draws
   for July, what the war's figure sheet names its figures, and whether a reload keeps the session. */
process.env.AB_WHO = 'w2'
const L = await import('./ab-lib.mjs')
const S = await import('./ab-sched.mjs')
const W = await import('./w2-lib.mjs')
const { openHi } = await import('../am/w2-lib.mjs')
const { browser, page, errors } = await openHi({ width: 1440, height: 900, who: 'a', dpr: 1 })
await L.toastSpy(page)
const cs = await W.csOf(page)
const free = await S.freeMen(page, [0, 1, 2, 3, 4, 5, 6])
console.log('free', free.map(f => f + '=' + cs[f]).join(' '))
const julyIn = await page.evaluate(() => window.INPUTS.filter(x => /^Jul (1[0-9]|2[0-9]|3[01])/.test(x.date)).map(x => `${x.person}:${x.type} ${x.date}${x.endDate ? '–' + x.endDate : ''}`))
console.log('july inputs', julyIn.length, JSON.stringify(julyIn))
const M = free[0]
const figs0 = await L.figures(page, M).catch(e => ({ err: String(e) }))
await L.lwOpen(page, '2026-07-20')
console.log('figs', JSON.stringify(await L.figures(page, M)))
console.log('run', JSON.stringify(await L.rowRun(page, M, ['2026-07-18', '2026-07-19', '2026-07-20', '2026-07-21', '2026-07-22'])))
console.log('mon', await W.calTo(page, '2026-07'))
for (const d of ['2026-07-13', '2026-07-18', '2026-07-20', '2026-07-22']) console.log(d, JSON.stringify(await W.calDay(page, d)))
await L.shot(page, 'w2-00-cal-july-desktop')
await L.inputsView(page, 'med')
await L.shot(page, 'w2-00-medview-desktop')
console.log('medview', await page.evaluate(() => (document.querySelector('#medView') || {}).innerText?.replace(/\s+/g, ' ').slice(0, 800)))
console.log('medbtn', await page.evaluate(() => (document.querySelector('#inMedBtn') || {}).innerText?.replace(/\s+/g, ' ')))
await W.reload(page, 'a')
console.log('after reload page', await page.evaluate(() => window.CURPAGE), 'login?', await page.locator('#luser:visible').count())
console.log('errors', JSON.stringify(errors.slice(0, 10)))
await browser.close()
