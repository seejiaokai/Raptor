/* W2 probe b — one calendar drag of a medical onto a different-type medical, to learn the gesture before the walk. */
process.env.AB_WHO = 'w2'
const L = await import('./ab-lib.mjs')
const W = await import('./w2-lib.mjs')
const { openHi } = await import('../am/w2-lib.mjs')
const { browser, page, errors } = await openHi({ width: 1440, height: 900, who: 'a', dpr: 1 })
await L.toastSpy(page)
const M = 'dice'
const a = await L.fileInput(page, { person: M, type: 'HL', from: '2026-07-20', to: '2026-07-24', remarks: 'probe HL' })
const b = await L.fileInput(page, { person: M, type: 'ATT C', from: '2026-07-18', remarks: 'probe ATT C' })
console.log('filed', JSON.stringify({ a, b }))
console.log('rows', JSON.stringify(await W.medRows(page, M)))
console.log('mon', await W.calTo(page, '2026-07'))
for (const d of ['2026-07-18', '2026-07-22']) console.log(d, JSON.stringify(await W.calDay(page, d)))
await L.shot(page, 'w2-00b-cal-before')
await L.toasts(page)
const dr = await W.calDragMouse(page, b.iid, '2026-07-18', '2026-07-22')
console.log('drag', JSON.stringify(dr))
console.log('confirm', JSON.stringify(await W.confirmNow(page)))
console.log('toasts', JSON.stringify(await L.toasts(page)))
console.log('rows after', JSON.stringify(await W.medRows(page, M)))
console.log('ghost', JSON.stringify(await W.ghostLeft(page)))
await L.shot(page, 'w2-00b-cal-after')
console.log('errors', JSON.stringify(errors.slice(0, 10)))
await browser.close()
