const L = await import('./msq-pa-a-lib.mjs')
const { X, say, sleep } = L
say('msq-pa-a-probe v1', L.size)
const w = await L.start(true)
await X.login(w.page, 'ad2')
await L.toUsers(w)
await L.openRow(w, 'Osprey')
say('READ', await L.rowRead(w, 'Osprey'))
say('EDIT', await L.editWords(w))
await L.press(w, L.btn(w, /^Suspend$/), 'probe-suspend')
say('EDIT2', await L.editWords(w))
say('READ2', await L.rowRead(w, 'Osprey'))
say('NOTES', JSON.stringify(await L.notes(w)))
say('TOP', await w.page.evaluate(() => [...document.querySelectorAll('button:visible, [role=button]')].filter(b => b.getBoundingClientRect().width > 2 && /undo|redo/i.test((b.id || '') + (b.getAttribute('aria-label') || '') + b.innerText)).map(b => b.id + '|' + b.getAttribute('aria-label') + '|' + b.innerText + '|' + b.disabled).join(' ; ')))
await L.done(w)
