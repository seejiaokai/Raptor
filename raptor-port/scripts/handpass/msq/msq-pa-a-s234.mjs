const L = await import('./msq-pa-a-lib.mjs')
const { X, say, sleep, sj, tap } = L
say('msq-pa-a-s234 v1', L.size)
const O = 'Osprey'
// ---- S2: Hunter WITHOUT Plan
{
  const w = await L.start(false)
  await X.login(w.page, 'ad2'); await L.toUsers(w)
  say('S2 list contains Osprey?', await L.rowBtn(w, O).count())
  if (!(await L.rowBtn(w, O).count()) && !(await L.find(w).count())) say('no Osprey row for a Hunter without Plan')
  await L.search(w, O)
  const cnt = await L.rowBtn(w, O).count()
  say('S2 Osprey rows after search', cnt)
  await X.pic(w, 's2-0-search')
  if (cnt) {
    await L.openRow(w, O)
    await L.press(w, w.page.locator('#accEdOnOff'), 's2-1-suspend')
    let s = await L.state(w, O)
    say('S2 after suspend', sj(s))
    const ok = /He is 149.s\. Only an admin of 149 can change his account\./.test(s.toast + ' ' + (s.row === 'NO ROW' ? '' : s.row.editWords))
    L.rep('S2', 'Hunter (no Plan): Osprey Suspend', 'refused: "He is 149\'s. Only an admin of 149 can change his account."', 'toast=' + s.toast + ' dot=' + (s.row === 'NO ROW' ? 'NO ROW' : s.row.signin), ok ? 'PASS' : 'FAIL', 's2-1-suspend')
    await L.openRow(w, O)
    await L.press(w, w.page.locator('#accEdArchive'), 's2-2-archive')
    s = await L.state(w, O)
    say('S2 after archive', sj(s))
    L.rep('S2', 'Hunter (no Plan): Osprey Archive', 'RECORD', 'toast=' + s.toast + ' header=' + (s.row === 'NO ROW' ? 'NO ROW' : s.row.header), 'RECORDED', 's2-2-archive')
  } else L.rep('S2', 'Hunter (no Plan): find Osprey row', 'a row to press', 'no Osprey row found by search (the list does not show him)', 'FAIL', 's2-0-search')
  await L.done(w)
}
// ---- S3 and S4 in one world, Hunter with Plan
{
  const w = await L.start(true)
  await X.login(w.page, 'ad2'); await L.toUsers(w)
  // S3
  await L.openRow(w, 'Kestrel')
  await L.press(w, w.page.locator('#accEdOnOff'), 's3-1-kestrel-suspend')
  let s = await L.state(w, 'Kestrel')
  say('S3 after Kestrel suspend', sj(s))
  const ok = /Kestrel is 149.s last admin\. Make another admin of 149 first\./.test(s.toast + ' ' + (s.row === 'NO ROW' ? '' : s.row.editWords))
  L.rep('S3', 'Plan: Kestrel Suspend', 'refused: "Kestrel is 149\'s last admin. Make another admin of 149 first."', 'toast=' + s.toast + ' dot=' + s.row.signin, ok ? 'PASS' : 'FAIL', 's3-1-kestrel-suspend')
  await L.openRow(w, O)
  await w.page.selectOption('#accEdRole', 'admin'); await sleep(300)
  await L.press(w, w.page.locator('#accEdSave'), 's3-2-osprey-admin')
  s = await L.state(w, O)
  say('S3 Osprey admin', sj(s))
  L.rep('S3', 'Plan: Osprey role Admin, Save', 'saved', 'toast=' + s.toast + ' badge=' + s.row.badge, /admin/i.test(s.row.badge) ? 'PASS' : 'FAIL', 's3-2-osprey-admin')
  await L.openRow(w, 'Kestrel')
  await L.press(w, w.page.locator('#accEdOnOff'), 's3-3-kestrel-suspend-again')
  s = await L.state(w, 'Kestrel')
  say('S3 Kestrel suspend again', sj(s))
  L.rep('S3', 'Plan: Kestrel Suspend again (Osprey now admin)', 'RECORD (expected allowed)', 'toast=' + s.toast + ' dot=' + s.row.signin, 'RECORDED', 's3-3-kestrel-suspend-again')
  // S4
  await L.openRow(w, 'Saber')
  await L.press(w, w.page.locator('#accEdOnOff'), 's4-1-saber-suspend')
  s = await L.state(w, 'Saber')
  say('S4 Saber suspend', sj(s))
  L.rep('S4', 'Plan: Saber (master admin) Suspend', 'refused "Only a master admin can do that"', 'toast=' + s.toast + ' dot=' + s.row.signin, /Only a master admin can do that/.test(s.toast + (s.row.editWords || '')) ? 'PASS' : 'FAIL', 's4-1-saber-suspend')
  await L.openRow(w, 'Saber')
  await w.page.selectOption('#accEdRole', 'main'); await sleep(300)
  await X.pic(w, 's4-2-saber-role-member')
  await L.press(w, w.page.locator('#accEdSave'), 's4-3-saber-save')
  s = await L.state(w, 'Saber')
  say('S4 Saber role save', sj(s))
  L.rep('S4', 'Plan: Saber Role Member, Save', 'RECORD', 'toast=' + s.toast + ' badge=' + s.row.badge, 'RECORDED', 's4-3-saber-save')
  await L.done(w)
}
