/* msq-j2-w1-d v1 — W1-D: the plain-user round for the master (desktop) */
process.env.MSQ_WHO = 'w1'
process.env.MSQ_RUN = process.env.MSQ_RUN || 'd1'
const Hm = await import('./msq-j2-w1-h2.mjs')
const H = await (await import('./msq-j2-w1-h.mjs')).mk()
const { X, U, say, sleep, row } = H
const { iso, T } = Hm
say('msq-j2-w1-d v1')
const w = await X.open({ user: 'ad' })
const p = w.page
const ONLY = (process.env.ONLY || "D1,D2,D3,D4,D5").split(","); const step = async (name, fn) => { if (!ONLY.includes(name)) return; try { await fn() } catch (e) { say('STEP FAILED', name, e.message.slice(0, 200)); try { await X.pic(w, 'fail-' + name) } catch {}; row(name, 'desktop', 'script step', 'completes', 'script error: ' + e.message.slice(0, 150), 'OWED', 'fail-' + name + '.png') } }
const rg = await U.pidOf(p, 'Ranger'), ko = await U.pidOf(p, 'Hunter')
await step('D1', async () => {
  const o = await H.openRow(w, 'Ranger')
  await p.locator('#accEdName').fill('typed-test-j2'); await sleep(400)
  await X.pic(w, 'd1-01-typed')
  await p.locator('#accEdCancel').click(); await sleep(700)
  await X.pic(w, 'd1-02-after-cancel')
  await p.locator(`.acc-row[data-person="${rg}"] .acc-tap`).first().click(); await sleep(800)
  const v = await p.locator('#accEdName').inputValue()
  await X.pic(w, 'd1-03-reopened')
  row('W1-D', 'desktop', 'ad: Users, search Ranger, open row, type in the sign-in box, Cancel, reopen', 'the typing is gone (RECORD)', 'sign-in box after reopen reads: "' + v + '"', 'RECORD', 'd1-01..03')
  // another row, close by pressing its name again
  await p.locator(H.FIND).fill('Hunter'); await sleep(600)
  await p.locator(`.acc-row[data-person="${ko}"] .acc-tap`).first().click(); await sleep(800)
  await X.pic(w, 'd1-04-hunter-open')
  const open1 = await p.locator('#accEdSave').isVisible().catch(() => false)
  await p.locator(`.acc-row[data-person="${ko}"] .acc-tap`).first().click(); await sleep(800)
  await X.pic(w, 'd1-05-hunter-closed')
  const open2 = await p.locator('#accEdSave').isVisible().catch(() => false)
  row('W1-D', 'desktop', "ad: open Hunter's row, close it by pressing his name again", 'row closes', 'editor visible after open: ' + open1 + '; after pressing name again: ' + open2, open1 && !open2 ? 'PASS' : 'FAIL', 'd1-04, d1-05')
})
await step('D2', async () => {
  await H.usersPage(w)
  await p.locator('#accAddCs').fill('J2Saber'); await p.locator('#accAddIni').fill('JJ')
  await p.locator('#accAddSeat').selectOption({ label: 'Pilot' })
  const cats = await p.locator('#accAddCat option').allTextContents(); say('cats', cats.join(','))
  await p.locator('#accAddCat').selectOption({ label: 'CAT' }).catch(async () => { await p.locator('#accAddCat').selectOption({ index: 1 }) })
  const catPicked = await p.locator('#accAddCat').evaluate(s => s.options[s.selectedIndex].text)
  await p.locator('#accAddPostIn').click(); await sleep(700)
  await X.pic(w, 'd2-01-calendar-open')
  const open1 = await p.locator('[data-testid="dcal-day-' + iso(T, 1) + '"]').isVisible().catch(() => false)
  await p.mouse.click(300, 600); await sleep(700)
  await X.pic(w, 'd2-02-calendar-after-outside-press')
  const open2 = await p.locator('[data-testid="dcal-day-' + iso(T, 1) + '"]').isVisible().catch(() => false)
  row('W1-D', 'desktop', 'add-person form: open the Post in calendar, press outside it', 'calendar closes, nothing else changes', 'calendar visible before: ' + open1 + ' after: ' + open2 + ' ; callsign box: ' + await p.locator('#accAddCs').inputValue() + ' ; post in: ' + (await p.locator('#accAddPostIn').textContent()).trim(), open1 && !open2 ? 'PASS' : 'FAIL', 'd2-01, d2-02')
  await p.locator('#accAddPostIn').click(); await sleep(700)
  await p.locator('[data-testid="dcal-day-' + iso(T, 1) + '"]').click(); await sleep(700)
  await X.pic(w, 'd2-03-picked-T1')
  const pi = (await p.locator('#accAddPostIn').textContent()).trim()
  await p.locator('#accAdd').click(); await sleep(1200)
  await X.pic(w, 'd2-04-added')
  const t = await U.bodyText(p)
  row('W1-D', 'desktop', 'add J2Saber, initials JJ, Pilot, CAT ' + catPicked + ', post in T+1', 'person added', 'post-in box read: ' + pi + ' ; words: ' + (t.match(/J2Saber[^.]{0,80}/) || ['(not on screen)'])[0] + ' ; note: ' + (t.match(/J2Saber (added|is)[^.]{0,80}/) || [''])[0], /J2Saber/.test(t) ? 'RECORD' : 'FAIL', 'd2-03, d2-04')
})
await step('D3', async () => {
  await X.L.go(p, 'quals'); await sleep(1500)
  await X.pic(w, 'd3-01-quals')
  const t = await U.bodyText(p)
  const has = /J2Saber/.test(t), ranger = /Ranger/.test(t), kestrel = /Kestrel/.test(t)
  const sq = await p.evaluate(() => (document.querySelector('.topbar, header')?.innerText || '').replace(/\s+/g, ' ').slice(0, 120))
  row('W1-D', 'desktop', "ad opens Quals; is J2Saber listed, whose squadron's Quals", 'J2Saber listed (RECORD whose squadron)', 'J2Saber on page: ' + has + ' ; Ranger (142): ' + ranger + ' ; Kestrel (149): ' + kestrel + ' ; top: ' + sq, 'RECORD', 'd3-01-quals.png')
})
await step('D4', async () => {
  await X.L.go(p, 'leavewar'); await sleep(2500)
  const gone = async () => !(await p.locator('button:visible', { hasText: /^Post out$/ }).count()) || !(await p.getByText(/PO FROM/i).first().isVisible().catch(() => false))
  const sheetOpen = () => p.getByText(/PO FROM/i).first().isVisible().catch(() => false)
  const ds = iso(T, 2)
  const openSheet = async () => {
    const cell = p.locator(`[data-testid="cell-${rg}-${ds}"]`).first()
    await cell.scrollIntoViewIfNeeded(); await cell.click(); await sleep(900)
    await p.locator('button:visible', { hasText: '⋯' }).last().click({ timeout: 4000 }); await sleep(600)
    await p.locator('button:visible', { hasText: /^Post out/ }).first().click(); await sleep(800)
  }
  const kinds = [['Close', async () => { const xs = p.locator('button:visible', { hasText: '✕' }); await xs.last().click() }], ['Escape', async () => { await p.keyboard.press('Escape') }], ['outside press', async () => { await p.mouse.click(1450, 120) }]]
  let i = 0
  for (const [nm, fn] of kinds) {
    i++
    await openSheet()
    await X.pic(w, `d4-${i}a-sheet-open`)
    const o = await sheetOpen()
    await fn(); await sleep(900)
    await X.pic(w, `d4-${i}b-after-${nm.replace(' ', '-')}`)
    const o2 = await sheetOpen()
    const dayWin = await p.evaluate(() => (document.body.innerText.match(/Ranger\s+[A-Z][a-z]{2} \d+ Nov/) || ['(no day window)'])[0])
    const grid = await p.locator('button:visible', { hasText: /^Post out/ }).count()
    row('W1-D', 'desktop', `Leave War: Ranger's cell on ${ds} → day window → ⋯ → Post out → sheet; dismiss by ${nm}`, 'sheet gone, page under it as it was', `sheet open before: ${o}; after: ${o2}; day window words: ${dayWin}; Post out controls still visible: ${grid}`, o && !o2 ? 'PASS' : 'FAIL', `d4-${i}a / d4-${i}b`)
    await p.keyboard.press('Escape'); await sleep(500)
  }
})
await step('D5', async () => {
  await X.L.go(p, 'leavewar'); await sleep(2500)
  await p.locator(`[data-testid="cell-${rg}-${T}"]`).first().scrollIntoViewIfNeeded(); const el = p.locator("span.puck:visible", { hasText: /^Ranger/ }).first()
  await el.click(); await sleep(900)
  await X.pic(w, 'd5-01-person-open')
  const vis = () => p.getByText('BALANCES').first().isVisible().catch(() => false)
  const o = await vis()
  await p.locator('button:visible', { hasText: '✕' }).first().click(); await sleep(700)
  await X.pic(w, 'd5-02-after-x')
  const c = await vis()
  row('W1-D', 'desktop', "Leave War: open a man's person window from his name, close by ✕", 'closes', 'open: ' + o + ' after ✕: ' + c, o && !c ? 'PASS' : 'FAIL', 'd5-01, d5-02')
  await el.click(); await sleep(900)
  const o3 = await vis()
  await p.keyboard.press('Escape'); await sleep(700)
  await X.pic(w, 'd5-03-after-escape')
  const c3 = await vis()
  row('W1-D', 'desktop', 'reopen the person window, close by Escape', 'closes', 'open: ' + o3 + ' after Escape: ' + c3, o3 && !c3 ? 'PASS' : 'FAIL', 'd5-03')
})
await X.fin(w)
