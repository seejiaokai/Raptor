import { open, go, version, shot, tapBox, scenario, keysUp, keysDown, state, record } from './kbs-A-lib.mjs'
version('a9+O1-O3')
const { browser, page, errors } = await open()
await go(page, 'admin')
const openDuty = async () => { await page.evaluate(() => document.getElementById('admDutyTpl').click()); await page.waitForSelector('#tplModal'); await page.waitForTimeout(800) }
const closeDuty = async () => { await keysDown(page); await page.evaluate(() => { document.activeElement && document.activeElement.blur() }); await page.evaluate(() => document.getElementById('tplClose').click()); await page.waitForTimeout(500) }
const tms = () => page.locator('#tplModal input.tm')
const win = () => page.evaluate(() => { const m = document.querySelector('#tplModal'); const kids = [...m.querySelectorAll('*')].filter(e => e.style && e.style.translate).map(e => (e.id || e.className) + ':' + e.style.translate); const mm = m.style.translate ? ['#tplModal:' + m.style.translate] : []; const box = m.firstElementChild; const r = box.getBoundingClientRect(); return { translates: [...mm, ...kids], boxTop: Math.round(r.top), boxBottom: Math.round(r.bottom), boxCls: String(box.className), pageScroll: document.scrollingElement.scrollTop } })
await openDuty()
console.log('tm count', await tms().count())
const lastEnd = tms().last()
console.log('win initial', JSON.stringify(await win()))
const A9 = await scenario(page, 'A9', lastEnd, { what: 'Duty templates: last role End time', skipLow: true, inWindow: true, keepUp: true })
const raised = await win()
console.log('win raised', JSON.stringify(raised))
await shot(page, 'A9-raised-detail')
await keysDown(page)
const dn = await win(); const dnS = await state(page, await lastEnd.elementHandle())
await shot(page, 'A9-3-keys-down')
record({ id: 'A9-down', what: 'A9 keys down: window put back', translates: dn.translates, boxTop: [210, dn.boxTop], endRect: dnS.rect, summary: `A9 keys down: translates ${JSON.stringify(dn.translates)} box top ${dn.boxTop} (was 224 before lift); End rect ${JSON.stringify(dnS.rect)} focused ${dnS.focused}` })
await keysUp(page)
await page.waitForTimeout(500)
// O2: with window raised (keys still up), tap box near top (template name)
await page.evaluate(() => document.activeElement.blur())
await page.waitForTimeout(300)
const name = page.locator('#tplModal input.tpl-name')
await tapBox(page, name); await page.waitForTimeout(700)
const o2 = await win(); const o2s = await state(page, await name.elementHandle())
await shot(page, 'O2-name-box-tapped')
record({ id: 'O2', what: 'A9 window raised then tap name box near top', raised: raised.translates, afterTopTap: o2.translates, boxTop: [raised.boxTop, o2.boxTop], nameRect: o2s.rect, covered: o2s.covered, focused: o2s.focused, summary: `O2 raised ${JSON.stringify(raised.translates)} top ${raised.boxTop} -> after tap ${JSON.stringify(o2.translates)} top ${o2.boxTop}; name rect ${JSON.stringify(o2s.rect)} focused ${o2s.focused}` })
// O3: raise again by tapping last End, then tap blank space
await tapBox(page, lastEnd); await page.waitForTimeout(700)
const r3 = await win()
await shot(page, 'O3-raised-again')
const blank = page.locator('#tplModal').getByText(/An ordinary desk/).first()
const bb = await blank.boundingBox().catch(() => null)
console.log('blank bb', JSON.stringify(bb))
if (bb) await page.touchscreen.tap(bb.x + bb.width / 2, bb.y + bb.height / 2)
await page.waitForTimeout(700)
const o3 = await win()
const act = await page.evaluate(() => document.activeElement.tagName + '#' + document.activeElement.id + '.' + document.activeElement.className)
await shot(page, 'O3-after-blank-tap')
record({ id: 'O3', what: 'window raised then tap blank space', raised: r3.translates, afterBlank: o3.translates, active: act, boxTop: [r3.boxTop, o3.boxTop], summary: `O3 raised ${JSON.stringify(r3.translates)} top ${r3.boxTop}; after blank tap ${JSON.stringify(o3.translates)} top ${o3.boxTop} active ${act}` })
await closeDuty()
// O1: keys up already, tap SECOND box lower in same window (first row End, then last row End)
await openDuty()
const first = tms().nth(1)  // first role's End
await tapBox(page, first); await page.waitForTimeout(400)
await keysUp(page); await page.waitForTimeout(400)
const s1 = await state(page, await first.elementHandle()); const w1 = await win()
await shot(page, 'O1-1-first-box-keys-up')
await tapBox(page, lastEnd); await page.waitForTimeout(800)
const s2 = await state(page, await lastEnd.elementHandle()); const w2 = await win()
await shot(page, 'O1-2-second-box-tapped-keys-up')
record({ id: 'O1', what: 'keys up, tap second box lower in the same window', first: { rect: s1.rect, translates: w1.translates }, second: { rect: s2.rect, covered: s2.covered, focused: s2.focused, translates: w2.translates }, summary: `O1 first ${JSON.stringify(s1.rect)} tr ${JSON.stringify(w1.translates)}; second ${JSON.stringify(s2.rect)} room 538 covered ${s2.covered} focused ${s2.focused} tr ${JSON.stringify(w2.translates)}` })
await closeDuty()
console.log('errors', errors)
await browser.close()
