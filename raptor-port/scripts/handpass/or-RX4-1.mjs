// RX4-1: the window's route. Ranger (member) files an OD for Ranger, Hex, Hunter; Saber publishes Wed; un-pick Ranger, Save; then Hex's 10:00.
import * as L from './or-RX4-lib.mjs'
const { j } = L
const out = {}
const { ctx, page: p } = await L.open('us', 'us')
out.filed = await L.fileInput(p, { type: 'OD', people: ['Ranger', 'Hex', 'Hunter'], from: L.ISO, to: L.ISO })
console.log('filed', j(out.filed))
const iid = out.filed[0].iid
out.toastFiled = await L.toast(p)
await L.signOut(p); await L.signIn(p, 'ad', 'a')
out.pub = await L.signAndPublish(p, L.DI); console.log('PUBLISH', j(out.pub))
out.c0 = await L.counts(p, { noBoard: true }); console.log('COUNTS 0', L.fmt(out.c0))
await L.toMonth(p, L.ISO); await L.openDay(p, L.ISO)
out.card0 = (await L.dayCardText(p)).filter(t => /OD|Hex/.test(t)); console.log('card0', j(out.card0))
await L.shot(p, 'rx4-1-1-card-before'); await L.closeDay(p)
await L.openInputWindow(p, iid, L.ISO)
await L.shot(p, 'rx4-1-2-window')
const rid = await L.csId(p, 'Ranger')
await p.locator(`${L.WIN} [data-pp="${rid}"]`).click(); await p.waitForTimeout(200)
out.pressedAfter = await p.evaluate(sel => [...document.querySelectorAll(`${sel} [data-pp][aria-pressed="true"]`)].map(b => window.PEOPLE[b.getAttribute('data-pp')]?.cs), L.WIN)
console.log('pressed after un-pick', j(out.pressedAfter))
await L.shot(p, 'rx4-1-3-ranger-unpicked')
const m = await L.toastMark(p)
await p.locator('#inpEditSave').click(); await p.waitForTimeout(800)
out.saveToasts = await L.toastsSince(p, m); console.log('save toasts', out.saveToasts, '| sheets', j(await L.sheets(p)))
out.inputs1 = (await L.allInputs(p)).filter(r => r.type === 'OD'); console.log('OD inputs', j(out.inputs1))
out.c1 = await L.counts(p, { keepWin: true, noBoard: true }); console.log('COUNTS 1', L.fmt(out.c1))
await L.shot(p, 'rx4-1-4-togoout-ranger-out')
await p.locator('.chgwin .win-x').first().click().catch(() => {}); await p.waitForTimeout(300)
await L.toMonth(p, L.ISO); await L.openDay(p, L.ISO)
out.card1 = (await L.dayCardText(p)).filter(t => /OD|Hex/.test(t)); console.log('card1', j(out.card1))
await L.shot(p, 'rx4-1-5-card-after-takeout'); await L.closeDay(p)
// Hex's row of Wed's Unavailable list, 10:00 in the start box
await L.toWeek(p)
const row = L.day(p).locator('.sec-unav .pl-row').filter({ has: p.locator('.puck', { hasText: 'Hex' }) }).first()
await row.scrollIntoViewIfNeeded(); await p.waitForTimeout(300)
out.rowBefore = (await row.innerText()).replace(/\s+/g, ' ')
console.log('Hex row before:', out.rowBefore)
await L.shot(p, 'rx4-1-6-hex-row-before')
const box = row.locator('.t-s').first()
await box.click(); await p.keyboard.press('Control+A'); await p.keyboard.type('10:00'); await box.evaluate(x => x.blur()); await p.waitForTimeout(900)
out.toastType = await L.toast(p); console.log('toast:', out.toastType)
out.inputs2 = (await L.allInputs(p)).filter(r => r.type === 'OD'); console.log('OD inputs after typing', j(out.inputs2))
out.c2 = await L.counts(p, { keepWin: true }); console.log('COUNTS 2', L.fmt(out.c2))
await L.shot(p, 'rx4-1-7-togoout-hex-own')
out.winAll = await L.winRead(p)
await p.locator('.chgwin .win-x').first().click().catch(() => {}); await p.waitForTimeout(300)
await L.toWeek(p)
out.unav = await p.evaluate(di => { const d = [...document.querySelectorAll('#eWeek .day:not(.peek)')][di]; return [...d.querySelectorAll('.sec-unav .pl-row')].map(r => r.innerText.replace(/\s+/g, ' ').trim()) }, L.DI)
console.log('Wed unavailable rows:', j(out.unav))
await L.shot(p, 'rx4-1-8-unavailable-after')
await L.toMonth(p, L.ISO); await L.openDay(p, L.ISO)
out.card2 = (await L.dayCardText(p)).filter(t => /OD|Hex/.test(t)); console.log('card2', j(out.card2))
await L.shot(p, 'rx4-1-9-card-final'); await L.closeDay(p)
console.log('ERRORS', L.errs.join(' | ') || 'none')
out.errs = L.errs.slice()
L.saveRes('1', out)
await ctx.close(); await L.browser.close()
