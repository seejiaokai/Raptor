import * as L from './sf-C-lib.mjs'
const { launch, ctxOpen, openBoard, closeBoard, bPut, bPutKey, bPutFill, puckAt, bType, bf, sleep, shot, rec, go, errors, chipLine, warnLines } = L
const S = '19'
const b = await launch()
const { p } = await ctxOpen(b, {})
await go(p, 'editsched')
await p.evaluate(() => { window.addWave(4, 'sc'); window.addWave(4, 'avalon') }); await sleep(500)
await openBoard(p, 4)
const st = []
// SC AM spares: row 2 Wildcard (OCU, no SC day currency) ; row 3 Recon (OCU, no SC day currency)
st.push(await bPut(p, 4, 0, 0, 2, 'p', ['ignite']))
st.push(await bPut(p, 4, 0, 0, 3, 'p', ['bruise']))
// SC PM spare pair that breaks a seat rule: D pilot Diesel with C WSO Hex (CO approval)
st.push(await bPut(p, 4, 0, 1, 2, 'p', ['fantom']))
st.push(await bPut(p, 4, 0, 1, 2, 'w', ['rocky']))
// AVALON spare: Torch (no night currency)
st.push(await bPut(p, 4, 1, 0, 2, 'p', ['razer']))
rec(S, 'set-up through the arm-and-pick route', 'seated', st, st.every(x => x !== 'FAILED') ? 'PASS' : 'NOT WALKED')
// the two SC-AM spares lose their SC DAY currency afterwards (the palette refuses a non-current man, so he is seated first)
await closeBoard(p)
// set-up through the Quals page's own control: take SC DAY currency off Torch and Gambit
await go(p, 'quals'); await p.locator('#qEdit').click(); await sleep(500)
for (const id of ['ignite', 'bruise']) { await p.locator(`td[data-q="${id}|scDay"]`).click(); await sleep(300) }
const qOff = await p.evaluate(() => ['ignite', 'bruise'].map(i => i + ':' + window.PEOPLE[i].quals.scDay))
rec(S, 'set-up: SC DAY currency taken off Torch and Gambit on the Quals page', 'scDay false for both', qOff, qOff.every(x => /false/.test(x)) ? 'PASS' : 'NOT WALKED')
await openBoard(p, 4)
const w0 = await warnLines(p), c0 = await chipLine(p)
await shot(p, '19-1-standing')
const mine = w => w.filter(x => /Gambit|Diesel|Hex|Torch|Ridge/.test(x))
rec(S, 'all three shifts standing by', 'designer expected silence for all; the app (before this change) already checks currency on standby rows — RECORD each; the seat rule (Diesel+Hex) must be silent', { mine: mine(w0), w0 }, !mine(w0).some(x => /CO approval|combination|solo/i.test(x)) ? 'RECORD' : 'FAIL', 'C-19-1-standing.png')
// type SC AM R, SC PM R, AVALON R
await bType(p, bf(4, 0, 0, 'rl'), '06:30')
const w1 = await warnLines(p)
await shot(p, '19-2-sc-am-flies')
const cur1 = mine(w1).filter(x => /currency|current|lapsed|SC/i.test(x))
rec(S, 'type SC AM R 06:30 (Torch and Gambit on the two SPARE rows; neither holds SC day currency now)', 'a currency warning for them now; asked once per shift (one line each at most, not one per row)', { mine: mine(w1), cur1 }, cur1.length >= 1 ? 'PASS' : 'FAIL', 'C-19-2-sc-am-flies.png')
await bType(p, bf(4, 0, 1, 'rl'), '12:30')
const w2 = await warnLines(p)
await shot(p, '19-3-sc-pm-flies')
const seat2 = mine(w2).filter(x => /Diesel|Hex/.test(x) && /approval|combination|solo/i.test(x))
rec(S, 'type SC PM R 12:30 (Diesel in front, Hex behind: a CAT D pilot with a CAT C WSO)', 'the seat-rule warning appears for that row', { mine: mine(w2), seat2 }, seat2.length >= 1 ? 'PASS' : 'FAIL', 'C-19-3-sc-pm-flies.png')
await bType(p, bf(4, 1, 0, 'rl'), '18:30')
const w3 = await warnLines(p)
await shot(p, '19-4-avalon-flies')
rec(S, 'type AVALON R 18:30 (Ridge SPARE, no night currency)', 'a currency warning for Ridge', { ridge: w3.filter(x => /Ridge/.test(x)) }, w3.some(x => /Ridge/.test(x) && /currency|current|night/i.test(x)) ? 'PASS' : 'FAIL', 'C-19-4-avalon-flies.png')
// clear them all: back to silence
await bType(p, bf(4, 0, 0, 'rl'), ''); await bType(p, bf(4, 0, 1, 'rl'), ''); await bType(p, bf(4, 1, 0, 'rl'), '')
const w4 = await warnLines(p)
rec(S, 'clear all three R', 'the standing currency lines stay (they existed before R); no seat-rule line', { mine: mine(w4) }, !mine(w4).some(x => /CO approval|combination/i.test(x)) ? 'PASS' : 'FAIL')
rec(S, 'browser error list', 'empty', errors, errors.length ? 'FAIL' : 'PASS')
await b.close()
