import { world, usualSat, groundNow, oilOf, drag, puckSel, rowSel, frameBoard, toast, toastsAll, undoState, measure, SAT_DI } from './on-A-lib.mjs'
const W = await world({ tag: 'A9' })
const { page, tid, press, shot, errors } = W
const iid = await usualSat(W)
await frameBoard(page)
await drag(page, page.locator(puckSel(1)), page.locator(puckSel(0)))
await press(tid('oilconf-cancel')); await page.waitForTimeout(700)
console.log('bar', await tid('oilbar-text').innerText().catch(() => 'NO'))
const before = await groundNow(page), oil0 = await oilOf(page, iid)
// the Hangar open day row's buttons
const rowEl = page.locator('#sbBoard .sb-arow').filter({ has: page.locator(`[data-slot="g:${SAT_DI}.1"]`) }).first()
console.log('row buttons', JSON.stringify(await rowEl.evaluate(r => [...r.querySelectorAll('button')].map(b => (b.title || b.getAttribute('aria-label') || '') + '|' + b.textContent.trim() + '|' + (b.className || '').slice(0, 20) + '|' + (b.getAttribute('data-bdel') || b.getAttribute('data-del') || '')))))
const x = rowEl.locator('button').last()
await x.click(); await page.waitForTimeout(700)
console.log('after delete click: ground', JSON.stringify(await groundNow(page)), 'toast', await toast(page), 'confirm?', await page.locator('[data-testid*="conf"], .airpop-box').count(), 'bar still', await tid('oilbar').count(), 'question', await tid('oilconf').count())
await shot('A9-1-after-row-deleted')
const rows = await groundNow(page)
const undo0 = await undoState(page)
await press(tid('oilbar-answer')); await page.waitForTimeout(500)
console.log('after Answer OIL: question', await tid('oilconf').count(), 'bar', await tid('oilbar').count(), 'bar text', await tid('oilbar-text').innerText().catch(() => 'NO'), 'toast', await toast(page), '| toasts', JSON.stringify((await toastsAll(page)).slice(-3)))
console.log('ground', JSON.stringify(await groundNow(page)), 'same as after delete', JSON.stringify(await groundNow(page)) === JSON.stringify(rows), 'oil', (await oilOf(page, iid)) === oil0, 'undoSame', (await undoState(page)) === undo0)
await shot('A9-2-after-answer-oil')
console.log('errors', JSON.stringify(errors))
await W.ctx.close(); process.exit(0)
