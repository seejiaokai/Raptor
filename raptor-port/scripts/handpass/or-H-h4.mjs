import { declareHoliday, launch, open, fileInput, openFromList, describeWin, shot, WIN, toastMark, toastsSince, save, errs, as, badgeText, bellRead, drag, oilAnswer } from './or-H-lib.mjs'
const out = {}
const log = (k, v) => { out[k] = v; console.log('## ' + k + ' ' + JSON.stringify(v)) }
const browser = await launch()
const { ctx, page } = await open(browser)
const who = iid => page.evaluate(i => { const r = window.INPUTS.find(x => x.iid === i); return r ? { people: r.people.map(e => window.PEOPLE[e.p].cs + '(by ' + window.PEOPLE[e.by]?.cs + ')'), by: window.PEOPLE[r.by]?.cs, oil: r.oil === undefined ? 'undefined' : r.oil, date: r.date } : null }, iid)
await as(page, 'Ranger')
const r = await fileInput(page, { type: 'Training', from: '2026-07-15', to: '2026-07-15', timed: ['09:00', '12:00'] })
const iid = r[0].iid
log('filed-no-question', await who(iid))
await as(page, 'Saber')
log('holiday-declared-wed15', await declareHoliday(page, '2026-07-15'))
await shot(page, 'H4-0-holiday-declared')
log('stuck-dialogs', await page.locator('[data-testid="oilconf"]').count())
await shot(page, 'H4-1-after-filing-closed')
/* Saber adds Tally */
await as(page, 'Saber')
await page.evaluate(() => window.go('editsched')); await page.locator('#eWeek .day').first().waitFor()
const day = page.locator('#eWeek .day:not(.peek)').nth(2); await day.scrollIntoViewIfNeeded()
const row = day.locator('.sec-grnd .pl-row', { hasText: 'Training' }).first()
log('row-found', await row.count())
await row.scrollIntoViewIfNeeded()
const tally = page.locator('#eRoster .rpuck[data-person="nick"]:visible').first()
let m = await toastMark(page)
await drag(page, tally, row.getByText('+ add').first())
log('after-add', { toast: await toastsSince(page, m), inputs: await who(iid), oilSheet: await page.locator('[data-testid="oilconf"]').count(), sheetText: await page.locator('[data-testid="oilconf"]').first().innerText().catch(() => null) })
await shot(page, 'H4-2-after-add-question')
log('close-again', await oilAnswer(page, 'close'))
await page.waitForTimeout(400)
log('after-close', { sheet: await page.locator('[data-testid="oilconf"]').count(), inputs: await who(iid) })
await shot(page, 'H4-3-after-close')
/* before he steps out: where does each bell go? (the question waits on the filer at the time) */
await as(page, 'Ranger')
const pre = await bellRead(page, { close: false })
log('pre-ranger-bell', { oilQuestionOpened: pre.oilQuestionOpened, list: pre.list })
await shot(page, 'H4-3b-ranger-bell-before-stepping-out')
if (pre.oilQuestionOpened) await oilAnswer(page, 'close')
await page.keyboard.press('Escape')
await as(page, 'Saber')
const pre2 = await bellRead(page, { close: false })
log('pre-saber-bell', { oilQuestionOpened: pre2.oilQuestionOpened, list: pre2.list })
if (pre2.oilQuestionOpened) await oilAnswer(page, 'close')
await page.keyboard.press('Escape'); await page.locator('#notifyBell').click().catch(() => {})
/* Ranger takes himself out */
await as(page, 'Ranger')
await openFromList(page, iid)
const d = await describeWin(page)
log('ranger-window', { fields: d.fields.map(f => f.id), buttons: d.buttons.map(b => b.id + ':' + b.text).filter(t => t.length > 5), tail: d.text.slice(-260) })
m = await toastMark(page)
await page.locator('[data-testid="inped-takeout"]').click(); await page.waitForTimeout(400)
await page.locator('[data-testid="inped-takeout-yes"]').click(); await page.waitForTimeout(700)
log('after-take-out', { toast: await toastsSince(page, m), inputs: await who(iid), sheet: await page.locator('[data-testid="oilconf"]').count() })
await shot(page, 'H4-4-after-ranger-out')
/* the card and the List */
await page.evaluate(() => window.go('inputs')); await page.waitForTimeout(300)
await page.locator('#inListBtn[aria-pressed="false"]').click().catch(() => {})
await page.locator('#inRangeBtn').click().catch(() => {}); await page.locator('#inRangeAll').click().catch(() => {}); await page.waitForTimeout(300)
await page.locator('select').first().selectOption({ label: 'Everyone' }).catch(() => {})
log('list-rows', await page.evaluate(() => [...document.querySelectorAll('[data-popiid]')].map(e => e.innerText.replace(/\s+/g, ' ').slice(0, 140))))
await shot(page, 'H4-5-list')
await page.locator('#inCalBtn').click(); await page.waitForTimeout(300)
const MON = ['january', 'february', 'march', 'april', 'may', 'june', 'july']
for (let i = 0; i < 12 && !(await page.locator('[data-icday="2026-07-15"]').count()); i++) {
  const [mn, yr] = (await page.locator('#inpCal .ic-mon').textContent()).trim().toLowerCase().split(/\s+/)
  const at = +yr * 12 + ['january','february','march','april','may','june','july','august','september','october','november','december'].findIndex(x => x.startsWith(mn))
  await page.locator(at < 2026 * 12 + 6 ? '#icNext' : '#icPrev').click(); await page.waitForTimeout(200)
}
await page.locator('[data-icday="2026-07-15"]').focus(); await page.keyboard.press('Enter'); await page.waitForSelector('[data-testid="win-inputsday"]')
log('card', await page.locator('[data-testid="win-inputsday"]').innerText().then(t => t.replace(/\s+/g, ' ')))
await shot(page, 'H4-6-card')
await page.locator('[data-testid="win-inputsday-x"]').click().catch(() => {})
/* bells */
await as(page, 'Saber')
const sb = await bellRead(page, { close: false })
log('saber-bell-tap', { before: sb.before, oilQuestionOpened: sb.oilQuestionOpened, list: sb.list })
await shot(page, 'H4-7-saber-bell')
await as(page, 'Ranger')
await page.keyboard.press('Escape')
const rb = await bellRead(page, { close: false })
log('ranger-bell-tap', { before: rb.before, oilQuestionOpened: rb.oilQuestionOpened, list: rb.list })
await shot(page, 'H4-8-ranger-bell')
log('errors', errs)
save('H4', out)
await browser.close()
