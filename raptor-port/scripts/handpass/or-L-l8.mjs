await page.locator('#eWeek .day:not(.peek)').nth(2).locator('.sec-grnd').scrollIntoViewIfNeeded()
await page.locator('#eWeek .day:not(.peek)').nth(2).locator('.sec-grnd').screenshot({ path: 'docs/img/handpass/2026-10-12-one-rule/L/l8-3-week-ground.png' })
