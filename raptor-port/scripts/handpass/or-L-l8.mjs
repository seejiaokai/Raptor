R.inputs1 = R.inputs1.filter(r => r.title === 'L8 training')
/* now drag that ALL AVAIL puck onto the Training's row */
const src = page.locator('#schedBoard .sb-panel.grnd .sb-arow', { has: page.locator('[data-fill="g:2.3.+"]') }).locator('.puck.allavail, .puck[data-person="allavail"]').first()
const trow = page.locator('#schedBoard .sb-panel.grnd .sb-arow', { hasText: 'L8 TRAINING' }).first()
const tdest = trow.locator('.ppl').first()
await tdest.scrollIntoViewIfNeeded()
sb = await src.boundingBox(); db = await tdest.boundingBox()
m = await toastMark(page)
await mouseDrag(page, centre(sb), { x: db.x + db.width - 12, y: db.y + db.height / 2 })
R.step2Toast = await toastsSince(page, m)
await shot(page, 'l8-2-after-drag-board')
R.boardAfter2 = await page.evaluate(() => [...document.querySelectorAll('#schedBoard .sb-panel.grnd .sb-arow')].filter(r => r.offsetParent).map(r => ({ name: r.querySelector('textarea.ain')?.value, pucks: [...r.querySelectorAll('.puck')].map(p => p.innerText.replace(/\s+/g, ' ').trim()) })))
