await page.locator('#schedBoard [data-gradd="2"]:visible').first().click(); await page.waitForTimeout(600)
const own = page.locator('#schedBoard [data-fill="g:2.3.+"]:visible').first()
const ph = page.locator('#sbRoster .rpuck[data-person="allavail"]:visible').first()
await own.scrollIntoViewIfNeeded()
let sb = await ph.boundingBox(), db = await own.boundingBox()
let m = await toastMark(page)
await mouseDrag(page, centre(sb), centre(db))
R.step1Toast = await toastsSince(page, m)
await shot(page, 'l8-1-allavail-on-own-row')
