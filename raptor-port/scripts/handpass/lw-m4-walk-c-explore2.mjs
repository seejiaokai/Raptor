// walker C — exploration 2: the Move flow, the approved leave's window, the delete flow, the bell's tap
process.env.LW_OUT ||= '../../docs/img/handpass/2026-10-27-lw-m4/c/explore'
const L = await import('./lw-m4-lib.mjs')
const { T, shot, press, vis, txt } = L
console.log('[lw-m4-walk-c-explore2 v1]')
const w = await L.newCtx('desk')
const P = w.page
const ids = () => P.evaluate(() => [...document.querySelectorAll('[data-testid]')].filter(e => e.getBoundingClientRect().height > 0).map(e => e.dataset.testid).filter(t => /^(bid|decide|sel|dl|portion|sheet|move|settings|open|bell|undo|closed|remarks|award)/.test(t)))
await L.signIn(w, 'member')
await L.openCell(w, 'bane', '2026-01-13')
await L.placeLeave(w, 'LL')
await L.switchTo(w, 'admin')
await L.openCell(w, 'bane', '2026-01-13')
await press(w, T('decide-shift'))
await P.waitForTimeout(500)
console.log('AFTER Move press:', JSON.stringify(await ids()))
await shot(w, 'move-armed')
await press(w, T('cell-bane-2026-01-14'))
await P.waitForTimeout(500)
console.log('AFTER dest tap:', JSON.stringify(await ids()))
await shot(w, 'move-dest')
if (await vis(P, T('move-confirm'))) { await press(w, T('move-confirm')); await P.waitForTimeout(600) }
console.log('AFTER confirm:', JSON.stringify(await ids()))
await shot(w, 'move-done')
// the moved bid's window
await L.openCell(w, 'bane', '2026-01-14')
console.log('Window on 14th:', JSON.stringify(await ids()))
await press(w, T('decide-approve'))
await P.waitForTimeout(500)
await shot(w, 'approved-in-window')
console.log('After approve:', JSON.stringify(await ids()), await txt(P, T('bid-placed')))
await L.closeWin(w)
await L.openCell(w, 'bane', '2026-01-14')
console.log('Reopened approved:', JSON.stringify(await ids()), await txt(P, T('bid-placed')))
await shot(w, 'approved-reopen')
console.log('errs', w.errs)
await w.ctx.close()
await L.closeBrowser()
console.log('DONE')
