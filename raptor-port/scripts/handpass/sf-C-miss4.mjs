import * as L from './sf-C-lib.mjs'
const { launch, ctxOpen, openBoard, closeBoard, bPut, bType, bf, sleep, shot, rec, go, errors, chipLine } = L
const S = 'P'
const b = await launch()
const { p } = await ctxOpen(b, {})
await go(p, 'editsched'); await sleep(400)
const hd = () => p.evaluate(() => document.querySelector('#eWeek .day-head') ? document.querySelector('#eWeek .day-head').innerText.replace(/\s+/g, ' ').slice(0, 40) : '')
const tabs = await p.evaluate(() => [...document.querySelectorAll('button')].filter(e => e.offsetParent && /^Jul \d+$/.test(e.innerText.trim())).map(e => e.innerText.trim() + '|' + e.className + '|' + JSON.stringify(e.dataset)))
console.log(tabs)
await p.getByRole('button', { name: 'Jul 20', exact: true }).first().click(); await sleep(1500)
console.log('now', await hd())
await p.evaluate(() => { window.addWave(0, 'avalon'); window.addWave(0, 'sc'); window.addWave(0, 'bb') }); await sleep(500)
await openBoard(p, 0)
const st = [await bPut(p, 0, 2, 0, 0, 'p', ['dice']), await bPut(p, 0, 2, 0, 2, 'p', ['bane']), await bPut(p, 0, 3, 0, 2, 'p', ['nact']), await bPut(p, 0, 4, 0, 2, 'p', ['taipan'])]
await bType(p, bf(0, 2, 0, 'rl'), '18:30'); await bType(p, bf(0, 3, 0, 'rl'), '06:30')
await p.locator('#schedBoard [data-safly="0.4.0.2"]:visible').first().click(); await sleep(600)
const kinds = await p.evaluate(() => window.DAYS[0].waves.map(w => w.kind))
const chW2 = await chipLine(p)
const badge2 = await p.evaluate(() => document.querySelectorAll('#eWeek .day')[0].querySelector('.badge').textContent)
rec(S, 'next week loaded; Monday: AVALON R 18:30, SC AM R 06:30, one BB row ticked by hand', 'chips lit', { st, kinds, chW2, badge2 }, 'RECORD')
await closeBoard(p); await go(p, 'editsched')
await p.getByRole('button', { name: 'Jul 13', exact: true }).first().click(); await sleep(1500)
console.log('back on', await hd())
const pk = await p.evaluate(() => { const d = document.querySelector('#eWeek .day.peek[data-peek-day="0"]'); return d ? { head: d.querySelector('.day-head').innerText.replace(/\s+/g, ' '), flies: (d.innerText.match(/✓ FLIES[^\n]{0,40}/g) || []).slice(0, 12), text: d.innerText.replace(/\s+/g, ' ').slice(0, 900) } : null })
await p.locator('#eWeek .day.peek[data-peek-day="0"]').scrollIntoViewIfNeeded(); await sleep(400)
await shot(p, 'P-1-peek-monday')
rec(S, 'the next-week peek (week of Jul 13, looking at Monday Jul 20)', '"✓ FLIES ·" before the words of the rows that fly; the day figure agrees with the week (AVALON term, SC term, BB term)', pk, pk && pk.flies.length ? 'RECORD' : 'FAIL', 'C-P-1-peek-monday.png')
rec(S, 'browser error list', 'empty', errors, errors.length ? 'FAIL' : 'PASS')
await b.close()
