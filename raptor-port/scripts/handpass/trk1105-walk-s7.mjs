/* S7 — a save that failed BEFORE the Tracker was ever opened (D admin).  node scripts/handpass/trk1105-walk-s7.mjs */
import { open, navTo, words, grade, mark, click, shot, setFail, retryBtn, mk, sleep } from './trk1105-walk-lib.mjs'
console.log('trk1105-walk-s7 v1')
const L = mk('S7')
const { browser, page, errors } = await open({ tracker: false, fail: true })
await navTo(page, 'editsched'); await sleep(800)
await setFail(page, true)
await page.locator('.txed:visible').first().click(); await page.keyboard.type('walk note 1105'); await page.keyboard.press('Tab'); await sleep(3500)
let w = await words(page)
L.ok('Edit Schedule change with saves blocked: the band shows', 'D', 'admin', /Not saved/.test(w.band), `band "${w.band}"`, await shot(page, 'S7-1-band-on-editschedule'))
// open the Tracker for the first time, polling every ~40 ms for a corner that says saved beside the band
await page.evaluate(() => { window.__viol = []; window.__poll = setInterval(() => { const s = document.getElementById('saveStat'), b = document.querySelector('.topbar .savestat.failed'); if (s && b && s.getBoundingClientRect().width > 1 && /saved/i.test(s.textContent)) window.__viol.push(s.textContent.trim() + '@' + Math.round(performance.now())) }, 40) })
await page.locator('#topnav a[data-page="tracker"]:visible').click()
await page.waitForSelector('#flowSvg .ball', { timeout: 30000 })
await sleep(300)
const first = await shot(page, 'S7-2-tracker-first-frame')
await sleep(1500)
await mark(page, 'ST-02', 'dco', false, 2500)
w = await words(page)
const viol = await page.evaluate(() => window.__viol)
L.ok('first visit + a mark: the corner never said saved while the band stood (polled every 40 ms)', 'D', 'admin', viol.length === 0 && w.corner === '' && /Not saved/.test(w.band), `violations ${JSON.stringify(viol)}; corner "${w.corner}"; band "${w.band}"`, await shot(page, 'S7-3-marked-failing'))
await setFail(page, false)
await retryBtn(page).click(); await sleep(2800)
w = await words(page)
L.ok('block lifted + Retry: the band goes and the corner words come back', 'D', 'admin', !w.band && /saved/.test(w.corner), `band "${w.band}" corner "${w.corner}"`, await shot(page, 'S7-4-recovered'))
L.note('errors', errors.join(' | ').slice(0, 400) || 'none')
await browser.close()
L.save('S7')
