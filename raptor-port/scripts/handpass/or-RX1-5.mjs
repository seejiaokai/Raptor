// RX1-5 — ALL AVAIL dropped on "+ add" of a weekday Personal input's row (Wed 15 Jul, Ranger 17:00-18:00)
import { launch, openWorld, fileX, shotX, rowIdx, inputOf, errs, toWeek, openBoard, centre, weekRowEl, weekRowNames, boardRowEl, boardRowNames, weekLines, boardLines, inputsSurf, closeDayWin, listRow, log, drag2, drag3, rosterPuckOf, toastMark, toastsSince, toastNow, waitQuiet, undoTitle, undoRedo } from './or-RX1-lib.mjs'
const browser = await launch()
const { page: p } = await openWorld(browser, { fresh: false })
const DI = 2
const f = await fileX(p, { type: 'Personal', person: 'Ranger', from: '2026-07-15', to: '2026-07-15', timed: ['17:00', '18:00'] })
const iid = f.made[0].iid
const ri = await rowIdx(p, DI, iid)
await openBoard(p, DI)
let row = boardRowEl(p, DI, ri); await centre(row); await p.waitForTimeout(300); await waitQuiet(p)
let m = await toastMark(p)
await drag2(p, await rosterPuckOf(p, '#sbRoster', 'ALL AVAIL'), row.locator('.addz').first())
log('toasts', await toastsSince(p, m), '| now', await toastNow(p), '| oilq', await p.locator('[data-testid="oilconf"]').count())
log('people', (await inputOf(p, iid)).people, 'board row', (await boardRowNames(p, DI, ri)).names, 'lines', await boardLines(p, DI))
row = boardRowEl(p, DI, ri); await centre(row); await p.waitForTimeout(250)
const html = await row.evaluate(r => [...r.querySelectorAll('.puck')].map(e => e.outerHTML.slice(0, 400)))
log('puck html', html)
const cnt = await row.evaluate(r => [...r.querySelectorAll('*')].filter(e => e.children.length === 0 && /^\d+$/.test(e.textContent.trim())).map(e => ({ tag: e.tagName, cls: e.className, text: e.textContent, attrs: [...e.attributes].map(a => a.name + '=' + a.value).join(' ') })))
log('numeric leaves in row', cnt)
await shotX(p, 'rx1-5-1-board-after-drop')
/* tap on the count (board, OIL Earn off) */
const winFacts = () => p.evaluate(() => { const w = document.querySelector('.availwin'); if (!w) return null; return { head: w.innerText.replace(/\s+/g, ' ').slice(0, 200), names: [...w.querySelectorAll('.rpuck')].map(e => e.textContent.trim().replace(/\s+/g, ' ')), n: w.querySelectorAll('.rpuck').length } })
await row.locator('.oilcount').first().click(); await p.waitForTimeout(800)
const w1 = await winFacts()
log('window after tapping the count', w1 && { head: w1.head, n: w1.n, hasRanger: w1.names.some(x => x.startsWith('Ranger')), first10: w1.names.slice(0, 10) })
await shotX(p, 'rx1-5-2-board-count-window')
await p.keyboard.press('Escape'); await p.waitForTimeout(300)
if (await p.locator('.availwin').count()) { await p.locator('.availwin [title="Close"], .availwin .win-x, .availwin button[aria-label*="lose"]').first().click().catch(() => {}); await p.waitForTimeout(300) }
log('window closed', await p.locator('.availwin').count() === 0)
/* the week */
await waitQuiet(p)
await toWeek(p)
const wrow = weekRowEl(p, DI, ri); await centre(wrow); await p.waitForTimeout(300)
log('week row', await weekRowNames(p, DI, ri), 'lines', await weekLines(p, DI), 'count', await wrow.locator('.oilcount').first().textContent(), await wrow.locator('.oilcount').first().getAttribute('title'))
await centre(weekRowEl(p, DI, ri)); await shotX(p, 'rx1-5-3-week-row')
await weekRowEl(p, DI, ri).locator('.oilcount').first().click(); await p.waitForTimeout(800)
const w2 = await winFacts()
log('week count window', w2 && { n: w2.n, hasRanger: w2.names.some(x => x.startsWith('Ranger')) })
await shotX(p, 'rx1-5-4-week-count-window')
await p.keyboard.press('Escape'); await p.waitForTimeout(300)
const sf = await inputsSurf(p, iid, '2026-07-15'); log('card', sf); await shotX(p, 'rx1-5-5-card')
log('errs', errs)
await browser.close()
