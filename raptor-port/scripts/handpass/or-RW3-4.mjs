import { open, fileInput, toWeek, shot, saveRes, errs, browser, toast, inputsOf, signAndPublish, dayStat, openChanges, changesRead, closeChanges, toView, undoRedo } from './or-RW3-lib.mjs'
const R = {}
const DI3 = 3
const { ctx, page } = await open('ad', 'a')
const unav = async root => page.evaluate(([root]) => { const d = [...document.querySelectorAll(`${root} .day:not(.peek)`)][3]; return [...d.querySelectorAll('.sec-unav .pl-row, .sec-inp .pl-row')].map(r => r.innerText.replace(/\s+/g, ' ').trim()).filter(t => /^OD /.test(t) && /Drifter|Hunter/.test(t)) }, [root])
R.filed = await fileInput(page, { type: 'OD', people: ['Drifter', 'Hunter'], from: '2026-07-16', to: '2026-07-16' })
R.pub = await signAndPublish(page, DI3)
await toWeek(page)
R.beforeRows = await unav('#eWeek')
R.statBefore = await dayStat(page, DI3)
const box = page.locator('#eWeek .day:not(.peek)').nth(DI3).locator('[data-inp$="~slipway.str"]').first()
await box.scrollIntoViewIfNeeded()
await box.click(); await page.waitForTimeout(150)
await page.keyboard.press('Control+A'); await page.keyboard.type('10:00'); await page.keyboard.press('Tab')
await page.waitForTimeout(800)
R.toastTyped = await toast(page)
R.inputs = (await inputsOf(page)).filter(r => r.type === 'OD' && /Jul 16/.test(r.date))
R.rowsAfter = await unav('#eWeek')
R.statAfter = await dayStat(page, DI3)
await page.locator('#eWeek .day:not(.peek)').nth(DI3).locator('.sec-unav').scrollIntoViewIfNeeded()
await page.locator('#eWeek .day:not(.peek)').nth(DI3).locator('.sec-unav').screenshot({ path: 'docs/img/handpass/2026-10-12-one-rule/RW3/rw3-4-1-unav-after-typing.png' })
await openChanges(page, DI3)
R.changes = await changesRead(page)
await shot(page, 'rw3-4-2-changes-window')
await closeChanges(page)
/* publish again */
R.pub2 = await signAndPublish(page, DI3)
await toWeek(page)
R.statAfterPub = await dayStat(page, DI3)
R.weekRowsAfterPub = await unav('#eWeek')
await toView(page)
R.viewRowsAfterPub = await unav('#vWeek')
await page.locator('#vWeek .day:not(.peek)').nth(DI3).scrollIntoViewIfNeeded()
await page.locator('#vWeek .day:not(.peek)').nth(DI3).locator('.sec-unav').screenshot({ path: 'docs/img/handpass/2026-10-12-one-rule/RW3/rw3-4-3b-viewonly-unav-after-publish.png' })
await shot(page, 'rw3-4-3-viewonly-after-publish')
R.inputsEnd = (await inputsOf(page)).filter(r => r.type === 'OD' && /Jul 16/.test(r.date))
saveRes('RW3-4', R)
console.log(JSON.stringify(R, null, 1))
console.log('ERRS', errs.join('\n'))
await browser.close()
