// G3 (load an older version) - Wed 15 Jul: Meeting of three, publish, add Tally, publish AL1, add Hex, load ORIGINAL
import { open, fileInput, toWeek, toBoard, toView, shot, shotEl, browser, errs, readRows, inputsRead, signAndPublish, counts, sleep, toastMark, toastsSince, dragLocToLoc, rosterPuckOf, weekRow, csId, reload, saveData } from './or-G-lib.mjs'
const rec = {}
const DI = 2, TITLE = 'Range brief'
const { ctx, page } = await open()
const mine = async () => (await inputsRead(page)).filter(r => r.title === TITLE)
const T = await csId(page, 'Tally'), H = await csId(page, 'Hex')
rec.filed = await fileInput(page, { type: 'Meeting', people: ['Drifter', 'Hunter', 'Ranger'], from: '2026-07-15', to: '2026-07-15', timed: ['14:00', '15:00'], title: TITLE })
console.log('filed', JSON.stringify(rec.filed))
rec.pub1 = await signAndPublish(page, DI); console.log('pub1', JSON.stringify(rec.pub1))
await toWeek(page)
let m = await toastMark(page)
await dragLocToLoc(page, rosterPuckOf(page, T), weekRow(page, DI, TITLE).locator('.addz'))
rec.addTally = await toastsSince(page, m)
rec.afterTally = { inputs: await mine(), counts: await counts(page, DI) }
console.log('addTally', rec.addTally, JSON.stringify(rec.afterTally.counts.a), JSON.stringify(rec.afterTally.counts.lines))
rec.pub2 = await signAndPublish(page, DI); console.log('pub2', JSON.stringify(rec.pub2))
await toWeek(page)
m = await toastMark(page)
await dragLocToLoc(page, rosterPuckOf(page, H), weekRow(page, DI, TITLE).locator('.addz'))
rec.addHex = await toastsSince(page, m)
rec.beforeLoad = { inputs: await mine(), rows: await readRows(page, TITLE), counts: await counts(page, DI) }
console.log('addHex', rec.addHex, JSON.stringify(rec.beforeLoad.counts), JSON.stringify(rec.beforeLoad.rows))
await shot(page, 'G3-before-load')
/* the version list on the day */
await toWeek(page)
await page.locator(`[data-planmenu="${DI}"]`).first().scrollIntoViewIfNeeded()
await page.locator(`[data-planmenu="${DI}"]`).first().click(); await sleep(500)
rec.menu = await page.evaluate(() => { const w = document.querySelector('.wavemenu'); return w ? w.innerText.replace(/\s+/g, ' ') : 'NO MENU' })
console.log('menu', rec.menu)
await page.locator('.wavemenu button', { hasText: /^Original/ }).first().click(); await sleep(900)
await shot(page, 'G3-original-look')
rec.lookText = await page.evaluate(() => { const b = document.querySelector('.dprev, .dprev-restore'); const el = b ? (b.closest('.dprev') || b.parentElement) : null; return el ? el.innerText.replace(/\s+/g, ' ').slice(0, 400) : 'no .dprev' })
console.log('look', rec.lookText)
const b = page.locator('.dprev-restore').first()
rec.loadBtn = (await b.innerText()).replace(/\s+/g, ' ')
m = await toastMark(page)
await b.click(); await sleep(900)
rec.loadToast = await toastsSince(page, m)
rec.loadButtons = await page.evaluate(() => [...document.querySelectorAll('button')].filter(b => b.offsetParent !== null && /discard|load|already|nothing|keep|restor/i.test(b.textContent)).map(b => b.className + ': ' + b.textContent.trim().slice(0, 80)))
rec.loadDialog = await page.evaluate(() => { const d = [...document.querySelectorAll('.modal, .dlg, [role=dialog], .win')].filter(e => e.offsetParent); return d.map(e => e.innerText.replace(/\s+/g, ' ').slice(0, 400)) })
console.log('load', rec.loadToast, JSON.stringify(rec.loadButtons), JSON.stringify(rec.loadDialog))
await shot(page, 'G3-after-load')
rec.afterLoad = { inputs: await mine(), rows: await readRows(page, TITLE) }
console.log('afterLoad', JSON.stringify(rec.afterLoad.rows), JSON.stringify(rec.afterLoad.inputs.map(i => i.people)))
rec.afterLoad.counts = await counts(page, DI, { keepWin: true })
console.log('afterLoad counts', JSON.stringify(rec.afterLoad.counts))
rec.chgText = await page.evaluate(() => { const w = document.querySelector('.chgwin'); return w ? w.innerText.replace(/\s+/g, ' ').slice(0, 900) : 'NO chgwin' })
rec.chgButtons = await page.evaluate(() => [...document.querySelectorAll('.chgwin button')].map(b => b.textContent.trim().replace(/\s+/g, ' ')))
console.log('chg', rec.chgText, JSON.stringify(rec.chgButtons))
await shot(page, 'G3-changes-window')
saveData('G3', rec)
console.log('errs', JSON.stringify(errs))
await ctx.close(); await browser.close()
