import { launch, open, fileInput, openFromList, describeWin, shot, WIN, toastMark, toastsSince, inputOf, oilAnswer, drag, save, errs } from './or-H-lib.mjs'
const out = {}
const log = (k, v) => { out[k] = v; console.log('## ' + k + ' ' + JSON.stringify(v)) }
const browser = await launch()
const { ctx, page } = await open(browser)
const asRanger = () => page.evaluate(() => { window.raptorMe('bane'); window.raptorRole('member') })
const asSaber = () => page.evaluate(() => { window.raptorMe('stiff'); window.raptorRole('admin') })
const badge = () => page.evaluate(() => document.getElementById('roleBadge').textContent)
log('badge-start', await badge())
/* gear */
await page.evaluate(() => window.go('inputs')); await page.waitForTimeout(300)
await page.locator('#inGear').click(); await page.waitForTimeout(300)
log('gear-memberfile', await page.locator('[data-testid="iset-memberfile"]').isChecked())
await shot(page, 'H1-0-gear')
await page.locator('[data-testid="win-inputsset-x"]').click(); await page.waitForTimeout(300)
/* a */
const r = await fileInput(page, { type: 'Training', person: 'Ranger', from: '2026-07-15', to: '2026-07-15', timed: ['10:00', '11:00'], oil: 'yes' })
log('filed', r)
const iid = r[0].iid
await asRanger(); await page.waitForTimeout(500)
log('badge-ranger', await badge())
await openFromList(page, iid)
log('window-ranger', await describeWin(page))
await shot(page, 'H1-1-ranger-window')
/* re-time */
let m = await toastMark(page)
await page.fill('#inpEditStart', '11:00'); await page.fill('#inpEditEnd', '12:00')
await page.locator('#inpEditSave').click(); await page.waitForTimeout(600)
log('retime', { toast: await toastsSince(page, m), inputs: (await inputOf(page, iid)).s + '-' + (await inputOf(page, iid)).e, winOpen: await page.locator(WIN).count() })
await shot(page, 'H1-2-after-retime')
/* re-word */
await openFromList(page, iid)
m = await toastMark(page)
await page.fill('#inpEditOwnTitle', 'Range check')
await page.locator('#inpEditSave').click(); await page.waitForTimeout(600)
log('reword', { toast: await toastsSince(page, m), title: (await inputOf(page, iid)).title, winOpen: await page.locator(WIN).count() })
/* move to Sat 18 */
await openFromList(page, iid)
m = await toastMark(page)
await page.locator('#inpEdCal [data-cal="2026-07-18"]').click(); await page.waitForTimeout(200)
await shot(page, 'H1-3-date-picked')
await page.locator('#inpEditSave').click(); await page.waitForTimeout(500)
log('oil-sheet', { count: await page.locator('[data-testid="oilconf"]').count(), text: await page.locator('[data-testid="oilconf"]').first().innerText().catch(() => null) })
await shot(page, 'H1-4-oil-question')
log('oil-answer', await oilAnswer(page, 'yes'))
await page.waitForTimeout(500)
const cur = await inputOf(page, iid)
log('moved', { toast: await toastsSince(page, m), date: cur.date, oil: cur.oil, winOpen: await page.locator(WIN).count() })
await shot(page, 'H1-5-after-move')
/* schedule as Saber: drag Ranger's puck off */
await asSaber(); await page.waitForTimeout(400)
log('badge-saber', await badge())
await page.evaluate(() => window.go('editsched')); await page.locator('#eWeek .day').first().waitFor()
const day = page.locator('#eWeek .day:not(.peek)').nth(5)
await day.scrollIntoViewIfNeeded()
const row = day.locator('.sec-grnd .pl-row', { hasText: 'Range check' }).first()
log('row-found', await row.count())
await row.scrollIntoViewIfNeeded()
await shot(page, 'H1-6-saber-week-row')
log('row-controls', await row.evaluate(r => [...r.querySelectorAll('button, [role=button], [data-grx], [data-grcx], .x, [title]')].map(b => (b.id || b.className || '') + '|' + (b.getAttribute('title') || '') + '|' + (b.innerText || '').trim().slice(0, 20) + '|vis=' + (b.getClientRects().length > 0))))
log('row-text', (await row.innerText()).replace(/\s+/g, ' '))
const puck = row.locator('.ppl .puck').first()
m = await toastMark(page)
const before = JSON.stringify((await inputOf(page, iid)).people)
await drag(page, puck, { x: 8, y: 450 })
log('drag-off', { toast: await toastsSince(page, m), peopleBefore: before, peopleAfter: JSON.stringify((await inputOf(page, iid)).people) })
await shot(page, 'H1-7-after-drag-off')
m = await toastMark(page)
await puck.click({ button: 'right' }); await page.waitForTimeout(500)
log('right-click-off', { toast: await toastsSince(page, m), peopleAfter: JSON.stringify((await inputOf(page, iid)).people) })
await shot(page, 'H1-8-after-rightclick')
/* the board's row: does the X exist */
const sbd = page.locator('#eWeek [data-sbday="5"]:visible').first(); await sbd.scrollIntoViewIfNeeded(); await sbd.click()
await page.waitForSelector('#schedBoard', { timeout: 5000 }); await page.waitForTimeout(400)
log('board-row-controls', await page.evaluate(() => [...document.querySelectorAll('#schedBoard .sb-panel.grnd .sb-arow')].filter(r => r.getClientRects().length).map(r => ({ title: (r.querySelector('textarea.ain, input.ain') || {}).value, controls: [...r.querySelectorAll('button')].filter(b => b.getClientRects().length).map(b => (b.id || b.className) + '|' + (b.getAttribute('title') || b.getAttribute('aria-label') || '') + '|' + b.innerText.trim().slice(0, 12)) }))))
await shot(page, 'H1-8b-board')
m = await toastMark(page)
const bp = page.locator('#schedBoard .sb-panel.grnd:visible .sb-arow .puck').first()
await drag(page, bp, { x: 700, y: 880 })
log('board-drag-off', { toast: await toastsSince(page, m), people: JSON.stringify((await inputOf(page, iid)).people) })
await page.locator('#sbDone').click(); await page.waitForTimeout(400)
/* delete as Ranger */
await asRanger(); await page.waitForTimeout(400)
await openFromList(page, iid)
m = await toastMark(page)
await page.locator('#inpEditDel').click(); await page.waitForTimeout(500)
await shot(page, 'H1-9-delete-pressed')
log('after-delete-inputs', await page.evaluate(i => !!window.INPUTS.find(x => x.iid === i), iid))
log('toast-delete', await toastsSince(page, m))
log('errors', errs)
save('H1', out)
await browser.close()
