import * as F from './cal-F-lib.mjs'
const b = await F.launch()
const ctx = await F.newCtx(b)
const p = await F.newPage(ctx)
await F.signIn(p, 'ad')
await F.go(p, 'inputs')
await F.month(p, 2026, 7)
const ids = await Promise.all(['Ace', 'Anvil', 'Basher'].map(c => F.pidOf(p, c)))
console.log(ids)
await p.locator('[data-icday="2026-07-18"]').click({ position: { x: 8, y: 8 } })
await F.sleep(400)
await p.locator('#icPopAdd').click()
await F.sleep(400)
await p.selectOption('#inpEditType', 'Duty')
await p.locator('#inpEditPop [data-testid="pp-several"]').click()
await F.sleep(200)
// first picked is the current select value (Saber?)
const state0 = await p.evaluate(() => [...document.querySelectorAll('#inpEditPop [data-pp][aria-pressed="true"]')].map(e => e.dataset.pp))
console.log('picked at start', state0)
for (const id of ids) await p.locator(`#inpEditPop [data-pp="${id}"]`).click()
// unpick Saber
const saber = await F.pidOf(p, 'Saber')
if (state0.includes(saber)) await p.locator(`#inpEditPop [data-pp="${saber}"]`).click()
await F.sleep(200)
console.log('picked', await p.evaluate(() => [...document.querySelectorAll('#inpEditPop [data-pp][aria-pressed="true"]')].map(e => e.dataset.pp)))
console.log('allday', await p.locator('#inpEditAllday').count(), await p.locator('#inpEditAllday').isChecked().catch(() => 'n/a'))
await F.pic(p, 'recon2-before-save')
await p.locator('#inpEditSave').click()
await F.sleep(700)
await F.pic(p, 'recon2-after-save')
const dlg = await p.evaluate(() => [...document.querySelectorAll('[data-testid]')].filter(e => e.offsetParent !== null).map(e => e.dataset.testid).join(' '))
console.log('visible testids', dlg)
console.log(await p.evaluate(() => { const e = document.querySelector('[data-testid="oilconf"]'); return e ? e.innerText : 'no oilconf' }))
await b.close()
console.log(F.errors)
