// B2 — swap from a flying seat
import { launch, openWorld, fileInput, shot, rowIdx, rowData, inputOf, toastMark, toastsSince, undoRedo, saveJson, loadJson, errs, csId,
  toWeek, openBoard, centre, weekRowEl, weekRowNames, boardRowNames, weekLines, boardLines, inputsSurf, closeDayWin, listRow, drag3 } from './or-B-lib2.mjs'
const R = {}
const say = (k, v) => { R[k] = v; console.log(k, typeof v === 'string' ? v : JSON.stringify(v)) }
const browser = await launch()
const { page: p } = await openWorld(browser)
const f = await fileInput(p, { type: 'Training', person: 'Ranger', from: '2026-07-15', to: '2026-07-15', timed: ['17:00', '18:00'] })
const iid = f[0].iid; const DI = 2
say('filed', f)
say('oilq left', await p.locator('[data-testid="oilconf"]').count())
await toWeek(p)
const ri = await rowIdx(p, DI, iid)
say('ri', ri)
const seat = '2.0.1.0.p'
const seatEl = p.locator(`#eWeek .day:not(.peek) [data-slot="${seat}"]`).first()
say('seat count', await seatEl.count())
const seatBefore = await p.evaluate(s => { const d = window.DAYS[2]; const a = d.waves[0].formations[1].aircraft[0]; return (window.PEOPLE[a.p] || {}).cs }, seat)
say('seat man before', seatBefore)
say('week row before', await weekRowNames(p, DI, ri))
const puck = seatEl.locator('.puck').first()
const target = weekRowEl(p, DI, ri).locator('.puck').first()
await centre(weekRowEl(p, DI, ri)); await shot(p, 's02-1-before')
const m0 = await toastMark(p)
await drag3(p, puck, target)
say('toasts', await toastsSince(p, m0))
say('oilq after', await p.locator('[data-testid="oilconf"]').count())
say('input after', await inputOf(p, iid))
const seatAfter = await p.evaluate(() => { const a = window.DAYS[2].waves[0].formations[1].aircraft[0]; return (window.PEOPLE[a.p] || {}).cs })
say('seat man after', seatAfter)
say('week row after', await weekRowNames(p, DI, ri))
say('week lines', await weekLines(p, DI))
await centre(weekRowEl(p, DI, ri)); await shot(p, 's02-2-week-row-after')
await seatEl.evaluate(e => e.scrollIntoView({ block: 'center' })); await shot(p, 's02-3-seat-after')
await openBoard(p, DI)
say('board row', await boardRowNames(p, DI, ri))
say('board lines', await boardLines(p, DI))
say('board seat', await p.evaluate(() => { const e = [...document.querySelectorAll('#schedBoard [data-slot="2.0.1.0.p"] .puck .nm')].find(x => x.offsetParent); return e ? e.textContent : null }))
await p.locator('#schedBoard [data-bfld="gr:2.' + ri + '.prog"]:visible').first().evaluate(e => e.scrollIntoView({ block: 'center' })); await shot(p, 's02-4-board-after')
const sf = await inputsSurf(p, iid, '2026-07-15'); say('inputs surf', sf); await shot(p, 's02-5-card')
say('list', await listRow(p, iid))
/* ONE undo */
await openBoard(p, DI)
const u = await undoRedo(p, 'undo'); say('undo1', u)
say('after undo input', await inputOf(p, iid))
say('after undo seat', await p.evaluate(() => (window.PEOPLE[window.DAYS[2].waves[0].formations[1].aircraft[0].p] || {}).cs))
say('after undo board row', await boardRowNames(p, DI, ri))
await p.locator('#schedBoard [data-bfld="gr:2.' + ri + '.prog"]:visible').first().evaluate(e => e.scrollIntoView({ block: 'center' })); await shot(p, 's02-6-after-undo')
const rd = await undoRedo(p, 'redo'); say('redo1', rd)
say('after redo input', await inputOf(p, iid))
say('after redo seat', await p.evaluate(() => (window.PEOPLE[window.DAYS[2].waves[0].formations[1].aircraft[0].p] || {}).cs))
say('errs', errs)
const all = loadJson('docs/handpass/parts/or-B.json'); all.B2 = R; saveJson('docs/handpass/parts/or-B.json', all)
await browser.close()
