// shr-c-probe v1 — walker C proves the route on the frozen build: the Inputs window's calendar (for Mon–Wed), the people's
// sign-in names, the Leave War grid on 15 Jul, Ranger's cell, its window and Remarks box (admin and Ranger).
import * as C from './shr-c-lib.mjs'
const { L, T, J, sleep } = C
console.log('shr-c-probe v1')
const w = await C.world(process.env.SZ || 'desk')
const P = w.page
await C.signIn(w, 'ad')
const ppl = await P.evaluate(() => Object.entries(window.PEOPLE || {}).slice(0, 80).map(([k, v]) => `${k}:${v.cs}:${v.user || v.login || v.un || ''}:${v.role || ''}`))
console.log('PEOPLE', J(ppl))
const keys = await P.evaluate(() => { const v = Object.values(window.PEOPLE || {})[0]; return Object.keys(v || {}) })
console.log('PERSON KEYS', J(keys))
/* the Inputs window on Wed: its calendar's testids */
await L.openDay(w, L.WED)
await C.press(w, '#icPopAdd')
await P.locator('#inpEditPop #inpEditType').waitFor()
await P.selectOption('#inpEditPop #inpEditType', 'LL')
const tids = await P.evaluate(() => [...document.querySelectorAll('#inpEditPop [data-testid]')].filter(e => e.getBoundingClientRect().width > 0).map(e => e.dataset.testid))
console.log('WINDOW TIDS', J(tids.filter(t => !/^pp-|^inpEdCal-day/.test(t))), 'days', tids.filter(t => /inpEdCal-day/.test(t)).length, tids.filter(t => /inpEdCal-day/.test(t)).slice(0, 3))
console.log('RANGE READ', await C.txt(P, '#inpEditPop .rc-read'))
await P.keyboard.press('Escape'); await sleep(400)
const d = P.getByRole('button', { name: /Discard|Close it/ }).first(); if (await d.count()) await d.click().catch(() => {})
await sleep(300)
if (await P.locator('[data-testid="win-inputsday-x"]').count()) await C.press(w, '[data-testid="win-inputsday-x"]')
const iid = await C.fileShared(w, 'probe')
console.log('FILED', iid, J(await C.store(P, ['bane', 'rocky'], ['Jul 15'])))
await C.toWar(w)
console.log('WAR month shown', await C.monthShown(P), 'month buttons', J(await P.evaluate(() => [...document.querySelectorAll('[data-testid^="month-"]')].map(b => b.dataset.testid + '/' + b.className).slice(0, 14))))
const r = await C.reachCell(w, 'bane', '2026-07-15')
console.log('REACH', J(r), 'cells', J(await C.cellSays(P, 'bane', '2026-07-15')), J(await C.cellSays(P, 'rocky', '2026-07-15')))
await C.openCell(w, 'bane', '2026-07-15')
console.log('ADMIN WINDOW', J(await C.sheet(P)))
await C.pic(w, 'probe-admin-window')
await C.closeAny(w)
/* sign-in names: try 'us' and others */
await C.signOutIn(w, 'us')
console.log('SIGNED IN as us: who', await P.evaluate(() => JSON.stringify({ me: window.ME || window.CURUSER || null, role: window.ROLE || null })))
await C.toWar(w)
await C.reachCell(w, 'bane', '2026-07-15')
await C.openCell(w, 'bane', '2026-07-15')
console.log('MEMBER WINDOW', J(await C.sheet(P)))
await C.pic(w, 'probe-member-window')
console.log('ERRORS', J(L.facts.errors))
await L.finish()
