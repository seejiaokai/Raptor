import * as L from './sf-C-lib.mjs'
const { launch, ctxOpen, openBoard, closeBoard, bPut, bType, bf, bPublish, sleep, shot, rec, go, errors, weekHead, chipLine, oilOpen, oilClose, oilLine, changesText, changesClose, undo, redo, reloadTo, signInfo, pendText, trackerCredits, trackerClose, warnLines, bAddFlyingWave } = L
const b = await launch()
const { p } = await ctxOpen(b, {})
const S = '2'
await go(p, 'editsched')
await p.evaluate(() => window.addWave(5, 'avalon')); await sleep(500)
await openBoard(p, 5)
const seats = []
for (const [ai, pid] of [[0, 'stiff'], [1, 'bane'], [2, 'slipway'], [3, 'dj']]) seats.push(await bPut(p, 5, 0, 0, ai, 'p', [pid]))
rec(S, 'set-up: AVALON on Sat, seated by the arm-and-pick route', 'Saber, Ranger MAIN; Drifter, Ace SPARE', seats.join(','), seats.every(x => x !== 'FAILED') ? 'PASS' : 'NOT WALKED')
// Sunday flying line with Ace
await openBoard(p, 6)
await bAddFlyingWave(p, 6)
await bType(p, bf(6, 0, 0, 'cs'), 'VL'); await bType(p, bf(6, 0, 0, 'to'), '09:00'); await bType(p, bf(6, 0, 0, 'ld'), '10:30')
const ace6 = await bPut(p, 6, 0, 0, 0, 'p', ['dj'])
const sunW0 = await warnLines(p)
await shot(p, '2-01-sunday-before')
rec(S, 'Sunday flying line 09:00 with Ace, AVALON standing by', 'Ace clean on Sunday (AVALON stands by)', { ace6, warn: sunW0 }, sunW0.some(w => /Ace/.test(w) && /rest/i.test(w)) ? 'FAIL' : 'PASS', 'C-2-01-sunday-before.png')
await openBoard(p, 5)
const pub = await bPublish(p, 5)
rec(S, 'Pub Sat', 'published ORIG', pub, pub.published ? 'PASS' : 'NOT WALKED')
const h0 = await weekHead(p, 5)
await shot(p, '2-02-pub-sat')
rec(S, 'Saturday standing by, published', 'badge shows no AVALON term; chips dashed', { head: h0, chips: await chipLine(p) }, 'RECORD', 'C-2-02-pub-sat.png')
// type R
await bType(p, bf(5, 0, 0, 'rl'), '18:30')
const h1 = await weekHead(p, 5)
const w1 = await warnLines(p)
const ch1 = await chipLine(p)
await shot(p, '2-03-R-typed')
rec(S, 'type AVALON R 18:30 (Pub Sat)', 'all four lit; badge gains an AVALON term; 4 long-day notes', { head: h1, chips: ch1, warn: w1 }, (ch1.match(/\+ON/g) || []).length === 4 ? 'PASS' : 'FAIL', 'C-2-03-R-typed.png')
rec(S, 'long-day note on each of the four', '12h30, 18:30 -> 07:00', w1, w1.filter(x => /long work day: 12h30, 18:30/.test(x)).length === 4 ? 'PASS' : 'FAIL', 'C-2-03-R-typed.png')
const sg = await signInfo(p, 5), pt = await pendText(p)
rec(S, 'sign-offs after the change on the published day', 'the four sign-offs fall; 1 pending', { sg, pt }, /locked/.test(sg.publish || '') && /1 pending/.test(pt || '') ? 'PASS' : 'FAIL', 'C-2-03-R-typed.png')
// changes window
const chg = await changesText(p, 5)
await shot(p, '2-04-changes')
rec(S, 'changes window after typing R', 'names the AVALON R change in words', chg.slice(0, 500), 'RECORD', 'C-2-04-changes.png')
await changesClose(p)
await undo(p); const chU = await chipLine(p), ptU = await pendText(p)
rec(S, 'Undo the R', 'chips dashed, pending gone', { chU, ptU }, !/\+ON/.test(chU) && !/pending/.test(ptU || '') ? 'PASS' : 'FAIL')
await redo(p); const chR = await chipLine(p), ptR = await pendText(p)
rec(S, 'Redo the R', 'all four lit, 1 pending', { chR, ptR }, (chR.match(/\+ON/g) || []).length === 4 && /1 pending/.test(ptR || '') ? 'PASS' : 'FAIL')
await L.reloadTo(p, 5); const chL = await chipLine(p), ptL = await pendText(p)
await shot(p, '2-04b-after-reload')
rec(S, 'reload', 'all four still lit, 1 pending', { chL, ptL }, (chL.match(/\+ON/g) || []).length === 4 && /1 pending/.test(ptL || '') ? 'PASS' : 'FAIL', 'C-2-04b-after-reload.png')
// OIL Earn
await oilOpen(p)
const oil1 = await oilLine(p)
await shot(p, '2-05-oil-earn')
rec(S, 'OIL Earn mode, AVALON R 18:30', 'all four ON by default, a full day (12h30)', oil1, /Saber:ON\/FO.*Ranger:ON\/FO.*Drifter:ON\/FO.*Ace:ON\/FO/.test(oil1) ? 'PASS' : 'FAIL', 'C-2-05-oil-earn.png')
await oilClose(p)
// Sunday Ace
await openBoard(p, 6)
const w6 = await warnLines(p)
const aceP = await p.evaluate(() => { const e = [...document.querySelectorAll('#schedBoard [data-slot="6.0.0.0.p"] .puck')][0]; return e ? { cls: e.className, title: e.title } : null })
await shot(p, '2-06-sunday-ace')
rec(S, 'Sunday: Ace crew rest after AVALON', 'red crew rest naming the AVALON shift and its 07:00 end; no debrief added', { warn: w6, puck: aceP }, w6.some(x => /Ace/.test(x) && /rest/i.test(x) && /07:00/.test(x)) ? 'PASS' : 'FAIL', 'C-2-06-sunday-ace.png')
await openBoard(p, 5)
// clear R
await bType(p, bf(5, 0, 0, 'rl'), '')
const h2 = await weekHead(p, 5), ch2 = await chipLine(p), w2 = await warnLines(p)
await shot(p, '2-07-R-cleared')
rec(S, 'clear AVALON R', 'chips dashed again, badge term gone, no warnings', { head: h2, chips: ch2, warn: w2 }, !/\+ON/.test(ch2) && !w2.some(x => /⚠/.test(x)) ? 'PASS' : 'FAIL', 'C-2-07-R-cleared.png')
const chg2 = await changesText(p, 5); await changesClose(p)
rec(S, 'changes window after R cleared', 'nothing waiting to go out', { pend: h2.pend, chg: chg2.slice(0, 300) }, /nothing waiting to go out/.test(chg2) ? 'PASS' : 'FAIL')
await oilOpen(p); const oil2 = await oilLine(p); await oilClose(p)
rec(S, 'OIL Earn after R cleared', 'AVALON item off (standby default)', oil2, /AV:off/.test(oil2) ? 'PASS' : 'FAIL')
await openBoard(p, 6)
const w6b = await warnLines(p)
rec(S, 'Sunday after R cleared', 'Ace clean', w6b, w6b.some(x => /Ace/.test(x) && /rest/i.test(x)) ? 'FAIL' : 'PASS')
// retype R and publish AL1 -> tracker
await openBoard(p, 5)
await bType(p, bf(5, 0, 0, 'rl'), '18:30')
const pubAl = await bPublish(p, 5)
const h3 = await weekHead(p, 5)
rec(S, 'retype R and Publish AL1', 'AL1 out', { pubAl, head: h3 }, pubAl.published ? 'PASS' : 'FAIL')
await closeBoard(p)
const tr = await trackerCredits(p, '18 Jul', '2-08-tracker')
rec(S, "Leave War OIL tracker after AL1", 'Saber, Ranger, Drifter, Ace each +1 on 18 Jul, 18:30-23:59 (the hours past midnight earn the next day nothing, D42)', tr, ['Saber', 'Ranger', 'Drifter', 'Ace'].every(n => tr.some(x => x.startsWith(n))) ? 'PASS' : 'FAIL', 'C-2-08-tracker.png')
await trackerClose(p)
// clear R, publish AL2
await openBoard(p, 5)
await bType(p, bf(5, 0, 0, 'rl'), '')
const pubAl2 = await bPublish(p, 5)
await closeBoard(p)
const tr2 = await trackerCredits(p, '18 Jul', '2-09-tracker-after-clear')
rec(S, "tracker after R cleared and AL2", 'the four credits gone', { pubAl2, tr2 }, !['Saber', 'Ranger', 'Drifter', 'Ace'].some(n => tr2.some(x => x.startsWith(n))) ? 'PASS' : 'FAIL', 'C-2-09-tracker-after-clear.png')
await trackerClose(p)
console.log('ERRORS', errors)
rec(S, 'browser error list', 'empty', errors, errors.length ? 'FAIL' : 'PASS')
await b.close()
