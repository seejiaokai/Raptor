import * as L from './on-RX1-lib.mjs'
import { warnRead, ensureOpen } from './on-RX1-warn.mjs'
const W = await L.world({ tag: 'R2' })
const { page, tid, shot, press } = W
const iid = await L.usualSat(W, { goToBoard: false, hangar: ['09:30', '11:00'] })
const J = o => JSON.stringify(o)
await L.frameGrnd(page); await ensureOpen(page); await L.frameGrnd(page)
const src = L.wkSel(1), tgt = L.wkSel(0)
const S = async () => ({ warn: await warnRead(page), ground: await L.groundNow(page), rec: await L.oilOf(page, iid), undo: await L.undoState(page) })
const b0 = await S()
console.log('BEFORE', J(b0))
await shot('RX1-2-0-before')
await L.drag(page, page.locator(src), page.locator(tgt))
const q = { up: await tid('oilconf').count(), lead: await tid('oilconf-lead').innerText().catch(() => 'NO'), btns: [await tid('oilconf-cancel').innerText().catch(() => ''), await tid('oilconf-save').innerText().catch(() => '')] }
console.log('QUESTION', J(q))
const b1 = await S()
console.log('BEHIND_Q', J(b1.warn), 'same', J(b1.warn) === J(b0.warn), J(b1.ground) === J(b0.ground))
await W.hush(); await shot('RX1-2-1-question'); await W.unhush()
await press(tid('oilconf-cancel')); await page.waitForTimeout(700)
const b2 = await S()
console.log('AFTER_DONT', J(b2.warn), 'same', J(b2.warn) === J(b0.warn), 'ground same', J(b2.ground) === J(b0.ground), 'undo same', b2.undo === b0.undo, await tid('oilbar-text').innerText().catch(() => 'NO'))
await W.hush(); await shot('RX1-2-2-bar'); await W.unhush()
await press(tid('oilbar-answer')); await page.waitForTimeout(400)
await press(tid('oil-yes')); await press(tid('oilconf-save')); await page.waitForTimeout(500)
const tNow = await L.toast(page)
const tAll = await L.toastsAll(page)
await page.waitForTimeout(500)
const b3 = await S()
console.log('TOAST_NOW', tNow, 'ALL', J(tAll.slice(-4)))
console.log('AFTER_SWAP', J(b3))
await shot('RX1-2-3-swapped')
console.log('errors', J(W.errors))
L.note({ id: 'RX1-2', b0, q, b1: b1.warn, b2: b2.warn, b3, tNow, tAll: tAll.slice(-4), errors: W.errors })
await W.ctx.close(); process.exit(0)
