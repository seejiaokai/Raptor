// W2: S17 — undo across a publish; Unpublish; Load onto working copy of the Original (a note made public).
import { L, pubDay, face, editWeek, showDay, closeBoard, toGoOut, closeChg, sleep, npub, typeNote, head, pressPub, viewNotes, undoTitle } from './ibc-w2-lib.mjs'
const { check, note, shot } = L
console.log('ibc-w2-undopub v2')
const DI = 2, W = 'Brief 0700 main room'
{
  const { page } = await L.session('desktop')
  await typeNote(page, 'pn', DI, W)
  await pubDay(page, false, DI)
  const f0 = await face(page, DI)
  check('S17', 'premise: ORIG nothing pending', f0 && f0.tag === 'ORIG' && !f0.pend.length, f0)
  await pressPub(page, 'pn', DI)
  const p2 = await pubDay(page, false, DI)
  const f1 = await face(page, DI)
  check('S17', 'premise: AL1 published carrying the public note, nothing pending', /AL1/.test(f1.tag) && !f1.pend.length, { p2: p2.kind, f1 })
  const v1 = await viewNotes(page, DI)
  check('S17', 'premise: view-only shows the note', v1.notes.some(t => t.includes(W)), v1)
  await editWeek(page); await showDay(page, DI)
  note('S17', `Undo button before pressing: ${JSON.stringify(await undoTitle(page))}`)
  await page.locator('#undoBtn').click(); await sleep(700)
  const n1 = await L.notes(page), t1 = await L.toastText(page)
  note('S17', `after Undo 1: toast ${JSON.stringify(t1)}; last notes ${JSON.stringify(n1.slice(-3))}; npub ${JSON.stringify(await npub(page, DI))}; face ${JSON.stringify(await face(page, DI))}`)
  check('S17', 'EXPECTED undo refused with "A day on this week was published after that change — tap Unpublish…" (literal: the first Undo)', /published after that change/i.test(String(t1) + n1.slice(-2).join(' ')) && JSON.stringify(await npub(page, DI)) === '["pn"]', { toast: t1, npub: await npub(page, DI) })
  await shot(page, 'S17', 'desktop', 'undo1')
  note('S17', `Undo button now: ${JSON.stringify(await undoTitle(page))}`)
  await page.locator('#undoBtn').click(); await sleep(700)
  note('S17', `after Undo 2: toast ${JSON.stringify(await L.toastText(page))}; last notes ${JSON.stringify((await L.notes(page)).slice(-2))}; npub ${JSON.stringify(await npub(page, DI))}; face ${JSON.stringify(await face(page, DI))}`)
  await shot(page, 'S17', 'desktop', 'undo2')
  await page.locator('#redoBtn').click(); await sleep(600)
  await page.locator('#redoBtn').click().catch(() => {}); await sleep(600)
  note('S17', `after Redo x2: face ${JSON.stringify(await face(page, DI))}; npub ${JSON.stringify(await npub(page, DI))}; notes ${JSON.stringify((await L.notes(page)).slice(-2))}`)
  /* now the published AL stands again: Unpublish it */
  await editWeek(page); await showDay(page, DI)
  const un = page.locator(`#eWeek [data-unpub="${DI}"]:visible`).first()
  note('S17', `Unpublish button present: ${await un.count()}; title ${JSON.stringify(await un.getAttribute('title').catch(() => null))}`)
  await un.click(); await sleep(700)
  note('S17', `Unpublish toast: ${JSON.stringify(await L.toastText(page))}`)
  const f2 = await face(page, DI)
  note('S17', `after Unpublish: face ${JSON.stringify(f2)}; npub ${JSON.stringify(await npub(page, DI))}`)
  check('S17', 'EXPECTED Unpublish: working copy keeps public', JSON.stringify(await npub(page, DI)) === '["pn"]', await npub(page, DI))
  await shot(page, 'S17', 'desktop', 'after-unpublish')
  note('S17', `view-only after Unpublish: ${JSON.stringify(await viewNotes(page, DI))}`)
  const p3 = await pubDay(page, false, DI)
  const f3 = await face(page, DI), v3 = await viewNotes(page, DI)
  check('S17', 'EXPECTED publish again -> view-only shows it', v3.notes.some(t => t.includes(W)), { kind: p3.kind, f3, v3 })
  await shot(page, 'S17', 'desktop', 'view-after-republish')
  await page.context().close()
}
{
  const { page } = await L.session('desktop')
  await typeNote(page, 'pn', DI, W)
  await pubDay(page, false, DI)
  await pressPub(page, 'pn', DI)
  await pubDay(page, false, DI)
  await editWeek(page); await showDay(page, DI)
  await page.locator(`#eWeek [data-planmenu="${DI}"]`).first().click(); await sleep(500)
  const it = page.locator('button', { hasText: /^Original/ }).first()
  note('S17', `plan menu Original item present: ${await it.count()}`)
  if (!(await it.count())) L.notWalked('S17', 'premise: no Original in plan menu')
  else {
    await it.click(); await sleep(700)
    const rb = page.locator(`#eWeek [data-restore="${DI}"]:visible`).first()
    note('S17', `Load button: ${await rb.count()} label ${JSON.stringify(await rb.innerText().catch(() => null))}`)
    await shot(page, 'S17', 'desktop', 'original-preview')
    await rb.click(); await sleep(700)
    if (await page.locator(`#eWeek [data-restore="${DI}"]:visible`).count()) { note('S17', `second tap needed; label ${JSON.stringify(await page.locator(`#eWeek [data-restore="${DI}"]:visible`).first().innerText())}`); await page.locator(`#eWeek [data-restore="${DI}"]:visible`).first().click(); await sleep(700) }
    note('S17', `after Load: toast ${JSON.stringify(await L.toastText(page))}; npub ${JSON.stringify(await npub(page, DI))}`)
    const f4 = await face(page, DI), h4 = await head(page, 'pn', DI)
    check('S17', 'EXPECTED Load of Original: note returns to scheduler-only, pending as a change', (await npub(page, DI)) === null && f4.pend.length > 0, { f4, h4, npub: await npub(page, DI) })
    await shot(page, 'S17', 'desktop', 'after-load-original')
    const tg = await toGoOut(page, DI, ['S17', 'desktop', 'to-go-out-after-load'])
    note('S17', `To go out after Load: ${JSON.stringify(tg.text)}`)
  }
  await page.context().close()
}
await L.finish('undopub')
