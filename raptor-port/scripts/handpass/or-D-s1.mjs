// D1 — a Meeting for Drifter and Hunter by touch; a man added to its row on Edit Schedule; then ALL AVAIL
import { open, fileInput, shot, sleep, log, goWeek, goBoard, errs, browser, DI, csId, press, toast, toastBox, inputsOf, inputsPages, schedSurfaces, weekRowToTop, inlineCrew, touchDrag, openDrawer } from './or-D-lib.mjs'
const { ctx, page } = await open()
const f = await fileInput(page, { type: 'Meeting', people: ['Drifter', 'Hunter'], from: '2026-07-15', to: '2026-07-15', timed: ['14:00', '15:00'], title: 'Range brief' })
const iid = f[0].iid
log('D1 filed', f)
await goWeek(page)
const row = await weekRowToTop(page, 'Range brief')
await shot(page, 'D1-01-week-before')
// (a) the arm: a tap on the row's + add
const pb = await row.locator('.ppl').boundingBox()
await page.touchscreen.tap(pb.x + 40, pb.y + pb.height - 6); await sleep(500)
log('D1 tap on + add: body class', await page.evaluate(() => document.body.className), '| planning chip', await page.evaluate(() => !!document.querySelector('.ros-arm')))
await shot(page, 'D1-02-tap-addz')
// (b) the finger drag: Blade (Tally is struck through in the crew list on Wed) from the Available Crew list onto the row
const bl = await inlineCrew(page, 'Blade')
log('D1 blade in the crew list', bl && bl.b)
const pb2 = await row.locator('.ppl').boundingBox()
await touchDrag(page, { x: bl.b.x + bl.b.width / 2, y: bl.b.y + bl.b.height / 2 }, { x: pb2.x + 40, y: pb2.y + pb2.height - 6 }, { settle: 150 })
log('D1 note (Blade)', await toastBox(page))
await shot(page, 'D1-03-after-blade')
log('D1 INPUTS', await inputsOf(page, 'Range brief'))
const s1 = await schedSurfaces(page, 'Range brief'); log('D1 sched after Blade', JSON.stringify(s1))
const p1 = await inputsPages(page, iid, { picDay: 'D1-04-blade', title: 'Range brief' }); log('D1 pages after Blade', JSON.stringify(p1))
// (c) ALL AVAIL: open the drawer (AIRCREW tab) and long-press-drag ALL AVAIL onto the row's name
await goWeek(page)
const row2 = await weekRowToTop(page, 'Range brief')
await openDrawer(page, false); await sleep(500)
await shot(page, 'D1-05-drawer')
const ph = page.locator('#eRoster [data-ph="allavail"], #eRoster .rpuck[data-person="allavail"] , #eRoster .puck[data-person="allavail"]').filter({ visible: true }).first()
const phb = await ph.boundingBox(); log('D1 ALL AVAIL puck in drawer', phb)
const nb = await row2.locator('.nm').first().boundingBox(); log('D1 row name cell', nb)
await touchDrag(page, { x: phb.x + phb.width / 2, y: phb.y + phb.height / 2 }, { x: nb.x + 30, y: nb.y + 12 }, { settle: 150 })
log('D1 note (ALL AVAIL)', await toastBox(page))
await shot(page, 'D1-06-after-allavail')
log('D1 INPUTS', await inputsOf(page, 'Range brief'))
const s2 = await schedSurfaces(page, 'Range brief'); log('D1 sched after ALL AVAIL', JSON.stringify(s2))
const p2 = await inputsPages(page, iid, { picDay: 'D1-07-allavail', title: 'Range brief' }); log('D1 pages after ALL AVAIL', JSON.stringify(p2))
log('D1 errs', errs)
await ctx.close(); await browser.close()
