/* Builds docs/handpass/parts/trk1105/walk-report.md from the walk's result files (docs/handpass/parts/trk1105/walk/*.json).
   The reading of each script-world FAIL is the override list below (walk-scripts section 7); nothing else is changed.
     node scripts/handpass/trk1105-walk-report.mjs */
import { readFileSync, writeFileSync, readdirSync } from 'node:fs'
import { dirname, resolve } from 'node:path'
import { fileURLToPath } from 'node:url'
const ROOT = resolve(dirname(fileURLToPath(import.meta.url)), '..', '..')
const DIR = resolve(ROOT, 'docs/handpass/parts/trk1105/walk')
const OUT = resolve(ROOT, 'docs/handpass/parts/trk1105/walk-report.md')
console.log('trk1105-walk-report v1')
/* [file, step contains, size/role contains] -> { pass, reading } */
const OVERRIDE = [
  ['S11', 'phone: icon-only, order Undo', null, { pass: true, reading: "SCRIPT's world: the check read textContent, which keeps the clipped label; re-read by drawn boxes in S11b (pair draws only its ↶ ↷ glyphs, order Undo · Redo · sync · bell, bar bottom 49 above tabs at 126)" }],
  ['S11', 'sideways phone: top bar is one row', null, { pass: true, reading: "SCRIPT's world: #topnav links are present but visibility:hidden (a hidden fit-measuring copy); S11b counts drawn links = 0, burger drawn, bar 59 high; picture S11-L-member-bar.png shows one row" }],
  ['S12p', 'top bar undo (tap) puts the ball back', 'L/', { pass: true, reading: "SCRIPT's world: the start position was read before the chart was scrolled to the ball; the ball moved back exactly 60 px in x (626→566) = the 60 px dragged, y differs by the scroll" }],
  ['S19d', "the person's window from Quals", null, { pass: null, reading: 'NOT WALKED: the script found "Recon" on Quals but a click on the callsign opened no person window (picture S19-13-person-window.png); the Quals row shows nothing of the Tracker (category OCU, remarks "OCU (ab-initio)")' }],
]
const files = readdirSync(DIR).filter(f => f.endsWith('.json')).sort((a, b) => a.localeCompare(b, undefined, { numeric: true }))
const rows = []
for (const f of files) {
  const name = f.replace('.json', '')
  const j = JSON.parse(readFileSync(resolve(DIR, f), 'utf8'))
  for (const r of j.rows) {
    if (r.note !== undefined) { rows.push({ file: name, note: r.note, scn: r.scn, step: r.step }); continue }
    let pass = r.pass, reading = ''
    for (const [of, sub, sz, o] of OVERRIDE) if (of === name && r.step.includes(sub) && (!sz || `${r.size}/`.startsWith(sz))) { reading = o.reading; pass = o.pass }
    rows.push({ file: name, ...r, pass, reading, orig: r.pass })
  }
}
const mark = p => p === true ? 'PASS' : p === false ? 'FAIL' : 'NOT WALKED'
let md = `# The Tracker tidy — the walker's report (5 Nov 26, \`claude/tracker-standalone-tidy\`, bundle index-DTX1F34K at http://127.0.0.1:4180)\n\n`
md += `Walker: Sonnet 5.5. Generated by \`scripts/handpass/trk1105-walk-report.mjs\` from \`docs/handpass/parts/trk1105/walk/*.json\`. Pictures: \`docs/img/handpass/2026-11-05-tracker-tidy/walk/\`.\n\n`
const checks = rows.filter(r => r.note === undefined)
const cnt = { PASS: checks.filter(r => r.pass === true).length, FAIL: checks.filter(r => r.pass === false).length, NW: checks.filter(r => r.pass === null).length }
md += `**Totals (after reading each script-world FAIL, section 7 of walk-scripts): ${cnt.PASS} PASS · ${cnt.FAIL} FAIL · ${cnt.NW} NOT WALKED**, across S1–S19. Rows whose first-run FAIL was the script's own mistake say so in the reading column.\n\n`
md += `## Steps\n\n| scenario · file | step | size | role | result | what the screen / storage showed | pictures |\n|---|---|---|---|---|---|---|\n`
for (const r of checks) {
  const said = (r.said || '').replace(/\n/g, ' ').slice(0, 330) + (r.reading ? ` — READING: ${r.reading}` : '')
  md += `| ${r.scn} (${r.file}) | ${r.step.replace(/\|/g, '/')} | ${r.size} | ${r.role} | ${mark(r.pass)}${r.orig !== r.pass ? ' (first read FAIL)' : ''} | ${said.replace(/\|/g, '/')} | ${r.pics || ''} |\n`
}
md += `\n## Notes the scripts recorded\n\n`
for (const r of rows.filter(r => r.note !== undefined)) md += `- ${r.scn || r.file}: ${r.step} — ${String(r.note).replace(/\n/g, ' ')}\n`
writeFileSync(OUT, md)
console.log(`${cnt.PASS} PASS · ${cnt.FAIL} FAIL · ${cnt.NW} NOT WALKED; wrote ${OUT}`)
