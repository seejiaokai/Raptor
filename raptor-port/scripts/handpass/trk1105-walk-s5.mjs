/* S5 — an old ocu: record is never read by the running Tracker (D admin).  node scripts/handpass/trk1105-walk-s5.mjs */
import { open, back, keys, mark, click, showAllSel, shot, mk, sleep } from './trk1105-walk-lib.mjs'
console.log('trk1105-walk-s5 v1')
const L = mk('S5')
const { browser, page, errors } = await open({})
await mark(page, 'ST-02', 'dco', false); await sleep(1200)
const ck = Object.keys(await keys(page)).filter(k => /courses|master:course/.test(k))
L.note('course-related keys in storage', ck.join(', '))
const PLANT = JSON.stringify([{ id: 'czzprobe', name: 'ZZ-OCU-PROBE' }])
await page.evaluate(v => localStorage.setItem('ocu:v3:courses', v), PLANT)
await page.reload(); await back(page, 'a', false)
const opts = await page.locator('#courseSel option').allInnerTexts()
await click(page, '#fileMenuBtn'); await sleep(300)
const menu = (await page.locator('body').innerText())
await page.keyboard.press('Escape')
await click(page, '#showAllBtn'); await sleep(900)
const sa = (await page.locator('body').innerText())
const pic = await shot(page, 'S5-showall-after-plant')
await page.keyboard.press('Escape'); await sleep(300)
L.ok('ZZ-OCU-PROBE appears nowhere (course pick, File menu, Show All)', 'D', 'admin', !opts.join().includes('ZZ-OCU') && !menu.includes('ZZ-OCU') && !sa.includes('ZZ-OCU'), `courses ${opts.join('/')}`, pic)
await mark(page, 'ST-01', 'dco', false); await sleep(1200)
await page.reload(); await back(page, 'a', false)
const k = await keys(page)
L.ok('planted key still there, unchanged, after a mark and a reload', 'D', 'admin', k['ocu:v3:courses'] === PLANT, String(k['ocu:v3:courses']).slice(0, 120))
L.ok('no other ocu: key appeared', 'D', 'admin', Object.keys(k).filter(x => /^ocu:/.test(x)).join() === 'ocu:v3:courses', Object.keys(k).filter(x => /^ocu:/.test(x)).join())
const opts2 = await page.locator('#courseSel option').allInnerTexts()
L.ok('still no probe course after the second reload', 'D', 'admin', !opts2.join().includes('ZZ-OCU'), opts2.join('/'))
L.note('errors', errors.join(' | ') || 'none')
await browser.close()
L.save('S5')
