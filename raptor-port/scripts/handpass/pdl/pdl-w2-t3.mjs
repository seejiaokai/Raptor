async function reads(tag) {
  await L.closeBoard(page)
  await L.go(page, 'editsched'); await sleep(600)
  await page.locator('#eWeek .day[data-day="1"]').first().evaluate(e => e.scrollIntoView({ block: 'start', inline: 'start' })); await sleep(300)
  const head = await L.head(page, 1)
  const ep = await page.evaluate(() => (document.querySelector('#alPanel') || {}).innerText || 'NO PANEL').then(t => t.replace(/\s+/g, ' ').trim())
  const eForm = await formText('#eWeek', 1), eB = await bBox(), eSec = await secText('#eWeek', 1)
  await pic(page, `${tag}-edit`)
  await page.evaluate(() => window.scrollBy(0, -400)); await sleep(300); await pic(page, `${tag}-edit-head`)
  await L.go(page, 'viewsched'); await sleep(600)
  await page.locator('#vWeek .day[data-day="1"]').first().evaluate(e => e.scrollIntoView({ block: 'start', inline: 'start' })); await sleep(300)
  const vForm = await formText('#vWeek', 1), vSec = await secText('#vWeek', 1)
  const vPend = await page.evaluate(() => { const s = document.querySelector('#vWeek .day[data-day="1"]'); return { dpend: (s.querySelector('.dpend') || {}).innerText || '', verchip: (s.querySelector('.verchip') || {}).innerText || '', signedStrip: [...s.querySelectorAll('.signed, .so-line, .signline, [class*=signed]')].map(e => e.innerText.replace(/\s+/g, ' ')).slice(0, 3) } })
  await pic(page, `${tag}-view`)
  const o = { head, alPanel: ep, eForm, eB, eSec, vForm, vSec, vPend }
  console.log('READS', tag, JSON.stringify(o))
  return o
}
