/* rcsb-w2-probe3 v1 — W2: look at the surfaces (Edit week strip markup, Logic page, Insights button) for one man on leave on Thursday. */
const C = await import('./rcsb-w2-common.mjs')
C.setShots('probe3')
console.log('rcsb-w2-probe3 v1', process.env.HP_SHOTS)
const Q = await C.load()
const { R, I, W, X, L, sleep } = Q
const w = await R.world('pc')
const { page } = w
const id = w.ID('Vandal'), THU = 3, ISO = '2026-07-16'
const f = await C.fileInput(w, Q, ISO, id, 'LL', 'p-leave-form')
console.log('filed', f.added, C.j(await page.evaluate(i => window.INPUTS.filter(x => x.person === i).map(x => ({ t: x.type, d: x.date, ad: x.allday })), id)))
await L.board(page, THU)
const gi = await X.addWave(w, THU, '')
await X.typeIn(w, `[data-bfld="ff:${THU}.${gi}.0.to"]`, '10:00'); await X.typeIn(w, `[data-bfld="ff:${THU}.${gi}.0.ld"]`, '11:30')
console.log('seat', await X.seatPhoneAware(w, `[data-slot="${THU}.${gi}.0.0.p"]`, id))
const g = await C.addGround(w, Q, THU, 'BRIEFING', '09:00', '10:00')
console.log('seat ground', await X.seatPhoneAware(w, `[data-fill="g:${THU}.${g}.+"]`, id))
console.log('boardWarn', C.j((await X.boardWarn(page, w)).items.filter(t => /Vandal/.test(t))))
await R.shot(page, 'b1-board')
// html of the issues list line
console.log('wln html', await page.evaluate(() => [...document.querySelectorAll('#schedBoard .wln')].filter(e => e.offsetWidth && /Vandal/.test(e.innerText)).map(e => e.outerHTML.slice(0, 500))))
console.log('insights btns', C.j(await page.evaluate(() => [...document.querySelectorAll('button,a,[role=button]')].filter(e => e.offsetWidth && /insight/i.test(e.innerText + e.title + e.id + (e.getAttribute('aria-label') || ''))).map(e => e.tagName + '#' + e.id + ' ' + e.className + ' | ' + e.innerText.trim().slice(0, 30) + ' | ' + e.title))))
await L.closeBoard(page)
await L.go(page, 'editsched'); await sleep(600)
console.log('insights btns edit', C.j(await page.evaluate(() => [...document.querySelectorAll('button,a,[role=button]')].filter(e => e.offsetWidth && /insight/i.test(e.innerText + e.title + e.id + (e.getAttribute('aria-label') || ''))).map(e => e.tagName + '#' + e.id + ' ' + e.className + ' | ' + e.innerText.trim().slice(0, 30) + ' | ' + e.title))))
const s = await X.stripItems(page, '#eWeek', THU)
console.log('strip', C.j(s))
console.log('witem html', await page.evaluate(() => [...document.querySelectorAll('#eWeek [data-dwbox="3"] .witem')].filter(e => /Vandal/.test(e.innerText)).map(e => e.outerHTML.slice(0, 600))))
await R.shot(page, 'e1-edit')
await L.go(page, 'logic'); await sleep(800)
console.log('logic text', await page.evaluate(() => { const t = document.querySelector('#page-logic').innerText.replace(/\s+/g, ' '); const i = t.search(/On leave/); return t.slice(Math.max(0, i - 200), i + 400) }))
console.log('logic filters', C.j(await page.evaluate(() => [...document.querySelectorAll('#page-logic input')].map(e => e.tagName + '#' + e.id + ' type=' + e.type + ' ph=' + e.placeholder + ' vis=' + !!e.offsetWidth))))
await R.shot(page, 'l1-logic')
console.log('errors', C.j(w.errors))
await w.browser.close()
