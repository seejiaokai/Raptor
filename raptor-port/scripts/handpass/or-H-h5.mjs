import { launch, open, fileInput, openFromList, describeWin, shot, WIN, toastMark, toastsSince, save, errs, as, badgeText, bellRead } from './or-H-lib.mjs'
const out = {}
const log = (k, v) => { out[k] = v; console.log('## ' + k + ' ' + JSON.stringify(v)) }
const browser = await launch()
const { ctx, page } = await open(browser)
const who = iid => page.evaluate(i => { const r = window.INPUTS.find(x => x.iid === i); return r ? { people: r.people.map(e => (window.PEOPLE[e.p]?.cs || e.p) + '(by ' + (window.PEOPLE[e.by]?.cs || e.by) + ')'), by: window.PEOPLE[r.by]?.cs, oil: r.oil, type: r.type, date: r.date } : null }, iid)
await as(page, 'Saber'); log('badge', await badgeText(page))
const r = await fileInput(page, { type: 'Duty', people: ['Ranger'], placeholder: 'ALL AVAIL', from: '2026-07-18', to: '2026-07-18', timed: ['09:00', '12:00'], oil: 'yes' })
const iid = r[0].iid
log('filed', await who(iid))
await as(page, 'Ranger'); log('badge2', await badgeText(page))
await openFromList(page, iid)
const d = await describeWin(page)
log('ranger-window', { fields: d.fields.map(f => f.id + '=' + f.value), buttons: d.buttons.map(b => b.id + ':' + b.text).filter(t => t.length > 4), picker: d.picker, tail: d.text.slice(-420) })
await shot(page, 'H5-1-ranger-window')
await page.locator(`${WIN} [data-testid="inped-takeout"]`).scrollIntoViewIfNeeded()
await shot(page, 'H5-2-ranger-window-bottom')
log('save-button', await page.locator('#inpEditSave').count())
const tl = page.locator('#inpEditOwnTitle'); const tv = await tl.inputValue().catch(() => null)
await tl.click({ force: true }).catch(() => {}); await page.keyboard.type('ZZ')
log('ranger-typed-title', { before: tv, after: await tl.inputValue().catch(() => null) })
const m = await toastMark(page)
await page.locator('[data-testid="inped-takeout"]').click(); await page.waitForTimeout(400)
await shot(page, 'H5-3-confirm')
await page.locator('[data-testid="inped-takeout-yes"]').click(); await page.waitForTimeout(700)
log('after-take-out', { toast: await toastsSince(page, m), inputs: await who(iid), win: await page.locator(WIN).count() })
await shot(page, 'H5-4-after')
log('errors', errs)
save('H5', out)
await browser.close()
