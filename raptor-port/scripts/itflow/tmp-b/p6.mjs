await page.click('button[data-alpub="0"]'); await page.waitForTimeout(900)
console.log('toast', await toast())
console.log('AL1', await head())
console.log('issued marks', await page.evaluate(() => [...document.querySelectorAll('#eWeek .day[data-day="0"] [data-alc]')].slice(0,6).map(e => { const b = e.getBoundingClientRect(); return `${e.tagName}.${String(e.className).slice(0,40)} alc=${e.dataset.alc} "${e.innerText.replace(/\s+/g,' ').slice(0,30)}" @${Math.round(b.x)},${Math.round(b.y)} ${Math.round(b.width)}x${Math.round(b.height)}` })))
await shot(page, 'p6-al1')
await page.click('button[data-unpub="0"]'); await page.waitForTimeout(900)
