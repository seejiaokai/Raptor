await tueLine.click(); await page.waitForTimeout(1000)
console.log('after tap: week scrollLeft', sx0, '->', await page.evaluate(() => document.querySelector('#eWeek')?.scrollLeft), 'winY', await page.evaluate(() => window.scrollY))
console.log('bubble', await page.evaluate(() => { const b = document.querySelector('.histbub'); return b && b.offsetWidth ? b.innerText.replace(/\s+/g,' ') + ' @' + JSON.stringify(b.getBoundingClientRect()) : 'none' }))
console.log('flash/focus', await page.evaluate(() => [...document.querySelectorAll('.lift-land, .hl-focus, .flash, [class*=flash], .cw-focus')].map(e => e.className + ' ' + e.innerText?.slice(0, 20))))
