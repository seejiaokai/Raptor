// tap the Tuesday line
const tueLine = page.locator('.chgwin button.cw-l').filter({ hasText: /Tue|SODB|Havoc/ }).last()
console.log('tap line', await tueLine.innerText().catch(() => 'none'))
await page.evaluate(() => window.scrollTo(0, 0))
