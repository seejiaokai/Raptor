console.log(await dump())
await page.click('.chgwin .cw-g-btn:has-text("Who")'); await page.waitForTimeout(500)
await shot(page, 'p9-who')
console.log('WHO\n' + await dump())
await page.click('.chgwin .cw-g-btn:has-text("Item")'); await page.waitForTimeout(500)
