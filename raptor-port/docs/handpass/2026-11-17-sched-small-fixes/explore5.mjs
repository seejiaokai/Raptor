import { launch, go, pic, say } from './wlib.mjs'
say('explore5 v2')
const { browser, page } = await launch('chromium', false)
await go(page, 'editsched')
const cnt = () => page.evaluate(() => JSON.stringify(window.DAYS.map((d, i) => [i, ['allhands', 'ground'].map(k => (d[k] || []).filter(r => r.who === 'allavail').length).join('/')]).filter(x => x[1] !== '0/0')))
say('before', await cnt())
const seat = page.locator('#eWeek .day[data-day="0"] [data-fill="a:0.0.+"]').first()
await seat.click()
await page.waitForTimeout(400)
say('scrollX after arm', await page.evaluate(() => [...document.querySelectorAll('#eWeek, #eWeek *')].filter(e => e.scrollLeft > 0).map(e => e.id + e.className + e.scrollLeft).join('|')))
say('ARM', await page.evaluate(() => JSON.stringify(window.ARM)), 'panel', await page.locator('text=AIRCREW').first().evaluate(e => e.parentElement.innerText.replace(/\n/g, ' ').slice(0, 50)))
await pic(page, 'x-explore5-armed')
const chip = page.locator('.puck.allavail:visible', { hasText: /ALL AVAIL/ }).first()
const b = await chip.boundingBox()
say('chip box', JSON.stringify(b))
await page.mouse.click(b.x + b.width / 2, b.y + b.height / 2)
await page.waitForTimeout(600)
say('after', await cnt())
say('panel', await page.locator('text=AIRCREW').first().evaluate(e => e.parentElement.innerText.replace(/\n/g, ' ').slice(0, 50)))
await pic(page, 'x-explore5')
await browser.close()
