import { launch, go, pic, cropPic, say, state, press } from './wlib.mjs'
say('explore9 v4')
const { browser, page } = await launch('chromium', false, true)
await go(page, 'editsched')
await page.getByRole('button', { name: 'Jul 20' }).click()
await page.waitForTimeout(800)
await press(page, page.locator('#eWeek .day[data-day="3"] [data-inpedit]').first(), false); await page.waitForTimeout(700)
const rmk = page.locator('#inpEditRmk')
await rmk.click(); await page.keyboard.press('End'); await page.keyboard.type(' zz'); await page.waitForTimeout(300)
say('rmk value', await rmk.inputValue())
await page.keyboard.press('Escape'); await page.waitForTimeout(500)
say('ask after Esc', await page.locator('[data-testid="inped-escask"]').count(), 'win', await page.locator('#inpEditPop').count())
await pic(page, 'x-explore9-esc-dirty')
await page.locator('#inpEditPop .airpop-head button').first().click().catch(e => say('x err', e.message.split('\n')[0])); await page.waitForTimeout(500)
say('ask after X', await page.locator('[data-testid="inped-escask"]').count(), 'win', await page.locator('#inpEditPop').count())
await pic(page, 'x-explore9-x-dirty')
await browser.close()
