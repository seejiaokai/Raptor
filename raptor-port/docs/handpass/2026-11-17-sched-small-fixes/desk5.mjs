// desk5: the plain-user round (desktop Chromium, as a scheduler would). v1
import { launch, go, pic, cropPic, say, rec, state, press, errors } from './wlib.mjs'
say('desk5 v1')
const { browser, page } = await launch('chromium', false, true)
await go(page, 'editsched')
async function scenario(id, fn) { try { await fn() } catch (e) { rec(id, false, 'SCRIPT ERROR ' + String(e.message).split('\n')[0]) } }
const blur = () => page.evaluate(() => { if (document.activeElement && document.activeElement !== document.body) document.activeElement.blur() })
const esc = async () => { await page.keyboard.press('Escape'); await page.waitForTimeout(400) }
const D0 = '#eWeek .day[data-day="0"]'
await scenario('U1 board and the count', async () => {
  await press(page, page.locator(`${D0} .dt.sb-open`), false)
  await page.waitForSelector('#schedBoard:not([hidden])'); await page.waitForTimeout(600)
  const nb = await page.locator('#schedBoard .oilcount').count(); say('board chips', nb)
  const chip = page.locator('#schedBoard .oilcount').last()
  const sent = await chip.getAttribute('data-oilsent')
  await blur(); await press(page, chip, false); await page.waitForTimeout(600)
  const s1 = await state(page)
  await pic(page, 'u1-board-window-open')
  // tap a man for his reason
  const man = page.locator('.availwin:not([hidden]) .puck.flag, .availwin:not([hidden]) .puck').nth(3)
  await press(page, man, false); await page.waitForTimeout(500)
  await pic(page, 'u1-board-window-reason')
  const stillOpen = (await state(page)).ava
  rec('U1 window from the board count, tap a man for his reason', s1.ava && stillOpen, `opened=${s1.ava} sent=${sent}; after tapping a man window still open=${stillOpen}`)
  // close by X
  await press(page, page.locator('.availwin:not([hidden]) .win-x'), false); await page.waitForTimeout(400)
  const s2 = await state(page)
  // reopen, close by Escape
  await blur(); await press(page, chip, false); await page.waitForTimeout(500)
  const s3 = await state(page); await blur(); await esc(); const s4 = await state(page)
  // reopen, tap outside (stays)
  await press(page, chip, false); await page.waitForTimeout(500)
  await page.mouse.click(600, 420); await page.waitForTimeout(500)
  const s5 = await state(page); await pic(page, 'u1-board-tap-outside')
  rec('U1 close by X, by Escape; a tap outside leaves it up', !s2.ava && s3.ava && !s4.ava && s5.ava, `X closed=${!s2.ava}; reopened=${s3.ava}; Esc closed=${!s4.ava}; after a tap outside open=${s5.ava}`)
  // Done, leave the board; page change closes it
  await press(page, page.locator('#sbDone'), false); await page.waitForTimeout(600)
  const s6 = await state(page)
  await go(page, 'viewsched'); await page.waitForTimeout(400)
  const s7 = await state(page)
  rec('U1 a page change closes it', s7.page === 'viewsched' && !s7.ava, `after Done: window open=${s6.ava} (board closed=${!s6.board}); after going to View-only: open=${s7.ava}`)
  await go(page, 'editsched')
})
await scenario('U2 the changes window: clock, X, Escape, tap outside', async () => {
  await press(page, page.locator('#histBtn'), false); await page.waitForTimeout(500)
  const a = await state(page)
  await press(page, page.locator('.chgwin:not([hidden]) .win-x'), false); await page.waitForTimeout(400)
  const b = await state(page)
  await press(page, page.locator('#histBtn'), false); await page.waitForTimeout(500)
  await blur(); await esc(); const c = await state(page)
  await press(page, page.locator('#histBtn'), false); await page.waitForTimeout(500)
  await page.mouse.click(400, 160); await page.waitForTimeout(500)
  const d = await state(page); await pic(page, 'u2-chg-tap-outside')
  rec('U2 the changes window: clock, X, Escape, tap outside', a.chg && !b.chg && !c.chg && d.chg, `clock opened=${a.chg}; X closed=${!b.chg}; Esc closed=${!c.chg}; a tap outside leaves it up=${d.chg}`)
  await blur(); await esc()
})
await scenario('U3 Undo and Redo after', async () => {
  const box = page.locator(`${D0} [data-txt="ap:0.0.str"]`).first()
  await box.scrollIntoViewIfNeeded()
  const before = (await box.innerText()).trim()
  await box.click(); await page.keyboard.press('Control+A'); await page.keyboard.type('07:50'); await page.keyboard.press('Tab'); await page.waitForTimeout(500)
  const edited = (await box.innerText()).trim()
  await press(page, page.locator('#undoBtn'), false); await page.waitForTimeout(500)
  const undone = (await box.innerText()).trim()
  await press(page, page.locator('#redoBtn'), false); await page.waitForTimeout(500)
  const redone = (await box.innerText()).trim()
  await pic(page, 'u3-undo-redo')
  rec('U3 Undo and Redo after', edited !== before && undone === before && redone === edited, `before=${before} edited=${edited} undone=${undone} redone=${redone}`)
  await press(page, page.locator('#undoBtn'), false); await page.waitForTimeout(400)
})
await scenario('U4 the week, the board and View-only looked at', async () => {
  await go(page, 'editsched'); await page.evaluate(() => window.scrollTo(0, 0))
  await pic(page, 'u4-week')
  await go(page, 'viewsched'); await page.evaluate(() => window.scrollTo(0, 0))
  await pic(page, 'u4-viewonly')
  const c = await page.locator('#vWeek .day[data-day="0"] .oilcount').count()
  rec('U4 View-only shows the row and its count', c >= 3, `counts on Monday in View-only=${c}`)
})
console.log('ERRORS', JSON.stringify(errors))
await browser.close()
