// desk2: W2 (changes window), W3 (both windows), W4 (box / armed seat / bell) — desktop, Chromium. v1
import { launch, go, pic, cropPic, say, rec, state, press, errors } from './wlib.mjs'
say('desk2 v1')
const { browser, page } = await launch('chromium', false, true)
await go(page, 'editsched')
async function scenario(id, fn) { try { await fn() } catch (e) { rec(id, false, 'SCRIPT ERROR ' + String(e.message).split('\n')[0]) } }
const blur = () => page.evaluate(() => { if (document.activeElement && document.activeElement !== document.body) document.activeElement.blur() })
const esc = async () => { await page.keyboard.press('Escape'); await page.waitForTimeout(350) }
const D0 = '#eWeek .day[data-day="0"]'
const hist = () => page.evaluate(() => { const b = document.querySelector('#histBtn'); return b ? b.classList.contains('on') : null })
const sbhist = () => page.evaluate(() => { const b = document.querySelector('#sbHist'); return b ? b.classList.contains('on') : null })
const closeAll = async () => { for (let i = 0; i < 3; i++) { const s = await state(page); if (!s.ava && !s.chg && !s.board) break; await esc() } }

await scenario('W2 clock icon', async () => {
  await blur(); await press(page, page.locator('#histBtn'), false); await page.waitForTimeout(500)
  const s1 = await state(page), h1 = await hist()
  await pic(page, 'w2-clock-open')
  await blur(); await esc()
  const s2 = await state(page), h2 = await hist()
  await pic(page, 'w2-clock-after-esc')
  rec('W2 clock icon', s1.chg && !s2.chg && h1 && !h2, `open=${s1.chg} histOn=${h1} afterEsc open=${s2.chg} histOn=${h2} keys=${s2.active}`)
})
await scenario('W2 a day count on the week', async () => {
  await blur(); await press(page, page.locator(`${D0} .dchg`).first(), false); await page.waitForTimeout(500)
  const s1 = await state(page)
  await pic(page, 'w2-daycount-open')
  await blur(); await esc()
  const s2 = await state(page)
  await cropPic(page, 'w2-daycount-after-esc', page.locator(`${D0} .dchg`).first(), 120)
  rec('W2 a day count on the week', s1.chg && !s2.chg, `open=${s1.chg} afterEsc open=${s2.chg} keys=${s2.active}`)
})
await scenario('W2 board strip count and History button', async () => {
  await press(page, page.locator(`${D0} .dt.sb-open`), false)
  await page.waitForSelector('#schedBoard:not([hidden])'); await page.waitForTimeout(500)
  const cnt = page.locator('#schedBoard .dchg').first()
  await blur(); await press(page, cnt, false); await page.waitForTimeout(500)
  const s1 = await state(page)
  await pic(page, 'w2-board-count-open')
  await blur(); await esc()
  const s2 = await state(page)
  await pic(page, 'w2-board-count-after-esc')
  // History button
  await blur(); await press(page, page.locator('#sbHist'), false); await page.waitForTimeout(500)
  const s3 = await state(page), h3 = await sbhist()
  await pic(page, 'w2-board-hist-open')
  await blur(); await esc()
  const s4 = await state(page), h4 = await sbhist()
  await pic(page, 'w2-board-hist-after-esc')
  rec('W2 board strip count and History button', s1.chg && !s2.chg && s2.board && s3.chg && !s4.chg && s4.board && h3 && !h4, `count: open=${s1.chg} after=${s2.chg} boardStays=${s2.board}; History: open=${s3.chg} on=${h3} after=${s4.chg} boardStays=${s4.board} on=${h4}`)
  await press(page, page.locator('#sbDone'), false); await page.waitForTimeout(400)
})
await scenario('W2 View-only count', async () => {
  await go(page, 'viewsched')
  const c = page.locator('#vWeek .day[data-day="0"] .dchg, #vWeek .day[data-day="0"] .dpend').first()
  const n = await c.count()
  if (!n) { rec('W2 View-only count', false, 'NOT WALKED: no count chip on View-only Sched day 0 for admin'); return }
  await blur(); await press(page, c, false); await page.waitForTimeout(500)
  const s1 = await state(page)
  await pic(page, 'w2-viewonly-open')
  await blur(); await esc()
  const s2 = await state(page)
  rec('W2 View-only count', s1.chg && !s2.chg, `open=${s1.chg} afterEsc open=${s2.chg}`)
  await go(page, 'editsched')
})

// W3
await scenario('W3 avail then chg', async () => {
  await closeAll()
  await blur(); await press(page, page.locator(`${D0} [data-fill="a:0.0.+"] .oilcount`).first(), false); await page.waitForTimeout(400)
  await press(page, page.locator('#histBtn'), false); await page.waitForTimeout(500)
  const s1 = await state(page)
  await pic(page, 'w3-avail-then-chg-open')
  await blur(); await esc()
  const s2 = await state(page)
  await blur(); await esc()
  const s3 = await state(page)
  await pic(page, 'w3-avail-then-chg-closed')
  rec('W3 avail then chg', s1.ava && s1.chg && !s2.chg && s2.ava && !s3.ava, `both=${s1.ava && s1.chg} esc1 -> chg=${s2.chg} ava=${s2.ava}; esc2 -> chg=${s3.chg} ava=${s3.ava}`)
})
