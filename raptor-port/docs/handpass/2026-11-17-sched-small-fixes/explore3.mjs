import { launch, go, pic, say } from './wlib.mjs'
say('explore3 v1')
const { browser, page } = await launch('chromium', false)
await go(page, 'editsched')
const pchip = page.locator('.puck.allavail:visible', { hasText: /ALL AVAIL/ }).first()
say('chip parent', await pchip.evaluate(e => e.parentElement.outerHTML.slice(0, 300)))
await pchip.click()
await page.waitForTimeout(300)
say('ARM', await page.evaluate(() => JSON.stringify(window.ARM)))
await page.locator('#eWeek .day[data-day="0"] .ah-row .ppl').first().click()
await page.waitForTimeout(600)
say('oilcounts', await page.locator('#eWeek .day[data-day="0"] .oilcount').count())
say('ah0', await page.evaluate(() => JSON.stringify(window.DAYS[0].allhands[0])))
await pic(page, 'x-explore3')
await browser.close()
