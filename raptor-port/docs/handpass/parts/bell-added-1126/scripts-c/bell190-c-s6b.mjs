// bell190-c S6b (desktop): Undo AFTER Ranger read the line — the line read by a tap on it (opening the bell alone leaves it
// unread, seen in S6). Saber keeps tab 1 signed in (Undo's list clears at sign-out, D148); Ranger reads in tab 2 of the same
// browser. Two live tabs never sync (walk-scripts §3): tab 2 is reloaded after the Undo, and the result is read again in one
// tab. [F46, A38]
const L = await import('./bell190-c-lib.mjs')
console.log('bell190-c-s6b v1')
const w = await L.newWorld('desk')
const P = w.page
const store = async pg => (await pg.evaluate(() => JSON.parse(JSON.stringify(window.NOTICES || [])))).filter(n => n.to === 'bane').map(n => L.fmt(n) + ' read=' + JSON.stringify(n.read || n.seen || n.readAt || null))
await L.signIn(w, 'ad', 'a'); await L.toWar(w)
await L.openCell(w, 'bane', '2026-07-23'); await L.setAuto(w, true); console.log('place 23', JSON.stringify(await L.place(w, 'LL')))
const p2 = await w.ctx.newPage()
const w2 = { ctx: w.ctx, page: p2, errs: [], phone: false }
await L.signIn(w2, 'us', 'us')
const r1 = await L.bell(w2, 'c-s6b-01-ranger-bell')
console.log('Ranger (tab 2) bell:', JSON.stringify(r1.lines.map(l => [l.unread, l.text])))
const t = await L.tapLine(w2, r1.lines[0].id, 'c-s6b-02-ranger-taps-line')
console.log('Ranger taps the line ->', JSON.stringify(t))
const r1b = await L.bell(w2, 'c-s6b-03-ranger-line-read'); await L.tap(w2, '#notifyBell')
console.log('Ranger bell after his tap:', JSON.stringify(r1b.lines.map(l => [l.unread, l.text])))
console.log('tab-2 store:', JSON.stringify(await store(p2)))
console.log('local storage keys holding notices:', await p2.evaluate(() => Object.keys(localStorage).filter(k => /notic|bell/i.test(k)).join(',')))
await P.bringToFront()
console.log('tab 1 shows:', await P.evaluate(() => document.body.innerText.match(/[A-Z]+ · (ADMIN|MEMBER)/)?.[0]), 'undo enabled:', await P.evaluate(() => !document.querySelector('#undoBtn').disabled))
await L.undo(w)
console.log('after Undo in tab 1: cell', JSON.stringify(await L.cellText(w, 'bane', '2026-07-23')), 'tab-1 store', JSON.stringify(await store(P)))
await p2.reload({ waitUntil: 'domcontentloaded' }); await p2.waitForTimeout(1500)
if (await L.vis(p2, '#luser')) await L.signIn(w2, 'us', 'us')
const r2 = await L.bell(w2, 'c-s6b-04-ranger-after-undo')
console.log('Ranger bell after the Undo (tab 2 reloaded):', JSON.stringify({ lit: r2.lit && r2.lit.cls, lines: r2.lines.map(l => [l.unread, l.text]), list: r2.list }))
await L.tap(w2, '#notifyBell').catch(() => {})
await p2.close()
await L.signOut(w); await L.signIn(w, 'us', 'us'); await L.toWar(w)
const r3 = await L.bell(w, 'c-s6b-05-ranger-one-tab')
console.log('Ranger bell, one tab, fresh sign-in:', JSON.stringify({ lit: r3.lit && r3.lit.cls, lines: r3.lines.map(l => [l.unread, l.text]), list: r3.list }))
console.log('Ranger 23 Jul cell:', JSON.stringify(await L.cellText(w, 'bane', '2026-07-23')))
await L.reach(w, 'bane', '2026-07-23'); await L.shot(w, 'c-s6b-06-ranger-grid-23jul')
console.log('errors', w.errs)
await L.closeAll()
