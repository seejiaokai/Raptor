// bell190 walker A — exploration 2: file a Training for Tally on Wed through the Inputs calendar, then see its row on Edit Schedule
import * as L from './bell190-a-lib.mjs'
console.log('bell190-a-explore2 v1')
const w = await L.newWorld('desk')
await L.signIn(w, 'ad')
const types = await w.page.evaluate(() => Object.keys(window.INPUT_TYPES || {}).slice(0, 60))
console.log('types', L.J(types))
const n0 = await L.allNotices(w.page)
const iid = await L.fileInput(w, L.WED, { type: 'Training', people: [L.ID.Tally], from: '09:00', to: '11:00' })
console.log('iid', iid, L.J(await L.rec(w.page, iid)))
const n1 = await L.allNotices(w.page)
console.log('new notices', L.newSince(n0, n1).map(n => JSON.stringify(n)).join('\n'))
await L.go(w.page, 'editsched')
console.log(L.J(await L.groundDump(w.page, 2), null, 1))
const dom = await w.page.evaluate(() => [...document.querySelectorAll('#eWeek [data-slot^="g:2."], #eWeek [data-fill^="g:2."], #eWeek [data-inpseat]')].map(e => `${e.tagName}.${String(e.className).slice(0, 40)} slot=${e.getAttribute('data-slot')} fill=${e.getAttribute('data-fill')} inpseat=${e.getAttribute('data-inpseat')} w=${Math.round(e.getBoundingClientRect().width)} x=${Math.round(e.getBoundingClientRect().left)} y=${Math.round(e.getBoundingClientRect().top)} t="${(e.textContent || '').trim().slice(0, 30)}"`))
console.log(dom.join('\n'))
const ros = await w.page.evaluate(() => { const r = [...document.querySelectorAll('.eroster [data-person], #eRoster [data-person]')]; return { n: r.length, first: r.slice(0, 6).map(e => `${e.tagName}.${String(e.className).slice(0, 40)} p=${e.getAttribute('data-person')} vis=${e.getBoundingClientRect().width > 3} draggable=${e.getAttribute('draggable')}`) } })
console.log(L.J(ros, null, 1))
const rangerPucks = await w.page.evaluate(() => [...document.querySelectorAll('[data-person="bane"]')].filter(e => e.getBoundingClientRect().width > 3).map(e => `${e.tagName}.${String(e.className).slice(0, 40)} parent=${e.parentElement?.className?.slice?.(0, 40)} in=${e.closest('[id]')?.id} slot=${e.closest('[data-slot]')?.getAttribute('data-slot')}`))
console.log('ranger pucks', rangerPucks.join('\n'))
await L.shot(w, 'explore2-editsched')
console.log('errs', w.errs)
await L.closeAll()
